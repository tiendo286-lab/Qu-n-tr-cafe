-- ---------------------------------------------------------------- Hàm phụ
create or replace function public.app__dt_total(p_program bigint) returns integer
language sql stable security definer set search_path = public as $$
  select count(*)::int from public.training_items where program_id = p_program
$$;

create or replace function public.app__dt_achieved(p_training bigint) returns integer
language sql stable security definer set search_path = public as $$
  select count(*)::int from public.training_marks where training_id = p_training and level is not null
$$;

-- hoan_thanh / dao_tao_tiep / dang_dao_tao
create or replace function public.app__dt_status(t public.trainings) returns text
language sql stable security definer set search_path = public as $$
  select case
    when public.app__dt_achieved(t.id) >= public.app__dt_total(t.program_id) then 'hoan_thanh'
    when to_char(public.vn_now(), 'YYYY-MM-DD') >= to_char(t.start_date::date + 8, 'YYYY-MM-DD') or t.cont_trainer_kind is not null then 'dao_tao_tiep'
    else 'dang_dao_tao' end
$$;

create or replace function public.app__dt_can_edit(t public.trainings) returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce(public.app_can('dao_tao'), false)
      or coalesce(public.app_my_employee() = any(array_remove(array[t.instructor_id, t.cont_trainer_id], null)), false)
$$;

create or replace function public.app__dt_need(p_id bigint) returns public.trainings
language plpgsql security definer set search_path = public as $$
declare t public.trainings;
begin
  perform public.app__need(null);
  select * into t from public.trainings where id = p_id;
  if t.id is null then raise exception 'Không tìm thấy phiếu đào tạo.'; end if;
  if not public.app__dt_can_edit(t) then raise exception 'Chỉ người hướng dẫn / quản lý phụ trách / người có quyền Đào tạo mới cập nhật được phiếu này.'; end if;
  return t;
end $$;

create or replace function public.app__dt_summary(t public.trainings) returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'id', t.id, 'employee_id', t.employee_id, 'start_date', t.start_date, 'branch_id', t.branch_id,
    'branch', (select coalesce(b.display_code, b.code) from public.branches b where b.id = t.branch_id),
    'instructor', (select e.code || ' – ' || e.name from public.employees e where e.id = t.instructor_id),
    'manager', public.app__acc_name(t.manager_id),
    'achieved', public.app__dt_achieved(t.id), 'total', public.app__dt_total(t.program_id),
    'status', public.app__dt_status(t),
    'missing', (select coalesce(jsonb_agg(i.no order by i.no), '[]') from public.training_items i
                 where i.program_id = t.program_id and not exists (select 1 from public.training_marks m where m.training_id = t.id and m.item_no = i.no and m.level is not null)))
$$;

