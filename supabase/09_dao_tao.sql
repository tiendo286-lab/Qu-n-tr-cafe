create or replace function public.app_dt_options() returns jsonb
language plpgsql stable security definer set search_path = public as $$
begin
  perform public.app__need('dao_tao');
  return jsonb_build_object(
    'employees', coalesce((select jsonb_agg(jsonb_build_object('id', e.id, 'code', e.code, 'name', e.name, 'rank', e.rank) order by e.code) from public.employees e where e.status = 'Đang làm'), '[]'),
    'managers', coalesce((select jsonb_agg(jsonb_build_object('id', a.id, 'name', public.app__acc_name(a.id)) order by public.app__acc_name(a.id))
                           from public.accounts a left join public.employees e on e.id = a.employee_id
                          where a.system_role in ('chu', 'ql_tong', 'ql') and a.locked = 0 and (a.employee_id is null or e.status = 'Đang làm')), '[]'),
    'branches', coalesce((select jsonb_agg(jsonb_build_object('id', b.id, 'code', coalesce(b.display_code, b.code)) order by b.sort_order) from public.branches b where b.status = 'Đang hoạt động'), '[]'));
end $$;

-- ---------------------------------------------------------------- Tạo, xem, sửa phiếu
create or replace function public.app_dt_create(p_employee bigint, p jsonb) returns bigint
language plpgsql security definer set search_path = public as $$
declare a public.accounts; nid bigint; prog bigint;
begin
  a := public.app__need('dao_tao');
  select id into prog from public.training_programs where code = coalesce(p ->> 'program', 'chay_ban');
  if exists (select 1 from public.trainings where employee_id = p_employee and program_id = prog) then raise exception 'Nhân viên này đã có phiếu đào tạo chạy bàn.'; end if;
  if coalesce(p ->> 'start_date', '') !~ '^\d{4}-\d{2}-\d{2}$' then raise exception 'Chọn ngày bắt đầu đào tạo.'; end if;
  insert into public.trainings(employee_id, program_id, branch_id, start_date, instructor_id, manager_id, created_by)
  values (p_employee, prog, nullif(p ->> 'branch_id', '')::bigint, p ->> 'start_date', nullif(p ->> 'instructor_id', '')::bigint, nullif(p ->> 'manager_id', '')::bigint, a.id)
  returning id into nid;
  -- gắn các nhiệm vụ đào tạo (tab Họp) của nhân viên này vào phiếu
  update public.tasks set training_id = nid where kind = 'dao_tao' and employee_id = p_employee and training_id is null;
  perform public.app_log('tao_phieu_dao_tao', 'employee=' || p_employee);
  return nid;
end $$;

create or replace function public.app_dt_get(p_id bigint) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare t public.trainings; me_emp bigint; pr public.training_programs;
begin
  perform public.app__need(null);
  select * into t from public.trainings where id = p_id;
  if t.id is null then raise exception 'Không tìm thấy phiếu đào tạo.'; end if;
  me_emp := public.app_my_employee();
  if not (public.app_can('dao_tao') or public.app_can('quan_ly_nhan_vien')
          or coalesce(me_emp = any(array_remove(array[t.employee_id, t.instructor_id, t.cont_trainer_id], null)), false)
          or coalesce((public.app_account()).id = t.manager_id, false)) then
    raise exception 'Bạn không xem được phiếu đào tạo này.';
  end if;
  select * into pr from public.training_programs where id = t.program_id;
  return to_jsonb(t) || public.app__dt_summary(t) || jsonb_build_object(
    'program', jsonb_build_object('name', pr.name, 'days', pr.days),
    'employee', (select jsonb_build_object('code', e.code, 'name', e.name, 'rank', e.rank) from public.employees e where e.id = t.employee_id),
    'cont_trainer', (select e.code || ' – ' || e.name from public.employees e where e.id = t.cont_trainer_id),
    'items', (select jsonb_agg(jsonb_build_object('no', i.no, 'day', i.day, 'title', i.title, 'page', i.page,
                 'introduced', coalesce(m.introduced, false), 'practiced', coalesce(m.practiced, false), 'level', m.level,
                 'by', public.app__acc_name(m.by_account), 'at', m.at) order by i.no)
                from public.training_items i left join public.training_marks m on m.training_id = t.id and m.item_no = i.no where i.program_id = t.program_id),
    'days_log', coalesce((select jsonb_object_agg(d.day, jsonb_build_object('comment', d.comment, 'trainee_at', d.trainee_at, 'instructor_at', d.instructor_at,
                 'instructor_by', public.app__acc_name(d.instructor_by))) from public.training_days d where d.training_id = t.id), '{}'),
    'tasks', coalesce((select jsonb_agg(jsonb_build_object('id', k.id, 'content', k.content, 'status', k.status, 'due_date', k.due_date, 'assignee', public.app__acc_name(k.assignee_id)) order by k.id)
                         from public.tasks k where k.training_id = t.id), '[]'),
    'can_edit', public.app__dt_can_edit(t),
    'can_admin', public.app_can('dao_tao'),
    'is_trainee', coalesce(me_emp = t.employee_id, false));
end $$;

-- Thông tin phiếu (ngày 8, đánh giá cuối khóa, đào tạo tiếp…). Thông tin chính chỉ người có quyền Đào tạo sửa.
create or replace function public.app_dt_update(p_id bigint, p jsonb) returns void
language plpgsql security definer set search_path = public as $$
declare t public.trainings; admin boolean;
begin
  t := public.app__dt_need(p_id);
  admin := public.app_can('dao_tao');
  if not admin and (p ? 'branch_id' or p ? 'start_date' or p ? 'instructor_id' or p ? 'manager_id' or p ? 'cont_trainer_id' or p ? 'cont_trainer_kind') then
    raise exception 'Chỉ người có quyền Đào tạo mới đổi cơ sở, ngày bắt đầu, người hướng dẫn, quản lý phụ trách, người đào tạo tiếp.';
  end if;
  if p ? 'start_date' and coalesce(p ->> 'start_date', '') !~ '^\d{4}-\d{2}-\d{2}$' then raise exception 'Ngày bắt đầu không hợp lệ.'; end if;
  if p ? 'day8_shift' and nullif(p ->> 'day8_shift', '') is not null and not (p ->> 'day8_shift' = any(public.app__shifts())) then raise exception 'Ca không hợp lệ.'; end if;
  update public.trainings set
    branch_id = case when p ? 'branch_id' then nullif(p ->> 'branch_id', '')::bigint else branch_id end,
    start_date = case when p ? 'start_date' then p ->> 'start_date' else start_date end,
    instructor_id = case when p ? 'instructor_id' then nullif(p ->> 'instructor_id', '')::bigint else instructor_id end,
    manager_id = case when p ? 'manager_id' then nullif(p ->> 'manager_id', '')::bigint else manager_id end,
    day8_shift = case when p ? 'day8_shift' then nullif(p ->> 'day8_shift', '') else day8_shift end,
    day8_date = case when p ? 'day8_date' then nullif(p ->> 'day8_date', '') else day8_date end,
    day8_review = case when p ? 'day8_review' then nullif(trim(p ->> 'day8_review'), '') else day8_review end,
    strengths = case when p ? 'strengths' then nullif(trim(p ->> 'strengths'), '') else strengths end,
    improvements = case when p ? 'improvements' then nullif(trim(p ->> 'improvements'), '') else improvements end,
    cont_trainer_kind = case when p ? 'cont_trainer_kind' then nullif(p ->> 'cont_trainer_kind', '') else cont_trainer_kind end,
    cont_trainer_id = case when p ? 'cont_trainer_id' then nullif(p ->> 'cont_trainer_id', '')::bigint else cont_trainer_id end,
    cont_trainer_name = case when p ? 'cont_trainer_name' then nullif(trim(p ->> 'cont_trainer_name'), '') else cont_trainer_name end,
    cont_done_date = case when p ? 'cont_done_date' then nullif(p ->> 'cont_done_date', '') else cont_done_date end,
    cont_result = case when p ? 'cont_result' then nullif(p ->> 'cont_result', '') else cont_result end,
    updated_at = public.vn_now_text()
  where id = t.id;
end $$;

-- Cập nhật 1 hạng mục: giới thiệu / thực hành / mức đạt
create or replace function public.app_dt_mark(p_id bigint, p_no integer, p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare a public.accounts; t public.trainings; m public.training_marks; intro boolean; prac boolean; lv text;
begin
  t := public.app__dt_need(p_id);
  a := public.app_account();
  if not exists (select 1 from public.training_items where program_id = t.program_id and no = p_no) then raise exception 'Hạng mục không hợp lệ.'; end if;
  select * into m from public.training_marks where training_id = t.id and item_no = p_no;
  intro := case when p ? 'introduced' then (p ->> 'introduced')::boolean else coalesce(m.introduced, false) end;
  prac := case when p ? 'practiced' then (p ->> 'practiced')::boolean else coalesce(m.practiced, false) end;
  lv := case when p ? 'level' then nullif(p ->> 'level', '') else m.level end;
  if prac and not intro then raise exception 'Hạng mục % phải “Đã giới thiệu” trước khi “Đã thực hành”.', p_no; end if;
  if lv is not null and not (intro and prac) then raise exception 'Hạng mục % phải đủ “Đã giới thiệu” và “Đã thực hành có giám sát” rồi mới đánh giá mức đạt.', p_no; end if;
  if lv is not null and lv not in ('tb', 'kha', 'tot') then raise exception 'Mức đạt không hợp lệ.'; end if;
  insert into public.training_marks(training_id, item_no, introduced, practiced, level, by_account, at)
  values (t.id, p_no, intro, prac, lv, a.id, public.vn_now_text())
  on conflict (training_id, item_no) do update set introduced = excluded.introduced, practiced = excluded.practiced, level = excluded.level,
         by_account = excluded.by_account, at = excluded.at;
  update public.trainings set updated_at = public.vn_now_text() where id = t.id;
  return jsonb_build_object('by', public.app__acc_name(a.id), 'at', public.vn_now_text(), 'achieved', public.app__dt_achieved(t.id), 'status', public.app__dt_status(t));
end $$;

-- Nhận xét cuối ngày (người hướng dẫn)
create or replace function public.app_dt_day_comment(p_id bigint, p_day integer, p_comment text) returns void
language plpgsql security definer set search_path = public as $$
declare t public.trainings;
begin
  t := public.app__dt_need(p_id);
  if p_day not between 1 and 8 then raise exception 'Ngày không hợp lệ.'; end if;
  insert into public.training_days(training_id, day, comment) values (t.id, p_day, nullif(trim(coalesce(p_comment, '')), ''))
  on conflict (training_id, day) do update set comment = excluded.comment;
end $$;

-- Xác nhận cuối ngày: p_who = 'nv' (chính nhân viên được đào tạo) hoặc 'hd' (người hướng dẫn / quản lý)
create or replace function public.app_dt_day_confirm(p_id bigint, p_day integer, p_who text, p_on boolean) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts; t public.trainings;
begin
  a := public.app__need(null);
  select * into t from public.trainings where id = p_id;
  if t.id is null then raise exception 'Không tìm thấy phiếu đào tạo.'; end if;
  if p_day not between 1 and 8 then raise exception 'Ngày không hợp lệ.'; end if;
  if p_who = 'nv' then
    if a.employee_id is distinct from t.employee_id then raise exception 'Chỉ chính nhân viên được đào tạo mới xác nhận phần của nhân viên.'; end if;
    insert into public.training_days(training_id, day, trainee_at, trainee_by) values (t.id, p_day, case when p_on then public.vn_now_text() end, case when p_on then a.id end)
    on conflict (training_id, day) do update set trainee_at = excluded.trainee_at, trainee_by = excluded.trainee_by;
  elsif p_who = 'hd' then
    if not public.app__dt_can_edit(t) then raise exception 'Chỉ người hướng dẫn / người có quyền Đào tạo mới xác nhận phần người hướng dẫn.'; end if;
    insert into public.training_days(training_id, day, instructor_at, instructor_by) values (t.id, p_day, case when p_on then public.vn_now_text() end, case when p_on then a.id end)
    on conflict (training_id, day) do update set instructor_at = excluded.instructor_at, instructor_by = excluded.instructor_by;
  else
    raise exception 'Không hợp lệ.';
  end if;
end $$;

create or replace function public.app_dt_delete(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
begin
  perform public.app__need('dao_tao');
  update public.tasks set training_id = null where training_id = p_id;
  delete from public.trainings where id = p_id;
  perform public.app_log('xoa_phieu_dao_tao', 'training=' || p_id);
end $$;

-- Phiếu liên quan đến tôi: tôi được đào tạo, hoặc tôi hướng dẫn / đào tạo tiếp / quản lý phụ trách
create or replace function public.app_dt_mine() returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare a public.accounts;
begin
  a := public.app__need(null);
  return coalesce((select jsonb_agg(public.app__dt_summary(t) || jsonb_build_object(
      'employee', (select e.code || ' – ' || e.name from public.employees e where e.id = t.employee_id),
      'role', case when t.employee_id = a.employee_id then 'hoc' when t.manager_id = a.id then 'quan_ly' else 'huong_dan' end) order by t.start_date desc)
    from public.trainings t
   where t.employee_id = a.employee_id or t.instructor_id = a.employee_id or t.cont_trainer_id = a.employee_id or t.manager_id = a.id), '[]');
end $$;

-- Nhiệm vụ đào tạo giao ở tab Họp: tự gắn vào phiếu đào tạo của nhân viên (nếu đã có)
create or replace function public.app__task_link_training() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.kind = 'dao_tao' and new.training_id is null and new.employee_id is not null then
    new.training_id := (select id from public.trainings where employee_id = new.employee_id order by id desc limit 1);
  end if;
  return new;
end $$;
drop trigger if exists task_link_training on public.tasks;
create trigger task_link_training before insert on public.tasks for each row execute function public.app__task_link_training();

-- ---------------------------------------------------------------- Cấp quyền gọi hàm
do $$
declare f record;
begin
  for f in select p.oid::regprocedure as sig, p.proname from pg_proc p join pg_namespace n on n.oid = p.pronamespace
            where n.nspname = 'public' and (p.proname like 'app\_dt\_%' or p.proname like 'app\_\_dt\_%' or p.proname in ('app__perm_keys', 'app__task_link_training')) loop
    execute format('revoke execute on function %s from public, anon', f.sig);
    if f.proname like 'app\_\_%' then
      execute format('revoke execute on function %s from authenticated', f.sig);
    else
      execute format('grant execute on function %s to authenticated', f.sig);
    end if;
  end loop;
end $$;
