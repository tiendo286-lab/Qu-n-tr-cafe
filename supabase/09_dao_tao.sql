create or replace function public.app_dt_list() returns jsonb
language plpgsql stable security definer set search_path = public as $$
begin
  perform public.app__need('dao_tao');
  return coalesce((select jsonb_agg(jsonb_build_object('employee_id', e.id, 'code', e.code, 'name', e.name, 'rank', e.rank,
      'branches', (select coalesce(jsonb_agg(coalesce(b.display_code, b.code) order by b.sort_order), '[]') from public.employee_branches eb join public.branches b on b.id = eb.branch_id where eb.employee_id = e.id),
      'roles', (select coalesce(jsonb_agg(er.role), '[]') from public.employee_roles er where er.employee_id = e.id),
      'training', (select public.app__dt_summary(t) from public.trainings t where t.employee_id = e.id order by t.id desc limit 1))
    order by e.code) from public.employees e where e.status = 'Đang làm'), '[]');
end $$;

