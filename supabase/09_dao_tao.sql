create table if not exists public.training_programs (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  days jsonb not null default '[]'
);

create table if not exists public.training_items (
  program_id bigint not null references public.training_programs(id) on delete cascade,
  no integer not null,
  day integer not null,
  title text not null,
  page text,
  primary key (program_id, no)
);

create table if not exists public.trainings (
  id bigint generated by default as identity primary key,
  employee_id bigint not null references public.employees(id) on delete cascade,
  program_id bigint not null references public.training_programs(id),
  branch_id bigint references public.branches(id) on delete set null,
  start_date text not null,
  instructor_id bigint references public.employees(id) on delete set null,     -- người hướng dẫn chính
  manager_id bigint references public.accounts(id) on delete set null,         -- quản lý phụ trách
  day8_shift text, day8_date text, day8_review text,
  strengths text, improvements text,
  cont_trainer_kind text check (cont_trainer_kind in ('quan_ly', 'cap_1')),
  cont_trainer_id bigint references public.employees(id) on delete set null,
  cont_trainer_name text,
  cont_done_date text,
  cont_result text check (cont_result in ('dat')),
  created_by bigint,
  created_at text not null default public.vn_now_text(),
  updated_at text not null default public.vn_now_text(),
  unique (employee_id, program_id)
);

create table if not exists public.training_marks (
  training_id bigint not null references public.trainings(id) on delete cascade,
  item_no integer not null,
  introduced boolean not null default false,
  practiced boolean not null default false,
  level text check (level in ('tb', 'kha', 'tot')),
  by_account bigint,
  at text,
  primary key (training_id, item_no)
);

create table if not exists public.training_days (
  training_id bigint not null references public.trainings(id) on delete cascade,
  day integer not null,
  comment text,
  trainee_at text, trainee_by bigint,
  instructor_at text, instructor_by bigint,
  primary key (training_id, day)
);

do $$
declare t text;
begin
  foreach t in array array['training_programs', 'training_items', 'trainings', 'training_marks', 'training_days'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon, authenticated', t);
  end loop;
end $$;

