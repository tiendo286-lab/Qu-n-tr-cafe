--  * Tạo sẵn (khi chưa có loại nào): Chi phí cố định (Mặt bằng, Lương, Điện nước) · Chi phí bán hàng (Nguyên liệu, Vật dụng)
--    · Chi phí khác (nhóm chi còn lại) · Thu khác (mọi nhóm thu). Chủ / Quản lý tổng sửa ở Cài đặt › Loại & nhóm thu chi.
--  * Trang Thu chi: tổng chi theo loại › nhóm, lọc theo loại / nhóm (app_fin_types).
