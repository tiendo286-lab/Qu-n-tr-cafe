create table if not exists public.fin_cat_types (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('chi', 'thu')),
  name text not null,
  sort_order integer not null default 0,
  active integer not null default 1,
  created_at text not null default public.vn_now_text()
);
create unique index if not exists fin_cat_types_name on public.fin_cat_types (kind, lower(name));
alter table public.fin_cat_types enable row level security;
revoke all on public.fin_cat_types from anon, authenticated;
alter table public.fin_categories add column if not exists type_id bigint references public.fin_cat_types(id) on delete set null;

do $$
declare t_fix bigint; t_sale bigint; t_other bigint; t_thu bigint;
begin
  if exists (select 1 from public.fin_cat_types) then return; end if;
  insert into public.fin_cat_types(kind, name, sort_order) values ('chi', 'Chi phí cố định', 1) returning id into t_fix;
  insert into public.fin_cat_types(kind, name, sort_order) values ('chi', 'Chi phí bán hàng', 2) returning id into t_sale;
  insert into public.fin_cat_types(kind, name, sort_order) values ('chi', 'Chi phí khác', 3) returning id into t_other;
  insert into public.fin_cat_types(kind, name, sort_order) values ('thu', 'Thu khác', 1) returning id into t_thu;
  update public.fin_categories set type_id = case
      when lower(name) like any (array['mặt bằng%', 'lương%', 'điện nước%']) then t_fix
      when lower(name) like any (array['nguyên liệu%', 'vật dụng%']) then t_sale
      else t_other end
   where kind = 'chi' and type_id is null;
  update public.fin_categories set type_id = t_thu where kind = 'thu' and type_id is null;
end $$;

-- Danh sách loại + nhóm (trang Thu chi, Cài đặt)
create or replace function public.app_fin_types() returns jsonb
language plpgsql stable security definer set search_path = public as $$
begin
  perform public.app__need(null);
  if not (public.app_can('doi_soat') or public.app_can('chot_thang') or public.app_can('ke_toan')) then raise exception 'Bạn không có quyền thực hiện thao tác này.'; end if;
  return jsonb_build_object(
    'types', coalesce((select jsonb_agg(jsonb_build_object('id', t.id, 'kind', t.kind, 'name', t.name, 'sort_order', t.sort_order, 'active', t.active = 1) order by t.kind, t.sort_order, t.name) from public.fin_cat_types t), '[]'),
    'cats', coalesce((select jsonb_agg(jsonb_build_object('id', c.id, 'kind', c.kind, 'name', c.name, 'type_id', c.type_id, 'sort_order', c.sort_order, 'active', c.active = 1) order by c.kind, c.sort_order, c.name) from public.fin_categories c), '[]'),
    'can_edit', public.app__fin_admin());
end $$;

create or replace function public.app_fin_type_save(p_id bigint, p_kind text, p_name text, p_sort integer, p_active boolean) returns bigint
language plpgsql security definer set search_path = public as $$
declare nid bigint;
begin
  if not public.app__fin_admin() then raise exception 'Chỉ Chủ và Quản lý tổng sửa được loại thu chi.'; end if;
  if trim(coalesce(p_name, '')) = '' then raise exception 'Nhập tên loại.'; end if;
  if p_id is null then
    if coalesce(p_kind, '') not in ('chi', 'thu') then raise exception 'Chọn loại chi hay loại thu.'; end if;
    insert into public.fin_cat_types(kind, name, sort_order) values (p_kind, trim(p_name), coalesce(p_sort, 50)) returning id into nid;
  else
    update public.fin_cat_types set name = trim(p_name), sort_order = coalesce(p_sort, sort_order), active = case when coalesce(p_active, true) then 1 else 0 end
     where id = p_id returning id into nid;
    if nid is null then raise exception 'Không tìm thấy loại.'; end if;
  end if;
  perform public.app_log('loai_thu_chi', 'type=' || nid || ' ' || trim(p_name));
  return nid;
exception when unique_violation then raise exception 'Đã có loại tên này.';
end $$;

create or replace function public.app_fin_category_type_set(p_cat bigint, p_type bigint) returns void
language plpgsql security definer set search_path = public as $$
declare c public.fin_categories;
begin
  if not public.app__fin_admin() then raise exception 'Chỉ Chủ và Quản lý tổng sửa được loại thu chi.'; end if;
  select * into c from public.fin_categories where id = p_cat;
  if c.id is null then raise exception 'Không tìm thấy nhóm.'; end if;
  if p_type is not null and not exists (select 1 from public.fin_cat_types t where t.id = p_type and t.kind = c.kind) then raise exception 'Loại không đúng (chi / thu).'; end if;
  update public.fin_categories set type_id = p_type where id = p_cat;
  perform public.app_log('nhom_thu_chi_loai', 'cat=' || p_cat || ' type=' || coalesce(p_type::text, '-'));
end $$;

