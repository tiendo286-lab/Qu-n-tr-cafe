-- ---------------------------------------------------------------- Tài liệu
create or replace function public.app_tl_list(p_kind text) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare a public.accounts; editor boolean;
begin
  a := public.app__need(null);
  editor := public.app_can('soan_tai_lieu');
  return coalesce((select jsonb_agg(jsonb_build_object(
      'id', d.id, 'title', case when editor then d.title else d.published_title end, 'published_title', d.published_title,
      'sort_order', d.sort_order, 'published_html', d.published_html, 'published_version', d.published_version,
      'published_at', d.published_at, 'published_by', public.app__acc_name(d.published_by),
      'updated_at', d.updated_at, 'updated_by', public.app__acc_name(d.updated_by),
      'has_draft', editor and d.draft_html is distinct from coalesce(d.published_html, '') or (editor and d.title is distinct from d.published_title),
      'read_version', (select r.version from public.doc_reads r where r.doc_id = d.id and r.employee_id = a.employee_id),
      'read_at', (select r.read_at from public.doc_reads r where r.doc_id = d.id and r.employee_id = a.employee_id))
    order by d.sort_order, d.id)
    from public.docs d where d.kind = p_kind and (editor or d.published_version > 0)), '[]');
end $$;

create or replace function public.app_tl_get(p_id bigint) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare d public.docs;
begin
  perform public.app__need('soan_tai_lieu');
  select * into d from public.docs where id = p_id;
  if d.id is null then raise exception 'Không tìm thấy tài liệu.'; end if;
  return to_jsonb(d) || jsonb_build_object('updated_by_name', public.app__acc_name(d.updated_by), 'published_by_name', public.app__acc_name(d.published_by));
end $$;

-- Lưu nháp (tạo mới khi p_id null)
create or replace function public.app_tl_save(p_id bigint, p_kind text, p_title text, p_html text) returns bigint
language plpgsql security definer set search_path = public as $$
declare a public.accounts; nid bigint;
begin
  a := public.app__need('soan_tai_lieu');
  if trim(coalesce(p_title, '')) = '' then raise exception 'Nhập tiêu đề tài liệu.'; end if;
  if length(coalesce(p_html, '')) > 2000000 then raise exception 'Tài liệu quá dài.'; end if;
  if p_id is null then
    if p_kind not in ('noi_quy', 'quy_trinh') then raise exception 'Loại tài liệu không hợp lệ.'; end if;
    insert into public.docs(kind, title, draft_html, sort_order, created_by, updated_by)
    values (p_kind, trim(p_title), coalesce(p_html, ''), coalesce((select max(sort_order) + 1 from public.docs where kind = p_kind), 0), a.id, a.id)
    returning id into nid;
    return nid;
  end if;
  update public.docs set title = trim(p_title), draft_html = coalesce(p_html, ''), updated_by = a.id, updated_at = public.vn_now_text() where id = p_id;
  if not found then raise exception 'Không tìm thấy tài liệu.'; end if;
  return p_id;
end $$;

-- Đăng bản nháp cho nhân viên xem (mỗi lần đăng tăng phiên bản → mọi người phải đọc lại)
create or replace function public.app_tl_publish(p_id bigint) returns integer
language plpgsql security definer set search_path = public as $$
declare a public.accounts; d public.docs; x bigint;
begin
  a := public.app__need('soan_tai_lieu');
  select * into d from public.docs where id = p_id for update;
  if d.id is null then raise exception 'Không tìm thấy tài liệu.'; end if;
  if trim(regexp_replace(d.draft_html, '<[^>]*>', '', 'g')) = '' and d.draft_html !~* '<img' then raise exception 'Tài liệu đang trống.'; end if;
  update public.docs set published_html = draft_html, published_title = title, published_version = published_version + 1,
         published_at = public.vn_now_text(), published_by = a.id where id = p_id;
  perform public.app_log('dang_tai_lieu', 'doc=' || p_id || ' v' || (d.published_version + 1));
  for x in select ac.id from public.accounts ac left join public.employees e on e.id = ac.employee_id
            where ac.locked = 0 and (ac.employee_id is null or e.status = 'Đang làm') and ac.id <> a.id loop
    perform public.app__notify(x, case when d.kind = 'noi_quy' then 'Nội quy' else 'Quy trình' end
      || case when d.published_version = 0 then ' mới: ' else ' cập nhật: ' end || d.title,
      case when d.kind = 'noi_quy' then 'Hãy đọc và bấm “Tôi đã đọc”.' else 'Mở để xem nội dung.' end,
      case when d.kind = 'noi_quy' then '/noi-quy' else '/quy-trinh' end || '?id=' || p_id);
  end loop;
  return d.published_version + 1;
end $$;

create or replace function public.app_tl_unpublish(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
begin
  perform public.app__need('soan_tai_lieu');
  update public.docs set published_html = null, published_title = null, published_version = 0, published_at = null, published_by = null where id = p_id;
  delete from public.doc_reads where doc_id = p_id;
end $$;

create or replace function public.app_tl_delete(p_id bigint) returns setof text
language plpgsql security definer set search_path = public as $$
declare d public.docs;
begin
  perform public.app__need('soan_tai_lieu');
  select * into d from public.docs where id = p_id;
  if d.id is null then return; end if;
  delete from public.docs where id = p_id;
  perform public.app_log('xoa_tai_lieu', d.title);
  -- trả về đường dẫn ảnh trong tài liệu để trang web xóa khỏi kho
  return query select distinct m[1] from regexp_matches(coalesce(d.draft_html, '') || coalesce(d.published_html, ''), 'data-path="([^"]+)"', 'g') m;
end $$;

create or replace function public.app_tl_move(p_id bigint, p_dir integer) returns void
language plpgsql security definer set search_path = public as $$
declare d public.docs; ids bigint[]; i int; tmp bigint;
begin
  perform public.app__need('soan_tai_lieu');
  select * into d from public.docs where id = p_id;
  if d.id is null then return; end if;
  ids := array(select id from public.docs where kind = d.kind order by sort_order, id);
  i := array_position(ids, p_id);
  if (p_dir < 0 and i <= 1) or (p_dir > 0 and i >= array_length(ids, 1)) then return; end if;
  tmp := ids[i]; ids[i] := ids[i + sign(p_dir)::int]; ids[i + sign(p_dir)::int] := tmp;
  update public.docs x set sort_order = array_position(ids, x.id) where x.kind = d.kind;
end $$;

-- Nhân viên tự xác nhận đã đọc bản đang đăng
create or replace function public.app_tl_read(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts; d public.docs;
begin
  a := public.app__need(null);
  if a.employee_id is null then raise exception 'Tài khoản này không gắn với nhân viên.'; end if;
  select * into d from public.docs where id = p_id and published_version > 0;
  if d.id is null then raise exception 'Tài liệu chưa được đăng.'; end if;
  insert into public.doc_reads(doc_id, employee_id, version, read_at, confirmed_by)
  values (p_id, a.employee_id, d.published_version, public.vn_now_text(), a.id)
  on conflict (doc_id, employee_id) do update set version = excluded.version, read_at = excluded.read_at, confirmed_by = excluded.confirmed_by;
end $$;

-- ---------------------------------------------------------------- Cột Nội quy / Cam kết (tab Nhân viên)
create or replace function public.app_tl_staff_status() returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare n_docs int;
begin
  perform public.app__need('quan_ly_nhan_vien');
  select count(*) into n_docs from public.docs where kind = 'noi_quy' and published_version > 0;
  return jsonb_build_object('noi_quy_docs', n_docs, 'rows', coalesce((select jsonb_agg(jsonb_build_object(
      'employee_id', e.id,
      'read', (select count(*) from public.docs d join public.doc_reads r on r.doc_id = d.id and r.employee_id = e.id and r.version = d.published_version
                where d.kind = 'noi_quy' and d.published_version > 0),
      'read_at', (select max(r.read_at) from public.docs d join public.doc_reads r on r.doc_id = d.id and r.employee_id = e.id
                   where d.kind = 'noi_quy' and d.published_version > 0),
      'commit', coalesce(c.status, 'chua_ky'), 'commit_note', c.note, 'commit_at', c.updated_at, 'commit_by', public.app__acc_name(c.updated_by)))
    from public.employees e left join public.employee_commitments c on c.employee_id = e.id), '[]'));
end $$;

-- Quản lý đánh dấu thay: đã đọc (mọi nội quy đang đăng) / bỏ đánh dấu
create or replace function public.app_tl_mark_read(p_employee bigint, p_read boolean) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts;
begin
  a := public.app__need('quan_ly_nhan_vien');
  if p_read then
    insert into public.doc_reads(doc_id, employee_id, version, read_at, confirmed_by)
    select d.id, p_employee, d.published_version, public.vn_now_text(), a.id from public.docs d where d.kind = 'noi_quy' and d.published_version > 0
    on conflict (doc_id, employee_id) do update set version = excluded.version, read_at = excluded.read_at, confirmed_by = excluded.confirmed_by;
  else
    delete from public.doc_reads r using public.docs d where d.id = r.doc_id and d.kind = 'noi_quy' and r.employee_id = p_employee;
  end if;
  perform public.app_log('danh_dau_doc_noi_quy', 'employee=' || p_employee || '=' || p_read);
end $$;

create or replace function public.app_tl_set_commit(p_employee bigint, p_status text, p_note text) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts;
begin
  a := public.app__need('quan_ly_nhan_vien');
  if p_status not in ('chua_ky', 'da_ky_chua_nop', 'da_ky_nop') then raise exception 'Trạng thái cam kết không hợp lệ.'; end if;
  insert into public.employee_commitments(employee_id, status, note, updated_by, updated_at)
  values (p_employee, p_status, nullif(trim(coalesce(p_note, '')), ''), a.id, public.vn_now_text())
  on conflict (employee_id) do update set status = excluded.status, note = coalesce(excluded.note, public.employee_commitments.note),
         updated_by = excluded.updated_by, updated_at = excluded.updated_at;
  perform public.app_log('cam_ket', 'employee=' || p_employee || ':' || p_status);
end $$;

-- ---------------------------------------------------------------- Cấp quyền gọi hàm
do $$
declare f record;
begin
  for f in select p.oid::regprocedure as sig, p.proname from pg_proc p join pg_namespace n on n.oid = p.pronamespace
            where n.nspname = 'public' and (p.proname like 'app\_tl\_%' or p.proname = 'app__perm_keys') loop
    execute format('revoke execute on function %s from public, anon', f.sig);
    if f.proname like 'app\_\_%' then
      execute format('revoke execute on function %s from authenticated', f.sig);
    else
      execute format('grant execute on function %s to authenticated', f.sig);
    end if;
  end loop;
end $$;
