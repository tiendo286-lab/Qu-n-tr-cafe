--  * Đã đọc nội quy: nhân viên tự bấm "Tôi đã đọc" trên bản đang đăng; quản lý cũng đánh dấu thay được.
--    Đăng bản mới (sửa nội dung) → mọi người về "Chưa đọc" với tài liệu đó.
--  * Cam kết: quản lý chọn trạng thái Chưa ký / Đã ký, chưa nộp / Đã ký và nộp, kèm ghi chú. Chưa có tải minh chứng.
