create table if not exists public.docs (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('noi_quy', 'quy_trinh')),
  title text not null,
  sort_order integer not null default 0,
  draft_html text not null default '',
  published_html text,
  published_title text,
  published_version integer not null default 0,
  published_at text,
  published_by bigint,
  created_by bigint,
  created_at text not null default public.vn_now_text(),
  updated_by bigint,
  updated_at text not null default public.vn_now_text()
);

create table if not exists public.doc_reads (
  doc_id bigint not null references public.docs(id) on delete cascade,
  employee_id bigint not null references public.employees(id) on delete cascade,
  version integer not null,
  read_at text not null,
  confirmed_by bigint,              -- tài khoản bấm xác nhận (chính nhân viên hoặc quản lý)
  primary key (doc_id, employee_id)
);

create table if not exists public.employee_commitments (
  employee_id bigint primary key references public.employees(id) on delete cascade,
  status text not null default 'chua_ky' check (status in ('chua_ky', 'da_ky_chua_nop', 'da_ky_nop')),
  note text,
  updated_by bigint,
  updated_at text not null default public.vn_now_text()
);

do $$
declare t text;
begin
  foreach t in array array['docs', 'doc_reads', 'employee_commitments'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon, authenticated', t);
  end loop;
end $$;

