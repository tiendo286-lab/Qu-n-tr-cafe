create table if not exists public.bank_accounts (
  id bigint generated by default as identity primary key,
  branch_id bigint not null references public.branches(id),
  bank text not null default 'BIDV',
  account_no text not null,
  holder text,
  label text,
  active int not null default 1,
  sort_order int not null default 0,
  created_by bigint,
  created_at text not null default public.vn_now_text(),
  updated_at text
);
create unique index if not exists bank_accounts_uq on public.bank_accounts(branch_id, bank, account_no);

create table if not exists public.bank_account_balances (
  report_id bigint not null references public.shift_reports(id) on delete cascade,
  account_id bigint not null references public.bank_accounts(id),
  opening bigint, closing bigint, transfers_out bigint not null default 0, note text,
  updated_by bigint, updated_at text not null default public.vn_now_text(),
  primary key (report_id, account_id)
);
do $$
declare t text;
begin
  foreach t in array array['bank_accounts', 'bank_account_balances'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon, authenticated', t);
  end loop;
end $$;

