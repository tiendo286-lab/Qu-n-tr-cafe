create or replace function public.app_kt_accounts() returns jsonb
language plpgsql stable security definer set search_path = public as $$
begin
  if not (public.app_can('ke_toan') or public.app_can('doi_soat')) then raise exception 'Bạn không có quyền.'; end if;
  return coalesce((select jsonb_agg(jsonb_build_object('id', k.id, 'branch_id', k.branch_id, 'branch_code', coalesce(b.display_code, b.code),
            'bank', k.bank, 'account_no', k.account_no, 'holder', k.holder, 'label', k.label, 'active', k.active = 1,
            'used', exists (select 1 from public.bank_account_balances x where x.account_id = k.id))
            order by b.sort_order, k.active desc, k.sort_order, k.id)
          from public.bank_accounts k join public.branches b on b.id = k.branch_id), '[]');
end $$;

create or replace function public.app_kt_account_save(p_id bigint, p_branch bigint, p_bank text, p_no text, p_holder text, p_label text, p_active boolean)
returns bigint language plpgsql security definer set search_path = public as $$
declare a public.accounts; old public.bank_accounts; no text := regexp_replace(coalesce(p_no, ''), '[\s.\-]', '', 'g');
        bk text := upper(trim(coalesce(p_bank, ''))); nid bigint;
begin
  a := public.app__need('ke_toan');
  if p_branch is null or not exists (select 1 from public.branches where id = p_branch) then raise exception 'Chọn chi nhánh.'; end if;
  if bk = '' then raise exception 'Nhập tên ngân hàng (vd BIDV).'; end if;
  if no !~ '^[0-9]{4,20}$' then raise exception 'Số tài khoản chỉ gồm chữ số (4–20 số).'; end if;
  if exists (select 1 from public.bank_accounts where branch_id = p_branch and bank = bk and account_no = no and id <> coalesce(p_id, 0)) then
    raise exception 'Chi nhánh này đã có tài khoản % %.', bk, no;
  end if;
  if p_id is null then
    insert into public.bank_accounts(branch_id, bank, account_no, holder, label, active, sort_order, created_by)
    values (p_branch, bk, no, nullif(trim(coalesce(p_holder, '')), ''), nullif(trim(coalesce(p_label, '')), ''), case when coalesce(p_active, true) then 1 else 0 end,
            coalesce((select max(sort_order) + 1 from public.bank_accounts where branch_id = p_branch), 0), a.id)
    returning id into nid;
    perform public.app_log('ke_toan_them_tai_khoan', 'bank_account=' || nid || ' ' || bk || ' ' || no);
    return nid;
  end if;
  select * into old from public.bank_accounts where id = p_id for update;
  if old.id is null then raise exception 'Không tìm thấy tài khoản.'; end if;
  if (old.branch_id <> p_branch or old.account_no <> no or old.bank <> bk)
     and exists (select 1 from public.bank_account_balances x where x.account_id = p_id) then
    raise exception 'Tài khoản đã có số dư theo ca nên không đổi được chi nhánh / ngân hàng / số tài khoản. Hãy ngừng dùng tài khoản này và thêm tài khoản mới.';
  end if;
  update public.bank_accounts set branch_id = p_branch, bank = bk, account_no = no, holder = nullif(trim(coalesce(p_holder, '')), ''),
         label = nullif(trim(coalesce(p_label, '')), ''), active = case when coalesce(p_active, true) then 1 else 0 end, updated_at = public.vn_now_text()
   where id = p_id;
  perform public.app_log('ke_toan_sua_tai_khoan', 'bank_account=' || p_id || ' ' || bk || ' ' || no || case when coalesce(p_active, true) then '' else ' (ngừng dùng)' end);
  return p_id;
end $$;

create or replace function public.app_kt_account_delete(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
declare k public.bank_accounts;
begin
  perform public.app__need('ke_toan');
  select * into k from public.bank_accounts where id = p_id;
  if k.id is null then raise exception 'Không tìm thấy tài khoản.'; end if;
  if exists (select 1 from public.bank_account_balances x where x.account_id = p_id) then
    raise exception 'Tài khoản đã có số dư theo ca nên không xóa được (giữ lịch sử). Hãy chọn "Ngừng dùng".';
  end if;
  delete from public.bank_accounts where id = p_id;
  perform public.app_log('ke_toan_xoa_tai_khoan', 'bank_account=' || p_id || ' ' || k.bank || ' ' || k.account_no);
end $$;

-- ---------------------------------------------------------------- Số dư theo tài khoản
create or replace function public.app__kt_prev_closing_acc(r public.shift_reports, p_acc bigint) returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object('closing', b.closing, 'work_date', p.work_date, 'shift', p.shift)
    from public.shift_reports p join public.bank_account_balances b on b.report_id = p.id and b.account_id = p_acc
   where p.branch_id = r.branch_id and b.closing is not null
     and (p.work_date < r.work_date or (p.work_date = r.work_date and array_position(public.app__shifts(), p.shift) < array_position(public.app__shifts(), r.shift)))
   order by p.work_date desc, array_position(public.app__shifts(), p.shift) desc limit 1
$$;

-- Thay bản 17: trả danh sách tài khoản của chi nhánh (đang dùng + đã có số dư ở phiếu này) và tổng tiền nhận
create or replace function public.app__kt_bank_json(r public.shift_reports) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare d jsonb := public.app__ca_eff(r.id); accs jsonb; tot bigint; n_in int; n_all int; l_by text; l_at text;
begin
  select coalesce(jsonb_agg(jsonb_build_object('account_id', k.id, 'bank', k.bank, 'account_no', k.account_no, 'holder', k.holder, 'label', k.label,
            'active', k.active = 1, 'opening', x.opening, 'closing', x.closing, 'transfers_out', coalesce(x.transfers_out, 0), 'note', x.note,
            'received', case when x.opening is not null and x.closing is not null then x.closing - x.opening + coalesce(x.transfers_out, 0) end,
            'updated_by', public.app__acc_name(x.updated_by), 'updated_at', x.updated_at,
            'prev', public.app__kt_prev_closing_acc(r, k.id)) order by k.sort_order, k.id), '[]'),
         sum(case when x.opening is not null and x.closing is not null then x.closing - x.opening + coalesce(x.transfers_out, 0) end),
         count(*) filter (where x.opening is not null and x.closing is not null), count(*)
    into accs, tot, n_in, n_all
    from public.bank_accounts k
    left join public.bank_account_balances x on x.report_id = r.id and x.account_id = k.id
   where k.branch_id = r.branch_id and (k.active = 1 or x.report_id is not null);
  select public.app__acc_name(x.updated_by), x.updated_at into l_by, l_at
    from public.bank_account_balances x where x.report_id = r.id order by x.updated_at desc limit 1;
  return jsonb_build_object('report_id', r.id, 'status', r.status, 'recon_status', r.recon_status,
    'rev_start', d ->> 'rev_start', 'rev_end', d ->> 'rev_end',
    'pos_transfer', (d ->> 'pos_transfer')::bigint, 'reported_transfer', (d ->> 'reported_transfer')::bigint,
    'accounts', accs, 'received', tot, 'entered', n_in, 'account_count', n_all,
    'updated_by', l_by, 'updated_at', l_at,
    'locked', r.recon_status = 'hoan_thanh');
end $$;

create or replace function public.app_kt_bank_save_accounts(p_report bigint, p_rows jsonb) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts; r public.shift_reports; e jsonb; acc public.bank_accounts; old public.bank_account_balances;
        v_open bigint; v_close bigint; v_out bigint; v_note text; k text; o jsonb; n jsonb; tag text;
begin
  a := public.app__need('ke_toan');
  select * into r from public.shift_reports where id = p_report for update;
  if r.id is null then raise exception 'Không tìm thấy phiếu ca.'; end if;
  if r.recon_status = 'hoan_thanh' then raise exception 'Quản lý đã HOÀN THÀNH ĐỐI SOÁT ca này nên số liệu kế toán đã khóa. Cần quản lý mở lại đối soát.'; end if;
  if jsonb_typeof(coalesce(p_rows, '[]')) <> 'array' then raise exception 'Dữ liệu không hợp lệ.'; end if;
  for e in select * from jsonb_array_elements(coalesce(p_rows, '[]')) loop
    select * into acc from public.bank_accounts where id = (e ->> 'account_id')::bigint;
    if acc.id is null or acc.branch_id <> r.branch_id then raise exception 'Tài khoản không thuộc chi nhánh của phiếu ca này.'; end if;
    v_open := (e ->> 'opening')::bigint; v_close := (e ->> 'closing')::bigint; v_out := coalesce((e ->> 'transfers_out')::bigint, 0);
    v_note := nullif(trim(coalesce(e ->> 'note', '')), '');
    if v_out < 0 then raise exception 'Tiền chuyển ra không được âm (tài khoản %).', acc.account_no; end if;
    select * into old from public.bank_account_balances where report_id = p_report and account_id = acc.id;
    if old.report_id is null and v_open is null and v_close is null and v_out = 0 and v_note is null then continue; end if;
    if old.report_id is null and acc.active <> 1 then raise exception 'Tài khoản % đã ngừng dùng.', acc.account_no; end if;
    insert into public.bank_account_balances(report_id, account_id, opening, closing, transfers_out, note, updated_by, updated_at)
    values (p_report, acc.id, v_open, v_close, v_out, v_note, a.id, public.vn_now_text())
    on conflict (report_id, account_id) do update set opening = excluded.opening, closing = excluded.closing, transfers_out = excluded.transfers_out,
           note = excluded.note, updated_by = excluded.updated_by, updated_at = excluded.updated_at
     where (bank_account_balances.opening, bank_account_balances.closing, bank_account_balances.transfers_out, bank_account_balances.note)
           is distinct from (excluded.opening, excluded.closing, excluded.transfers_out, excluded.note);
    tag := 'TK ' || acc.bank || ' ' || acc.account_no;
    foreach k in array array['opening', 'closing', 'transfers_out', 'note'] loop
      o := case k when 'opening' then to_jsonb(old.opening) when 'closing' then to_jsonb(old.closing) when 'transfers_out' then to_jsonb(old.transfers_out) else to_jsonb(old.note) end;
      n := case k when 'opening' then to_jsonb(v_open) when 'closing' then to_jsonb(v_close) when 'transfers_out' then to_jsonb(v_out) else to_jsonb(v_note) end;
      if o is distinct from n and not (old.report_id is null and (n = 'null'::jsonb or (k = 'transfers_out' and n = '0'::jsonb))) then
        insert into public.shift_recon_log(report_id, action, field, before, after, reason, by_account) values (p_report, 'ke_toan', 'bank_' || k, o, n, tag, a.id);
      end if;
    end loop;
  end loop;
  perform public.app_log('ke_toan_so_du', 'report=' || p_report);
end $$;

