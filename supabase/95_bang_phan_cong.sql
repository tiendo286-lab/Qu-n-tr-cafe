    perform public.app__gv_ev(p_task, a.id, 'gia_han', 'Không đồng ý gia hạn — giữ hạn cũ', null);
  end if;
  perform public.app__notify(k.assignee_id, case when p_ok then 'Được gia hạn việc' else 'Không được gia hạn' end, k.content, '/viec');
end $$;

