create or replace function public.app_gv_create(p jsonb) returns bigint
language plpgsql security definer set search_path = public as $$
declare a public.accounts := public.app__need(null); d text[]; id bigint; who bigint := (p->>'assignee_id')::bigint; rv bigint := (p->>'reviewer_id')::bigint;
begin
  if not public.app__gv_can_give() then raise exception 'Bạn không có quyền giao việc.'; end if;
  if trim(coalesce(p->>'content', '')) = '' then raise exception 'Ghi nội dung việc.'; end if;
  if who is null then raise exception 'Chọn người làm.'; end if;
  if rv is null then raise exception 'Chọn người kiểm tra.'; end if;
  if rv = who then raise exception 'Người kiểm tra phải khác người làm.'; end if;
  d := public.app__gv_due(p->>'due');
  insert into public.tasks(kind, content, branch_id, assignee_id, reviewer_id, giver_id, created_by, status, assigned_at, started_at, due_date, due_time, priority)
  values ('viec', trim(p->>'content'), nullif(p->>'branch_id', '')::bigint, who, rv, a.id, a.id,
          case when who = a.id then 'dang_xu_ly' else 'da_giao' end, public.vn_now_text(), case when who = a.id then public.vn_now_text() end,
          d[1], d[2], coalesce(nullif(p->>'priority', ''), 'binh_thuong'))
  returning tasks.id into id;
  perform public.app__gv_ev(id, a.id, 'giao', 'Giao cho ' || public.app__acc_name(who) || ' · kiểm tra: ' || public.app__acc_name(rv) || ' · hạn ' || to_char((d[1] || ' ' || d[2])::timestamp, 'DD/MM HH24:MI'), null);
  if who <> a.id then perform public.app__notify(who, case when p->>'priority' = 'gap' then 'Việc GẤP được giao' else 'Việc được giao cho bạn' end, trim(p->>'content'), '/viec'); end if;
  return id;
end $$;

create or replace function public.app_gv_classify(p_task bigint, p jsonb) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts := public.app__need(null); k public.tasks; d text[]; who bigint; rv bigint; m text := p->>'mode';
begin
  select * into k from public.tasks where id = p_task for update;
  if k.id is null or k.status <> 'chua_phan_cong' or k.cancelled_at is not null then raise exception 'Việc đã được phân loại.'; end if;
  if not (a.id = any(public.app__pc_who(24, 'branch', k.branch_id)) or a.system_role in ('chu', 'ql_tong')) then raise exception 'Việc này không giao cho bạn phân loại.'; end if;
  if m = 'bo' then
    if trim(coalesce(p->>'reason', '')) = '' then raise exception 'Ghi lý do không cần xử lý.'; end if;
    update public.tasks set cancelled_at = public.vn_now_text(), review_note = trim(p->>'reason'), giver_id = a.id where id = p_task;
    update public.handover_items set done_at = public.vn_now_text(), done_by = a.id where id = k.handover_item_id and done_at is null;
    perform public.app__gv_ev(p_task, a.id, 'bo', 'Không cần xử lý: ' || trim(p->>'reason'), null);
    return;
  end if;
  who := case when m = 'tu' then a.id else (p->>'assignee_id')::bigint end; rv := (p->>'reviewer_id')::bigint;
  if who is null then raise exception 'Chọn người làm.'; end if;
  if rv is null then raise exception 'Chọn người kiểm tra.'; end if;
  if rv = who then raise exception 'Người kiểm tra phải khác người làm.'; end if;
  d := public.app__gv_due(p->>'due');
  update public.tasks set assignee_id = who, reviewer_id = rv, giver_id = a.id, assigned_at = public.vn_now_text(),
         status = case when who = a.id then 'dang_xu_ly' else 'da_giao' end, started_at = case when who = a.id then public.vn_now_text() end,
         due_date = d[1], due_time = d[2], priority = coalesce(nullif(p->>'priority', ''), 'binh_thuong')
   where id = p_task;
  perform public.app__gv_ev(p_task, a.id, 'giao', case when m = 'tu' then 'Tự làm' else 'Giao cho ' || public.app__acc_name(who) end
          || ' · kiểm tra: ' || public.app__acc_name(rv) || ' · hạn ' || to_char((d[1] || ' ' || d[2])::timestamp, 'DD/MM HH24:MI'), null);
  if who <> a.id then perform public.app__notify(who, 'Việc được giao cho bạn', k.content, '/viec'); end if;
end $$;

