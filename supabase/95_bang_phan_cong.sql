create table if not exists public.pc_jobs (
  job int primary key,
  enabled boolean not null default true,
  fine bigint not null default 50000,
  same_as_1 boolean not null default false,
  steps jsonb not null,
  updated_by bigint, updated_at text not null default public.vn_now_text()
);
create table if not exists public.pc_assign (
  job int not null, branch_id bigint not null references public.branches(id) on delete cascade,
  accounts bigint[] not null default '{}', updated_by bigint, updated_at text not null default public.vn_now_text(),
  primary key (job, branch_id)
);
create table if not exists public.pc_tasks (
  id bigint generated by default as identity primary key,
  job int not null, key text, branch_id bigint references public.branches(id),
  title text not null, link text,
  created_at text not null default public.vn_now_text(), done_at text, done_by bigint, done_note text
);
create unique index if not exists pc_tasks_key on public.pc_tasks(key) where key is not null;
create index if not exists pc_tasks_open on public.pc_tasks(job, branch_id) where done_at is null;
create table if not exists public.pc_steps (
  id bigint generated by default as identity primary key,
  task_id bigint not null references public.pc_tasks(id) on delete cascade,
  step int not null, name text not null, accounts bigint[] not null default '{}',
  start_at text not null, due_at text, done_at text, done_by bigint
);
create index if not exists pc_steps_task on public.pc_steps(task_id);
create table if not exists public.pc_items (
  id bigint generated by default as identity primary key,
  task_id bigint not null references public.pc_tasks(id) on delete cascade,
  key text not null, title text not null, link text, start_at text not null, due_at text, done_at text
);
create unique index if not exists pc_items_open_key on public.pc_items(key) where done_at is null;
create index if not exists pc_items_task on public.pc_items(task_id);
create table if not exists public.pc_penalties (
  id bigint generated by default as identity primary key,
  key text not null unique, src text not null, ref_id bigint, job int not null, branch_id bigint,
  account_id bigint not null references public.accounts(id), title text not null, step_name text,
  due_at text not null, detected_at text not null default public.vn_now_text(),
  status text not null default 'cho' check (status in ('cho', 'phat', 'bo')),
  amount bigint, reason text, decided_by bigint, decided_at text
);
create index if not exists pc_penalties_acc on public.pc_penalties(account_id, status);
