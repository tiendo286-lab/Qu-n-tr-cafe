create or replace function public.app_pc_kt_set(p_account bigint, p_apply boolean) returns int
language plpgsql security definer set search_path = public as $$
declare a public.accounts := public.app__need('phan_cong'); old bigint; n int := 0;
begin
  if a.system_role <> 'chu' then raise exception 'Chỉ tài khoản Chủ đổi được người làm Kế toán.'; end if;
  old := (select value::bigint from public.settings where key = 'pc_kt' and value ~ '^\d+$');
  if p_account is not null and not exists(select 1 from public.accounts where id = p_account and coalesce(locked, 0) = 0) then raise exception 'Tài khoản không hợp lệ.'; end if;
  if p_account is null then delete from public.settings where key = 'pc_kt';
  else insert into public.settings(key, value) values ('pc_kt', p_account::text) on conflict (key) do update set value = excluded.value;
       insert into public.account_perms(account_id, perm, granted_by) values (p_account, 'ke_toan', a.id) on conflict do nothing; end if;
  if old is not null and old is distinct from p_account then delete from public.account_perms where account_id = old and perm = 'ke_toan'; end if;
  if p_apply then
    update public.pc_steps s set accounts = public.app__pc_who(pt.job, 'kt', null)
      from public.pc_tasks pt join public.pc_jobs pj on pj.job = pt.job
     where pt.id = s.task_id and s.done_at is null and pt.done_at is null and (pj.steps->s.step->>'who') = 'kt';
    get diagnostics n = row_count;
  end if;
  perform public.app_log('pc_kt_set', coalesce(p_account::text, 'null'));
  return n;
end $$;

