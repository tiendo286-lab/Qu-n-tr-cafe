create or replace function public.app_pc_penalty_set(p_id bigint, p_status text, p_amount bigint, p_reason text) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts := public.app__need('phan_cong'); p public.pc_penalties;
begin
  if a.system_role <> 'chu' then raise exception 'Chỉ tài khoản Chủ xác nhận phạt.'; end if;
  if p_status not in ('cho', 'phat', 'bo') then raise exception 'Trạng thái không hợp lệ.'; end if;
  if p_status = 'phat' and coalesce(p_amount, 0) <= 0 then raise exception 'Nhập số tiền phạt.'; end if;
  if p_status = 'bo' and trim(coalesce(p_reason, '')) = '' then raise exception 'Ghi lý do bỏ qua.'; end if;
  update public.pc_penalties set status = p_status,
         amount = case when p_status = 'phat' then p_amount end,
         reason = case p_status when 'phat' then 'Bị phạt do không hoàn thành công việc đúng hạn' when 'bo' then trim(p_reason) end,
         decided_by = case when p_status <> 'cho' then a.id end, decided_at = case when p_status <> 'cho' then public.vn_now_text() end
   where id = p_id returning * into p;
  if p.id is null then raise exception 'Không tìm thấy.'; end if;
  if p_status = 'phat' then
    perform public.app__notify(p.account_id, 'Bị phạt ' || public.app__vnd(p_amount),
      'Bị phạt do không hoàn thành công việc đúng hạn: ' || p.title || coalesce(' (' || p.step_name || ')', ''), '/viec');
  end if;
  perform public.app_log('pc_penalty_set', 'id=' || p_id || ' ' || p_status);
end $$;

