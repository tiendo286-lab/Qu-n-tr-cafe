create or replace function public.app_pc_job_save(p_job int, p jsonb) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts := public.app__need('phan_cong'); j public.pc_jobs; st jsonb := p->'steps'; e jsonb; i int := 0; au int;
begin
  if a.system_role <> 'chu' then raise exception 'Chỉ tài khoản Chủ sửa được Bảng phân công.'; end if;
  select * into j from public.pc_jobs where job = p_job for update;
  if j.job is null then raise exception 'Không tìm thấy việc.'; end if;
  au := public.app__pc_auto(p_job);
  if p_job = 24 then   -- các bước cố định, chỉ đổi hạn phân loại / kiểm tra
    st := jsonb_set(jsonb_set(j.steps, '{0,d}', to_jsonb(greatest(coalesce((p->>'d0')::numeric, 1), 0.25))), '{2,d}', to_jsonb(greatest(coalesce((p->>'d2')::numeric, 1), 0.25)));
  else
    if jsonb_typeof(st) <> 'array' or jsonb_array_length(st) < au or jsonb_array_length(st) > 6 then raise exception 'Việc này cần từ % đến 6 bước.', au; end if;
    for e in select * from jsonb_array_elements(st) loop
      if trim(coalesce(e->>'n', '')) = '' then raise exception 'Bước % chưa có tên.', i + 1; end if;
      if coalesce(e->>'who', '') !~ '^(branch|branch\+ql_tong|kt|acc:\d+)$' then raise exception 'Bước % chưa chọn người làm.', i + 1; end if;
      if e->>'d' is not null and (e->>'d')::numeric <= 0 then raise exception 'Hạn bước % phải lớn hơn 0.', i + 1; end if;
      i := i + 1;
    end loop;
  end if;
  update public.pc_jobs set enabled = coalesce((p->>'enabled')::boolean, enabled), fine = greatest(coalesce((p->>'fine')::bigint, fine), 0), steps = st,
         updated_by = a.id, updated_at = public.vn_now_text() where job = p_job;
  perform public.app_log('pc_job_save', 'job=' || p_job);
end $$;

create or replace function public.app_pc_assign_save(p_job int, p_branch bigint, p_accounts bigint[], p_apply boolean) returns int
language plpgsql security definer set search_path = public as $$
declare a public.accounts := public.app__need('phan_cong'); j public.pc_jobs; n int := 0; t record;
begin
  if a.system_role <> 'chu' then raise exception 'Chỉ tài khoản Chủ sửa được Bảng phân công.'; end if;
  select * into j from public.pc_jobs where job = p_job for update;
  if j.job is null then raise exception 'Không tìm thấy việc.'; end if;
  if j.same_as_1 then   -- tách khỏi "như Đối soát ca": chép cột của việc 1 rồi sửa riêng
    insert into public.pc_assign(job, branch_id, accounts) select p_job, branch_id, accounts from public.pc_assign where job = 1
    on conflict (job, branch_id) do update set accounts = excluded.accounts;
    update public.pc_jobs set same_as_1 = false where job = p_job;
  end if;
  insert into public.pc_assign(job, branch_id, accounts, updated_by) values (p_job, p_branch, coalesce(p_accounts, '{}'), a.id)
  on conflict (job, branch_id) do update set accounts = excluded.accounts, updated_by = a.id, updated_at = public.vn_now_text();
  if p_apply then
    for t in select s.id, pt.job from public.pc_steps s join public.pc_tasks pt on pt.id = s.task_id join public.pc_jobs pj on pj.job = pt.job
              where s.done_at is null and pt.done_at is null and pt.branch_id = p_branch
                and (pt.job = p_job or (p_job = 1 and pj.same_as_1)) and (pj.steps->s.step->>'who') like 'branch%' loop
      update public.pc_steps set accounts = public.app__pc_who(t.job, (select steps->step->>'who' from public.pc_jobs where job = t.job), p_branch) where id = t.id;
      n := n + 1;
    end loop;
  end if;
  perform public.app_log('pc_assign_save', 'job=' || p_job || ' branch=' || p_branch);
  return n;
end $$;

