  if not (a.id = coalesce(k.giver_id, k.created_by) or a.system_role = 'chu') then raise exception 'Chỉ người giao việc duyệt gia hạn.'; end if;
  if p_ok then
    nd := public.app__pc_add(greatest(coalesce(k.due_date || ' ' || coalesce(k.due_time, '23:59') || ':00', public.vn_now_text()), public.vn_now_text()), k.ext_days);
    update public.tasks set due_date = left(nd, 10), due_time = substr(nd, 12, 5), ext_days = null, ext_reason = null, ext_at = null where id = p_task;
    perform public.app__gv_ev(p_task, a.id, 'gia_han', 'Đồng ý gia hạn → hạn mới ' || to_char(nd::timestamp, 'DD/MM HH24:MI'), null);
