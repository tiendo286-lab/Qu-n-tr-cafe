alter table public.employees add column if not exists pay_cash boolean not null default false;   -- trả lương tiền mặt, không dùng app
alter table public.shift_report_staff add column if not exists cash_paid bigint;                   -- lương tiền mặt đã trả trong ca

create table if not exists public.shift_covers (
  id bigint generated by default as identity primary key,
  report_id bigint not null references public.shift_reports(id) on delete cascade,
  absent_id bigint references public.employees(id) on delete set null,     -- người nghỉ (null: làm thêm vì thiếu lịch)
  reason text not null check (reason in ('tu_tim', 'nho_ql', 'ma_chay', 'thieu_lich')),
  helper_id bigint references public.employees(id) on delete set null,     -- người làm thay / làm thêm (nhân viên quán)
  helper_name text,                                                        -- người ngoài quán (chỉ ghi chú báo cáo lương)
  hours numeric(5, 2) not null default 0,                                  -- giờ người làm thay làm
  x2 boolean not null default false,
  deduct_hours numeric(5, 2) not null default 0,                           -- giờ người nghỉ bị trừ
  note text,
  complaint_absent text, complaint_absent_at text,
  complaint_helper text, complaint_helper_at text,
  resolved_by bigint, resolved_at text, resolve_note text,
  created_at text not null default public.vn_now_text()
);
create index if not exists idx_shift_covers_report on public.shift_covers (report_id);

create table if not exists public.shift_cover_reviews (
  report_id bigint primary key references public.shift_reports(id) on delete cascade,
  set_by bigint, set_at text,              -- quản lý tổng phân loại
  ok_by bigint, ok_at text, ok_note text   -- Chủ duyệt
);

