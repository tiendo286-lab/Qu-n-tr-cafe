create or replace function public.app__recon_snapshot(p_id bigint) returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'rev_start', r.rev_start, 'rev_end', r.rev_end, 'total_revenue', r.total_revenue, 'pos_cash', r.pos_cash,
    'pos_transfer', r.pos_transfer, 'reported_transfer', r.reported_transfer, 'cash_counted', r.cash_counted,
    'opening_cash', r.opening_cash, 'cups', r.cups, 'goods_status', r.goods_status, 'goods_note', r.goods_note,
    'moves', coalesce((select jsonb_agg(jsonb_build_object('kind', m.kind, 'amount', m.amount, 'note', m.note) order by m.sort_order, m.id)
                       from public.shift_report_moves m where m.report_id = r.id), '[]'),
    'staff', coalesce((select jsonb_agg(jsonb_build_object('employee_id', s.employee_id, 'source', s.source, 'role', s.role, 'worked', s.worked = 1,
                         'time_in', s.time_in, 'time_out', s.time_out, 'absent_reason', s.absent_reason, 'note', s.note, 'cash_paid', s.cash_paid) order by s.id)
                       from public.shift_report_staff s where s.report_id = r.id), '[]'),
    'goods', coalesce((select jsonb_agg(jsonb_build_object('item', g.item, 'qty', g.qty) order by g.id)
                       from public.shift_report_goods g where g.report_id = r.id), '[]'))
    from public.shift_reports r where r.id = p_id
$$;

create or replace function public.app_ca_recon(p_id bigint) returns jsonb
language plpgsql security definer set search_path = public as $$
declare a public.accounts; r public.shift_reports; d jsonb; staff_names jsonb;
begin
  a := public.app__need('doi_soat');
  select * into r from public.shift_reports where id = p_id;
  if r.id is null then raise exception 'Không tìm thấy phiếu.'; end if;
  if r.status <> 'hoan_thanh' then raise exception 'Nhân viên chưa hoàn thành phiếu này nên chưa có bản đối soát.'; end if;
  insert into public.shift_report_recon(report_id, data, updated_by) values (p_id, public.app__recon_snapshot(p_id), a.id)
  on conflict (report_id) do nothing;
  select data into d from public.shift_report_recon where report_id = p_id;
  select coalesce(jsonb_object_agg(e.id::text, jsonb_build_object('code', e.code, 'name', e.name, 'rank', e.rank, 'pay_cash', e.pay_cash)), '{}') into staff_names
    from public.employees e
   where e.id in (select (x ->> 'employee_id')::bigint from jsonb_array_elements(d -> 'staff') x
                  union select (x ->> 'employee_id')::bigint from jsonb_array_elements(public.app__recon_snapshot(p_id) -> 'staff') x);
  return jsonb_build_object(
    'data', d,
    'original', public.app__recon_snapshot(p_id),
    'employees', staff_names,
    'editable', r.recon_status <> 'hoan_thanh',
    'recon_status', r.recon_status,
    'log', coalesce((select jsonb_agg(jsonb_build_object('action', l.action, 'field', l.field, 'before', l.before, 'after', l.after,
                       'reason', l.reason, 'by', public.app__acc_name(l.by_account), 'at', l.at) order by l.id desc)
                     from public.shift_recon_log l where l.report_id = p_id), '[]'));
end $$;

create or replace function public.app__ca_save_core(p_id bigint, p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare a public.accounts; r public.shift_reports; x jsonb; i int := 0; keep bigint[]; nid bigint;
        h_ids jsonb := '[]'; d_ids jsonb := '[]'; forced text;
begin
  a := public.app_account();
  r := public.app__ca_need_edit(p_id);
  forced := public.app__ca_forced_start(r);
  update public.shift_reports set
    rev_start = coalesce(forced, nullif(p ->> 'rev_start', '')),
    rev_end = nullif(p ->> 'rev_end', ''),
    total_revenue = nullif(p ->> 'total_revenue', '')::bigint,
    pos_cash = nullif(p ->> 'pos_cash', '')::bigint,
    pos_transfer = nullif(p ->> 'pos_transfer', '')::bigint,
    reported_transfer = nullif(p ->> 'reported_transfer', '')::bigint,
    cash_counted = nullif(p ->> 'cash_counted', '')::bigint,
    opening_cash = case when r.shift = (public.app__shifts())[1] then 1000000
                        when not public.app__ca_chain(r.shift) then nullif(p ->> 'opening_cash', '')::bigint
                        else r.opening_cash end,
    opening_note = nullif(trim(coalesce(p ->> 'opening_note', '')), ''),
    ipos_opening = case when p ? 'ipos_opening' then nullif(p ->> 'ipos_opening', '')::bigint else r.ipos_opening end,
    cups = nullif(p ->> 'cups', '')::int,
    goods_status = nullif(p ->> 'goods_status', ''),
    goods_note = nullif(p ->> 'goods_note', ''),
    updated_by = a.id, updated_at = public.vn_now_text()
  where id = r.id;

  delete from public.shift_report_moves where report_id = r.id;
  for x in select * from jsonb_array_elements(coalesce(p -> 'moves', '[]')) loop
    i := i + 1;
    insert into public.shift_report_moves(report_id, kind, amount, note, sort_order)
    values (r.id, x ->> 'kind', coalesce(nullif(x ->> 'amount', '')::bigint, 0), coalesce(x ->> 'note', ''), i);
  end loop;

  delete from public.shift_report_staff where report_id = r.id;
  for x in select * from jsonb_array_elements(coalesce(p -> 'staff', '[]')) loop
    if coalesce(nullif(x ->> 'cash_paid', '')::bigint, 0) < 0 then raise exception 'Số tiền lương đã trả không được âm.'; end if;
    insert into public.shift_report_staff(report_id, employee_id, source, role, worked, absent_reason, time_in, time_out, note, cash_paid)
    values (r.id, (x ->> 'employee_id')::bigint, coalesce(x ->> 'source', 'ho_tro'), nullif(x ->> 'role', ''),
            case when (x ->> 'worked')::boolean then 1 else 0 end, nullif(x ->> 'absent_reason', ''),
            nullif(x ->> 'time_in', ''), nullif(x ->> 'time_out', ''), nullif(x ->> 'note', ''),
            case when (x ->> 'worked')::boolean and exists (select 1 from public.employees e where e.id = (x ->> 'employee_id')::bigint and e.pay_cash)
                 then nullif(nullif(x ->> 'cash_paid', '')::bigint, 0) end)
    on conflict (report_id, employee_id) do nothing;
  end loop;

  delete from public.shift_report_goods where report_id = r.id;
  insert into public.shift_report_goods(report_id, item, qty)
  select r.id, trim(g ->> 'item'), coalesce(g ->> 'qty', '') from jsonb_array_elements(coalesce(p -> 'goods', '[]')) g
   where trim(coalesce(g ->> 'item', '')) <> '';

  keep := array(select (h ->> 'id')::bigint from jsonb_array_elements(coalesce(p -> 'handover', '[]')) h where h ->> 'id' is not null);
  delete from public.handover_items where report_id = r.id and task_id is null and not (id = any(keep));
  for x in select * from jsonb_array_elements(coalesce(p -> 'handover', '[]')) loop
    if trim(coalesce(x ->> 'content', '')) = '' then h_ids := h_ids || 'null'::jsonb; continue; end if;
    if x ->> 'id' is null then
      insert into public.handover_items(branch_id, report_id, content, created_by) values (r.branch_id, r.id, trim(x ->> 'content'), a.id)
      returning id into nid;
    else
      nid := (x ->> 'id')::bigint;
      update public.handover_items set content = trim(x ->> 'content') where id = nid and report_id = r.id and task_id is null;
    end if;
    h_ids := h_ids || to_jsonb(nid);
  end loop;

  keep := array(select (d ->> 'id')::bigint from jsonb_array_elements(coalesce(p -> 'debts', '[]')) d where d ->> 'id' is not null);
  delete from public.shift_debts where report_id = r.id and closed_at is null and not (id = any(keep));
  for x in select * from jsonb_array_elements(coalesce(p -> 'debts', '[]')) loop
    if trim(coalesce(x ->> 'table_name', '')) = '' then d_ids := d_ids || 'null'::jsonb; continue; end if;
    if x ->> 'id' is null then
      insert into public.shift_debts(branch_id, report_id, table_name, amount, note, created_by)
      values (r.branch_id, r.id, trim(x ->> 'table_name'), coalesce(nullif(x ->> 'amount', '')::bigint, 0), nullif(x ->> 'note', ''), a.id)
      returning id into nid;
    else
      nid := (x ->> 'id')::bigint;
      update public.shift_debts set table_name = trim(x ->> 'table_name'), amount = coalesce(nullif(x ->> 'amount', '')::bigint, 0),
             note = nullif(x ->> 'note', '')
       where id = nid and report_id = r.id and closed_at is null;
    end if;
    d_ids := d_ids || to_jsonb(nid);
  end loop;
  return jsonb_build_object('at', public.vn_now_text(), 'rev_start', coalesce(forced, nullif(p ->> 'rev_start', '')),
                            'handover_ids', h_ids, 'debt_ids', d_ids);
end $$;

create or replace function public.app_ca_save(p_id bigint, p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare a public.accounts; r public.shift_reports; mine text[]; q jsonb := coalesce(p, '{}'::jsonb);
begin
  a := public.app_account();
  r := public.app__ca_need_edit(p_id);
  select coalesce(array_agg(part), '{}') into mine from public.shift_report_parts
   where report_id = r.id and claimed_by = a.id and done_at is null;
  if not ('tien' = any(mine) or 'nhan_su' = any(mine)) then
    return jsonb_build_object('at', public.vn_now_text(), 'skipped', true, 'rev_start', r.rev_start, 'handover_ids', '[]'::jsonb, 'debt_ids', '[]'::jsonb);
  end if;
  if not ('tien' = any(mine)) then
    q := q || jsonb_build_object('rev_start', r.rev_start, 'rev_end', r.rev_end, 'total_revenue', r.total_revenue, 'pos_cash', r.pos_cash,
      'pos_transfer', r.pos_transfer, 'reported_transfer', r.reported_transfer, 'cash_counted', r.cash_counted, 'opening_cash', r.opening_cash,
      'opening_note', r.opening_note, 'ipos_opening', r.ipos_opening, 'cups', r.cups,
      'moves', coalesce((select jsonb_agg(jsonb_build_object('kind', m.kind, 'amount', m.amount, 'note', m.note) order by m.sort_order, m.id)
                           from public.shift_report_moves m where m.report_id = r.id), '[]'::jsonb),
      'debts', coalesce((select jsonb_agg(jsonb_build_object('id', d.id, 'table_name', d.table_name, 'amount', d.amount, 'note', d.note) order by d.id)
                           from public.shift_debts d where d.report_id = r.id), '[]'::jsonb));
  end if;
  if not ('nhan_su' = any(mine)) then
    q := q || jsonb_build_object(
      'staff', coalesce((select jsonb_agg(jsonb_build_object('employee_id', s.employee_id, 'source', s.source, 'role', s.role, 'worked', s.worked = 1,
                           'absent_reason', s.absent_reason, 'time_in', s.time_in, 'time_out', s.time_out, 'note', s.note, 'cash_paid', s.cash_paid))
                           from public.shift_report_staff s where s.report_id = r.id), '[]'::jsonb),
      'handover', coalesce((select jsonb_agg(jsonb_build_object('id', h.id, 'content', h.content) order by h.id)
                              from public.handover_items h where h.report_id = r.id), '[]'::jsonb));
  end if;
  -- nhập hàng kiểu cũ: giữ nguyên
  q := q || jsonb_build_object('goods_status', r.goods_status, 'goods_note', r.goods_note,
    'goods', coalesce((select jsonb_agg(jsonb_build_object('item', g.item, 'qty', g.qty) order by g.id) from public.shift_report_goods g where g.report_id = r.id), '[]'::jsonb));
  return public.app__ca_save_core(p_id, q) || jsonb_build_object('parts', to_jsonb(mine));
end $$;

create or replace function public.app_ca_get(p_id bigint) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare a public.accounts; r public.shift_reports; prev public.shift_reports; prev_shift text; b public.branches; out jsonb; pe jsonb;
        h jsonb; ds boolean := public.app_can('doi_soat'); hide_prev boolean; hide_own boolean := false; nx public.shift_reports; ns text;
begin
  a := public.app__need('chot_ca');
  select * into r from public.shift_reports where id = p_id;
  if r.id is null then raise exception 'Không tìm thấy phiếu chốt ca.'; end if;
  select * into b from public.branches where id = r.branch_id;
  prev_shift := public.app__ca_prev_shift(r.shift);
  if prev_shift is not null then
    select * into prev from public.shift_reports where branch_id = r.branch_id and work_date = r.work_date and shift = prev_shift;
    if prev.id is not null then pe := public.app__ca_eff(prev.id); end if;
  end if;
  h := public.app__ca_hand(r.id);
  -- chưa đếm nhận két → không cho nhân viên thấy số két ca trước khai
  hide_prev := not ds and r.opening_cash is null and r.shift <> (public.app__shifts())[1] and public.app__ca_chain(r.shift);
  if h is not null and hide_prev then h := h || jsonb_build_object('prev_cash', null, 'gap', null, 'hidden', true); end if;
  -- phiếu đã hoàn thành mà ca sau chưa đếm nhận két → giấu số két (và ảnh phiếu iPOS) với người khác
  ns := public.app__ca_next_shift(r.shift);
  if r.status = 'hoan_thanh' and not ds and coalesce(r.completed_by, -1) <> a.id and ns is not null then
    select * into nx from public.shift_reports where branch_id = r.branch_id and work_date = r.work_date and shift = ns;
    hide_own := nx.id is null or nx.opening_cash is null;
  end if;
  out := to_jsonb(r) || jsonb_build_object(
    'branch_code', coalesce(b.display_code, b.code), 'branch_name', b.name,
    'first_shift', (public.app__shifts())[1], 'second_shift', (public.app__shifts())[2],
    'created_by_name', public.app__acc_name(r.created_by), 'completed_by_name', public.app__acc_name(r.completed_by),
    'recon_by_name', public.app__acc_name(r.recon_by), 'updated_by_name', public.app__acc_name(r.updated_by),
    'prev', case when prev_shift is null then null else jsonb_build_object(
        'shift', prev_shift, 'id', prev.id, 'status', prev.status,
        'cash_counted', case when hide_prev then null when prev.status = 'hoan_thanh' then (pe ->> 'cash_counted')::bigint else prev.cash_counted end,
        'rev_end', case when prev.status = 'hoan_thanh' then pe ->> 'rev_end' else prev.rev_end end) end,
    'cash_hand', h,
    'moves', coalesce((select jsonb_agg(to_jsonb(m) order by m.sort_order, m.id) from public.shift_report_moves m where m.report_id = r.id), '[]'),
    'staff', coalesce((select jsonb_agg(to_jsonb(s) || jsonb_build_object('code', e.code, 'name', e.name, 'rank', e.rank, 'pay_cash', e.pay_cash)
                         order by s.source, e.code) from public.shift_report_staff s join public.employees e on e.id = s.employee_id
                        where s.report_id = r.id), '[]'),
    'handover', coalesce((select jsonb_agg(to_jsonb(h2) || jsonb_build_object('created_by_name', public.app__acc_name(h2.created_by)) order by h2.id)
                            from public.handover_items h2 where h2.report_id = r.id), '[]'),
    'carried', coalesce((select jsonb_agg(to_jsonb(h2) || jsonb_build_object(
                            'created_by_name', public.app__acc_name(h2.created_by), 'done_by_name', public.app__acc_name(h2.done_by),
                            'from_date', o.work_date, 'from_shift', o.shift) order by o.work_date, h2.id)
                           from public.handover_items h2 join public.shift_reports o on o.id = h2.report_id
                          where h2.branch_id = r.branch_id and h2.report_id <> r.id
                            and (o.work_date, array_position(public.app__shifts(), o.shift)) < (r.work_date, array_position(public.app__shifts(), r.shift))
                            and (h2.done_at is null or h2.done_report_id = r.id)), '[]'),
    'goods', coalesce((select jsonb_agg(to_jsonb(g) order by g.id) from public.shift_report_goods g where g.report_id = r.id), '[]'),
    'photos', coalesce((select jsonb_agg(to_jsonb(p) order by p.id) from public.shift_report_photos p
                         where p.report_id = r.id and not (hide_own and p.kind = 'ipos')), '[]'),
    'debts', coalesce((select jsonb_agg(to_jsonb(d) order by d.id) from public.shift_debts d where d.report_id = r.id), '[]'),
    'open_debts', coalesce((select jsonb_agg(to_jsonb(d) || jsonb_build_object('from_date', o.work_date, 'from_shift', o.shift,
                            'closed_by_name', public.app__acc_name(d.closed_by)) order by d.id)
                           from public.shift_debts d join public.shift_reports o on o.id = d.report_id
                          where d.branch_id = r.branch_id and d.report_id <> r.id
                            and (o.work_date, array_position(public.app__shifts(), o.shift)) < (r.work_date, array_position(public.app__shifts(), r.shift))
                            and (d.closed_at is null or d.closed_report_id = r.id)), '[]'),
    'checks', coalesce((select jsonb_object_agg(c.item, jsonb_build_object('by', public.app__acc_name(c.checked_by), 'at', c.checked_at))
                          from public.shift_report_checks c where c.report_id = r.id), '{}'),
    'check_items', to_jsonb(public.app__ca_check_items()),
    'money_items', to_jsonb(public.app__ca_money_items()),
    'results', coalesce((select jsonb_object_agg(x.item, jsonb_build_object('result', x.result, 'amount', x.amount, 'computed', x.computed, 'basis', x.basis,
                           'reason', x.reason, 'by', public.app__acc_name(x.by_account), 'at', x.at))
                          from public.shift_report_results x where x.report_id = r.id), '{}'),
    'shortfalls', coalesce((select jsonb_agg(jsonb_build_object('id', s.id, 'item', s.item, 'employee_id', s.employee_id, 'employee', e.code || ' – ' || e.name,
                           'amount', s.amount, 'status', s.status, 'status_note', s.status_note, 'seen_at', s.seen_at, 'reply', s.reply) order by s.id)
                          from public.shift_shortfalls s join public.employees e on e.id = s.employee_id
                         where s.report_id = r.id and s.status <> 'huy'), '[]'),
    'money', case when r.status = 'hoan_thanh' and ds then public.app__ca_money(r.id) end,
    'forced_start', public.app__ca_forced_start(r),
    'tol', public.app__ca_tol(),
    'can_edit', r.status = 'dang_chot',
    'can_recon', ds and r.status = 'hoan_thanh',
    'can_reopen', public.app_can('mo_lai_phieu_ca') and r.status = 'hoan_thanh');
  if hide_own then out := out || jsonb_build_object('cash_counted', null, 'cash_hidden', true); end if;
  return out;
end $$;

create or replace function public.app_ca_result_set(p_id bigint, p_item text, p_result text, p_amount bigint, p_reason text, p_people jsonb) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts; r public.shift_reports; m jsonb; amt bigint; why text := nullif(trim(coalesce(p_reason, '')), '');
        x jsonb; tot bigint := 0; emps bigint[] := '{}'; e bigint; ea bigint; comp bigint; basis text;
begin
  a := public.app__need('doi_soat');
  select * into r from public.shift_reports where id = p_id for update;
  if r.id is null or r.status <> 'hoan_thanh' then raise exception 'Nhân viên chưa hoàn thành phiếu này.'; end if;
  if r.recon_status = 'hoan_thanh' then raise exception 'Phiếu đã HOÀN THÀNH ĐỐI SOÁT. Bấm "Mở lại đối soát" trước khi sửa.'; end if;
  if not (p_item = any(public.app__ca_money_items())) then raise exception 'Hạng mục không hợp lệ.'; end if;
  if p_result not in ('khop', 'thieu', 'thua') then raise exception 'Chọn KHỚP, THIẾU hoặc THỪA.'; end if;
  amt := case when p_result = 'khop' then 0 else coalesce(p_amount, 0) end;
  if p_result <> 'khop' and amt <= 0 then raise exception 'Nhập số tiền % (lớn hơn 0).', case when p_result = 'thieu' then 'thiếu' else 'thừa' end; end if;
  if p_result <> 'khop' and why is null then raise exception 'Ghi lý do % tiền.', case when p_result = 'thieu' then 'thiếu' else 'thừa' end; end if;
  if exists (select 1 from public.shift_shortfalls where report_id = p_id and item = p_item and status in ('da_bu', 'tru_luong', 'mien') and not (status = 'tru_luong' and auto_tru)) then
    raise exception 'Khoản âm của hạng mục này đã được xử lý (đã bù / trừ lương / miễn) nên không đổi được kết quả.';
  end if;
  if p_result = 'thieu' and not exists (select 1 from public.shift_report_checks c where c.report_id = p_id and c.item = 'nhan_su') then
    raise exception 'Đối soát bước Nhân sự trước (biết đủ người làm ca) rồi mới chọn THIẾU để chia tiền âm.';
  end if;
  if p_result = 'thieu' then
    if jsonb_typeof(coalesce(p_people, '[]')) <> 'array' or jsonb_array_length(coalesce(p_people, '[]')) = 0 then
      raise exception 'Chọn nhân viên chịu khoản thiếu.';
    end if;
    for x in select * from jsonb_array_elements(p_people) loop
      e := (x ->> 'employee_id')::bigint; ea := coalesce((x ->> 'amount')::bigint, 0);
      if not exists (select 1 from public.employees where id = e) then raise exception 'Nhân viên không hợp lệ.'; end if;
      if e = any(emps) then raise exception 'Mỗi nhân viên chỉ chọn một lần.'; end if;
      if ea <= 0 then raise exception 'Số tiền của từng nhân viên phải lớn hơn 0.'; end if;
      emps := emps || e; tot := tot + ea;
    end loop;
    if tot <> amt then raise exception 'Tổng tiền chia cho nhân viên (%) phải bằng số tiền thiếu (%).', public.app__vnd(tot), public.app__vnd(amt); end if;
  end if;
  m := public.app__ca_money(p_id);
  comp := case p_item when 'tien_mat' then (m ->> 'tm_left')::bigint when 'chuyen_khoan' then (m ->> 'ck_left')::bigint end;
  basis := case when p_item = 'chuyen_khoan' then m ->> 'ck_basis' end;
  -- khoản âm: thay danh sách chưa xử lý bằng danh sách mới
  perform public.app__ca_drop_shortfalls(p_id, p_item, emps, 'Quản lý đã đổi kết quả đối soát.');
  if p_result = 'thieu' then
    for x in select * from jsonb_array_elements(p_people) loop
      insert into public.shift_shortfalls(report_id, item, employee_id, amount, reason, created_by, status, auto_tru, status_note, status_by, status_at)
      values (p_id, p_item, (x ->> 'employee_id')::bigint, (x ->> 'amount')::bigint, why, a.id,
              'tru_luong', true, 'Mặc định trừ lương khi đối soát', a.id, public.vn_now_text());
      perform public.app__notify_emp((x ->> 'employee_id')::bigint, 'Bạn có khoản âm — mặc định trừ lương',
        public.app__ca_title(r) || ' · ' || public.app__ca_item_label(p_item) || ': bạn chịu ' || public.app__vnd((x ->> 'amount')::bigint)
        || E'\nLý do: ' || why || E'\nNgười đối soát: ' || public.app__acc_name(a.id)
        || E'\nMặc định: TRỪ LƯƠNG. Không đồng ý thì gửi giải trình ở mục Khoản âm của tôi.', '/cua-toi/khoan-am');
    end loop;
  end if;
  insert into public.shift_report_results(report_id, item, result, amount, computed, basis, reason, by_account, at)
  values (p_id, p_item, p_result, amt, comp, basis, why, a.id, public.vn_now_text())
  on conflict (report_id, item) do update set result = excluded.result, amount = excluded.amount, computed = excluded.computed, basis = excluded.basis,
         reason = excluded.reason, by_account = excluded.by_account, at = excluded.at;
  insert into public.shift_report_checks(report_id, item, checked_by, checked_at) values (p_id, p_item, a.id, public.vn_now_text())
  on conflict (report_id, item) do update set checked_by = excluded.checked_by, checked_at = excluded.checked_at;
  insert into public.shift_recon_log(report_id, action, field, after, reason, by_account)
  values (p_id, 'ket_qua', p_item, jsonb_build_object('result', p_result, 'amount', amt, 'people', coalesce(p_people, '[]')), why, a.id);
  perform public.app__ca_auto_finish(p_id, a.id);
  perform public.app_log('doi_soat_ket_qua', 'report=' || p_id || ' ' || p_item || '=' || p_result || ' ' || amt);
end $$;

create or replace function public.app__ca_auto_finish(p_id bigint, p_acc bigint) returns void
language plpgsql security definer set search_path = public as $$
declare r public.shift_reports; n int;
begin
  select * into r from public.shift_reports where id = p_id;
  select count(*) into n from public.shift_report_checks where report_id = p_id;
  if r.recon_status = 'chua' and n >= array_length(public.app__ca_check_items(), 1)
     and public.app__cv_state(p_id) in ('khong_can', 'da_duyet') then
    insert into public.shift_report_recon(report_id, data, updated_by) values (p_id, public.app__recon_snapshot(p_id), p_acc)
    on conflict (report_id) do nothing;
    update public.shift_reports set recon_status = 'hoan_thanh', recon_by = p_acc, recon_at = public.vn_now_text() where id = p_id;
    insert into public.shift_recon_log(report_id, action, by_account) values (p_id, 'hoan_thanh_doi_soat', p_acc);
  end if;
end $$;

create or replace function public.app_dg_board(p_month text, p_branch bigint) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare a public.accounts; mon text := coalesce(nullif(p_month, ''), to_char(public.vn_now(), 'YYYY-MM'));
begin
  a := public.app__dg_need();
  if mon !~ '^\d{4}-\d{2}$' then raise exception 'Tháng không hợp lệ.'; end if;
  return jsonb_build_object(
    'month', mon, 'open', public.app__dg_open(mon),
    'reopened', exists (select 1 from public.eval_month_open o where o.month = mon),
    'deadline', to_char(to_date(mon || '-01', 'YYYY-MM-DD') + interval '1 month' + interval '4 days', 'YYYY-MM-DD'),
    'is_owner', a.system_role = 'chu', 'me_employee', a.employee_id,
    'sets', (select jsonb_agg(jsonb_build_object('code', s.code, 'name', s.name) order by s.sort_order) from public.eval_sets s),
    'criteria', (select jsonb_agg(jsonb_build_object('code', c.code, 'set_code', c.set_code, 'name', c.name) order by c.set_code, c.sort_order) from public.eval_criteria c),
    'branches', coalesce((select jsonb_agg(jsonb_build_object('id', b.id, 'code', coalesce(b.display_code, b.code), 'name', b.name) order by b.sort_order)
                 from public.branches b where b.status = 'Đang hoạt động'), '[]'),
    'employees', coalesce((select jsonb_agg(x order by x ->> 'code') from (
        select jsonb_build_object('id', e.id, 'code', e.code, 'name', e.name, 'rank', e.rank, 'status', e.status,
          'branches', coalesce((select jsonb_agg(eb.branch_id) from public.employee_branches eb where eb.employee_id = e.id), '[]'),
          'set_code', public.app__dg_set_of(e.id),
          'set_saved', exists (select 1 from public.employee_eval_sets s where s.employee_id = e.id),
          'score', public.app__dg_score(e.id, mon),
          'n_tru', (select count(*) from public.eval_marks m where m.employee_id = e.id and left(m.work_date, 7) = mon and m.status = 'tru' and m.points > 0),
          'n_nhac', (select count(*) from public.eval_marks m where m.employee_id = e.id and left(m.work_date, 7) = mon and m.status = 'tru' and m.points = 0),
          'pending', (select count(*) from public.eval_marks m where m.employee_id = e.id and m.status = 'tru' and m.reply is not null and m.reviewed_at is null)) x
          from public.employees e
         where not e.pay_cash and (e.status = 'Đang làm' or exists (select 1 from public.eval_marks m where m.employee_id = e.id and left(m.work_date, 7) = mon and m.status <> 'huy'))
           and (p_branch is null or exists (select 1 from public.employee_branches eb where eb.employee_id = e.id and eb.branch_id = p_branch))) q), '[]'),
    'pending', coalesce((select jsonb_agg(public.app__dg_json(m) || jsonb_build_object('employee', e.code || ' – ' || e.name) order by m.reply_at)
                 from public.eval_marks m join public.employees e on e.id = m.employee_id
                where m.status = 'tru' and m.reply is not null and m.reviewed_at is null
                  and (p_branch is null or exists (select 1 from public.employee_branches eb where eb.employee_id = e.id and eb.branch_id = p_branch))), '[]'));
end $$;

-- ---------------------------------------------------------------- Nghỉ / làm thay (quy định x2)
create or replace function public.app__cv_classify_can() returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce((select a.system_role in ('chu', 'ql_tong') and coalesce(a.locked, 0) = 0 from public.accounts a where a.id = (public.app_account()).id), false)
$$;

-- Người cần phân loại trong ca: nghỉ (theo lịch, phát sinh nghỉ) + hỗ trợ (có làm)
create or replace function public.app__cv_people(p_id bigint) returns table(employee_id bigint, kind text, hours numeric)
language sql stable security definer set search_path = public as $$
  select (s ->> 'employee_id')::bigint, case when coalesce((s ->> 'worked')::boolean, true) then 'ho_tro' else 'nghi' end,
         public.app__hours(s ->> 'time_in', s ->> 'time_out')
    from jsonb_array_elements(coalesce(public.app__ca_eff(p_id) -> 'staff', '[]'::jsonb)) s
   where (s ->> 'source' = 'lich' and not coalesce((s ->> 'worked')::boolean, true))
      or (s ->> 'source' = 'ho_tro' and coalesce((s ->> 'worked')::boolean, true))
$$;

-- khong_can · chua_phan_loai · lech (danh sách người đã đổi, phân loại lại) · cho_duyet · da_duyet
create or replace function public.app__cv_state(p_id bigint) returns text
language plpgsql stable security definer set search_path = public as $$
declare na bigint[]; nh bigint[]; ra bigint[]; rh bigint[]; rv public.shift_cover_reviews;
begin
  select coalesce(array_agg(employee_id) filter (where kind = 'nghi'), '{}'), coalesce(array_agg(employee_id) filter (where kind = 'ho_tro'), '{}')
    into na, nh from public.app__cv_people(p_id);
  if cardinality(na) = 0 and cardinality(nh) = 0 then return 'khong_can'; end if;
  if not exists (select 1 from public.shift_covers where report_id = p_id) then return 'chua_phan_loai'; end if;
  select coalesce(array_agg(absent_id) filter (where absent_id is not null), '{}'), coalesce(array_agg(helper_id) filter (where helper_id is not null), '{}')
    into ra, rh from public.shift_covers where report_id = p_id;
  if not (na <@ ra and ra <@ na and nh <@ rh and rh <@ nh) then return 'lech'; end if;
  select * into rv from public.shift_cover_reviews where report_id = p_id;
  return case when rv.ok_at is not null then 'da_duyet' else 'cho_duyet' end;
end $$;

create or replace function public.app__cv_label(p_reason text) returns text
language sql immutable as $$
  select case p_reason when 'tu_tim' then 'Tự tìm người thay' when 'nho_ql' then 'Nhờ quản lý tìm người'
                       when 'ma_chay' then 'Ma chay tứ thân phụ mẫu' when 'thieu_lich' then 'Quản lý không xếp đủ lịch' else p_reason end
$$;

create or replace function public.app__cv_json(c public.shift_covers) returns jsonb
language sql stable security definer set search_path = public as $$
  select to_jsonb(c) || jsonb_build_object('reason_label', public.app__cv_label(c.reason),
    'absent', (select e.code || ' – ' || e.name from public.employees e where e.id = c.absent_id),
    'helper', coalesce((select e.code || ' – ' || e.name from public.employees e where e.id = c.helper_id), c.helper_name),
    'outsider', c.helper_id is null and c.helper_name is not null,
    'resolved_by_name', public.app__acc_name(c.resolved_by))
$$;

-- Tháng còn sửa được (quản lý tổng): tới hết ngày 5 tháng sau; Chủ luôn sửa được
create or replace function public.app__cv_open(p_date text) returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce((select a.system_role = 'chu' from public.accounts a where a.id = (public.app_account()).id), false)
      or to_char(public.vn_now(), 'YYYY-MM-DD') <= to_char(to_date(left(p_date, 7) || '-01', 'YYYY-MM-DD') + interval '1 month' + interval '4 days', 'YYYY-MM-DD')
$$;

create or replace function public.app_cv_get(p_id bigint) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare a public.accounts; r public.shift_reports; rv public.shift_cover_reviews;
begin
  a := public.app__need('doi_soat');
  select * into r from public.shift_reports where id = p_id;
  if r.id is null then raise exception 'Không tìm thấy phiếu.'; end if;
  select * into rv from public.shift_cover_reviews where report_id = p_id;
  return jsonb_build_object('state', public.app__cv_state(p_id), 'can_classify', public.app__cv_classify_can(), 'is_owner', a.system_role = 'chu',
    'open', public.app__cv_open(r.work_date), 'recon_status', r.recon_status,
    'people', coalesce((select jsonb_agg(jsonb_build_object('employee_id', p.employee_id, 'kind', p.kind, 'hours', p.hours,
                  'code', e.code, 'name', e.name, 'pay_cash', e.pay_cash) order by p.kind desc, e.code)
                from public.app__cv_people(p_id) p join public.employees e on e.id = p.employee_id), '[]'),
    'rows', coalesce((select jsonb_agg(public.app__cv_json(c) order by c.id) from public.shift_covers c where c.report_id = p_id), '[]'),
    'set_by', public.app__acc_name(rv.set_by), 'set_at', rv.set_at, 'ok_by', public.app__acc_name(rv.ok_by), 'ok_at', rv.ok_at, 'ok_note', rv.ok_note);
end $$;

-- Lưu phân loại. p_items: [{absent_id, reason, helper_id, helper_name, hours, x2, note}]
create or replace function public.app__cv_write(p_id bigint, p_items jsonb) returns void
language plpgsql security definer set search_path = public as $$
declare x jsonb; na bigint[]; nh bigint[]; seen_a bigint[] := '{}'; seen_h bigint[] := '{}'; ab bigint; hp bigint; hn text; rs text; hrs numeric; ph numeric;
begin
  if jsonb_typeof(coalesce(p_items, '[]')) <> 'array' then raise exception 'Dữ liệu phân loại không hợp lệ.'; end if;
  select coalesce(array_agg(employee_id) filter (where kind = 'nghi'), '{}'), coalesce(array_agg(employee_id) filter (where kind = 'ho_tro'), '{}')
    into na, nh from public.app__cv_people(p_id);
  delete from public.shift_covers where report_id = p_id;
  for x in select * from jsonb_array_elements(coalesce(p_items, '[]')) loop
    ab := nullif(x ->> 'absent_id', '')::bigint; hp := nullif(x ->> 'helper_id', '')::bigint; hn := nullif(trim(coalesce(x ->> 'helper_name', '')), '');
    rs := x ->> 'reason';
    if rs not in ('tu_tim', 'nho_ql', 'ma_chay', 'thieu_lich') then raise exception 'Chọn lý do cho từng người.'; end if;
    if ab is not null and not (ab = any(na)) then raise exception 'Người nghỉ không có trong ca (danh sách nhân sự đã đổi, tải lại trang).'; end if;
    if ab is not null and ab = any(seen_a) then raise exception 'Mỗi người nghỉ chỉ phân loại 1 lần.'; end if;
    if ab is null and rs <> 'thieu_lich' then raise exception 'Lý do "%" phải gắn với người nghỉ.', public.app__cv_label(rs); end if;
    if ab is not null and rs = 'thieu_lich' then raise exception 'Người nghỉ không dùng lý do "Quản lý không xếp đủ lịch".'; end if;
    if hp is not null and not (hp = any(nh)) then raise exception 'Người làm thay phải là người hỗ trợ có trong ca.'; end if;
    if hp is not null and hp = any(seen_h) then raise exception 'Mỗi người hỗ trợ chỉ gắn với 1 dòng.'; end if;
    if hp is null and hn is null and rs in ('nho_ql', 'thieu_lich') then raise exception 'Chọn người làm thay / làm thêm cho lý do "%".', public.app__cv_label(rs); end if;
    select p.hours into ph from public.app__cv_people(p_id) p where p.employee_id = hp;
    hrs := case when hp is not null then coalesce(nullif(x ->> 'hours', '')::numeric, ph, 0) else coalesce(nullif(x ->> 'hours', '')::numeric, 0) end;
    if hrs < 0 or hrs > 24 then raise exception 'Số giờ làm thay không hợp lệ.'; end if;
    if rs = 'nho_ql' and hrs <= 0 then raise exception 'Nhập số giờ người làm thay đã làm (để trừ người nghỉ).'; end if;
    insert into public.shift_covers(report_id, absent_id, reason, helper_id, helper_name, hours, x2, deduct_hours, note)
    values (p_id, ab, rs, hp, case when hp is null then hn end, hrs, coalesce((x ->> 'x2')::boolean, false) and (hp is not null or hn is not null),
            case when rs = 'nho_ql' then hrs else 0 end, nullif(trim(coalesce(x ->> 'note', '')), ''));
    if ab is not null then seen_a := seen_a || ab; end if;
    if hp is not null then seen_h := seen_h || hp; end if;
  end loop;
  if not (na <@ seen_a) then raise exception 'Còn người nghỉ chưa chọn lý do.'; end if;
  if not (nh <@ seen_h) then raise exception 'Còn người hỗ trợ chưa gắn vào dòng nào (làm thay ai, hoặc "Quản lý không xếp đủ lịch").'; end if;
end $$;

create or replace function public.app_cv_save(p_id bigint, p_items jsonb) returns text
language plpgsql security definer set search_path = public as $$
declare a public.accounts; r public.shift_reports; x bigint;
begin
  a := public.app__need('doi_soat');
  if not public.app__cv_classify_can() then raise exception 'Chỉ Quản lý tổng / Chủ phân loại nghỉ và làm thay.'; end if;
  select * into r from public.shift_reports where id = p_id for update;
  if r.id is null or r.status <> 'hoan_thanh' then raise exception 'Nhân viên chưa hoàn thành phiếu này.'; end if;
  if r.recon_status = 'hoan_thanh' then raise exception 'Phiếu đã HOÀN THÀNH ĐỐI SOÁT. Bấm "Mở lại đối soát" trước khi sửa.'; end if;
  perform public.app__cv_write(p_id, p_items);
  insert into public.shift_cover_reviews(report_id, set_by, set_at) values (p_id, a.id, public.vn_now_text())
  on conflict (report_id) do update set set_by = excluded.set_by, set_at = excluded.set_at, ok_by = null, ok_at = null, ok_note = null;
  perform public.app_log('phan_loai_nghi_lam_thay', 'report=' || p_id);
  if a.system_role <> 'chu' then
    for x in select id from public.accounts where system_role = 'chu' and coalesce(locked, 0) = 0 loop
      perform public.app__notify(x, 'Chờ duyệt nghỉ / làm thay', public.app__ca_title(r) || E'\nQuản lý tổng đã phân loại, Chủ duyệt thì phiếu mới hoàn thành đối soát.',
        '/quan-ly/doi-soat/ca?id=' || p_id);
    end loop;
  end if;
  return public.app__cv_state(p_id);
end $$;

-- Chủ duyệt (có thể sửa trước khi duyệt) → báo người nghỉ + người làm thay; đủ hạng mục thì phiếu tự hoàn thành đối soát
create or replace function public.app_cv_approve(p_id bigint, p_items jsonb, p_note text) returns text
language plpgsql security definer set search_path = public as $$
declare a public.accounts; r public.shift_reports; c public.shift_covers; st text; t text;
begin
  a := public.app__need('doi_soat');
  if a.system_role <> 'chu' then raise exception 'Chỉ Chủ duyệt nghỉ / làm thay.'; end if;
  select * into r from public.shift_reports where id = p_id for update;
  if r.id is null or r.status <> 'hoan_thanh' then raise exception 'Nhân viên chưa hoàn thành phiếu này.'; end if;
  if r.recon_status = 'hoan_thanh' then raise exception 'Phiếu đã HOÀN THÀNH ĐỐI SOÁT. Bấm "Mở lại đối soát" trước khi sửa.'; end if;
  if p_items is not null then perform public.app__cv_write(p_id, p_items); end if;
  st := public.app__cv_state(p_id);
  if st in ('chua_phan_loai', 'lech') then raise exception 'Chưa phân loại đủ người nghỉ / người hỗ trợ của ca.'; end if;
  if st = 'khong_can' then return st; end if;
  insert into public.shift_cover_reviews(report_id, set_by, set_at, ok_by, ok_at, ok_note) values (p_id, a.id, public.vn_now_text(), a.id, public.vn_now_text(), nullif(trim(coalesce(p_note, '')), ''))
  on conflict (report_id) do update set ok_by = excluded.ok_by, ok_at = excluded.ok_at, ok_note = excluded.ok_note,
     set_by = coalesce(public.shift_cover_reviews.set_by, excluded.set_by), set_at = coalesce(public.shift_cover_reviews.set_at, excluded.set_at);
  t := public.app__ca_title(r);
  for c in select * from public.shift_covers where report_id = p_id loop
    if c.absent_id is not null then
      perform public.app__notify_emp(c.absent_id, case when c.deduct_hours > 0 then 'Nghỉ ca: bị trừ ' || c.deduct_hours || ' giờ' else 'Nghỉ ca: không bị trừ' end,
        t || E'\nLý do: ' || public.app__cv_label(c.reason)
        || coalesce(E'\nNgười làm thay: ' || (select e.code || ' – ' || e.name from public.employees e where e.id = c.helper_id), E'\nNgười làm thay: ' || c.helper_name, '')
        || case when c.deduct_hours > 0 then E'\nSố giờ người làm thay đã làm được trừ vào lương của bạn.' else '' end
        || E'\nKhông đồng ý thì gửi khiếu nại ở Của tôi › Công của tôi.', '/cua-toi/cong');
    end if;
    if c.helper_id is not null then
      perform public.app__notify_emp(c.helper_id, case when c.x2 then 'Làm thay ca: được x2 lương' else 'Làm thay ca: lương thường' end,
        t || E'\n' || case when c.absent_id is not null then 'Làm thay: ' || (select e.code || ' – ' || e.name from public.employees e where e.id = c.absent_id) else 'Làm thêm (quản lý không xếp đủ lịch)' end
        || E'\nSố giờ: ' || c.hours || case when c.x2 then ' (được cộng thêm ' || c.hours || ' giờ)' else '' end
        || E'\nKhông đồng ý thì gửi khiếu nại ở Của tôi › Công của tôi.', '/cua-toi/cong');
    end if;
  end loop;
  perform public.app_log('duyet_nghi_lam_thay', 'report=' || p_id);
  perform public.app__ca_auto_finish(p_id, a.id);
  return public.app__cv_state(p_id);
end $$;

-- Người nghỉ / người làm thay khiếu nại
create or replace function public.app_cv_complain(p_cover bigint, p_text text) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts; c public.shift_covers; r public.shift_reports; tx text := nullif(trim(coalesce(p_text, '')), ''); x bigint; who text;
begin
  a := public.app__need(null);
  select * into c from public.shift_covers where id = p_cover for update;
  if c.id is null or a.employee_id is null or a.employee_id not in (coalesce(c.absent_id, -1), coalesce(c.helper_id, -1)) then raise exception 'Không tìm thấy.'; end if;
  if not exists (select 1 from public.shift_cover_reviews v where v.report_id = c.report_id and v.ok_at is not null) then raise exception 'Chủ chưa duyệt nên chưa khiếu nại được.'; end if;
  if tx is null then raise exception 'Nhập nội dung khiếu nại.'; end if;
  if length(tx) > 2000 then raise exception 'Khiếu nại quá dài.'; end if;
  if a.employee_id = c.absent_id then update public.shift_covers set complaint_absent = tx, complaint_absent_at = public.vn_now_text(), resolved_at = null where id = p_cover;
  else update public.shift_covers set complaint_helper = tx, complaint_helper_at = public.vn_now_text(), resolved_at = null where id = p_cover; end if;
  select * into r from public.shift_reports where id = c.report_id;
  select e.code || ' – ' || e.name into who from public.employees e where e.id = a.employee_id;
  for x in select id from public.accounts where system_role in ('chu', 'ql_tong') and coalesce(locked, 0) = 0 loop
    perform public.app__notify(x, 'Khiếu nại nghỉ / làm thay: ' || who, public.app__ca_title(r) || E'\n' || tx, '/quan-ly/bao-cao?tab=bang-cong&thang=' || left(r.work_date, 7));
  end loop;
  perform public.app_log('khieu_nai_lam_thay', 'cover=' || p_cover);
end $$;

-- Quản lý tổng / Chủ xử lý khiếu nại: giữ hoặc sửa x2 / giờ trừ
create or replace function public.app_cv_resolve(p_cover bigint, p_x2 boolean, p_deduct numeric, p_note text) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts; c public.shift_covers; r public.shift_reports; t text;
begin
  a := public.app__need(null);
  if not public.app__cv_classify_can() then raise exception 'Chỉ Quản lý tổng / Chủ xử lý khiếu nại.'; end if;
  select * into c from public.shift_covers where id = p_cover for update;
  if c.id is null then raise exception 'Không tìm thấy.'; end if;
  select * into r from public.shift_reports where id = c.report_id;
  if not public.app__cv_open(r.work_date) then raise exception 'Tháng % đã khóa (quá ngày 5 tháng sau). Nhờ Chủ sửa.', left(r.work_date, 7); end if;
  if p_deduct is not null and (p_deduct < 0 or p_deduct > 24) then raise exception 'Số giờ trừ không hợp lệ.'; end if;
  update public.shift_covers set x2 = coalesce(p_x2, x2) and (helper_id is not null or helper_name is not null), deduct_hours = coalesce(p_deduct, deduct_hours),
         resolved_by = a.id, resolved_at = public.vn_now_text(), resolve_note = nullif(trim(coalesce(p_note, '')), '') where id = p_cover;
  select * into c from public.shift_covers where id = p_cover;
  t := public.app__ca_title(r) || E'\nĐã xem khiếu nại: ' || coalesce(c.resolve_note, 'giữ nguyên / đã sửa') || E'\nNgười xem: ' || public.app__acc_name(a.id);
  if c.absent_id is not null then perform public.app__notify_emp(c.absent_id, 'Nghỉ ca: trừ ' || c.deduct_hours || ' giờ (đã xem khiếu nại)', t, '/cua-toi/cong'); end if;
  if c.helper_id is not null then perform public.app__notify_emp(c.helper_id, 'Làm thay ca: ' || case when c.x2 then 'x2 lương' else 'lương thường' end || ' (đã xem khiếu nại)', t, '/cua-toi/cong'); end if;
  perform public.app_log('xu_ly_khieu_nai_lam_thay', 'cover=' || p_cover);
end $$;

-- ---------------------------------------------------------------- Thực tế trên lịch
-- Mỗi người trong phiếu đã hoàn thành: có làm / nghỉ / hỗ trợ, giờ, chính thức (đã đối soát Nhân sự) hay chờ xác nhận
create or replace function public.app_lich_thuc_te(p_from text, p_to text, p_branch bigint) returns jsonb
language plpgsql stable security definer set search_path = public as $$
begin
  perform public.app__need(null);
  if not (public.app_can('xem_tat_ca') or public.app_can('bao_cao')) then raise exception 'Bạn không có quyền thực hiện thao tác này.'; end if;
  return coalesce((select jsonb_agg(jsonb_build_object('report_id', r.id, 'date', r.work_date, 'shift', r.shift, 'branch_id', r.branch_id,
            'employee_id', (s ->> 'employee_id')::bigint, 'code', e.code, 'name', e.name, 'pay_cash', e.pay_cash,
            'source', s ->> 'source', 'worked', coalesce((s ->> 'worked')::boolean, true), 'time_in', s ->> 'time_in', 'time_out', s ->> 'time_out',
            'hours', public.app__hours(s ->> 'time_in', s ->> 'time_out'),
            'official', exists (select 1 from public.shift_report_checks k where k.report_id = r.id and k.item = 'nhan_su'),
            'reason', (select public.app__cv_label(c.reason) from public.shift_covers c where c.report_id = r.id and (c.absent_id = e.id or c.helper_id = e.id) limit 1),
            'x2', (select c.x2 from public.shift_covers c join public.shift_cover_reviews v on v.report_id = c.report_id and v.ok_at is not null
                    where c.report_id = r.id and c.helper_id = e.id limit 1))
           order by r.work_date, r.shift, e.code)
      from public.shift_reports r
      cross join lateral jsonb_array_elements(coalesce(public.app__ca_eff(r.id) -> 'staff', '[]'::jsonb)) s
      join public.employees e on e.id = (s ->> 'employee_id')::bigint
     where r.status = 'hoan_thanh' and r.work_date between p_from and p_to and (p_branch is null or r.branch_id = p_branch)), '[]');
end $$;

-- ---------------------------------------------------------------- Bảng công tháng (đối chiếu khi chốt lương trên HRM)
create or replace function public.app_bang_cong(p_month text) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare a public.accounts; f text; t text;
begin
  a := public.app__need(null);
  if not (public.app_can('bao_cao') or public.app__cv_classify_can()) then raise exception 'Bạn không có quyền thực hiện thao tác này.'; end if;
  if coalesce(p_month, '') !~ '^\d{4}-\d{2}$' then raise exception 'Tháng không hợp lệ.'; end if;
  f := p_month || '-01'; t := to_char((f::date + interval '1 month' - interval '1 day'), 'YYYY-MM-DD');
  return jsonb_build_object('month', p_month, 'can_resolve', public.app__cv_classify_can(), 'is_owner', a.system_role = 'chu',
    'rows', coalesce((select jsonb_agg(x order by x ->> 'code') from (
        select jsonb_build_object('employee_id', e.id, 'code', e.code, 'name', e.name, 'rank', e.rank, 'pay_cash', e.pay_cash, 'status', e.status,
          'shifts', count(*) filter (where w.worked), 'hours', coalesce(sum(w.hours) filter (where w.worked), 0),
          'pending', count(*) filter (where w.worked and not w.official),
          'cash_paid', coalesce(sum(w.cash) filter (where w.worked), 0),
          'absent', count(*) filter (where not w.worked),
          'x2_hours', coalesce((select sum(c.hours) from public.shift_covers c join public.shift_reports r2 on r2.id = c.report_id
                         join public.shift_cover_reviews v on v.report_id = c.report_id and v.ok_at is not null
                        where c.helper_id = e.id and c.x2 and r2.work_date between f and t), 0),
          'deduct_hours', coalesce((select sum(c.deduct_hours) from public.shift_covers c join public.shift_reports r2 on r2.id = c.report_id
                         join public.shift_cover_reviews v on v.report_id = c.report_id and v.ok_at is not null
                        where c.absent_id = e.id and r2.work_date between f and t), 0)) x
          from public.employees e
          join (select (s ->> 'employee_id')::bigint eid, coalesce((s ->> 'worked')::boolean, true) worked, public.app__hours(s ->> 'time_in', s ->> 'time_out') hours,
                       coalesce(nullif(s ->> 'cash_paid', '')::bigint, 0) cash,
                       exists (select 1 from public.shift_report_checks k where k.report_id = r.id and k.item = 'nhan_su') official
                  from public.shift_reports r cross join lateral jsonb_array_elements(coalesce(public.app__ca_eff(r.id) -> 'staff', '[]'::jsonb)) s
                 where r.status = 'hoan_thanh' and r.work_date between f and t) w on w.eid = e.id
         group by e.id) q), '[]'),
    'covers', coalesce((select jsonb_agg(public.app__cv_json(c) || jsonb_build_object('date', r.work_date, 'shift', r.shift,
                  'branch', coalesce(b.display_code, b.code), 'approved', v.ok_at is not null, 'open', public.app__cv_open(r.work_date)) order by r.work_date, r.shift, c.id)
                from public.shift_covers c join public.shift_reports r on r.id = c.report_id join public.branches b on b.id = r.branch_id
                left join public.shift_cover_reviews v on v.report_id = c.report_id
               where r.work_date between f and t), '[]'));
end $$;

-- Công của tôi (nhân viên): ca / giờ tháng này + các lần nghỉ / làm thay đã duyệt, khiếu nại
create or replace function public.app_cong_mine(p_month text) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare a public.accounts; m text := coalesce(nullif(p_month, ''), to_char(public.vn_now(), 'YYYY-MM')); f text; t text;
begin
  a := public.app__need(null);
  if a.employee_id is null then return jsonb_build_object('month', m, 'shifts', '[]'::jsonb, 'covers', '[]'::jsonb); end if;
  f := m || '-01'; t := to_char((f::date + interval '1 month' - interval '1 day'), 'YYYY-MM-DD');
  return jsonb_build_object('month', m,
    'shifts', coalesce((select jsonb_agg(jsonb_build_object('date', r.work_date, 'shift', r.shift, 'branch', coalesce(b.display_code, b.code),
                  'worked', coalesce((s ->> 'worked')::boolean, true), 'source', s ->> 'source', 'time_in', s ->> 'time_in', 'time_out', s ->> 'time_out',
                  'hours', public.app__hours(s ->> 'time_in', s ->> 'time_out'),
                  'official', exists (select 1 from public.shift_report_checks k where k.report_id = r.id and k.item = 'nhan_su')) order by r.work_date, r.shift)
                from public.shift_reports r join public.branches b on b.id = r.branch_id
                cross join lateral jsonb_array_elements(coalesce(public.app__ca_eff(r.id) -> 'staff', '[]'::jsonb)) s
               where r.status = 'hoan_thanh' and r.work_date between f and t and (s ->> 'employee_id')::bigint = a.employee_id), '[]'),
    'covers', coalesce((select jsonb_agg(public.app__cv_json(c) || jsonb_build_object('date', r.work_date, 'shift', r.shift, 'branch', coalesce(b.display_code, b.code),
                  'me_absent', c.absent_id = a.employee_id) order by r.work_date desc)
                from public.shift_covers c join public.shift_reports r on r.id = c.report_id join public.branches b on b.id = r.branch_id
                join public.shift_cover_reviews v on v.report_id = c.report_id and v.ok_at is not null
               where (c.absent_id = a.employee_id or c.helper_id = a.employee_id) and r.work_date between f and t), '[]'));
end $$;

-- ---------------------------------------------------------------- Cấp quyền gọi hàm
do $$
declare f record;
begin
  for f in select p.oid::regprocedure as sig, p.proname from pg_proc p join pg_namespace n on n.oid = p.pronamespace
            where n.nspname = 'public' and (p.proname like 'app\_cv\_%' or p.proname like 'app\_\_cv\_%'
              or p.proname in ('app__hours', 'app__ca_eff', 'app_lich_thuc_te', 'app_bang_cong', 'app_cong_mine', 'app_save_employee', 'app_ca_employees',
                               'app__recon_snapshot', 'app_ca_recon', 'app__ca_save_core', 'app_ca_save', 'app_ca_get', 'app_ca_result_set', 'app__ca_auto_finish', 'app_dg_board')) loop
    execute format('revoke execute on function %s from public, anon', f.sig);
    if f.proname like 'app\_\_%' then
      execute format('revoke execute on function %s from authenticated', f.sig);
    else
      execute format('grant execute on function %s to authenticated', f.sig);
    end if;
  end loop;
end $$;
