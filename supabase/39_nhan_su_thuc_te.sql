-- Số giờ giữa 2 mốc HH:MM (qua nửa đêm thì cộng 24 giờ)
create or replace function public.app__hours(p_in text, p_out text) returns numeric
language sql immutable as $$
  select case when coalesce(p_in, '') ~ '^\d{1,2}:\d{2}' and coalesce(p_out, '') ~ '^\d{1,2}:\d{2}' then
    round((((split_part(p_out, ':', 1)::int * 60 + split_part(p_out, ':', 2)::int) - (split_part(p_in, ':', 1)::int * 60 + split_part(p_in, ':', 2)::int) + 1440) % 1440) / 60.0, 2)
  else 0 end
$$;

