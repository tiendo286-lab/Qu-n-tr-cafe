language plpgsql stable security definer set search_path = public as $$
declare a public.accounts;
begin
  a := public.app__dg_need();
  return coalesce((select jsonb_agg(public.app__dg_json(m) order by m.id) from public.eval_marks m where m.report_id = p_report and m.status <> 'huy'), '[]');
end $$;

-- ---------------------------------------------------------------- Nhân viên: điểm của tôi + giải trình
create or replace function public.app_dg_mine() returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare a public.accounts; mon text := to_char(public.vn_now(), 'YYYY-MM'); st text;
begin
  a := public.app__need(null);
  if a.employee_id is null then
    return jsonb_build_object('month', mon, 'score', null, 'marks', '[]'::jsonb, 'criteria', '[]'::jsonb, 'months', '[]'::jsonb);
  end if;
  st := public.app__dg_set_of(a.employee_id);
  return jsonb_build_object('month', mon, 'set_code', st, 'set_name', (select s.name from public.eval_sets s where s.code = st),
    'score', public.app__dg_score(a.employee_id, mon),
    'criteria', coalesce((select jsonb_agg(jsonb_build_object('code', c.code, 'name', c.name) order by c.sort_order) from public.eval_criteria c where c.set_code = st), '[]'),
    'months', coalesce((select jsonb_agg(jsonb_build_object('month', x.mo, 'score', public.app__dg_score(a.employee_id, x.mo),
                  'rating', public.app__dg_rating(public.app__dg_score(a.employee_id, x.mo))) order by x.mo desc)
                from (select distinct left(m.work_date, 7) mo from public.eval_marks m where m.employee_id = a.employee_id and m.status <> 'huy') x), '[]'),
    'marks', coalesce((select jsonb_agg(public.app__dg_json(m) order by m.work_date desc, m.id desc)
                from public.eval_marks m where m.employee_id = a.employee_id and m.status <> 'huy'), '[]'));
end $$;

create or replace function public.app_dg_reply(p_id bigint, p_text text) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts; m public.eval_marks; c public.eval_criteria; e public.employees; tx text := nullif(trim(coalesce(p_text, '')), '');
begin
  a := public.app__need(null);
  select * into m from public.eval_marks where id = p_id for update;
  if m.id is null or m.status = 'huy' or a.employee_id is null or m.employee_id <> a.employee_id then raise exception 'Không tìm thấy lần đánh giá này.'; end if;
  if m.status <> 'tru' or m.reviewed_at is not null then raise exception 'Quản lý đã xem lần đánh giá này nên không gửi giải trình nữa.'; end if;
  if tx is null then raise exception 'Nhập nội dung giải trình.'; end if;
  if length(tx) > 2000 then raise exception 'Giải trình quá dài.'; end if;
  update public.eval_marks set reply = tx, reply_at = public.vn_now_text() where id = p_id;
  select * into c from public.eval_criteria where code = m.criterion;
  select * into e from public.employees where id = m.employee_id;
  if m.created_by is not null and m.created_by <> a.id then
    perform public.app__notify(m.created_by, 'Giải trình đánh giá: ' || e.code || ' – ' || e.name,
      public.app__dg_label(m.points) || ' · ' || c.name || ' · ngày ' || to_char(to_date(m.work_date, 'YYYY-MM-DD'), 'DD/MM') || E'\n' || tx,
      '/quan-ly/danh-gia?nv=' || e.id);
  end if;
  perform public.app_log('danh_gia_tra_loi', 'id=' || p_id);
end $$;

-- ---------------------------------------------------------------- Cấp quyền gọi hàm
do $$
declare f record;
begin
  for f in select p.oid::regprocedure as sig, p.proname from pg_proc p join pg_namespace n on n.oid = p.pronamespace
            where n.nspname = 'public' and (p.proname like 'app\_dg\_%' or p.proname like 'app\_\_dg\_%') loop
    execute format('revoke execute on function %s from public, anon', f.sig);
    if f.proname like 'app\_\_%' then
      execute format('revoke execute on function %s from authenticated', f.sig);
    else
      execute format('grant execute on function %s to authenticated', f.sig);
    end if;
  end loop;
end $$;
