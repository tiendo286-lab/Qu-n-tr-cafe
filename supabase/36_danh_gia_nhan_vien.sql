create table if not exists public.employee_eval_sets (
  employee_id bigint primary key references public.employees(id) on delete cascade,
  set_code text not null references public.eval_sets(code),
  updated_by bigint,
  updated_at text not null default public.vn_now_text()
);

create table if not exists public.eval_marks (
  id bigint generated by default as identity primary key,
  employee_id bigint not null references public.employees(id) on delete cascade,
  work_date text not null,                       -- YYYY-MM-DD ngày phạm lỗi → tháng tính điểm
  criterion text not null references public.eval_criteria(code),
  points integer not null check (points between 0 and 5),   -- 0 = nhắc nhở
  note text not null,
  photo_path text,                               -- ảnh (bucket phieu-ca, thư mục dg/)
  report_id bigint references public.shift_reports(id) on delete set null,
  branch_id bigint references public.branches(id) on delete set null,
  status text not null default 'tru' check (status in ('tru', 'hoan', 'huy')),
  reply text, reply_at text,
  reviewed_by bigint, reviewed_at text, review_note text,
  created_by bigint, created_at text not null default public.vn_now_text(),
  updated_by bigint, updated_at text
);
create index if not exists idx_eval_marks_emp on public.eval_marks (employee_id, work_date);
create index if not exists idx_eval_marks_month on public.eval_marks (left(work_date, 7));
create index if not exists idx_eval_marks_report on public.eval_marks (report_id);

create table if not exists public.eval_month_open (
  month text primary key,                        -- YYYY-MM Chủ mở lại sau hạn ngày 5
  opened_by bigint,
  opened_at text not null default public.vn_now_text()
);

do $$
declare t text;
begin
