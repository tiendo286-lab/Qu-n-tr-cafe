create or replace function public.app_can(p text) returns boolean
language plpgsql stable security definer set search_path = public as $$
declare a public.accounts;
begin
  a := public.app_account();
  if a.id is null then return false; end if;
  if a.system_role = 'chu' then return true; end if;
  if p in ('phan_quyen', 'xoa_du_lieu_tuan', 'du_lieu') then return false; end if;
  -- Kế toán: chỉ tab Kế toán (+ nhận việc được giao)
  if a.system_role = 'ke_toan' then return p in ('ke_toan', 'nhan_viec'); end if;
  if p = 'ke_toan' then return false; end if;
  if p = 'chot_ca' then return true; end if;                                    -- ai cũng chốt ca được
  if p = 'nhan_viec' then return true; end if;                                  -- ai cũng nhận việc được giao
  if p = 'xu_ly_ho_tro' then return a.system_role in ('ql_tong', 'ql'); end if;
  if a.system_role = 'nv' then
    if p in ('order_ca', 'xem_lich_minh') then return true; end if;
    if p <> 'xem_tat_ca' then return false; end if;
  end if;
  return coalesce((select r.allowed = 1 from public.role_permissions r where r.role = a.system_role and r.perm = p), false);
end $$;

create or replace function public.app_set_system_role(p_account bigint, p_role text) returns void
language plpgsql security definer set search_path = public as $$
declare old text;
begin
  if not public.app_can('phan_quyen') then raise exception 'Chỉ Chủ được cấp vai trò.'; end if;
  if p_role not in ('ql_tong', 'ql', 'nv', 'ke_toan') then raise exception 'Vai trò không hợp lệ.'; end if;
  select system_role into old from public.accounts where id = p_account;
  if old is null then raise exception 'Không tìm thấy tài khoản.'; end if;
  if old = 'chu' then raise exception 'Không đổi được vai trò của Chủ.'; end if;
  update public.accounts set system_role = p_role where id = p_account;
  perform public.app_log('doi_vai_tro', p_account || ':' || old || '->' || p_role);
end $$;

-- ---------------------------------------------------------------- Bảng
create table if not exists public.delivery_invoices (
  id bigint generated by default as identity primary key,
  branch_id bigint not null references public.branches(id) on delete cascade,
  work_date text not null,                   -- YYYY-MM-DD: ngày giao, ca nào trong ngày nhận cũng được
  note text,
  created_by bigint, created_at text not null default public.vn_now_text(),
  updated_at text not null default public.vn_now_text(),
  -- báo cáo nhận hàng của nhân viên
  result text check (result in ('du', 'thieu')),
  receive_note text,
  received_by bigint, received_at text,
  received_report_id bigint references public.shift_reports(id) on delete set null
);
create index if not exists idx_inv_branch_date on public.delivery_invoices (branch_id, work_date);
create table if not exists public.delivery_invoice_files (
  id bigint generated by default as identity primary key,
  invoice_id bigint not null references public.delivery_invoices(id) on delete cascade,
  path text not null, name text not null, mime text, size bigint,
  created_by bigint, created_at text not null default public.vn_now_text()
);
create table if not exists public.delivery_receipt_photos (
  id bigint generated by default as identity primary key,
  invoice_id bigint not null references public.delivery_invoices(id) on delete cascade,
  path text not null, created_by bigint, created_at text not null default public.vn_now_text()
);
create table if not exists public.delivery_receipt_items (
  id bigint generated by default as identity primary key,
  invoice_id bigint not null references public.delivery_invoices(id) on delete cascade,
  item text not null, qty text not null default ''
);
create table if not exists public.bank_shift_balances (
  report_id bigint primary key references public.shift_reports(id) on delete cascade,
  opening bigint, closing bigint, transfers_out bigint not null default 0, note text,
  updated_by bigint, updated_at text not null default public.vn_now_text()
);
do $$
declare t text;
begin
  foreach t in array array['delivery_invoices','delivery_invoice_files','delivery_receipt_photos','delivery_receipt_items','bank_shift_balances'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon, authenticated', t);
  end loop;
end $$;

