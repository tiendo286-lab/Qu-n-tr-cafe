create or replace function public.app_kt_bank_save(p_report bigint, p_opening bigint, p_closing bigint, p_out bigint, p_note text) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts; r public.shift_reports; old public.bank_shift_balances; k text; o jsonb; n jsonb;
begin
  a := public.app__need('ke_toan');
  select * into r from public.shift_reports where id = p_report for update;
  if r.id is null then raise exception 'Không tìm thấy phiếu ca.'; end if;
  if r.recon_status = 'hoan_thanh' then raise exception 'Quản lý đã HOÀN THÀNH ĐỐI SOÁT ca này nên số liệu kế toán đã khóa. Cần quản lý mở lại đối soát.'; end if;
  if coalesce(p_out, 0) < 0 then raise exception 'Tiền chuyển ra không được âm.'; end if;
  select * into old from public.bank_shift_balances where report_id = p_report;
  insert into public.bank_shift_balances(report_id, opening, closing, transfers_out, note, updated_by, updated_at)
  values (p_report, p_opening, p_closing, coalesce(p_out, 0), nullif(trim(coalesce(p_note, '')), ''), a.id, public.vn_now_text())
  on conflict (report_id) do update set opening = excluded.opening, closing = excluded.closing, transfers_out = excluded.transfers_out,
         note = excluded.note, updated_by = excluded.updated_by, updated_at = excluded.updated_at;
  foreach k in array array['opening', 'closing', 'transfers_out', 'note'] loop
    o := case k when 'opening' then to_jsonb(old.opening) when 'closing' then to_jsonb(old.closing) when 'transfers_out' then to_jsonb(old.transfers_out) else to_jsonb(old.note) end;
    n := case k when 'opening' then to_jsonb(p_opening) when 'closing' then to_jsonb(p_closing) when 'transfers_out' then to_jsonb(coalesce(p_out, 0)) else to_jsonb(nullif(trim(coalesce(p_note, '')), '')) end;
    if o is distinct from n and not (old.report_id is null and n = 'null'::jsonb) then
      insert into public.shift_recon_log(report_id, action, field, before, after, by_account) values (p_report, 'ke_toan', 'bank_' || k, o, n, a.id);
    end if;
  end loop;
  perform public.app_log('ke_toan_so_du', 'report=' || p_report);
end $$;

