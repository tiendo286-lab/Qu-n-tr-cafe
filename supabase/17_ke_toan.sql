-- Báo nhận hàng: ĐỦ / THIẾU (+ từng món thiếu). Cần ít nhất 1 ảnh hàng thực nhận. Gửi lại được (cập nhật).
create or replace function public.app_hd_receive(p_invoice bigint, p_report bigint, p_result text, p_note text, p_items jsonb) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts; i public.delivery_invoices; r public.shift_reports; n int;
begin
  a := public.app__need('chot_ca');
  select * into i from public.delivery_invoices where id = p_invoice for update;
  select * into r from public.shift_reports where id = p_report;
  if i.id is null or r.id is null then raise exception 'Không tìm thấy hóa đơn hoặc phiếu ca.'; end if;
  if i.branch_id <> r.branch_id or i.work_date > r.work_date then raise exception 'Hóa đơn không thuộc cơ sở / ngày của phiếu này.'; end if;
  if i.result is not null and i.received_report_id is distinct from p_report then raise exception 'Hóa đơn đã được báo nhận ở ca khác.'; end if;
  if p_result not in ('du', 'thieu') then raise exception 'Chọn ĐỦ hoặc THIẾU.'; end if;
  if not exists (select 1 from public.delivery_receipt_photos where invoice_id = p_invoice) then raise exception 'Chụp / tải ít nhất 1 ảnh hàng thực nhận trước khi báo.'; end if;
  delete from public.delivery_receipt_items where invoice_id = p_invoice;
  if p_result = 'thieu' then
    insert into public.delivery_receipt_items(invoice_id, item, qty)
    select p_invoice, trim(x ->> 'item'), coalesce(trim(x ->> 'qty'), '') from jsonb_array_elements(coalesce(p_items, '[]')) x where trim(coalesce(x ->> 'item', '')) <> '';
    get diagnostics n = row_count;
    if n = 0 then raise exception 'Báo THIẾU thì ghi ít nhất 1 mặt hàng thiếu và số lượng.'; end if;
  end if;
  update public.delivery_invoices set result = p_result, receive_note = nullif(trim(coalesce(p_note, '')), ''), received_by = a.id,
         received_at = public.vn_now_text(), received_report_id = p_report, updated_at = public.vn_now_text() where id = p_invoice;
  perform public.app_log('bao_nhan_hang', 'invoice=' || p_invoice || ' ' || p_result);
end $$;

-- ---------------------------------------------------------------- Chuyển khoản thực nhận (số dư BIDV theo ca)
-- Ca trước (cùng cơ sở) có số dư cuối đã nhập: gợi ý số dư đầu
create or replace function public.app__kt_prev_closing(r public.shift_reports) returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object('closing', b.closing, 'work_date', p.work_date, 'shift', p.shift)
    from public.shift_reports p join public.bank_shift_balances b on b.report_id = p.id
   where p.branch_id = r.branch_id and b.closing is not null
     and (p.work_date < r.work_date or (p.work_date = r.work_date and array_position(public.app__shifts(), p.shift) < array_position(public.app__shifts(), r.shift)))
   order by p.work_date desc, array_position(public.app__shifts(), p.shift) desc limit 1
$$;

create or replace function public.app__kt_bank_json(r public.shift_reports) returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object('report_id', r.id, 'status', r.status, 'recon_status', r.recon_status,
    'rev_start', e.d ->> 'rev_start', 'rev_end', e.d ->> 'rev_end',
    'pos_transfer', (e.d ->> 'pos_transfer')::bigint, 'reported_transfer', (e.d ->> 'reported_transfer')::bigint,
    'opening', b.opening, 'closing', b.closing, 'transfers_out', b.transfers_out, 'note', b.note,
    'received', case when b.opening is not null and b.closing is not null then b.closing - b.opening + coalesce(b.transfers_out, 0) end,
    'updated_by', public.app__acc_name(b.updated_by), 'updated_at', b.updated_at,
    'prev', public.app__kt_prev_closing(r),
    'locked', r.recon_status = 'hoan_thanh')
  from (select public.app__ca_eff(r.id) as d) e
  left join public.bank_shift_balances b on b.report_id = r.id
$$;

-- Kế toán: bảng một ngày (mọi cơ sở × ca)
create or replace function public.app_kt_bank_day(p_date text) returns jsonb
language plpgsql stable security definer set search_path = public as $$
begin
  perform public.app__need('ke_toan');
  return coalesce((select jsonb_agg(jsonb_build_object('branch_id', b.id, 'branch_code', coalesce(b.display_code, b.code), 'branch_name', b.name,
                      'shift', sh.name, 'row', case when r.id is null then null else public.app__kt_bank_json(r) end) order by b.sort_order, sh.sort_order)
                     from public.branches b
                     join public.branch_shifts bs on bs.branch_id = b.id and bs.enabled = 1
                     join public.shifts sh on sh.id = bs.shift_id and sh.status = 'Đang sử dụng'
                     left join public.shift_reports r on r.branch_id = b.id and r.work_date = p_date and r.shift = sh.name
                    where b.status = 'Đang hoạt động'), '[]');
end $$;

