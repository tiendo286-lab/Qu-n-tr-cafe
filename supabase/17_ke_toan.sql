create or replace function public.app__hd_json(i public.delivery_invoices) returns jsonb
language sql stable security definer set search_path = public as $$
  select to_jsonb(i) || jsonb_build_object(
    'branch_code', (select coalesce(b.display_code, b.code) from public.branches b where b.id = i.branch_id),
    'status', case when i.result is null then 'chua_nhan' when i.result = 'du' then 'du' else 'thieu' end,
    'created_by_name', public.app__acc_name(i.created_by), 'received_by_name', public.app__acc_name(i.received_by),
    'received_shift', (select r.shift from public.shift_reports r where r.id = i.received_report_id),
    'files', coalesce((select jsonb_agg(jsonb_build_object('id', f.id, 'path', f.path, 'name', f.name, 'mime', f.mime, 'size', f.size) order by f.id)
                       from public.delivery_invoice_files f where f.invoice_id = i.id), '[]'),
    'photos', coalesce((select jsonb_agg(jsonb_build_object('id', p.id, 'path', p.path, 'by', public.app__acc_name(p.created_by), 'at', p.created_at) order by p.id)
                        from public.delivery_receipt_photos p where p.invoice_id = i.id), '[]'),
    'items', coalesce((select jsonb_agg(jsonb_build_object('item', x.item, 'qty', x.qty) order by x.id)
                       from public.delivery_receipt_items x where x.invoice_id = i.id), '[]'))
$$;

-- Kế toán: danh sách hóa đơn
create or replace function public.app_kt_invoices(p_from text, p_to text, p_branch bigint) returns jsonb
language plpgsql stable security definer set search_path = public as $$
begin
  perform public.app__need('ke_toan');
  return coalesce((select jsonb_agg(public.app__hd_json(i) order by i.work_date desc, i.branch_id, i.id desc)
                     from public.delivery_invoices i
                    where (p_from is null or i.work_date >= p_from) and (p_to is null or i.work_date <= p_to)
                      and (p_branch is null or i.branch_id = p_branch)), '[]');
end $$;

create or replace function public.app_kt_invoice_save(p_id bigint, p_branch bigint, p_date text, p_note text) returns bigint
language plpgsql security definer set search_path = public as $$
declare a public.accounts; i public.delivery_invoices; nid bigint;
begin
  a := public.app__need('ke_toan');
  if coalesce(p_date, '') !~ '^\d{4}-\d{2}-\d{2}$' then raise exception 'Chọn ngày giao hàng.'; end if;
  if not exists (select 1 from public.branches where id = p_branch) then raise exception 'Chọn cơ sở nhận.'; end if;
  if p_id is null then
    insert into public.delivery_invoices(branch_id, work_date, note, created_by) values (p_branch, p_date, nullif(trim(coalesce(p_note, '')), ''), a.id) returning id into nid;
    perform public.app_log('ke_toan_them_hoa_don', 'invoice=' || nid);
    return nid;
  end if;
  select * into i from public.delivery_invoices where id = p_id for update;
  if i.id is null then raise exception 'Không tìm thấy hóa đơn.'; end if;
  if i.result is not null and (i.branch_id <> p_branch or i.work_date <> p_date) then raise exception 'Hóa đơn đã được báo nhận, không đổi cơ sở / ngày được.'; end if;
  update public.delivery_invoices set branch_id = p_branch, work_date = p_date, note = nullif(trim(coalesce(p_note, '')), ''), updated_at = public.vn_now_text() where id = p_id;
  return p_id;
end $$;

