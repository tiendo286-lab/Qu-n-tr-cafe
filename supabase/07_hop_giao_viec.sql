-- BƯỚC 7: HỌP & GIAO VIỆC + NHẮC VIỆC. Chạy sau 06. Chạy lại nhiều lần không sao.
--
-- GIẢ ĐỊNH tạm (đặc tả mục 8 còn chờ chốt — chủ hệ thống xem lại):
--  * Cuộc họp gồm: tên, ngày họp, ghi chú/biên bản ngắn. Chưa làm thêm chi tiết khác (mục 8.10).
--  * Tạo họp, giao việc, duyệt báo cáo: quyền "Họp & giao việc" (mặc định chỉ Chủ). Người duyệt không được là người nhận việc.
--  * Người nhận việc: tài khoản Quản lý tổng / Quản lý.
--  * Chọn người phụ trách + hạn → việc tự chuyển "Đã giao" và người đó nhận thông báo trong web.
--  * Nhiệm vụ đào tạo: lưu nhân viên + nội dung còn thiếu; liên kết phiếu đào tạo làm ở phần Đào tạo.
-- =====================================================================

create table if not exists public.meetings (
  id bigint generated by default as identity primary key,
  title text not null,
  meeting_date text not null,                -- YYYY-MM-DD
  note text,
  created_by bigint,
  created_at text not null default public.vn_now_text(),
  updated_at text not null default public.vn_now_text()
);

create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  meeting_id bigint references public.meetings(id) on delete set null,
  kind text not null default 'viec' check (kind in ('viec', 'dao_tao')),
  content text not null,
  handover_item_id bigint references public.handover_items(id) on delete set null,
  employee_id bigint references public.employees(id) on delete set null,   -- nhiệm vụ đào tạo: nhân viên cần đào tạo
  training_id bigint,                                                       -- phiếu đào tạo (phần Đào tạo)
  assignee_id bigint references public.accounts(id) on delete set null,
  due_date text,                                                            -- YYYY-MM-DD
  status text not null default 'chua_phan_cong'
    check (status in ('chua_phan_cong', 'da_giao', 'dang_xu_ly', 'cho_duyet', 'hoan_thanh')),
  report text,
  review_note text,
  created_by bigint,
  created_at text not null default public.vn_now_text(),
  assigned_at text, started_at text, submitted_at text,
  approved_by bigint, approved_at text,
  updated_at text not null default public.vn_now_text()
);
create index if not exists idx_tasks_assignee on public.tasks (assignee_id, status);
create unique index if not exists tasks_handover_once on public.tasks (handover_item_id) where handover_item_id is not null;

create table if not exists public.task_events (
  id bigint generated by default as identity primary key,
  task_id bigint not null references public.tasks(id) on delete cascade,
  at text not null default public.vn_now_text(),
  by_account bigint,
  action text not null,       -- tao, giao, bat_dau, bao_cao, duyet, lam_lai, sua
  note text
);

do $$
declare t text;
begin
  foreach t in array array['meetings', 'tasks', 'task_events'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon, authenticated', t);
  end loop;
end $$;

-- ---------------------------------------------------------------- Quyền
create or replace function public.app__perm_keys() returns text[]
language sql immutable as $$
  select array['order_ca','xem_lich_minh','xem_tat_ca','xep_lich','chot_tuan','sua_order_sau_han',
    'quan_ly_nhan_vien','cai_gio_order','sua_danh_muc','bao_cao','danh_gia','phan_quyen','xoa_du_lieu_tuan','du_lieu',
    'chot_ca','doi_soat','mo_lai_phieu_ca','hop_giao_viec','nhan_viec']
$$;

create or replace function public.app_can(p text) returns boolean
language plpgsql stable security definer set search_path = public as $$
declare a public.accounts;
begin
  a := public.app_account();
  if a.id is null then return false; end if;
  if a.system_role = 'chu' then return true; end if;
  if p in ('phan_quyen', 'xoa_du_lieu_tuan', 'du_lieu') then return false; end if;
  if p = 'chot_ca' then return true; end if;                                    -- ai cũng chốt ca được
  if p = 'nhan_viec' then return a.system_role in ('ql_tong', 'ql'); end if;     -- quản lý nhận việc được giao
  if a.system_role = 'nv' then
    if p in ('order_ca', 'xem_lich_minh') then return true; end if;
    if p <> 'xem_tat_ca' then return false; end if;
  end if;
  return coalesce((select r.allowed = 1 from public.role_permissions r where r.role = a.system_role and r.perm = p), false);
end $$;

create or replace function public.app_set_perm(p_role text, p_perm text, p_allowed boolean) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.app_can('phan_quyen') then raise exception 'Chỉ Chủ được sửa phân quyền.'; end if;
  if p_role not in ('ql_tong', 'ql', 'nv') then raise exception 'Vai trò không hợp lệ.'; end if;
  if not (p_perm = any(public.app__perm_keys())) or p_perm in ('phan_quyen', 'xoa_du_lieu_tuan', 'du_lieu', 'chot_ca', 'nhan_viec') then
    raise exception 'Quyền không hợp lệ.';
  end if;
  if p_role = 'nv' and p_perm <> 'xem_tat_ca' then raise exception 'Quyền này không cấp được cho Nhân viên.'; end if;
  insert into public.role_permissions(role, perm, allowed, updated_at)
  values (p_role, p_perm, case when p_allowed then 1 else 0 end, public.vn_now_text())
  on conflict (role, perm) do update set allowed = excluded.allowed, updated_at = excluded.updated_at;
  perform public.app_log('phan_quyen', p_role || '.' || p_perm || '=' || p_allowed);
end $$;

insert into public.role_permissions(role, perm, allowed) values ('ql_tong', 'hop_giao_viec', 0), ('ql', 'hop_giao_viec', 0)
on conflict (role, perm) do nothing;

-- ---------------------------------------------------------------- Hàm phụ
-- Tài khoản có quyền duyệt (Chủ + vai trò được bật "Họp & giao việc")
create or replace function public.app__viec_approvers() returns setof bigint
language sql stable security definer set search_path = public as $$
  select a.id from public.accounts a left join public.employees e on e.id = a.employee_id
   where a.locked = 0 and (a.employee_id is null or e.status = 'Đang làm')
     and (a.system_role = 'chu' or exists (select 1 from public.role_permissions r where r.role = a.system_role and r.perm = 'hop_giao_viec' and r.allowed = 1))
$$;

create or replace function public.app__viec_event(p_task bigint, p_action text, p_note text) returns void
language sql security definer set search_path = public as $$
  insert into public.task_events(task_id, by_account, action, note) values (p_task, (public.app_account()).id, p_action, p_note)
$$;

-- Một việc đầy đủ thông tin để hiển thị
create or replace function public.app__viec_json(t public.tasks) returns jsonb
language sql stable security definer set search_path = public as $$
  select to_jsonb(t) || jsonb_build_object(
    'assignee_name', public.app__acc_name(t.assignee_id),
    'created_by_name', public.app__acc_name(t.created_by),
    'approved_by_name', public.app__acc_name(t.approved_by),
    'meeting_title', (select m.title from public.meetings m where m.id = t.meeting_id),
    'meeting_date', (select m.meeting_date from public.meetings m where m.id = t.meeting_id),
    'employee', (select e.code || ' – ' || e.name from public.employees e where e.id = t.employee_id),
    'source', (select jsonb_build_object('report_id', r.id, 'branch', coalesce(b.display_code, b.code), 'work_date', r.work_date, 'shift', r.shift,
                                         'content', h.content, 'by', public.app__acc_name(h.created_by))
                 from public.handover_items h join public.shift_reports r on r.id = h.report_id join public.branches b on b.id = h.branch_id
                where h.id = t.handover_item_id),
    'overdue', t.status not in ('hoan_thanh', 'cho_duyet') and t.due_date is not null and t.due_date < to_char(public.vn_now(), 'YYYY-MM-DD'),
    'events', coalesce((select jsonb_agg(jsonb_build_object('at', ev.at, 'by', public.app__acc_name(ev.by_account), 'action', ev.action, 'note', ev.note) order by ev.id)
                          from public.task_events ev where ev.task_id = t.id), '[]'))
$$;

-- ---------------------------------------------------------------- Cuộc họp
create or replace function public.app_viec_meetings() returns jsonb
language plpgsql stable security definer set search_path = public as $$
begin
  perform public.app__need('hop_giao_viec');
  return coalesce((select jsonb_agg(jsonb_build_object('id', m.id, 'title', m.title, 'meeting_date', m.meeting_date, 'note', m.note,
      'created_by', public.app__acc_name(m.created_by),
      'total', (select count(*) from public.tasks t where t.meeting_id = m.id),
      'done', (select count(*) from public.tasks t where t.meeting_id = m.id and t.status = 'hoan_thanh'),
      'waiting', (select count(*) from public.tasks t where t.meeting_id = m.id and t.status = 'cho_duyet'))
    order by m.meeting_date desc, m.id desc) from public.meetings m), '[]');
end $$;

create or replace function public.app_viec_meeting_save(p_id bigint, p_title text, p_date text, p_note text) returns bigint
language plpgsql security definer set search_path = public as $$
declare a public.accounts; nid bigint;
begin
  a := public.app__need('hop_giao_viec');
  if trim(coalesce(p_title, '')) = '' then raise exception 'Nhập tên cuộc họp.'; end if;
  if coalesce(p_date, '') !~ '^\d{4}-\d{2}-\d{2}$' then raise exception 'Chọn ngày họp.'; end if;
  if p_id is null then
    insert into public.meetings(title, meeting_date, note, created_by) values (trim(p_title), p_date, nullif(trim(coalesce(p_note, '')), ''), a.id) returning id into nid;
    perform public.app_log('tao_cuoc_hop', 'meeting=' || nid);
    return nid;
  end if;
  update public.meetings set title = trim(p_title), meeting_date = p_date, note = nullif(trim(coalesce(p_note, '')), ''), updated_at = public.vn_now_text() where id = p_id;
  if not found then raise exception 'Không tìm thấy cuộc họp.'; end if;
  return p_id;
end $$;

create or replace function public.app_viec_meeting_delete(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
begin
  perform public.app__need('hop_giao_viec');
  if exists (select 1 from public.tasks where meeting_id = p_id) then raise exception 'Cuộc họp đã có công việc. Hãy xóa các việc trước.'; end if;
  delete from public.meetings where id = p_id;
end $$;

create or replace function public.app_viec_meeting_get(p_id bigint) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare m public.meetings;
begin
  perform public.app__need('hop_giao_viec');
  select * into m from public.meetings where id = p_id;
  if m.id is null then raise exception 'Không tìm thấy cuộc họp.'; end if;
  return to_jsonb(m) || jsonb_build_object(
    'created_by_name', public.app__acc_name(m.created_by),
    'tasks', coalesce((select jsonb_agg(public.app__viec_json(t) order by t.id) from public.tasks t where t.meeting_id = m.id), '[]'),
    -- nội dung bàn giao chưa hoàn thành, chưa đưa vào việc nào
    'open_handover', coalesce((select jsonb_agg(jsonb_build_object('id', h.id, 'content', h.content, 'report_id', r.id, 'branch', coalesce(b.display_code, b.code),
                        'work_date', r.work_date, 'shift', r.shift, 'by', public.app__acc_name(h.created_by)) order by r.work_date, b.sort_order, h.id)
                       from public.handover_items h join public.shift_reports r on r.id = h.report_id join public.branches b on b.id = h.branch_id
                      where h.done_at is null and h.task_id is null), '[]'),
    'managers', coalesce((select jsonb_agg(jsonb_build_object('id', a.id, 'name', public.app__acc_name(a.id), 'role', a.system_role) order by a.system_role, public.app__acc_name(a.id))
                           from public.accounts a left join public.employees e on e.id = a.employee_id
                          where a.system_role in ('ql_tong', 'ql') and a.locked = 0 and (a.employee_id is null or e.status = 'Đang làm')), '[]'),
    'employees', coalesce((select jsonb_agg(jsonb_build_object('id', e.id, 'code', e.code, 'name', e.name, 'rank', e.rank) order by e.code)
                            from public.employees e where e.status = 'Đang làm'), '[]'));
end $$;

-- ---------------------------------------------------------------- Công việc
create or replace function public.app_viec_add(p_meeting bigint, p jsonb) returns bigint
language plpgsql security definer set search_path = public as $$
declare a public.accounts; nid bigint; h public.handover_items; kind text := coalesce(p ->> 'kind', 'viec'); content text;
begin
  a := public.app__need('hop_giao_viec');
  if not exists (select 1 from public.meetings where id = p_meeting) then raise exception 'Không tìm thấy cuộc họp.'; end if;
  content := trim(coalesce(p ->> 'content', ''));
  if (p ->> 'handover_item_id') is not null then
    select * into h from public.handover_items where id = (p ->> 'handover_item_id')::bigint for update;
    if h.id is null or h.done_at is not null then raise exception 'Nội dung bàn giao này đã xong hoặc không còn.'; end if;
    if h.task_id is not null then raise exception 'Nội dung bàn giao này đã được đưa vào một công việc khác.'; end if;
    if content = '' then content := h.content; end if;
  end if;
  if content = '' then raise exception 'Nhập nội dung công việc.'; end if;
  if kind = 'dao_tao' and (p ->> 'employee_id') is null then raise exception 'Chọn nhân viên cần đào tạo.'; end if;
  insert into public.tasks(meeting_id, kind, content, handover_item_id, employee_id, created_by)
  values (p_meeting, kind, content, h.id, case when kind = 'dao_tao' then (p ->> 'employee_id')::bigint end, a.id)
  returning id into nid;
  if h.id is not null then update public.handover_items set task_id = nid where id = h.id; end if;
  perform public.app__viec_event(nid, 'tao', null);
  if (p ->> 'assignee_id') is not null or (p ->> 'due_date') is not null then
    perform public.app_viec_update(nid, p);
  end if;
  return nid;
end $$;

-- Sửa nội dung / người phụ trách / hạn. Có đủ người + hạn → "Đã giao" (báo cho người nhận).
create or replace function public.app_viec_update(p_task bigint, p jsonb) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts; t public.tasks; new_ass bigint; new_due text; new_content text;
begin
  a := public.app__need('hop_giao_viec');
  select * into t from public.tasks where id = p_task for update;
  if t.id is null then raise exception 'Không tìm thấy công việc.'; end if;
  if t.status in ('cho_duyet', 'hoan_thanh') then raise exception 'Việc đang chờ duyệt hoặc đã hoàn thành, không sửa được.'; end if;
  new_ass := case when p ? 'assignee_id' then nullif(p ->> 'assignee_id', '')::bigint else t.assignee_id end;
  new_due := case when p ? 'due_date' then nullif(p ->> 'due_date', '') else t.due_date end;
  new_content := case when p ? 'content' and trim(coalesce(p ->> 'content', '')) <> '' then trim(p ->> 'content') else t.content end;
  if new_due is not null and new_due !~ '^\d{4}-\d{2}-\d{2}$' then raise exception 'Hạn hoàn thành không hợp lệ.'; end if;
  if new_ass is not null and not exists (select 1 from public.accounts where id = new_ass and system_role in ('ql_tong', 'ql') and locked = 0) then
    raise exception 'Chỉ giao được cho Quản lý tổng hoặc Quản lý.';
  end if;
  if new_ass is not null and new_ass = a.id then raise exception 'Không tự giao việc cho chính mình (người giao là người duyệt).'; end if;
  update public.tasks set assignee_id = new_ass, due_date = new_due, content = new_content, updated_at = public.vn_now_text(),
         status = case when new_ass is null then 'chua_phan_cong'
                       when new_due is null then (case when t.status = 'chua_phan_cong' then 'chua_phan_cong' else t.status end)
                       when t.status = 'chua_phan_cong' or new_ass is distinct from t.assignee_id then 'da_giao' else t.status end,
         assigned_at = case when new_ass is not null and new_due is not null and (t.status = 'chua_phan_cong' or new_ass is distinct from t.assignee_id) then public.vn_now_text() else t.assigned_at end,
         started_at = case when new_ass is distinct from t.assignee_id then null else t.started_at end
   where id = t.id;
  if new_ass is not null and new_due is not null and (t.status = 'chua_phan_cong' or new_ass is distinct from t.assignee_id) then
    perform public.app__viec_event(t.id, 'giao', public.app__acc_name(new_ass) || ' · hạn ' || to_char(new_due::date, 'DD/MM/YYYY'));
    perform public.app__notify(new_ass, 'Việc mới được giao',
      new_content || E'\nHạn: ' || to_char(new_due::date, 'DD/MM/YYYY') || ' · Người giao: ' || public.app__acc_name(a.id), '/viec');
  elsif new_due is distinct from t.due_date or new_content is distinct from t.content then
    perform public.app__viec_event(t.id, 'sua', case when new_due is distinct from t.due_date then 'Đổi hạn: ' || coalesce(to_char(new_due::date, 'DD/MM/YYYY'), 'không hạn') end);
  end if;
end $$;

create or replace function public.app_viec_delete(p_task bigint) returns void
language plpgsql security definer set search_path = public as $$
declare t public.tasks;
begin
  perform public.app__need('hop_giao_viec');
  select * into t from public.tasks where id = p_task;
  if t.id is null then return; end if;
  if t.status = 'hoan_thanh' then raise exception 'Việc đã hoàn thành, không xóa được.'; end if;
  update public.handover_items set task_id = null where task_id = t.id;
  delete from public.tasks where id = t.id;
  perform public.app_log('xoa_cong_viec', 'task=' || t.id);
end $$;

-- Tất cả việc (bảng theo dõi của người giao)
create or replace function public.app_viec_all() returns jsonb
language plpgsql stable security definer set search_path = public as $$
begin
  perform public.app__need('hop_giao_viec');
  return coalesce((select jsonb_agg(public.app__viec_json(t) order by t.due_date nulls last, t.id)
                     from public.tasks t where t.status <> 'hoan_thanh' or t.approved_at >= to_char(public.vn_now() - interval '30 days', 'YYYY-MM-DD')), '[]');
end $$;

-- ---------------------------------------------------------------- Người nhận việc
create or replace function public.app_viec_mine() returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare a public.accounts;
begin
  a := public.app__need('nhan_viec');
  return coalesce((select jsonb_agg(public.app__viec_json(t) order by t.due_date nulls last, t.id)
                     from public.tasks t where t.assignee_id = a.id and t.status <> 'chua_phan_cong'
                      and (t.status <> 'hoan_thanh' or t.approved_at >= to_char(public.vn_now() - interval '30 days', 'YYYY-MM-DD'))), '[]');
end $$;

create or replace function public.app_viec_start(p_task bigint) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts;
begin
  a := public.app__need('nhan_viec');
  update public.tasks set status = 'dang_xu_ly', started_at = public.vn_now_text(), updated_at = public.vn_now_text()
   where id = p_task and assignee_id = a.id and status = 'da_giao';
  if not found then raise exception 'Việc này không ở trạng thái Đã giao cho bạn.'; end if;
  perform public.app__viec_event(p_task, 'bat_dau', null);
end $$;

create or replace function public.app_viec_submit(p_task bigint, p_report text) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts; t public.tasks; x bigint;
begin
  a := public.app__need('nhan_viec');
  if trim(coalesce(p_report, '')) = '' then raise exception 'Nhập báo cáo kết quả xử lý.'; end if;
  update public.tasks set status = 'cho_duyet', report = trim(p_report), submitted_at = public.vn_now_text(), updated_at = public.vn_now_text(),
         started_at = coalesce(started_at, public.vn_now_text())
   where id = p_task and assignee_id = a.id and status in ('da_giao', 'dang_xu_ly')
  returning * into t;
  if t.id is null then raise exception 'Chỉ người được giao mới gửi báo cáo, và việc phải đang ở trạng thái Đã giao / Đang xử lý.'; end if;
  perform public.app__viec_event(t.id, 'bao_cao', trim(p_report));
  for x in select * from public.app__viec_approvers() loop
    if x <> a.id then
      perform public.app__notify(x, 'Báo cáo chờ duyệt', public.app__acc_name(a.id) || ': ' || t.content, '/quan-ly/hop?tab=cho-duyet');
    end if;
  end loop;
end $$;

-- Duyệt (p_ok = true) hoặc yêu cầu làm lại (kèm ý kiến)
create or replace function public.app_viec_review(p_task bigint, p_ok boolean, p_note text) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts; t public.tasks;
begin
  a := public.app__need('hop_giao_viec');
  select * into t from public.tasks where id = p_task for update;
  if t.id is null then raise exception 'Không tìm thấy công việc.'; end if;
  if t.status <> 'cho_duyet' then raise exception 'Việc này không ở trạng thái Chờ duyệt.'; end if;
  if t.assignee_id = a.id then raise exception 'Không tự duyệt việc được giao cho chính mình.'; end if;
  if p_ok then
    update public.tasks set status = 'hoan_thanh', approved_by = a.id, approved_at = public.vn_now_text(), review_note = nullif(trim(coalesce(p_note, '')), ''),
           updated_at = public.vn_now_text() where id = t.id;
    -- cập nhật về nội dung bàn giao gốc
    update public.handover_items set done_at = public.vn_now_text(), done_by = a.id where id = t.handover_item_id and done_at is null;
    perform public.app__viec_event(t.id, 'duyet', nullif(trim(coalesce(p_note, '')), ''));
    perform public.app__notify(t.assignee_id, 'Việc đã được duyệt hoàn thành', t.content, '/viec');
  else
    if trim(coalesce(p_note, '')) = '' then raise exception 'Ghi ý kiến khi yêu cầu làm lại.'; end if;
    update public.tasks set status = 'dang_xu_ly', review_note = trim(p_note), updated_at = public.vn_now_text() where id = t.id;
    perform public.app__viec_event(t.id, 'lam_lai', trim(p_note));
    perform public.app__notify(t.assignee_id, 'Yêu cầu làm lại', t.content || E'\nÝ kiến: ' || trim(p_note), '/viec');
  end if;
end $$;

-- Nhắc việc khi mở app: số việc của chính người đang đăng nhập (+ số báo cáo chờ mình duyệt)
create or replace function public.app_viec_reminder() returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare a public.accounts; today text := to_char(public.vn_now(), 'YYYY-MM-DD');
begin
  a := public.app_account();
  if a.id is null then return null; end if;
  return jsonb_build_object(
    'overdue', (select count(*) from public.tasks where assignee_id = a.id and status in ('da_giao', 'dang_xu_ly') and due_date < today),
    'today', (select count(*) from public.tasks where assignee_id = a.id and status in ('da_giao', 'dang_xu_ly') and due_date = today),
    'open', (select count(*) from public.tasks where assignee_id = a.id and status in ('da_giao', 'dang_xu_ly')),
    'waiting', (select count(*) from public.tasks where assignee_id = a.id and status = 'cho_duyet'),
    'to_review', case when public.app_can('hop_giao_viec') then (select count(*) from public.tasks where status = 'cho_duyet' and assignee_id is distinct from a.id) else 0 end,
    'items', coalesce((select jsonb_agg(jsonb_build_object('id', t.id, 'content', t.content, 'due_date', t.due_date, 'status', t.status, 'kind', t.kind,
                         'group', case when t.status = 'cho_duyet' then 'waiting' when t.due_date < today then 'overdue' when t.due_date = today then 'today' else 'open' end)
                         order by t.due_date nulls last, t.id)
                        from public.tasks t where t.assignee_id = a.id and t.status in ('da_giao', 'dang_xu_ly', 'cho_duyet')), '[]'));
end $$;

-- Phiếu chốt ca: việc đã giao qua tab Họp không được đánh dấu xong ở phiếu ca (đã có trong 06), giữ nguyên.

-- ---------------------------------------------------------------- Cấp quyền gọi hàm
do $$
declare f record;
begin
  for f in select p.oid::regprocedure as sig, p.proname from pg_proc p join pg_namespace n on n.oid = p.pronamespace
            where n.nspname = 'public' and (p.proname like 'app\_viec\_%' or p.proname like 'app\_\_viec\_%'
                  or p.proname in ('app__perm_keys', 'app_can', 'app_set_perm')) loop
    execute format('revoke execute on function %s from public, anon', f.sig);
    if f.proname like 'app\_\_%' then
      execute format('revoke execute on function %s from authenticated', f.sig);
    else
      execute format('grant execute on function %s to authenticated', f.sig);
    end if;
  end loop;
end $$;
