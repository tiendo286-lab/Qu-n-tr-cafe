-- Hạng mục "Nhập hàng" của Đối soát ca: chỉ đánh dấu được khi đã đối soát hết hàng nhận trong ca
create or replace function public.app_ca_check(p_id bigint, p_item text, p_on boolean) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts; r public.shift_reports; n int;
begin
  a := public.app__need('doi_soat');
  select * into r from public.shift_reports where id = p_id for update;
  if r.id is null then raise exception 'Không tìm thấy phiếu.'; end if;
  if r.status <> 'hoan_thanh' then raise exception 'Nhân viên chưa hoàn thành phiếu này.'; end if;
  if r.recon_status = 'hoan_thanh' then raise exception 'Phiếu đã HOÀN THÀNH ĐỐI SOÁT. Bấm "Mở lại đối soát" trước khi sửa.'; end if;
  if not (p_item = any(public.app__ca_check_items())) then raise exception 'Hạng mục không hợp lệ.'; end if;
  if p_item = any(public.app__ca_money_items()) then raise exception 'Hạng mục tiền: chọn kết quả KHỚP / THIẾU / THỪA.'; end if;
  if p_item = 'nhap_hang' and p_on then
    select count(*) into n from public.delivery_invoices d join public.delivery_lines l on l.invoice_id = d.id
     where d.received_report_id = p_id and l.checked_at is null;
    if n > 0 then raise exception 'Còn % món hàng nhận trong ca chưa đối soát. Bấm "Đối soát hàng" ở mục 7.', n; end if;
  end if;
  if p_on then
    insert into public.shift_report_checks(report_id, item, checked_by, checked_at) values (p_id, p_item, a.id, public.vn_now_text())
    on conflict (report_id, item) do nothing;
  else
    delete from public.shift_report_checks where report_id = p_id and item = p_item;
  end if;
  perform public.app__ca_auto_finish(p_id, a.id);
  perform public.app_log('doi_soat_ca', 'report=' || p_id || ' ' || p_item || '=' || p_on);
end $$;

