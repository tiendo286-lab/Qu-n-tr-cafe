-- Tạo hóa đơn từ file Excel (p.lines đã đọc trên trình duyệt). p.merge_id: ghép vào phiếu "nhận không hóa đơn".
create or replace function public.app_nh_create(p jsonb) returns bigint
language plpgsql security definer set search_path = public as $$
declare a public.accounts; br bigint := nullif(p ->> 'branch_id', '')::bigint; dn text := nullif(trim(coalesce(p ->> 'doc_no', '')), '');
        sa text := nullif(trim(coalesce(p ->> 'ship_at', '')), ''); kc text := nullif(trim(coalesce(p ->> 'kho_code', '')), '');
        mid bigint := nullif(p ->> 'merge_id', '')::bigint; nid bigint; x jsonb; k int := 0; tg public.delivery_invoices; lid bigint; n_mis int; b public.branches;
begin
  a := public.app__need('ke_toan');
  if br is null or not exists (select 1 from public.branches where id = br) then raise exception 'Chọn cơ sở nhận hàng.'; end if;
  if dn is null then raise exception 'File không có Số đơn.'; end if;
  if exists (select 1 from public.delivery_invoices where upper(doc_no) = upper(dn)) then raise exception 'Hóa đơn % đã tải lên rồi.', dn; end if;
  if sa is null or sa !~ '^\d{4}-\d{2}-\d{2}' then raise exception 'File không có Thời gian xuất hợp lệ.'; end if;
  if jsonb_array_length(coalesce(p -> 'lines', '[]')) = 0 then raise exception 'File không có dòng hàng nào.'; end if;
  if kc is not null then
    insert into public.nh_kho_map(kho_code, kho_name, branch_id) values (kc, p ->> 'kho_name', br)
    on conflict (kho_code) do update set branch_id = excluded.branch_id, kho_name = excluded.kho_name;
  end if;
  select * into b from public.branches where id = br;
  if mid is null then
    insert into public.delivery_invoices(branch_id, work_date, note, created_by, kind, state, doc_no, total, ship_at, kho_code, kho_name, ref, src_creator)
    values (br, left(sa, 10), nullif(trim(coalesce(p ->> 'note', '')), ''), a.id, 'hoa_don', 'dang_chuyen', dn, nullif(p ->> 'total', '')::bigint, sa, kc,
            p ->> 'kho_name', p ->> 'ref', p ->> 'src_creator') returning id into nid;
    for x in select * from jsonb_array_elements(p -> 'lines') loop
      k := k + 1;
      insert into public.delivery_lines(invoice_id, sort, code, name, unit, qty_invoice, price, amount)
      values (nid, k, nullif(trim(coalesce(x ->> 'code', '')), ''), coalesce(nullif(trim(coalesce(x ->> 'name', '')), ''), '(không tên)'), nullif(trim(coalesce(x ->> 'unit', '')), ''),
              coalesce(nullif(x ->> 'qty', '')::numeric, 0), nullif(x ->> 'price', '')::numeric::bigint, nullif(x ->> 'amount', '')::numeric::bigint);
    end loop;
    perform public.app__nh_notify(br, 'Hàng kho tổng đang chuyển tới ' || coalesce(b.display_code, b.code),
      'Hóa đơn ' || dn || ' · ' || k || ' món. Hàng tới thì nhân viên kiểm từng món trong phiếu chốt ca (mục 7).', '/ca', true, false);
    perform public.app_log('nhap_hang_hoa_don', 'id=' || nid || ' ' || dn);
    return nid;
  end if;
  -- ghép vào phiếu nhận không hóa đơn
  select * into tg from public.delivery_invoices where id = mid for update;
  if tg.id is null or tg.state <> 'cho_hoa_don' then raise exception 'Phiếu nhận hàng cần ghép không còn ở trạng thái Chờ hóa đơn.'; end if;
  if tg.branch_id <> br then raise exception 'Hóa đơn này của cơ sở khác với phiếu nhận hàng.'; end if;
  for x in select * from jsonb_array_elements(p -> 'lines') loop
    k := k + 1; lid := null;
    select l.id into lid from public.delivery_lines l where l.invoice_id = mid and l.qty_invoice is null
       and ((nullif(trim(coalesce(x ->> 'code', '')), '') is not null and upper(l.code) = upper(trim(x ->> 'code')))
            or public.app__nh_norm(l.name) = public.app__nh_norm(x ->> 'name'))
     order by (upper(coalesce(l.code, '')) = upper(trim(coalesce(x ->> 'code', '')))) desc, l.id limit 1;
    if lid is not null then
      update public.delivery_lines set code = coalesce(nullif(trim(coalesce(x ->> 'code', '')), ''), code), name = coalesce(nullif(trim(coalesce(x ->> 'name', '')), ''), name),
             unit = coalesce(nullif(trim(coalesce(x ->> 'unit', '')), ''), unit), qty_invoice = coalesce(nullif(x ->> 'qty', '')::numeric, 0),
             price = nullif(x ->> 'price', '')::numeric::bigint, amount = nullif(x ->> 'amount', '')::numeric::bigint, sort = k where id = lid;
    else
      insert into public.delivery_lines(invoice_id, sort, code, name, unit, qty_invoice, price, amount, qty_received)
      values (mid, k, nullif(trim(coalesce(x ->> 'code', '')), ''), coalesce(nullif(trim(coalesce(x ->> 'name', '')), ''), '(không tên)'), nullif(trim(coalesce(x ->> 'unit', '')), ''),
              coalesce(nullif(x ->> 'qty', '')::numeric, 0), nullif(x ->> 'price', '')::numeric::bigint, nullif(x ->> 'amount', '')::numeric::bigint, 0);
    end if;
  end loop;
  update public.delivery_lines set sort = sort + 1000 where invoice_id = mid and qty_invoice is null;
  update public.delivery_invoices set kind = 'hoa_don', state = 'da_nhan', doc_no = dn, total = nullif(p ->> 'total', '')::bigint, ship_at = sa, kho_code = kc,
         kho_name = p ->> 'kho_name', ref = p ->> 'ref', src_creator = p ->> 'src_creator', matched_by = a.id, matched_at = public.vn_now_text(), updated_at = public.vn_now_text()
   where id = mid;
  select count(*) into n_mis from public.delivery_lines l where l.invoice_id = mid and l.qty_invoice is distinct from coalesce(l.qty_checked, l.qty_received)
     and not (l.qty_invoice is null and coalesce(l.qty_checked, l.qty_received, 0) = 0);
  if n_mis > 0 then
    perform public.app__nh_notify(br, 'Nhận hàng lệch hóa đơn ' || dn || ' · ' || coalesce(b.display_code, b.code),
      n_mis || ' món khác số lượng so với hóa đơn (sau khi ghép phiếu nhận không hóa đơn).', '/ke-toan/hoa-don', true, true);
  end if;
  perform public.app_log('nhap_hang_ghep_hoa_don', 'id=' || mid || ' ' || dn);
  return mid;
end $$;

-- Xóa hóa đơn đang chuyển (chưa ai báo nhận). Trả về đường dẫn tệp để web xóa khỏi kho.
create or replace function public.app_nh_delete(p_id bigint) returns jsonb
language plpgsql security definer set search_path = public as $$
declare i public.delivery_invoices; paths jsonb;
begin
  perform public.app__need('ke_toan');
  select * into i from public.delivery_invoices where id = p_id for update;
  if i.id is null then return '[]'; end if;
  if i.state <> 'dang_chuyen' then raise exception 'Hàng đã được báo nhận, không xóa hóa đơn được.'; end if;
  select coalesce(jsonb_agg(path), '[]') into paths from (select path from public.delivery_invoice_files where invoice_id = p_id
                                                      union all select path from public.delivery_receipt_photos where invoice_id = p_id) x;
  delete from public.delivery_invoices where id = p_id;
  perform public.app_log('nhap_hang_xoa_hoa_don', 'id=' || p_id || ' ' || coalesce(i.doc_no, ''));
  return paths;
end $$;

-- Danh sách (kế toán / quản lý): theo tháng + mọi phiếu còn thiếu hồ sơ
create or replace function public.app_nh_list(p_month text, p_branch bigint) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare m boolean;
begin
  if not (public.app_can('ke_toan') or public.app_can('doi_soat')) then raise exception 'Bạn không có quyền xem nhập hàng.'; end if;
  perform public.app__fin_month_ok(p_month);
  m := public.app__nh_money();
  return jsonb_build_object(
    'rows', coalesce((select jsonb_agg(public.app__nh_json(i, m) order by i.work_date desc, i.id desc) from public.delivery_invoices i
                       where left(i.work_date, 7) = p_month and (p_branch is null or i.branch_id = p_branch)), '[]'),
    'open', coalesce((select jsonb_agg(j order by j ->> 'work_date', (j ->> 'id')::bigint) from (
                        select public.app__nh_json(i, m) j from public.delivery_invoices i where (p_branch is null or i.branch_id = p_branch)
                          and (i.state <> 'da_nhan' or i.recon_at is null or exists (select 1 from public.delivery_lines l where l.invoice_id = i.id and coalesce(l.qty_checked, l.qty_received, 0) > 0
                               and not exists (select 1 from public.delivery_photo_lines pl where pl.line_id = l.id)))) z
                       where jsonb_array_length(j -> 'missing') > 0), '[]'),
    'by_branch', coalesce((select jsonb_agg(jsonb_build_object('branch_id', b.id, 'code', coalesce(b.display_code, b.code),
                       'total', case when m then (select coalesce(sum(i.total), 0) from public.delivery_invoices i where i.branch_id = b.id and left(i.work_date, 7) = p_month and i.doc_no is not null) end,
                       'count', (select count(*) from public.delivery_invoices i where i.branch_id = b.id and left(i.work_date, 7) = p_month)) order by b.sort_order)
                     from public.branches b where b.status = 'Đang hoạt động'), '[]'),
    'money', m, 'kt', public.app_can('ke_toan'));
end $$;

-- ---------------------------------------------------------------- Nhân viên (phiếu chốt ca)
create or replace function public.app_nh_for_report(p_report bigint) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare r public.shift_reports; m boolean;
begin
  if not (public.app_can('chot_ca') or public.app_can('doi_soat') or public.app_can('ke_toan')) then raise exception 'Bạn không có quyền.'; end if;
  select * into r from public.shift_reports where id = p_report;
  if r.id is null then raise exception 'Không tìm thấy phiếu.'; end if;
  m := public.app__nh_money();
  return jsonb_build_object(
    'rows', coalesce((select jsonb_agg(public.app__nh_json(i, m) order by i.work_date, i.id) from public.delivery_invoices i
                       where i.branch_id = r.branch_id and ((i.state = 'dang_chuyen' and i.work_date <= r.work_date) or i.received_report_id = r.id)), '[]'),
    'catalog', coalesce((select jsonb_agg(jsonb_build_object('code', z.code, 'name', z.name, 'unit', z.unit) order by z.name) from (
                          select distinct on (public.app__nh_norm(l.name)) l.code, l.name, l.unit from public.delivery_lines l
                           where l.qty_invoice is not null order by public.app__nh_norm(l.name), l.id desc limit 400) z), '[]'),
    'today', public.app__nh_today());
end $$;

create or replace function public.app__nh_staff_can(i public.delivery_invoices, r public.shift_reports) returns void
language plpgsql stable security definer set search_path = public as $$
begin
  if i.id is null or r.id is null then raise exception 'Không tìm thấy hàng hoặc phiếu ca.'; end if;
  if i.branch_id <> r.branch_id then raise exception 'Hàng này của cơ sở khác.'; end if;
  if i.state = 'dang_chuyen' then
    if i.work_date > r.work_date then raise exception 'Hóa đơn này giao ngày % — chưa tới ngày.', to_char(i.work_date::date, 'DD/MM'); end if;
    return;
  end if;
  if i.received_report_id is distinct from r.id then raise exception 'Hàng này đã được báo nhận ở ca khác.'; end if;
  if i.recon_at is not null then raise exception 'Quản lý đã đối soát hàng này nên không sửa được nữa.'; end if;
  if i.received_date <> public.app__nh_today() then raise exception 'Chỉ sửa được báo cáo nhận hàng trong ngày nhận.'; end if;
end $$;

-- Báo nhận hàng có hóa đơn: số thực nhận từng món
create or replace function public.app_nh_receive(p_id bigint, p_report bigint, p_lines jsonb, p_note text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare a public.accounts; i public.delivery_invoices; r public.shift_reports; x jsonb; n_mis int; first boolean; b public.branches;
begin
  a := public.app__need('chot_ca');
  select * into i from public.delivery_invoices where id = p_id for update;
  select * into r from public.shift_reports where id = p_report;
  perform public.app__nh_staff_can(i, r);
  if i.state = 'cho_hoa_don' then raise exception 'Phiếu nhận không hóa đơn: dùng nút Lưu của phiếu đó.'; end if;
  if exists (select 1 from public.delivery_lines l where l.invoice_id = p_id
              and not exists (select 1 from jsonb_array_elements(coalesce(p_lines, '[]')) y where (y ->> 'id')::bigint = l.id and nullif(y ->> 'qty', '') is not null)) then
    raise exception 'Nhập số thực nhận cho tất cả các món (bấm "Đủ" nếu nhận đủ).';
  end if;
  for x in select * from jsonb_array_elements(p_lines) loop
    if (x ->> 'qty')::numeric < 0 then raise exception 'Số lượng không được âm.'; end if;
    update public.delivery_lines set qty_received = (x ->> 'qty')::numeric where id = (x ->> 'id')::bigint and invoice_id = p_id;
  end loop;
  first := i.state = 'dang_chuyen';
  update public.delivery_invoices set state = 'da_nhan', received_by = a.id, received_at = public.vn_now_text(), received_date = public.app__nh_today(),
         received_report_id = p_report, receive_note = nullif(trim(coalesce(p_note, '')), ''), updated_at = public.vn_now_text() where id = p_id;
  select count(*) into n_mis from public.delivery_lines l where l.invoice_id = p_id and l.qty_invoice is distinct from l.qty_received;
  select * into b from public.branches where id = i.branch_id;
  if n_mis > 0 then
    perform public.app__nh_notify(i.branch_id, 'Nhận hàng lệch hóa đơn ' || coalesce(i.doc_no, '') || ' · ' || coalesce(b.display_code, b.code),
      public.app__acc_name(a.id) || ' báo ' || n_mis || ' món khác số lượng hóa đơn (ca ' || r.shift || ' ' || to_char(r.work_date::date, 'DD/MM') || ').',
      '/ca/phieu?id=' || p_report, true, true);
  end if;
  perform public.app_log('nhap_hang_bao_nhan', 'id=' || p_id || ' lệch ' || n_mis);
  return jsonb_build_object('mismatch', n_mis, 'first', first);
end $$;

-- Nhận hàng KHÔNG có hóa đơn: tạo / sửa phiếu (p_lines: [{id?, code, name, unit, qty}])
create or replace function public.app_nh_receipt_save(p_id bigint, p_report bigint, p_lines jsonb, p_note text) returns bigint
language plpgsql security definer set search_path = public as $$
declare a public.accounts; i public.delivery_invoices; r public.shift_reports; x jsonb; nid bigint; k int := 0; keep bigint[] := '{}'; lid bigint; b public.branches;
begin
  a := public.app__need('chot_ca');
  select * into r from public.shift_reports where id = p_report;
  if r.id is null then raise exception 'Không tìm thấy phiếu ca.'; end if;
  if jsonb_array_length(coalesce(p_lines, '[]')) = 0 then raise exception 'Ghi ít nhất 1 món hàng đã nhận.'; end if;
  for x in select * from jsonb_array_elements(p_lines) loop
    if trim(coalesce(x ->> 'name', '')) = '' then raise exception 'Món hàng phải có tên.'; end if;
    if nullif(x ->> 'qty', '') is null or (x ->> 'qty')::numeric <= 0 then raise exception 'Nhập số lượng nhận cho món "%".', x ->> 'name'; end if;
  end loop;
  if p_id is null then
    insert into public.delivery_invoices(branch_id, work_date, created_by, kind, state, received_by, received_at, received_date, received_report_id, receive_note)
    values (r.branch_id, r.work_date, a.id, 'khong_hd', 'cho_hoa_don', a.id, public.vn_now_text(), public.app__nh_today(), p_report, nullif(trim(coalesce(p_note, '')), ''))
    returning id into nid;
  else
    select * into i from public.delivery_invoices where id = p_id for update;
    perform public.app__nh_staff_can(i, r);
    if i.state <> 'cho_hoa_don' then raise exception 'Phiếu này đã được ghép hóa đơn.'; end if;
    nid := p_id;
    update public.delivery_invoices set receive_note = nullif(trim(coalesce(p_note, '')), ''), received_at = public.vn_now_text(), updated_at = public.vn_now_text() where id = nid;
  end if;
  for x in select * from jsonb_array_elements(p_lines) loop
    k := k + 1; lid := nullif(x ->> 'id', '')::bigint;
    if lid is not null and exists (select 1 from public.delivery_lines where id = lid and invoice_id = nid) then
      update public.delivery_lines set sort = k, code = nullif(trim(coalesce(x ->> 'code', '')), ''), name = trim(x ->> 'name'), unit = nullif(trim(coalesce(x ->> 'unit', '')), ''),
             qty_received = (x ->> 'qty')::numeric where id = lid;
    else
      insert into public.delivery_lines(invoice_id, sort, code, name, unit, qty_received)
      values (nid, k, nullif(trim(coalesce(x ->> 'code', '')), ''), trim(x ->> 'name'), nullif(trim(coalesce(x ->> 'unit', '')), ''), (x ->> 'qty')::numeric) returning id into lid;
    end if;
    keep := keep || lid;
  end loop;
  delete from public.delivery_lines where invoice_id = nid and not (id = any(keep));
  if p_id is null then
    select * into b from public.branches where id = r.branch_id;
    perform public.app__nh_notify(r.branch_id, 'Nhận hàng KHÔNG có hóa đơn · ' || coalesce(b.display_code, b.code),
      public.app__acc_name(a.id) || ' nhận ' || k || ' món (ca ' || r.shift || ' ' || to_char(r.work_date::date, 'DD/MM') || '). Kế toán tải hóa đơn và ghép vào phiếu.',
      '/ke-toan/hoa-don', true, true);
  end if;
  perform public.app_log('nhap_hang_khong_hoa_don', 'id=' || nid || ' ' || k || ' món');
  return nid;
end $$;

