create or replace function public.app_ext_entry_save(p_id bigint, p jsonb) returns bigint
language plpgsql security definer set search_path = public as $$
declare a public.accounts; old public.ext_entries; d text := p ->> 'entry_date'; k text := p ->> 'kind'; cat bigint := nullif(p ->> 'category_id', '')::bigint;
        amt bigint := nullif(p ->> 'amount', '')::bigint; nt text := trim(coalesce(p ->> 'note', '')); pm text := coalesce(nullif(p ->> 'pay_method', ''), 'tien_mat');
        md text := coalesce(nullif(p ->> 'alloc_mode', ''), 'doanh_thu'); ab bigint := nullif(p ->> 'alloc_branch', '')::bigint; nid bigint; msum bigint;
begin
  a := public.app__ext_need();
  if p_id is not null then
    select * into old from public.ext_entries where id = p_id;
    if old.id is null then raise exception 'Không tìm thấy khoản này.'; end if;
    if public.app__ext_month_locked(left(old.entry_date, 7)) then raise exception 'Tháng % đã có cơ sở chốt nên khoản này không sửa được. Mở lại tháng các cơ sở trước.', left(old.entry_date, 7); end if;
  end if;
  if d is null or d !~ '^\d{4}-\d{2}-\d{2}$' then raise exception 'Chọn ngày.'; end if;
  if d < public.app__fund_start() then raise exception 'Quỹ ngoài bắt đầu từ %.', to_char(public.app__fund_start()::date, 'DD/MM/YYYY'); end if;
  if public.app__ext_month_locked(left(d, 7)) then raise exception 'Tháng % đã có cơ sở chốt nên không thêm khoản vào tháng này được.', left(d, 7); end if;
  if coalesce(k, '') not in ('chi', 'thu') then raise exception 'Chọn Thu hay Chi.'; end if;
  if amt is null or amt <= 0 then raise exception 'Nhập số tiền lớn hơn 0.'; end if;
  if nt = '' then raise exception 'Ghi nội dung khoản %.', k; end if;
  if pm not in ('tien_mat', 'chuyen_khoan') then raise exception 'Hình thức không hợp lệ.'; end if;
  if md not in ('doanh_thu', 'deu', 'mot', 'tu_nhap', 'kho_tong') then raise exception 'Cách chia không hợp lệ.'; end if;
  if md = 'kho_tong' then
    if k <> 'chi' then raise exception 'Thanh toán kho tổng là khoản chi.'; end if;
    select id into cat from public.fin_categories where kind = 'chi' and lower(name) = lower('Nguyên liệu (kho tổng)') limit 1;
  end if;
  if cat is null or not exists (select 1 from public.fin_categories where id = cat and kind = k) then raise exception 'Chọn nhóm % đúng loại.', k; end if;
  if md = 'mot' and (ab is null or not exists (select 1 from public.branches where id = ab)) then raise exception 'Chọn cơ sở nhận khoản này.'; end if;
  if md = 'tu_nhap' then
    select coalesce(sum((v.value)::bigint), 0) into msum from jsonb_each_text(coalesce(p -> 'manual', '{}')) v where v.value ~ '^\d+$';
    if msum <> amt then raise exception 'Tổng số tự nhập (%) phải bằng số tiền khoản (%).', public.app__vnd(msum), public.app__vnd(amt); end if;
  end if;
  if p_id is null then
    insert into public.ext_entries(entry_date, kind, category_id, amount, note, pay_method, alloc_mode, alloc_branch, created_by, updated_by)
    values (d, k, cat, amt, nt, pm, md, case when md = 'mot' then ab end, a.id, a.id) returning id into nid;
  else
    update public.ext_entries set entry_date = d, kind = k, category_id = cat, amount = amt, note = nt, pay_method = pm, alloc_mode = md,
           alloc_branch = case when md = 'mot' then ab end, updated_by = a.id, updated_at = public.vn_now_text() where id = p_id;
    nid := p_id;
  end if;
  delete from public.ext_alloc_manual where entry_id = nid;
  if md = 'tu_nhap' then
    insert into public.ext_alloc_manual(entry_id, branch_id, amount)
    select nid, v.key::bigint, v.value::bigint from jsonb_each_text(coalesce(p -> 'manual', '{}')) v
     where v.value ~ '^\d+$' and v.value::bigint > 0 and exists (select 1 from public.branches b where b.id = v.key::bigint);
  end if;
  perform public.app_log('quy_ngoai_khoan', 'entry=' || nid || ' ' || k || ' ' || amt || ' ' || md);
  return nid;
end $$;

-- Quỹ ngoài: thêm tổng tiền hàng kho tổng của tháng (để điền sẵn khoản thanh toán)
create or replace function public.app_ext_kho(p_month text) returns jsonb
language plpgsql stable security definer set search_path = public as $$
begin
  perform public.app__ext_need();
  perform public.app__fin_month_ok(p_month);
  return jsonb_build_object('total', public.app__nh_month_total(null, p_month),
    'paid', (select coalesce(sum(amount), 0) from public.ext_entries where alloc_mode = 'kho_tong' and left(entry_date, 7) >= p_month and note ilike '%' || to_char((p_month || '-01')::date, 'MM/YYYY') || '%'),
    'by_branch', coalesce((select jsonb_agg(jsonb_build_object('code', coalesce(b.display_code, b.code), 'total', public.app__nh_month_total(b.id, p_month)) order by b.sort_order)
                 from public.branches b where b.status = 'Đang hoạt động'), '[]'));
end $$;

create or replace function public.app__fin_full(p_branch bigint, p_month text) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare j jsonb; d0 text; d1 text; st text := public.app__fund_start(); ext jsonb; ext_chi bigint; ext_thu bigint; t jsonb; bycat jsonb;
        rv jsonb; mv_excl bigint; mv_tm bigint; mv_ck bigint; ka bigint; bu bigint; dep bigint; bin bigint; op bigint; cl bigint; wd bigint; wd_tm bigint; wd_ck bigint;
        profit bigint; must bigint; cash_diff bigint; bank_diff bigint; active boolean; kho jsonb; kho_tot bigint; kho_cat bigint;
begin
  j := public.app__fin_calc(p_branch, p_month);
  d0 := p_month || '-01'; d1 := to_char((d0::date + interval '1 month' - interval '1 day'), 'YYYY-MM-DD');
  select coalesce(jsonb_agg(jsonb_build_object('entry_id', e.id, 'date', e.entry_date, 'kind', e.kind, 'category_id', e.category_id, 'category', c.name,
           'note', e.note, 'total', e.amount, 'amount', a.amount, 'mode', e.alloc_mode) order by e.entry_date, e.id), '[]'),
         coalesce(sum(a.amount) filter (where e.kind = 'chi'), 0), coalesce(sum(a.amount) filter (where e.kind = 'thu'), 0)
    into ext, ext_chi, ext_thu
    from public.ext_entries e cross join lateral public.app__ext_alloc(e.id) a left join public.fin_categories c on c.id = e.category_id
   where e.entry_date between d0 and d1 and a.branch_id = p_branch and a.amount <> 0;
  -- hàng kho tổng (hóa đơn trong tháng)
  select id into kho_cat from public.fin_categories where kind = 'chi' and lower(name) = lower('Nguyên liệu (kho tổng)') limit 1;
  select coalesce(jsonb_agg(jsonb_build_object('id', i.id, 'doc_no', i.doc_no, 'date', i.work_date, 'total', coalesce(i.total, 0), 'state', i.state) order by i.work_date, i.id), '[]'),
         coalesce(sum(i.total), 0)
    into kho, kho_tot from public.delivery_invoices i where i.branch_id = p_branch and i.doc_no is not null and i.work_date between d0 and d1;
  t := j -> 'totals';
  profit := (t ->> 'profit')::bigint - ext_chi + ext_thu - kho_tot;
  t := t || jsonb_build_object('chi_ngoai', ext_chi, 'thu_ngoai', ext_thu, 'chi_kho', kho_tot,
    'chi', (t ->> 'chi')::bigint + ext_chi + kho_tot, 'thu', (t ->> 'thu')::bigint + ext_thu, 'profit', profit);
  select coalesce(jsonb_agg(jsonb_build_object('kind', y.kind, 'category_id', y.cid, 'name', coalesce(fc.name, 'Chưa phân nhóm'), 'amount', y.amt)
           order by y.kind, coalesce(fc.sort_order, 1000), fc.name), '[]')
    into bycat from (
      select kind, cid, sum(amt) amt from (
        select x ->> 'kind' kind, (x ->> 'category_id')::bigint cid, (x ->> 'amount')::bigint amt from jsonb_array_elements(j -> 'by_cat') x
        union all
        select x ->> 'kind', (x ->> 'category_id')::bigint, (x ->> 'amount')::bigint from jsonb_array_elements(ext) x
        union all
        select 'chi', kho_cat, kho_tot where kho_tot <> 0) u
      group by kind, cid) y left join public.fin_categories fc on fc.id = y.cid;

  active := d1 >= st;
  rv := j -> 'revenue';
  select coalesce(sum((m ->> 'amount')::bigint) filter (where (m ->> 'excluded')::boolean), 0),
         coalesce(sum((m ->> 'amount')::bigint) filter (where m ->> 'kind' = 'tien_mat'), 0),
         coalesce(sum((m ->> 'amount')::bigint) filter (where m ->> 'kind' = 'chuyen_khoan'), 0)
    into mv_excl, mv_tm, mv_ck from jsonb_array_elements(j -> 'moves') m;
  ka := coalesce((j -> 'shortfalls' ->> 'total')::bigint, 0);
  select coalesce(sum(r.amount) filter (where r.typ = 'bu_khoan_am'), 0), coalesce(sum(r.amount) filter (where r.typ = 'nop_quy'), 0), coalesce(sum(r.amount) filter (where r.typ = 'ck_ve'), 0)
    into bu, dep, bin from public.app__fund_rows(p_branch, d0, d1) r;
  if d0 <= st then
    op := coalesce((select sum(amount) from public.fund_openings where branch_id = p_branch), 0);
  else
    op := public.app__fund_balance(p_branch, 'tien_mat', to_char(d0::date - 1, 'YYYY-MM-DD')) + public.app__fund_balance(p_branch, 'chuyen_khoan', to_char(d0::date - 1, 'YYYY-MM-DD'));
  end if;
  cl := public.app__fund_balance(p_branch, 'tien_mat', d1) + public.app__fund_balance(p_branch, 'chuyen_khoan', d1);
  select coalesce(sum(amount), 0), coalesce(sum(amount) filter (where method = 'tien_mat'), 0), coalesce(sum(amount) filter (where method = 'chuyen_khoan'), 0)
    into wd, wd_tm, wd_ck from public.fund_withdrawals where branch_id = p_branch and wdate between d0 and d1;
  must := profit - (rv ->> 'debt_new')::bigint + (rv ->> 'debt_col_tm')::bigint + (rv ->> 'debt_col_ck')::bigint + ext_chi - ext_thu + kho_tot + mv_excl - ka + bu + op;
  cash_diff := dep - ((rv ->> 'pos_cash')::bigint + mv_tm + (rv ->> 'debt_col_tm')::bigint) + ka;
  bank_diff := bin - ((rv ->> 'pos_transfer')::bigint + mv_ck + (rv ->> 'debt_col_ck')::bigint);

  return j || jsonb_build_object('totals', t, 'by_cat', bycat, 'ext', ext, 'kho', kho,
    'recon', jsonb_build_object('active', active, 'profit', profit, 'debt_new', (rv ->> 'debt_new')::bigint,
       'debt_col', (rv ->> 'debt_col_tm')::bigint + (rv ->> 'debt_col_ck')::bigint, 'ext_cost', ext_chi - ext_thu, 'kho_cost', kho_tot, 'moves_excluded', mv_excl,
       'shortfalls', ka, 'bu', bu, 'opening', op, 'must', must, 'withdrawn', wd, 'withdrawn_tm', wd_tm, 'withdrawn_ck', wd_ck,
       'gap', wd - must, 'closing', cl, 'cash_diff', cash_diff, 'bank_diff', bank_diff, 'deposits', dep, 'bank_in', bin));
end $$;

