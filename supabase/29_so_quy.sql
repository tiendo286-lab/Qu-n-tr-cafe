--  * Kiểm quỹ: nhập số đếm / số dư thực tế → so với sổ (KHỚP / THIẾU / THỪA).
--  * Nhắc rút bớt khi quỹ tiền mặt vượt 20.000.000đ (báo Chủ, Quản lý tổng, quản lý của cơ sở; mỗi ngày tối đa 1 lần).
