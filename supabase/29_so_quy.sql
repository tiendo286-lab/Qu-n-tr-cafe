insert into public.settings(key, value) values ('fund_start_date', '2026-11-01') on conflict (key) do nothing;
insert into public.settings(key, value) values ('fund_cash_alert', '20000000') on conflict (key) do nothing;
insert into public.settings(key, value) values ('fund_cash_float', '1000000') on conflict (key) do nothing;

create table if not exists public.fund_openings (
  branch_id bigint not null references public.branches(id) on delete cascade,
  method text not null check (method in ('tien_mat', 'chuyen_khoan')),
  amount bigint not null default 0,
  note text, updated_by bigint, updated_at text not null default public.vn_now_text(),
  primary key (branch_id, method)
);

-- Số nộp quỹ / tiền về theo ngày do quản lý nhập tay (null = dùng số tự động)
create table if not exists public.fund_day_values (
  branch_id bigint not null references public.branches(id) on delete cascade,
  work_date text not null,
  cash_amount bigint, cash_note text,
  bank_amount bigint, bank_note text,
  updated_by bigint, updated_at text not null default public.vn_now_text(),
  primary key (branch_id, work_date)
);

create table if not exists public.fund_withdrawals (
  id bigint generated by default as identity primary key,
  branch_id bigint not null references public.branches(id) on delete cascade,
  method text not null check (method in ('tien_mat', 'chuyen_khoan')),
  kind text not null default 'giua_thang' check (kind in ('giua_thang', 'cuoi_thang')),
  wdate text not null,                                  -- YYYY-MM-DD
  amount bigint not null check (amount > 0),
  note text not null default '',
  status text not null default 'cho_nhan' check (status in ('cho_nhan', 'da_nhan')),
  created_by bigint, created_at text not null default public.vn_now_text(),
  updated_by bigint, updated_at text not null default public.vn_now_text(),
  received_by bigint, received_at text
);
create index if not exists idx_fund_withdrawals on public.fund_withdrawals (branch_id, wdate);

create table if not exists public.fund_counts (
  id bigint generated by default as identity primary key,
  branch_id bigint not null references public.branches(id) on delete cascade,
  method text not null check (method in ('tien_mat', 'chuyen_khoan')),
  count_date text not null,
  counted bigint not null,
  book bigint not null,
  note text,
  created_by bigint, created_at text not null default public.vn_now_text()
);
create index if not exists idx_fund_counts on public.fund_counts (branch_id, count_date);

create table if not exists public.fund_alerts (
  branch_id bigint not null references public.branches(id) on delete cascade,
  alert_date text not null,
  amount bigint,
  primary key (branch_id, alert_date)
);

