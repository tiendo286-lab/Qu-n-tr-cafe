$$;
create or replace function public.app__fund_start() returns text
language sql stable security definer set search_path = public as $$
  select coalesce(public.app__fund_set('fund_start_date'), '2026-11-01')
$$;

-- ---------------------------------------------------------------- Khóa tháng đã chốt (thêm các bảng sổ quỹ)
create or replace function public.app__fin_guard() returns trigger
language plpgsql security definer set search_path = public as $$
declare b bigint; d text; b2 bigint; d2 text; rid bigint;
begin
  if TG_TABLE_NAME in ('shift_reports', 'daily_cash_closings', 'fund_day_values') then
    if TG_OP <> 'INSERT' then b := OLD.branch_id; d := OLD.work_date; end if;
    if TG_OP <> 'DELETE' then b2 := NEW.branch_id; d2 := NEW.work_date; end if;
  elsif TG_TABLE_NAME = 'fin_entries' then
    if TG_OP <> 'INSERT' then b := OLD.branch_id; d := OLD.entry_date; end if;
    if TG_OP <> 'DELETE' then b2 := NEW.branch_id; d2 := NEW.entry_date; end if;
  elsif TG_TABLE_NAME = 'fund_withdrawals' then
    if TG_OP <> 'INSERT' then b := OLD.branch_id; d := OLD.wdate; end if;
    if TG_OP <> 'DELETE' then b2 := NEW.branch_id; d2 := NEW.wdate; end if;
  elsif TG_TABLE_NAME = 'fund_counts' then
    if TG_OP <> 'INSERT' then b := OLD.branch_id; d := OLD.count_date; end if;
    if TG_OP <> 'DELETE' then b2 := NEW.branch_id; d2 := NEW.count_date; end if;
  else  -- bảng gắn với phiếu ca qua report_id
    rid := case when TG_OP = 'DELETE' then OLD.report_id else NEW.report_id end;
    select branch_id, work_date into b, d from public.shift_reports where id = rid;
  end if;
  if public.app__fin_locked(b, d) or public.app__fin_locked(b2, d2) then
    raise exception 'Tháng % của cơ sở này đã CHỐT nên không sửa được. Chủ mở lại tháng (ghi lý do) trước khi sửa.',
      to_char((left(coalesce(d2, d), 7) || '-01')::date, 'MM/YYYY');
  end if;
  return case when TG_OP = 'DELETE' then OLD else NEW end;
end $$;

do $$
declare t text;
begin
  foreach t in array array['fund_day_values', 'fund_withdrawals', 'fund_counts'] loop
    execute format('drop trigger if exists fin_guard on public.%I', t);
    execute format('create trigger fin_guard before insert or update or delete on public.%I for each row execute function public.app__fin_guard()', t);
  end loop;
end $$;

-- ---------------------------------------------------------------- Số tự động theo ngày
-- TK: tổng chuyển khoản thực nhận của các ca trong ngày (chỉ ca kế toán đã nhập)
create or replace function public.app__fund_bank_auto(p_branch bigint, p_date text) returns bigint
language sql stable security definer set search_path = public as $$
  select sum((public.app__kt_bank_json(x) ->> 'received')::bigint)
    from public.shift_reports x where x.branch_id = p_branch and x.work_date = p_date and x.status = 'hoan_thanh'
$$;

-- Từng dòng của sổ (có dấu: + vào, − ra) trong khoảng ngày; không gồm số dư đầu
create or replace function public.app__fund_rows(p_branch bigint, p_from text, p_to text)
returns table(d text, method text, typ text, label text, amount bigint, auto boolean, ref jsonb)
language plpgsql stable security definer set search_path = public as $$
declare st text := public.app__fund_start(); fl bigint := coalesce(public.app__fund_set('fund_cash_float')::bigint, 1000000);
        f text := greatest(p_from, public.app__fund_start()); dd date;
begin
  if f > p_to then return; end if;
  for dd in select generate_series(f::date, p_to::date, interval '1 day')::date loop
    -- tiền mặt nộp quỹ cuối ngày
    return query
      select to_char(dd, 'YYYY-MM-DD'), 'tien_mat'::text, 'nop_quy'::text,
             case when v.cash_amount is not null then 'Nộp quỹ cuối ngày (quản lý nhập)' else 'Nộp quỹ cuối ngày (đếm ' || public.app__vnd(c.counted) || ' − để lại ' || public.app__vnd(fl) || ')' end,
             coalesce(v.cash_amount, c.counted - fl), v.cash_amount is null,
             jsonb_build_object('counted', c.counted, 'note', v.cash_note)
        from (select 1) one
        left join public.daily_cash_closings c on c.branch_id = p_branch and c.work_date = to_char(dd, 'YYYY-MM-DD')
        left join public.fund_day_values v on v.branch_id = p_branch and v.work_date = to_char(dd, 'YYYY-MM-DD')
       where coalesce(v.cash_amount, c.counted - fl) is not null and coalesce(v.cash_amount, c.counted - fl) <> 0;
    -- chuyển khoản về
    return query
      select to_char(dd, 'YYYY-MM-DD'), 'chuyen_khoan'::text, 'ck_ve'::text,
             case when v.bank_amount is not null then 'Chuyển khoản về (quản lý nhập)' else 'Chuyển khoản thực nhận (kế toán)' end,
             coalesce(v.bank_amount, a.s), v.bank_amount is null, jsonb_build_object('note', v.bank_note)
        from (select public.app__fund_bank_auto(p_branch, to_char(dd, 'YYYY-MM-DD')) s) a
        left join public.fund_day_values v on v.branch_id = p_branch and v.work_date = to_char(dd, 'YYYY-MM-DD')
       where coalesce(v.bank_amount, a.s) is not null and coalesce(v.bank_amount, a.s) <> 0;
  end loop;
  -- khoản thu chi quản lý tạo
  return query
    select e.entry_date, e.pay_method, 'thu_chi'::text, (case when e.kind = 'chi' then 'Chi: ' else 'Thu: ' end) || e.note || coalesce(' · ' || c.name, ''),
           case when e.kind = 'chi' then -e.amount else e.amount end, false, jsonb_build_object('entry_id', e.id)
      from public.fin_entries e left join public.fin_categories c on c.id = e.category_id
     where e.branch_id = p_branch and e.entry_date between f and p_to;
  -- nhân viên bù khoản âm (tiền mặt)
  return query
    select left(s.status_at, 10), 'tien_mat'::text, 'bu_khoan_am'::text, 'NV bù khoản âm: ' || coalesce(em.code || ' – ' || em.name, '?'),
           s.amount, false, jsonb_build_object('shortfall_id', s.id, 'report_id', s.report_id)
      from public.shift_shortfalls s join public.shift_reports r on r.id = s.report_id left join public.employees em on em.id = s.employee_id
     where r.branch_id = p_branch and s.status = 'da_bu' and left(s.status_at, 10) between f and p_to;
  -- phiếu rút
  return query
    select w.wdate, w.method, 'rut'::text,
           (case when w.kind = 'cuoi_thang' then 'Rút cuối tháng' else 'Rút giữ hộ' end) || case when w.status = 'da_nhan' then ' · Chủ đã nhận' else ' · chờ Chủ xác nhận' end
             || case when w.note <> '' then ' · ' || w.note else '' end,
           -w.amount, false, jsonb_build_object('withdrawal_id', w.id, 'status', w.status)
      from public.fund_withdrawals w where w.branch_id = p_branch and w.wdate between f and p_to;
end $$;

create or replace function public.app__fund_balance(p_branch bigint, p_method text, p_upto text) returns bigint
language sql stable security definer set search_path = public as $$
  select coalesce((select amount from public.fund_openings o where o.branch_id = p_branch and o.method = p_method), 0)
       + coalesce((select sum(r.amount) from public.app__fund_rows(p_branch, public.app__fund_start(), p_upto) r where r.method = p_method), 0)
$$;

-- Số dư tài khoản thực tế theo kế toán: tổng số dư cuối của ca gần nhất (≤ ngày) từng tài khoản
create or replace function public.app__fund_bank_actual(p_branch bigint, p_upto text) returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object('amount', sum(z.closing), 'accounts', count(*), 'at', max(z.work_date))
    from (select distinct on (k.id) k.id, x.closing, r.work_date
            from public.bank_accounts k
            join public.bank_account_balances x on x.account_id = k.id and x.closing is not null
            join public.shift_reports r on r.id = x.report_id and r.work_date <= p_upto
           where k.branch_id = p_branch and k.active = 1
           order by k.id, r.work_date desc, array_position(public.app__shifts(), r.shift) desc) z
$$;

-- ---------------------------------------------------------------- Nhắc rút bớt khi quỹ tiền mặt vượt mức
create or replace function public.app__fund_alert(p_branch bigint) returns void
language plpgsql security definer set search_path = public as $$
declare lim bigint := coalesce(public.app__fund_set('fund_cash_alert')::bigint, 20000000); today text := to_char(public.vn_now(), 'YYYY-MM-DD');
        bal bigint; b public.branches; x bigint;
begin
  if p_branch is null or today < public.app__fund_start() then return; end if;
  bal := public.app__fund_balance(p_branch, 'tien_mat', today);
  if bal <= lim or exists (select 1 from public.fund_alerts where branch_id = p_branch and alert_date = today) then return; end if;
  insert into public.fund_alerts(branch_id, alert_date, amount) values (p_branch, today, bal);
  select * into b from public.branches where id = p_branch;
  for x in select a.id from public.accounts a
            where coalesce(a.locked, 0) = 0
              and (a.system_role in ('chu', 'ql_tong')
                   or (a.system_role = 'ql' and (exists (select 1 from public.employee_branches eb where eb.employee_id = a.employee_id and eb.branch_id = p_branch)
                                              or exists (select 1 from public.fin_branch_managers m where m.account_id = a.id and m.branch_id = p_branch)))) loop
    perform public.app__notify(x, 'Quỹ tiền mặt ' || coalesce(b.display_code, b.code) || ' đang giữ ' || public.app__vnd(bal),
      'Vượt mức ' || public.app__vnd(lim) || '. Nên rút bớt tiền về (Chốt tháng › Sổ quỹ › Phiếu rút).', '/quan-ly/so-quy?cn=' || p_branch);
  end loop;
end $$;

create or replace function public.app__fund_alert_trg() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  begin perform public.app__fund_alert(NEW.branch_id); exception when others then null; end;  -- nhắc lỗi cũng không chặn việc lưu
  return null;
end $$;
do $$
declare t text;
begin
  foreach t in array array['daily_cash_closings', 'fund_day_values'] loop
    execute format('drop trigger if exists fund_alert on public.%I', t);
    execute format('create trigger fund_alert after insert or update on public.%I for each row execute function public.app__fund_alert_trg()', t);
  end loop;
end $$;

-- ---------------------------------------------------------------- Đọc
create or replace function public.app_fund_overview(p_month text) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare d0 text; d1 text; upto text; lim bigint := coalesce(public.app__fund_set('fund_cash_alert')::bigint, 20000000);
begin
  perform public.app__fin_month_ok(p_month);
  d0 := p_month || '-01'; d1 := to_char((d0::date + interval '1 month' - interval '1 day'), 'YYYY-MM-DD');
  upto := least(d1, to_char(public.vn_now(), 'YYYY-MM-DD'));
  return jsonb_build_object('month', p_month, 'start', public.app__fund_start(), 'alert', lim, 'branches',
    coalesce((select jsonb_agg(jsonb_build_object('id', b.id, 'code', coalesce(b.display_code, b.code), 'name', b.name,
        'cash', public.app__fund_balance(b.id, 'tien_mat', upto), 'bank', public.app__fund_balance(b.id, 'chuyen_khoan', upto),
        'bank_actual', public.app__fund_bank_actual(b.id, upto),
        'out_cash', (select coalesce(sum(amount), 0) from public.fund_withdrawals w where w.branch_id = b.id and w.method = 'tien_mat' and w.wdate between d0 and d1),
        'out_bank', (select coalesce(sum(amount), 0) from public.fund_withdrawals w where w.branch_id = b.id and w.method = 'chuyen_khoan' and w.wdate between d0 and d1),
        'pending', (select count(*) from public.fund_withdrawals w where w.branch_id = b.id and w.status = 'cho_nhan'),
        'closed', exists (select 1 from public.fin_month_closes c where c.branch_id = b.id and c.month = p_month)) order by b.sort_order)
       from public.branches b where b.status = 'Đang hoạt động' and public.app__tc_can(b.id)), '[]'),
    'owner', coalesce((public.app_account()).system_role, '') = 'chu');
end $$;

create or replace function public.app_fund_branch(p_branch bigint, p_month text) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare d0 text; d1 text; upto text; st text := public.app__fund_start(); b public.branches; fl bigint := coalesce(public.app__fund_set('fund_cash_float')::bigint, 1000000);
        open_tm bigint; open_ck bigint; rows jsonb; days jsonb;
begin
  perform public.app__tc_need(p_branch);
  perform public.app__fin_month_ok(p_month);
  select * into b from public.branches where id = p_branch;
  d0 := p_month || '-01'; d1 := to_char((d0::date + interval '1 month' - interval '1 day'), 'YYYY-MM-DD');
  upto := least(d1, to_char(public.vn_now(), 'YYYY-MM-DD'));
  open_tm := public.app__fund_balance(p_branch, 'tien_mat', to_char(d0::date - 1, 'YYYY-MM-DD'));
  open_ck := public.app__fund_balance(p_branch, 'chuyen_khoan', to_char(d0::date - 1, 'YYYY-MM-DD'));
  if d0 <= st then   -- tháng bắt đầu sổ: số dư đầu là số quản lý nhập
    open_tm := coalesce((select amount from public.fund_openings where branch_id = p_branch and method = 'tien_mat'), 0);
    open_ck := coalesce((select amount from public.fund_openings where branch_id = p_branch and method = 'chuyen_khoan'), 0);
  end if;
  select coalesce(jsonb_agg(jsonb_build_object('date', r.d, 'method', r.method, 'type', r.typ, 'label', r.label, 'amount', r.amount, 'auto', r.auto, 'ref', r.ref)
           order by r.d, case r.typ when 'nop_quy' then 1 when 'ck_ve' then 1 when 'bu_khoan_am' then 2 when 'thu_chi' then 3 else 4 end), '[]')
    into rows from public.app__fund_rows(p_branch, d0, d1) r;
  -- bảng theo ngày (để quản lý nhập bổ sung)
  select coalesce(jsonb_agg(jsonb_build_object('date', g.dd, 'counted', c.counted,
           'cash_auto', case when c.counted is not null then c.counted - fl end, 'cash_set', v.cash_amount, 'cash_note', v.cash_note,
           'bank_auto', public.app__fund_bank_auto(p_branch, g.dd), 'bank_set', v.bank_amount, 'bank_note', v.bank_note,
           'reports', (select count(*) from public.shift_reports x where x.branch_id = p_branch and x.work_date = g.dd and x.status = 'hoan_thanh'))
           order by g.dd), '[]')
    into days
    from (select to_char(x, 'YYYY-MM-DD') dd from generate_series(greatest(d0, st)::date, upto::date, interval '1 day') x) g
    left join public.daily_cash_closings c on c.branch_id = p_branch and c.work_date = g.dd
    left join public.fund_day_values v on v.branch_id = p_branch and v.work_date = g.dd;
  return jsonb_build_object('branch_id', b.id, 'code', coalesce(b.display_code, b.code), 'name', b.name, 'month', p_month,
    'from', d0, 'to', d1, 'upto', upto, 'start', st, 'float', fl, 'alert', coalesce(public.app__fund_set('fund_cash_alert')::bigint, 20000000),
    'is_start_month', left(st, 7) = p_month,
    'openings', jsonb_build_object('tien_mat', (select to_jsonb(o) from public.fund_openings o where o.branch_id = p_branch and o.method = 'tien_mat'),
                                   'chuyen_khoan', (select to_jsonb(o) from public.fund_openings o where o.branch_id = p_branch and o.method = 'chuyen_khoan')),
    'open', jsonb_build_object('tien_mat', open_tm, 'chuyen_khoan', open_ck),
    'balance', jsonb_build_object('tien_mat', public.app__fund_balance(p_branch, 'tien_mat', upto), 'chuyen_khoan', public.app__fund_balance(p_branch, 'chuyen_khoan', upto)),
    'bank_actual', public.app__fund_bank_actual(p_branch, upto),
    'rows', rows, 'days', days,
    'withdrawals', coalesce((select jsonb_agg(to_jsonb(w) || jsonb_build_object('by', public.app__acc_name(w.created_by), 'received_name', public.app__acc_name(w.received_by),
                       'locked', w.status = 'da_nhan' or public.app__fin_locked(w.branch_id, w.wdate)) order by w.wdate desc, w.id desc)
                     from public.fund_withdrawals w where w.branch_id = p_branch and (w.wdate between d0 and d1 or w.status = 'cho_nhan')), '[]'),
    'counts', coalesce((select jsonb_agg(to_jsonb(c) || jsonb_build_object('by', public.app__acc_name(c.created_by)) order by c.count_date desc, c.id desc)
                 from public.fund_counts c where c.branch_id = p_branch and c.count_date between d0 and d1), '[]'),
    'locked', public.app__fin_locked(p_branch, d0),
    'owner', coalesce((public.app_account()).system_role, '') = 'chu');
end $$;

-- Số dư 1 quỹ đến hết 1 ngày (để điền sẵn phiếu rút cuối tháng / kiểm quỹ)
create or replace function public.app_fund_balance(p_branch bigint, p_method text, p_date text) returns bigint
language plpgsql stable security definer set search_path = public as $$
begin
  perform public.app__tc_need(p_branch);
  if coalesce(p_method, '') not in ('tien_mat', 'chuyen_khoan') then raise exception 'Chọn tiền mặt hay tài khoản.'; end if;
  if p_date is null or p_date !~ '^\d{4}-\d{2}-\d{2}$' then raise exception 'Ngày không hợp lệ.'; end if;
  return public.app__fund_balance(p_branch, p_method, p_date);
end $$;

-- ---------------------------------------------------------------- Ghi
create or replace function public.app_fund_day_set(p_branch bigint, p_date text, p_method text, p_amount bigint, p_note text) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts; nt text := nullif(trim(coalesce(p_note, '')), '');
begin
  a := public.app__tc_need(p_branch);
  if p_date is null or p_date !~ '^\d{4}-\d{2}-\d{2}$' then raise exception 'Ngày không hợp lệ.'; end if;
  if p_date < public.app__fund_start() then raise exception 'Sổ quỹ bắt đầu từ %.', to_char(public.app__fund_start()::date, 'DD/MM/YYYY'); end if;
  if p_date > to_char(public.vn_now(), 'YYYY-MM-DD') then raise exception 'Không nhập trước cho ngày chưa tới.'; end if;
  if coalesce(p_method, '') not in ('tien_mat', 'chuyen_khoan') then raise exception 'Chọn tiền mặt hay tài khoản.'; end if;
  if p_method = 'chuyen_khoan' and p_amount is not null and p_amount < 0 then raise exception 'Tiền chuyển khoản về không được âm.'; end if;
  insert into public.fund_day_values(branch_id, work_date, cash_amount, cash_note, bank_amount, bank_note, updated_by)
  values (p_branch, p_date, case when p_method = 'tien_mat' then p_amount end, case when p_method = 'tien_mat' then nt end,
          case when p_method = 'chuyen_khoan' then p_amount end, case when p_method = 'chuyen_khoan' then nt end, a.id)
  on conflict (branch_id, work_date) do update set
    cash_amount = case when p_method = 'tien_mat' then excluded.cash_amount else fund_day_values.cash_amount end,
    cash_note = case when p_method = 'tien_mat' then excluded.cash_note else fund_day_values.cash_note end,
    bank_amount = case when p_method = 'chuyen_khoan' then excluded.bank_amount else fund_day_values.bank_amount end,
    bank_note = case when p_method = 'chuyen_khoan' then excluded.bank_note else fund_day_values.bank_note end,
    updated_by = a.id, updated_at = public.vn_now_text();
  perform public.app_log('so_quy_ngay', 'branch=' || p_branch || ' ' || p_date || ' ' || p_method || '=' || coalesce(p_amount::text, 'tự động'));
end $$;

create or replace function public.app_fund_opening_set(p_branch bigint, p_method text, p_amount bigint, p_note text) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts;
begin
  a := public.app__tc_need(p_branch);
  if coalesce(p_method, '') not in ('tien_mat', 'chuyen_khoan') then raise exception 'Chọn tiền mặt hay tài khoản.'; end if;
  if p_amount is null or p_amount < 0 then raise exception 'Nhập số dư (0 nếu không còn tiền).'; end if;
  if public.app__fin_locked(p_branch, public.app__fund_start()) then raise exception 'Tháng bắt đầu sổ quỹ đã chốt nên không sửa số dư đầu được.'; end if;
  insert into public.fund_openings(branch_id, method, amount, note, updated_by) values (p_branch, p_method, p_amount, nullif(trim(coalesce(p_note, '')), ''), a.id)
  on conflict (branch_id, method) do update set amount = excluded.amount, note = excluded.note, updated_by = excluded.updated_by, updated_at = public.vn_now_text();
  perform public.app_log('so_quy_so_du_dau', 'branch=' || p_branch || ' ' || p_method || '=' || p_amount);
end $$;

create or replace function public.app_fund_withdraw_save(p_id bigint, p jsonb) returns bigint
language plpgsql security definer set search_path = public as $$
declare a public.accounts; old public.fund_withdrawals; br bigint := nullif(p ->> 'branch_id', '')::bigint; m text := p ->> 'method';
        k text := coalesce(nullif(p ->> 'kind', ''), 'giua_thang'); d text := p ->> 'wdate'; amt bigint := nullif(p ->> 'amount', '')::bigint;
        nt text := trim(coalesce(p ->> 'note', '')); nid bigint; b public.branches; x bigint;
begin
  if p_id is not null then
    select * into old from public.fund_withdrawals where id = p_id;
    if old.id is null then raise exception 'Không tìm thấy phiếu rút.'; end if;
    perform public.app__tc_need(old.branch_id);
    if old.status = 'da_nhan' then raise exception 'Chủ đã xác nhận nhận tiền nên phiếu này không sửa được nữa.'; end if;
    br := old.branch_id;
  end if;
  if br is null or not exists (select 1 from public.branches where id = br) then raise exception 'Chọn cơ sở.'; end if;
  a := public.app__tc_need(br);
  if coalesce(m, '') not in ('tien_mat', 'chuyen_khoan') then raise exception 'Chọn rút tiền mặt hay chuyển khoản.'; end if;
  if k not in ('giua_thang', 'cuoi_thang') then raise exception 'Loại phiếu không hợp lệ.'; end if;
  if d is null or d !~ '^\d{4}-\d{2}-\d{2}$' then raise exception 'Chọn ngày rút.'; end if;
  if d < public.app__fund_start() then raise exception 'Sổ quỹ bắt đầu từ %.', to_char(public.app__fund_start()::date, 'DD/MM/YYYY'); end if;
  if d > to_char(public.vn_now(), 'YYYY-MM-DD') then raise exception 'Không tạo phiếu rút cho ngày chưa tới.'; end if;
  if amt is null or amt <= 0 then raise exception 'Nhập số tiền rút lớn hơn 0.'; end if;
  if p_id is null then
    insert into public.fund_withdrawals(branch_id, method, kind, wdate, amount, note, created_by, updated_by)
    values (br, m, k, d, amt, nt, a.id, a.id) returning id into nid;
    select * into b from public.branches where id = br;
    if coalesce(a.system_role, '') <> 'chu' then
      for x in select id from public.accounts where system_role = 'chu' and coalesce(locked, 0) = 0 loop
        perform public.app__notify(x, 'Phiếu rút ' || coalesce(b.display_code, b.code) || ' chờ anh xác nhận: ' || public.app__vnd(amt),
          public.app__acc_name(a.id) || ' giao ' || case when m = 'tien_mat' then 'tiền mặt' else 'chuyển khoản' end || ' ngày ' || to_char(d::date, 'DD/MM')
          || case when nt <> '' then ' · ' || nt else '' end || '. Nhận đủ thì bấm "Đã nhận tiền".', '/quan-ly/so-quy?cn=' || br || '&thang=' || left(d, 7));
      end loop;
    end if;
  else
    update public.fund_withdrawals set method = m, kind = k, wdate = d, amount = amt, note = nt, updated_by = a.id, updated_at = public.vn_now_text() where id = p_id;
    nid := p_id;
  end if;
  perform public.app_log('so_quy_phieu_rut', 'id=' || nid || ' ' || m || ' ' || amt);
  return nid;
end $$;

create or replace function public.app_fund_withdraw_delete(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
declare w public.fund_withdrawals;
begin
  select * into w from public.fund_withdrawals where id = p_id;
  if w.id is null then return; end if;
  perform public.app__tc_need(w.branch_id);
  if w.status = 'da_nhan' then raise exception 'Chủ đã xác nhận nhận tiền nên phiếu này không xóa được.'; end if;
  delete from public.fund_withdrawals where id = p_id;
  perform public.app_log('so_quy_xoa_phieu_rut', 'id=' || p_id || ' ' || w.method || ' ' || w.amount);
end $$;

-- Chủ xác nhận đã nhận tiền → khóa vĩnh viễn
create or replace function public.app_fund_withdraw_confirm(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts := public.app_account(); w public.fund_withdrawals;
begin
  if coalesce(a.system_role, '') <> 'chu' then raise exception 'Chỉ Chủ xác nhận đã nhận tiền.'; end if;
  select * into w from public.fund_withdrawals where id = p_id for update;
  if w.id is null then raise exception 'Không tìm thấy phiếu rút.'; end if;
  if w.status = 'da_nhan' then raise exception 'Phiếu này đã xác nhận rồi.'; end if;
  update public.fund_withdrawals set status = 'da_nhan', received_by = a.id, received_at = public.vn_now_text() where id = p_id;
  if w.created_by is not null and w.created_by <> a.id then
    perform public.app__notify(w.created_by, 'Chủ đã nhận ' || public.app__vnd(w.amount), 'Phiếu rút ngày ' || to_char(w.wdate::date, 'DD/MM') || ' đã được xác nhận và khóa.',
      '/quan-ly/so-quy?cn=' || w.branch_id || '&thang=' || left(w.wdate, 7));
  end if;
  perform public.app_log('so_quy_xac_nhan_rut', 'id=' || p_id || ' ' || w.amount);
end $$;

-- Khóa phiếu đã nhận ở mức bảng (phòng sửa bằng đường khác)
create or replace function public.app__fund_withdraw_lock() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if OLD.status = 'da_nhan' then raise exception 'Phiếu rút Chủ đã nhận tiền không sửa / xóa được.'; end if;
  return case when TG_OP = 'DELETE' then OLD else NEW end;
end $$;
drop trigger if exists fund_withdraw_lock on public.fund_withdrawals;
create trigger fund_withdraw_lock before update or delete on public.fund_withdrawals for each row execute function public.app__fund_withdraw_lock();

create or replace function public.app_fund_count_save(p_branch bigint, p_method text, p_date text, p_counted bigint, p_note text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare a public.accounts; bk bigint; nt text := nullif(trim(coalesce(p_note, '')), ''); nid bigint;
begin
  a := public.app__tc_need(p_branch);
  if coalesce(p_method, '') not in ('tien_mat', 'chuyen_khoan') then raise exception 'Chọn tiền mặt hay tài khoản.'; end if;
  if p_date is null or p_date !~ '^\d{4}-\d{2}-\d{2}$' then raise exception 'Chọn ngày kiểm.'; end if;
  if p_date < public.app__fund_start() or p_date > to_char(public.vn_now(), 'YYYY-MM-DD') then raise exception 'Ngày kiểm không hợp lệ.'; end if;
  if p_counted is null or p_counted < 0 then raise exception 'Nhập số tiền thực tế.'; end if;
  bk := public.app__fund_balance(p_branch, p_method, p_date);
  if bk <> p_counted and nt is null then raise exception 'Lệch % so với sổ — ghi lý do.', public.app__vnd(p_counted - bk); end if;
  insert into public.fund_counts(branch_id, method, count_date, counted, book, note, created_by) values (p_branch, p_method, p_date, p_counted, bk, nt, a.id) returning id into nid;
  perform public.app_log('so_quy_kiem_quy', 'branch=' || p_branch || ' ' || p_method || ' sổ ' || bk || ' thực ' || p_counted);
  return jsonb_build_object('id', nid, 'book', bk, 'diff', p_counted - bk);
end $$;

