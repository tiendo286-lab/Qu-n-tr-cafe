create table if not exists public.ext_entries (
  id bigint generated by default as identity primary key,
  entry_date text not null,
  kind text not null check (kind in ('chi', 'thu')),
  category_id bigint references public.fin_categories(id),
  amount bigint not null check (amount > 0),
  note text not null default '',
  pay_method text not null default 'tien_mat' check (pay_method in ('tien_mat', 'chuyen_khoan')),
  alloc_mode text not null default 'doanh_thu' check (alloc_mode in ('doanh_thu', 'deu', 'mot', 'tu_nhap')),
  alloc_branch bigint references public.branches(id),
  created_by bigint, created_at text not null default public.vn_now_text(),
  updated_by bigint, updated_at text not null default public.vn_now_text()
);
create index if not exists idx_ext_entries on public.ext_entries (entry_date);
create table if not exists public.ext_alloc_manual (
  entry_id bigint not null references public.ext_entries(id) on delete cascade,
  branch_id bigint not null references public.branches(id) on delete cascade,
  amount bigint not null check (amount >= 0),
  primary key (entry_id, branch_id)
);
create table if not exists public.ext_alloc_fixed (
  entry_id bigint not null references public.ext_entries(id) on delete cascade,
  branch_id bigint not null references public.branches(id) on delete cascade,
  amount bigint not null,
  primary key (entry_id, branch_id)
);
create table if not exists public.ext_openings (
  method text primary key check (method in ('tien_mat', 'chuyen_khoan')),
  amount bigint not null default 0,
  note text, updated_by bigint, updated_at text not null default public.vn_now_text()
);
do $$
declare t text;
begin
  foreach t in array array['ext_entries', 'ext_alloc_manual', 'ext_alloc_fixed', 'ext_openings'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon, authenticated', t);
  end loop;
end $$;

create or replace function public.app__ext_need() returns public.accounts
language plpgsql stable security definer set search_path = public as $$
declare a public.accounts := public.app_account();
begin
  if coalesce(a.system_role, '') <> 'chu' or coalesce(a.locked, 0) = 1 then raise exception 'Chỉ Chủ xem / sửa được Quỹ ngoài.'; end if;
  return a;
end $$;

-- Doanh thu tháng của 1 cơ sở (phiếu ca hoàn thành, số chính thức)
create or replace function public.app__ext_rev(p_branch bigint, p_month text) returns bigint
language sql stable security definer set search_path = public as $$
  select coalesce(sum((public.app__ca_eff(x.id) ->> 'total_revenue')::bigint), 0) from public.shift_reports x
   where x.branch_id = p_branch and left(x.work_date, 7) = p_month and x.status = 'hoan_thanh'
$$;

-- Một khoản ngoài chia cho từng cơ sở bao nhiêu
create or replace function public.app__ext_alloc(p_entry bigint) returns table(branch_id bigint, amount bigint)
language plpgsql stable security definer set search_path = public as $$
declare e public.ext_entries; m text;
begin
  select * into e from public.ext_entries where id = p_entry;
  if e.id is null then return; end if;
  if exists (select 1 from public.ext_alloc_fixed f where f.entry_id = p_entry) then
    return query select f.branch_id, f.amount from public.ext_alloc_fixed f where f.entry_id = p_entry; return;
  end if;
  m := left(e.entry_date, 7);
  if e.alloc_mode = 'mot' then
    if e.alloc_branch is not null then return query select e.alloc_branch, e.amount; end if;
    return;
  elsif e.alloc_mode = 'tu_nhap' then
    return query select x.branch_id, x.amount from public.ext_alloc_manual x where x.entry_id = p_entry and x.amount > 0; return;
  end if;
  -- chia đều / theo doanh thu cho các cơ sở đang hoạt động
  return query
    with w0 as (select b.id as bid, b.sort_order as so,
                       (case when e.alloc_mode = 'doanh_thu' then public.app__ext_rev(b.id, m) else 1 end)::numeric as wt
                  from public.branches b where b.status = 'Đang hoạt động'),
         t0 as (select coalesce(sum(wt), 0) as tot from w0),
         w1 as (select w0.bid, w0.so, case when t0.tot = 0 then 1::numeric else w0.wt end as wt from w0, t0),
         t1 as (select sum(wt) as tot from w1),
         base as (select w1.bid, w1.so, w1.wt, e.amount * w1.wt / t1.tot as ex, floor(e.amount * w1.wt / t1.tot)::bigint as a0 from w1, t1),
         rest as (select e.amount - coalesce(sum(a0), 0) as r from base),
         ranked as (select base.*, row_number() over (order by base.ex - base.a0 desc, base.wt desc, base.so) as rk from base)
    select ranked.bid, ranked.a0 + case when ranked.rk <= (select r from rest) then 1 else 0 end from ranked;
end $$;

create or replace function public.app__ext_ok(p_entry bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce((select sum(a.amount) from public.app__ext_alloc(p_entry) a), 0) = (select amount from public.ext_entries where id = p_entry)
$$;

-- Tháng của Quỹ ngoài bị khóa khi đã có cơ sở chốt tháng đó
create or replace function public.app__ext_month_locked(p_month text) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.fin_month_closes c where c.month = p_month)
$$;

-- Các dòng sổ Quỹ ngoài (có dấu) trong khoảng ngày
create or replace function public.app__ext_rows(p_from text, p_to text)
returns table(d text, method text, typ text, label text, amount bigint, ref jsonb)
language sql stable security definer set search_path = public as $$
  select w.wdate, w.method, 'nhan'::text, 'Nhận từ ' || coalesce(b.display_code, b.code) || ': ' || case when w.kind = 'cuoi_thang' then 'rút cuối tháng' else 'rút giữ hộ' end
           || case when w.note <> '' then ' · ' || w.note else '' end, w.amount, jsonb_build_object('withdrawal_id', w.id, 'branch_id', w.branch_id)
    from public.fund_withdrawals w join public.branches b on b.id = w.branch_id
   where w.status = 'da_nhan' and w.wdate between greatest(p_from, public.app__fund_start()) and p_to
  union all
  select e.entry_date, e.pay_method, 'thu_chi', (case when e.kind = 'chi' then 'Chi: ' else 'Thu: ' end) || e.note || coalesce(' · ' || c.name, ''),
         case when e.kind = 'chi' then -e.amount else e.amount end, jsonb_build_object('entry_id', e.id)
    from public.ext_entries e left join public.fin_categories c on c.id = e.category_id
   where e.entry_date between greatest(p_from, public.app__fund_start()) and p_to
$$;

create or replace function public.app__ext_balance(p_method text, p_upto text) returns bigint
language sql stable security definer set search_path = public as $$
  select coalesce((select amount from public.ext_openings where method = p_method), 0)
       + coalesce((select sum(r.amount) from public.app__ext_rows(public.app__fund_start(), p_upto) r where r.method = p_method), 0)
$$;

-- ---------------------------------------------------------------- Quỹ ngoài: đọc / ghi (chỉ Chủ)
create or replace function public.app_ext_month(p_month text) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare d0 text; d1 text; upto text; st text := public.app__fund_start(); bef text;
begin
  perform public.app__ext_need();
  perform public.app__fin_month_ok(p_month);
  d0 := p_month || '-01'; d1 := to_char((d0::date + interval '1 month' - interval '1 day'), 'YYYY-MM-DD');
  upto := least(d1, to_char(public.vn_now(), 'YYYY-MM-DD')); bef := to_char(d0::date - 1, 'YYYY-MM-DD');
  return jsonb_build_object('month', p_month, 'from', d0, 'to', d1, 'upto', upto, 'start', st, 'is_start_month', left(st, 7) = p_month,
    'locked', public.app__ext_month_locked(p_month),
    'openings', coalesce((select jsonb_object_agg(o.method, to_jsonb(o)) from public.ext_openings o), '{}'),
    'open', jsonb_build_object('tien_mat', case when d0 <= st then coalesce((select amount from public.ext_openings where method = 'tien_mat'), 0) else public.app__ext_balance('tien_mat', bef) end,
                               'chuyen_khoan', case when d0 <= st then coalesce((select amount from public.ext_openings where method = 'chuyen_khoan'), 0) else public.app__ext_balance('chuyen_khoan', bef) end),
    'balance', jsonb_build_object('tien_mat', public.app__ext_balance('tien_mat', upto), 'chuyen_khoan', public.app__ext_balance('chuyen_khoan', upto)),
    'rows', coalesce((select jsonb_agg(jsonb_build_object('date', r.d, 'method', r.method, 'type', r.typ, 'label', r.label, 'amount', r.amount, 'ref', r.ref)
                       order by r.d, case r.typ when 'nhan' then 1 else 2 end) from public.app__ext_rows(d0, d1) r), '[]'),
    'pending', coalesce((select jsonb_agg(jsonb_build_object('id', w.id, 'code', coalesce(b.display_code, b.code), 'branch_id', w.branch_id, 'wdate', w.wdate, 'method', w.method, 'amount', w.amount, 'note', w.note, 'by', public.app__acc_name(w.created_by)) order by w.wdate)
                          from public.fund_withdrawals w join public.branches b on b.id = w.branch_id where w.status = 'cho_nhan'), '[]'),
    'entries', coalesce((select jsonb_agg(to_jsonb(e) || jsonb_build_object('category', c.name, 'by', public.app__acc_name(e.created_by),
                   'ok', public.app__ext_ok(e.id), 'fixed', exists (select 1 from public.ext_alloc_fixed f where f.entry_id = e.id),
                   'alloc', coalesce((select jsonb_agg(jsonb_build_object('branch_id', a.branch_id, 'code', coalesce(b.display_code, b.code), 'amount', a.amount) order by b.sort_order)
                                        from public.app__ext_alloc(e.id) a join public.branches b on b.id = a.branch_id), '[]'),
                   'manual', coalesce((select jsonb_object_agg(x.branch_id::text, x.amount) from public.ext_alloc_manual x where x.entry_id = e.id), '{}'))
                   order by e.entry_date desc, e.id desc)
                 from public.ext_entries e left join public.fin_categories c on c.id = e.category_id where e.entry_date between d0 and d1), '[]'),
    'revenue', coalesce((select jsonb_agg(jsonb_build_object('branch_id', b.id, 'code', coalesce(b.display_code, b.code), 'revenue', public.app__ext_rev(b.id, p_month)) order by b.sort_order)
                 from public.branches b where b.status = 'Đang hoạt động'), '[]'),
    'branches', coalesce((select jsonb_agg(jsonb_build_object('id', b.id, 'code', coalesce(b.display_code, b.code), 'name', b.name) order by b.sort_order)
                 from public.branches b where b.status = 'Đang hoạt động'), '[]'),
    'categories', coalesce((select jsonb_agg(jsonb_build_object('id', c.id, 'kind', c.kind, 'name', c.name, 'active', c.active = 1) order by c.kind, c.sort_order, c.name) from public.fin_categories c), '[]'));
end $$;

create or replace function public.app_ext_entry_save(p_id bigint, p jsonb) returns bigint
language plpgsql security definer set search_path = public as $$
declare a public.accounts; old public.ext_entries; d text := p ->> 'entry_date'; k text := p ->> 'kind'; cat bigint := nullif(p ->> 'category_id', '')::bigint;
        amt bigint := nullif(p ->> 'amount', '')::bigint; nt text := trim(coalesce(p ->> 'note', '')); pm text := coalesce(nullif(p ->> 'pay_method', ''), 'tien_mat');
        md text := coalesce(nullif(p ->> 'alloc_mode', ''), 'doanh_thu'); ab bigint := nullif(p ->> 'alloc_branch', '')::bigint; nid bigint; msum bigint;
begin
  a := public.app__ext_need();
  if p_id is not null then
    select * into old from public.ext_entries where id = p_id;
    if old.id is null then raise exception 'Không tìm thấy khoản này.'; end if;
    if public.app__ext_month_locked(left(old.entry_date, 7)) then raise exception 'Tháng % đã có cơ sở chốt nên khoản này không sửa được. Mở lại tháng các cơ sở trước.', left(old.entry_date, 7); end if;
  end if;
  if d is null or d !~ '^\d{4}-\d{2}-\d{2}$' then raise exception 'Chọn ngày.'; end if;
  if d < public.app__fund_start() then raise exception 'Quỹ ngoài bắt đầu từ %.', to_char(public.app__fund_start()::date, 'DD/MM/YYYY'); end if;
  if public.app__ext_month_locked(left(d, 7)) then raise exception 'Tháng % đã có cơ sở chốt nên không thêm khoản vào tháng này được.', left(d, 7); end if;
  if coalesce(k, '') not in ('chi', 'thu') then raise exception 'Chọn Thu hay Chi.'; end if;
  if amt is null or amt <= 0 then raise exception 'Nhập số tiền lớn hơn 0.'; end if;
  if nt = '' then raise exception 'Ghi nội dung khoản %.', k; end if;
  if pm not in ('tien_mat', 'chuyen_khoan') then raise exception 'Hình thức không hợp lệ.'; end if;
  if cat is null or not exists (select 1 from public.fin_categories where id = cat and kind = k) then raise exception 'Chọn nhóm % đúng loại.', k; end if;
  if md not in ('doanh_thu', 'deu', 'mot', 'tu_nhap') then raise exception 'Cách chia không hợp lệ.'; end if;
  if md = 'mot' and (ab is null or not exists (select 1 from public.branches where id = ab)) then raise exception 'Chọn cơ sở nhận khoản này.'; end if;
  if md = 'tu_nhap' then
    select coalesce(sum((v.value)::bigint), 0) into msum from jsonb_each_text(coalesce(p -> 'manual', '{}')) v where v.value ~ '^\d+$';
    if msum <> amt then raise exception 'Tổng số tự nhập (%) phải bằng số tiền khoản (%).', public.app__vnd(msum), public.app__vnd(amt); end if;
  end if;
  if p_id is null then
    insert into public.ext_entries(entry_date, kind, category_id, amount, note, pay_method, alloc_mode, alloc_branch, created_by, updated_by)
    values (d, k, cat, amt, nt, pm, md, case when md = 'mot' then ab end, a.id, a.id) returning id into nid;
  else
    update public.ext_entries set entry_date = d, kind = k, category_id = cat, amount = amt, note = nt, pay_method = pm, alloc_mode = md,
           alloc_branch = case when md = 'mot' then ab end, updated_by = a.id, updated_at = public.vn_now_text() where id = p_id;
    nid := p_id;
  end if;
  delete from public.ext_alloc_manual where entry_id = nid;
  if md = 'tu_nhap' then
    insert into public.ext_alloc_manual(entry_id, branch_id, amount)
    select nid, v.key::bigint, v.value::bigint from jsonb_each_text(coalesce(p -> 'manual', '{}')) v
     where v.value ~ '^\d+$' and v.value::bigint > 0 and exists (select 1 from public.branches b where b.id = v.key::bigint);
  end if;
  perform public.app_log('quy_ngoai_khoan', 'entry=' || nid || ' ' || k || ' ' || amt || ' ' || md);
  return nid;
end $$;

create or replace function public.app_ext_entry_delete(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
declare e public.ext_entries;
begin
  perform public.app__ext_need();
  select * into e from public.ext_entries where id = p_id;
  if e.id is null then return; end if;
  if public.app__ext_month_locked(left(e.entry_date, 7)) then raise exception 'Tháng này đã có cơ sở chốt nên không xóa được.'; end if;
  delete from public.ext_entries where id = p_id;
  perform public.app_log('quy_ngoai_xoa', 'entry=' || p_id || ' ' || e.kind || ' ' || e.amount);
end $$;

create or replace function public.app_ext_opening_set(p_method text, p_amount bigint, p_note text) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts;
begin
  a := public.app__ext_need();
  if coalesce(p_method, '') not in ('tien_mat', 'chuyen_khoan') then raise exception 'Chọn tiền mặt hay tài khoản.'; end if;
  if p_amount is null or p_amount < 0 then raise exception 'Nhập số dư (0 nếu không có).'; end if;
  if public.app__ext_month_locked(left(public.app__fund_start(), 7)) then raise exception 'Tháng bắt đầu đã có cơ sở chốt nên không sửa số dư đầu được.'; end if;
  insert into public.ext_openings(method, amount, note, updated_by) values (p_method, p_amount, nullif(trim(coalesce(p_note, '')), ''), a.id)
  on conflict (method) do update set amount = excluded.amount, note = excluded.note, updated_by = excluded.updated_by, updated_at = public.vn_now_text();
end $$;

-- ---------------------------------------------------------------- Chốt tháng: số liệu đầy đủ (thêm quỹ ngoài + đối chiếu)
create or replace function public.app__fin_full(p_branch bigint, p_month text) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare j jsonb; d0 text; d1 text; st text := public.app__fund_start(); ext jsonb; ext_chi bigint; ext_thu bigint; t jsonb; bycat jsonb;
        rv jsonb; mv_excl bigint; mv_tm bigint; mv_ck bigint; ka bigint; bu bigint; dep bigint; bin bigint; op bigint; cl bigint; wd bigint; wd_tm bigint; wd_ck bigint;
        profit bigint; must bigint; cash_diff bigint; bank_diff bigint; active boolean;
begin
  j := public.app__fin_calc(p_branch, p_month);
  d0 := p_month || '-01'; d1 := to_char((d0::date + interval '1 month' - interval '1 day'), 'YYYY-MM-DD');
  -- phần chia từ quỹ ngoài
  select coalesce(jsonb_agg(jsonb_build_object('entry_id', e.id, 'date', e.entry_date, 'kind', e.kind, 'category_id', e.category_id, 'category', c.name,
           'note', e.note, 'total', e.amount, 'amount', a.amount, 'mode', e.alloc_mode) order by e.entry_date, e.id), '[]'),
         coalesce(sum(a.amount) filter (where e.kind = 'chi'), 0), coalesce(sum(a.amount) filter (where e.kind = 'thu'), 0)
    into ext, ext_chi, ext_thu
    from public.ext_entries e cross join lateral public.app__ext_alloc(e.id) a left join public.fin_categories c on c.id = e.category_id
   where e.entry_date between d0 and d1 and a.branch_id = p_branch and a.amount <> 0;
  t := j -> 'totals';
  profit := (t ->> 'profit')::bigint - ext_chi + ext_thu;
  t := t || jsonb_build_object('chi_ngoai', ext_chi, 'thu_ngoai', ext_thu, 'chi', (t ->> 'chi')::bigint + ext_chi, 'thu', (t ->> 'thu')::bigint + ext_thu, 'profit', profit);
  -- gộp nhóm chi / thu
  select coalesce(jsonb_agg(jsonb_build_object('kind', y.kind, 'category_id', y.cid, 'name', coalesce(fc.name, 'Chưa phân nhóm'), 'amount', y.amt)
           order by y.kind, coalesce(fc.sort_order, 1000), fc.name), '[]')
    into bycat from (
      select kind, cid, sum(amt) amt from (
        select x ->> 'kind' kind, (x ->> 'category_id')::bigint cid, (x ->> 'amount')::bigint amt from jsonb_array_elements(j -> 'by_cat') x
        union all
        select x ->> 'kind', (x ->> 'category_id')::bigint, (x ->> 'amount')::bigint from jsonb_array_elements(ext) x) u
      group by kind, cid) y left join public.fin_categories fc on fc.id = y.cid;

  -- đối chiếu tiền (chỉ khi sổ quỹ đã bắt đầu)
  active := d1 >= st;
  rv := j -> 'revenue';
  select coalesce(sum((m ->> 'amount')::bigint) filter (where (m ->> 'excluded')::boolean), 0),
         coalesce(sum((m ->> 'amount')::bigint) filter (where m ->> 'kind' = 'tien_mat'), 0),
         coalesce(sum((m ->> 'amount')::bigint) filter (where m ->> 'kind' = 'chuyen_khoan'), 0)
    into mv_excl, mv_tm, mv_ck from jsonb_array_elements(j -> 'moves') m;
  ka := coalesce((j -> 'shortfalls' ->> 'total')::bigint, 0);
  select coalesce(sum(r.amount) filter (where r.typ = 'bu_khoan_am'), 0), coalesce(sum(r.amount) filter (where r.typ = 'nop_quy'), 0), coalesce(sum(r.amount) filter (where r.typ = 'ck_ve'), 0)
    into bu, dep, bin from public.app__fund_rows(p_branch, d0, d1) r;
  if d0 <= st then
    op := coalesce((select sum(amount) from public.fund_openings where branch_id = p_branch), 0);
  else
    op := public.app__fund_balance(p_branch, 'tien_mat', to_char(d0::date - 1, 'YYYY-MM-DD')) + public.app__fund_balance(p_branch, 'chuyen_khoan', to_char(d0::date - 1, 'YYYY-MM-DD'));
  end if;
  cl := public.app__fund_balance(p_branch, 'tien_mat', d1) + public.app__fund_balance(p_branch, 'chuyen_khoan', d1);
  select coalesce(sum(amount), 0), coalesce(sum(amount) filter (where method = 'tien_mat'), 0), coalesce(sum(amount) filter (where method = 'chuyen_khoan'), 0)
    into wd, wd_tm, wd_ck from public.fund_withdrawals where branch_id = p_branch and wdate between d0 and d1;
  must := profit - (rv ->> 'debt_new')::bigint + (rv ->> 'debt_col_tm')::bigint + (rv ->> 'debt_col_ck')::bigint + ext_chi - ext_thu + mv_excl - ka + bu + op;
  cash_diff := dep - ((rv ->> 'pos_cash')::bigint + mv_tm + (rv ->> 'debt_col_tm')::bigint) + ka;
  bank_diff := bin - ((rv ->> 'pos_transfer')::bigint + mv_ck + (rv ->> 'debt_col_ck')::bigint);

  return j || jsonb_build_object('totals', t, 'by_cat', bycat, 'ext', ext,
    'recon', jsonb_build_object('active', active, 'profit', profit, 'debt_new', (rv ->> 'debt_new')::bigint,
       'debt_col', (rv ->> 'debt_col_tm')::bigint + (rv ->> 'debt_col_ck')::bigint, 'ext_cost', ext_chi - ext_thu, 'moves_excluded', mv_excl,
       'shortfalls', ka, 'bu', bu, 'opening', op, 'must', must, 'withdrawn', wd, 'withdrawn_tm', wd_tm, 'withdrawn_ck', wd_ck,
       'gap', wd - must, 'closing', cl, 'cash_diff', cash_diff, 'bank_diff', bank_diff, 'deposits', dep, 'bank_in', bin));
end $$;

create or replace function public.app_fin_month(p_branch bigint, p_month text) returns jsonb
language plpgsql stable security definer set search_path = public as $$
begin
  perform public.app__fin_need(p_branch);
  perform public.app__fin_month_ok(p_month);
  return public.app__fin_full(p_branch, p_month) || jsonb_build_object(
    'categories', coalesce((select jsonb_agg(to_jsonb(c) order by c.kind, c.sort_order, c.name) from public.fin_categories c), '[]'),
    'log', coalesce((select jsonb_agg(jsonb_build_object('action', l.action, 'reason', l.reason, 'by', public.app__acc_name(l.by_account), 'at', l.at) order by l.id desc)
                       from public.fin_close_log l where l.branch_id = p_branch and l.month = p_month), '[]'),
    'can_reopen', coalesce((public.app_account()).system_role, '') = 'chu',
    'ext_bad', (select count(*) from public.ext_entries e where left(e.entry_date, 7) = p_month and not public.app__ext_ok(e.id)));
end $$;

create or replace function public.app_fin_overview(p_month text) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare j jsonb;
begin
  perform public.app__fin_month_ok(p_month);
  select coalesce(jsonb_agg(jsonb_build_object('branch_id', b.id, 'code', coalesce(b.display_code, b.code), 'name', b.name,
           'revenue', c.j -> 'revenue', 'totals', c.j -> 'totals', 'cash', c.j -> 'cash', 'shortfalls', c.j -> 'shortfalls', 'closed', c.j -> 'closed', 'recon', c.j -> 'recon')
           order by b.sort_order), '[]')
    into j from public.branches b cross join lateral (select public.app__fin_full(b.id, p_month) as j) c
   where b.status = 'Đang hoạt động' and public.app__fin_can(b.id);
  return j;
end $$;

create or replace function public.app_fin_close(p_branch bigint, p_month text, p_note text) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts; j jsonb; n int; nt text := nullif(trim(coalesce(p_note, '')), ''); g bigint;
begin
  a := public.app__fin_need(p_branch);
  perform public.app__fin_month_ok(p_month);
  if p_month >= to_char(public.vn_now(), 'YYYY-MM') then raise exception 'Chỉ chốt được tháng đã kết thúc.'; end if;
  if exists (select 1 from public.fin_month_closes where branch_id = p_branch and month = p_month) then raise exception 'Tháng này đã chốt rồi.'; end if;
  j := public.app__fin_full(p_branch, p_month);
  if (j -> 'revenue' ->> 'in_progress')::int > 0 then
    raise exception 'Còn % phiếu chốt ca đang chốt dở trong tháng. Hoàn thành hết rồi mới chốt tháng.', j -> 'revenue' ->> 'in_progress';
  end if;
  if (j -> 'revenue' ->> 'recon')::int < (j -> 'revenue' ->> 'done')::int then
    raise exception 'Còn % ca chưa hoàn thành đối soát. Đối soát xong rồi mới chốt tháng.', (j -> 'revenue' ->> 'done')::int - (j -> 'revenue' ->> 'recon')::int;
  end if;
  select count(*) into n from public.app__tc_moves(p_branch, p_month || '-01', p_month || '-31') m
    left join public.fin_move_cats fc on fc.report_id = m.report_id and fc.mkey = m.mkey
   where coalesce(fc.checked, 0) = 0;
  if n > 0 then raise exception 'Còn % khoản thu chi ở phiếu chốt ca CHỜ ĐỐI SOÁT. Vào Quản lý ca › Thu chi đối soát hết rồi mới chốt tháng.', n; end if;
  if (j -> 'totals' ->> 'uncat')::int > 0 then
    raise exception 'Còn % khoản chi ở phiếu ca chưa phân nhóm. Chọn nhóm hoặc "Không tính" trước khi chốt.', j -> 'totals' ->> 'uncat';
  end if;
  select count(*) into n from public.ext_entries e where left(e.entry_date, 7) = p_month and not public.app__ext_ok(e.id);
  if n > 0 then raise exception 'Còn % khoản ở Quỹ ngoài chưa chia hết cho cơ sở. Chủ vào Sổ quỹ › Quỹ ngoài để chia.', n; end if;
  if (j -> 'recon' ->> 'active')::boolean then
    g := (j -> 'recon' ->> 'gap')::bigint;
    if g <> 0 and nt is null then
      raise exception 'Tiền đã rút về lệch % so với tiền phải rút về. Ghi lý do lệch rồi mới chốt tháng.', public.app__vnd(g);
    end if;
  end if;
  -- giữ cố định số chia quỹ ngoài của tháng (lần chốt đầu tiên của tháng)
  insert into public.ext_alloc_fixed(entry_id, branch_id, amount)
  select e.id, a2.branch_id, a2.amount from public.ext_entries e cross join lateral public.app__ext_alloc(e.id) a2
   where left(e.entry_date, 7) = p_month and not exists (select 1 from public.ext_alloc_fixed f where f.entry_id = e.id);
  insert into public.fin_month_closes(branch_id, month, note, snapshot, closed_by) values (p_branch, p_month, nt, j, a.id);
  insert into public.fin_close_log(branch_id, month, action, reason, by_account) values (p_branch, p_month, 'chot', nt, a.id);
  perform public.app_log('chot_thang', 'branch=' || p_branch || ' ' || p_month);
end $$;

-- Mở lại: khi không còn cơ sở nào chốt tháng đó thì bỏ số chia cố định (tính lại theo số mới)
create or replace function public.app_fin_reopen(p_branch bigint, p_month text, p_reason text) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts := public.app_account();
begin
  if coalesce(a.system_role, '') <> 'chu' then raise exception 'Chỉ Chủ được mở lại tháng đã chốt.'; end if;
  perform public.app__fin_month_ok(p_month);
  if trim(coalesce(p_reason, '')) = '' then raise exception 'Ghi lý do mở lại tháng.'; end if;
  delete from public.fin_month_closes where branch_id = p_branch and month = p_month;
  if not found then raise exception 'Tháng này chưa chốt.'; end if;
  insert into public.fin_close_log(branch_id, month, action, reason, by_account) values (p_branch, p_month, 'mo_lai', trim(p_reason), a.id);
  if not exists (select 1 from public.fin_month_closes where month = p_month) then
    delete from public.ext_alloc_fixed f using public.ext_entries e where e.id = f.entry_id and left(e.entry_date, 7) = p_month;
  end if;
  perform public.app_log('mo_lai_thang', 'branch=' || p_branch || ' ' || p_month);
end $$;

