-- Chạy sau 29. Chạy lại nhiều lần không sao.
--  * Quỹ ngoài: chỉ Chủ. Tiền vào = phiếu rút Chủ đã nhận (từ các cơ sở). Chủ ghi thu chi ngoài (tiền nhà, lương, kho tổng…).
--  * Mỗi khoản ngoài chia cho cơ sở: theo tỉ lệ doanh thu tháng (mặc định) / chia đều / 1 cơ sở / tự nhập.
--    Phần được chia tính vào chi phí (thu) của cơ sở ở Chốt tháng. Khi cơ sở đầu tiên chốt tháng, số chia của tháng đó được giữ cố định.
--  * Đối chiếu: Tiền phải rút về = Lãi tạm tính − nợ phát sinh + thu nợ + chi phí chia từ quỹ ngoài (không lấy tiền quán)
--               + thu chi phiếu ca "Không tính" − khoản âm NV + NV bù khoản âm + số dư quỹ đầu tháng.
--    So với tiền đã rút (phiếu rút trong tháng) → KHỚP / LỆCH. Lệch thì phải ghi lý do mới chốt tháng được.
