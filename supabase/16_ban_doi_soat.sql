alter table public.shift_reports drop constraint if exists shift_reports_recon_status_check;
alter table public.shift_reports add constraint shift_reports_recon_status_check check (recon_status in ('chua', 'hoan_thanh', 'mo_lai'));

create table if not exists public.shift_report_recon (
  report_id bigint primary key references public.shift_reports(id) on delete cascade,
  data jsonb not null,
  created_at text not null default public.vn_now_text(),
  updated_by bigint,
  updated_at text not null default public.vn_now_text()
);
-- Lịch sử sửa / mở lại (không có khóa ngoại để giữ lịch sử kể cả khi bản đối soát làm lại)
create table if not exists public.shift_recon_log (
  id bigint generated by default as identity primary key,
  report_id bigint not null,
  action text not null,            -- sua | mo_lai_doi_soat | hoan_thanh_doi_soat | lam_lai (NV sửa phiếu gốc)
  field text,
  before jsonb,
  after jsonb,
  reason text,
  by_account bigint,
  at text not null default public.vn_now_text()
);
create index if not exists idx_recon_log_report on public.shift_recon_log (report_id, id);
do $$ begin
  execute 'alter table public.shift_report_recon enable row level security';
  execute 'alter table public.shift_recon_log enable row level security';
  execute 'revoke all on public.shift_report_recon from anon, authenticated';
  execute 'revoke all on public.shift_recon_log from anon, authenticated';
end $$;

-- Các trường của bản đối soát
create or replace function public.app__recon_fields() returns text[]
language sql immutable as $$ select array['rev_start','rev_end','total_revenue','pos_cash','pos_transfer','reported_transfer',
  'cash_counted','opening_cash','cups','goods_status','goods_note','moves','staff','goods'] $$;

-- Ảnh chụp số liệu phiếu nhân viên (để tạo bản đối soát)
create or replace function public.app__recon_snapshot(p_id bigint) returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'rev_start', r.rev_start, 'rev_end', r.rev_end, 'total_revenue', r.total_revenue, 'pos_cash', r.pos_cash,
    'pos_transfer', r.pos_transfer, 'reported_transfer', r.reported_transfer, 'cash_counted', r.cash_counted,
    'opening_cash', r.opening_cash, 'cups', r.cups, 'goods_status', r.goods_status, 'goods_note', r.goods_note,
    'moves', coalesce((select jsonb_agg(jsonb_build_object('kind', m.kind, 'amount', m.amount, 'note', m.note) order by m.sort_order, m.id)
                       from public.shift_report_moves m where m.report_id = r.id), '[]'),
    'staff', coalesce((select jsonb_agg(jsonb_build_object('employee_id', s.employee_id, 'source', s.source, 'role', s.role, 'worked', s.worked = 1,
                         'time_in', s.time_in, 'time_out', s.time_out, 'absent_reason', s.absent_reason, 'note', s.note) order by s.id)
                       from public.shift_report_staff s where s.report_id = r.id), '[]'),
    'goods', coalesce((select jsonb_agg(jsonb_build_object('item', g.item, 'qty', g.qty) order by g.id)
                       from public.shift_report_goods g where g.report_id = r.id), '[]'))
    from public.shift_reports r where r.id = p_id
$$;

-- Số liệu "chính thức" của một phiếu: bản đối soát nếu có, không thì phiếu nhân viên
create or replace function public.app__ca_eff(p_id bigint) returns jsonb
language sql stable security definer set search_path = public as $$
  select coalesce((select data from public.shift_report_recon where report_id = p_id), public.app__recon_snapshot(p_id))
$$;

-- Lấy bản đối soát (tạo từ phiếu nhân viên nếu chưa có) + phiếu gốc + lịch sử sửa
create or replace function public.app_ca_recon(p_id bigint) returns jsonb
language plpgsql security definer set search_path = public as $$
declare a public.accounts; r public.shift_reports; d jsonb; staff_names jsonb;
begin
  a := public.app__need('doi_soat');
  select * into r from public.shift_reports where id = p_id;
  if r.id is null then raise exception 'Không tìm thấy phiếu.'; end if;
  if r.status <> 'hoan_thanh' then raise exception 'Nhân viên chưa hoàn thành phiếu này nên chưa có bản đối soát.'; end if;
  insert into public.shift_report_recon(report_id, data, updated_by) values (p_id, public.app__recon_snapshot(p_id), a.id)
  on conflict (report_id) do nothing;
  select data into d from public.shift_report_recon where report_id = p_id;
  select coalesce(jsonb_object_agg(e.id::text, jsonb_build_object('code', e.code, 'name', e.name, 'rank', e.rank)), '{}') into staff_names
    from public.employees e
   where e.id in (select (x ->> 'employee_id')::bigint from jsonb_array_elements(d -> 'staff') x
                  union select (x ->> 'employee_id')::bigint from jsonb_array_elements(public.app__recon_snapshot(p_id) -> 'staff') x);
  return jsonb_build_object(
    'data', d,
    'original', public.app__recon_snapshot(p_id),
    'employees', staff_names,
    'editable', r.recon_status <> 'hoan_thanh',
    'recon_status', r.recon_status,
    'log', coalesce((select jsonb_agg(jsonb_build_object('action', l.action, 'field', l.field, 'before', l.before, 'after', l.after,
                       'reason', l.reason, 'by', public.app__acc_name(l.by_account), 'at', l.at) order by l.id desc)
                     from public.shift_recon_log l where l.report_id = p_id), '[]'));
end $$;

-- Lưu bản đối soát: ghi lịch sử từng trường thay đổi
create or replace function public.app_ca_recon_save(p_id bigint, p jsonb, p_reason text) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts; r public.shift_reports; old jsonb; new jsonb := '{}'::jsonb; k text; v jsonb; reason text := nullif(trim(coalesce(p_reason, '')), '');
begin
  a := public.app__need('doi_soat');
  select * into r from public.shift_reports where id = p_id for update;
  if r.id is null or r.status <> 'hoan_thanh' then raise exception 'Phiếu chưa hoàn thành nên chưa đối soát được.'; end if;
  if r.recon_status = 'hoan_thanh' then raise exception 'Phiếu đã HOÀN THÀNH ĐỐI SOÁT. Bấm "Mở lại đối soát" trước khi sửa.'; end if;
  insert into public.shift_report_recon(report_id, data, updated_by) values (p_id, public.app__recon_snapshot(p_id), a.id)
  on conflict (report_id) do nothing;
  select data into old from public.shift_report_recon where report_id = p_id for update;
  -- dựng lại dữ liệu sạch theo đúng các trường cho phép
  foreach k in array public.app__recon_fields() loop
    v := case when p ? k then p -> k else old -> k end;
    if k in ('total_revenue','pos_cash','pos_transfer','reported_transfer','cash_counted','opening_cash','cups') then
      if v is not null and jsonb_typeof(v) <> 'null' then
        if jsonb_typeof(v) <> 'number' or (v::text)::numeric <> trunc((v::text)::numeric) then raise exception 'Số liệu % phải là số nguyên.', k; end if;
        if k <> 'opening_cash' and (v::text)::numeric < 0 then raise exception 'Số liệu % không được âm.', k; end if;
      end if;
    elsif k = 'goods_status' then
      if v is not null and jsonb_typeof(v) <> 'null' and (v #>> '{}') not in ('khong', 'du', 'thieu') then raise exception 'Trạng thái nhập hàng không hợp lệ.'; end if;
    elsif k = 'moves' then
      v := coalesce((select jsonb_agg(jsonb_build_object('kind', x ->> 'kind', 'amount', (x ->> 'amount')::bigint, 'note', coalesce(x ->> 'note', '')))
                       from jsonb_array_elements(coalesce(v, '[]')) x where x ->> 'kind' in ('tien_mat', 'chuyen_khoan') and (x ->> 'amount') is not null), '[]');
    elsif k = 'staff' then
      v := coalesce((select jsonb_agg(jsonb_build_object('employee_id', (x ->> 'employee_id')::bigint, 'source', coalesce(x ->> 'source', 'ho_tro'),
                        'role', x ->> 'role', 'worked', coalesce((x ->> 'worked')::boolean, true), 'time_in', nullif(x ->> 'time_in', ''),
                        'time_out', nullif(x ->> 'time_out', ''), 'absent_reason', nullif(x ->> 'absent_reason', ''), 'note', nullif(x ->> 'note', '')))
                       from jsonb_array_elements(coalesce(v, '[]')) x
                      where exists (select 1 from public.employees e where e.id = (x ->> 'employee_id')::bigint)), '[]');
    elsif k = 'goods' then
      v := coalesce((select jsonb_agg(jsonb_build_object('item', trim(x ->> 'item'), 'qty', coalesce(x ->> 'qty', '')))
                       from jsonb_array_elements(coalesce(v, '[]')) x where trim(coalesce(x ->> 'item', '')) <> ''), '[]');
    end if;
    new := new || jsonb_build_object(k, v);
    if (old -> k) is distinct from v then
      insert into public.shift_recon_log(report_id, action, field, before, after, reason, by_account)
      values (p_id, 'sua', k, old -> k, v, reason, a.id);
    end if;
  end loop;
  if new is distinct from old then
    update public.shift_report_recon set data = new, updated_by = a.id, updated_at = public.vn_now_text() where report_id = p_id;
  end if;
end $$;

-- Đánh dấu từng hạng mục. Đã HOÀN THÀNH ĐỐI SOÁT thì khóa (phải mở lại). Đang đối soát lại thì không tự hoàn thành.
create or replace function public.app_ca_check(p_id bigint, p_item text, p_on boolean) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts; r public.shift_reports; n int;
begin
  a := public.app__need('doi_soat');
  select * into r from public.shift_reports where id = p_id for update;
  if r.id is null then raise exception 'Không tìm thấy phiếu.'; end if;
  if r.status <> 'hoan_thanh' then raise exception 'Nhân viên chưa hoàn thành phiếu này.'; end if;
  if r.recon_status = 'hoan_thanh' then raise exception 'Phiếu đã HOÀN THÀNH ĐỐI SOÁT. Bấm "Mở lại đối soát" trước khi sửa.'; end if;
  if not (p_item = any(public.app__ca_check_items())) then raise exception 'Hạng mục không hợp lệ.'; end if;
  if p_on then
    insert into public.shift_report_checks(report_id, item, checked_by, checked_at) values (p_id, p_item, a.id, public.vn_now_text())
    on conflict (report_id, item) do nothing;
  else
    delete from public.shift_report_checks where report_id = p_id and item = p_item;
  end if;
  select count(*) into n from public.shift_report_checks where report_id = p_id;
  if r.recon_status = 'chua' and n >= array_length(public.app__ca_check_items(), 1) then
    insert into public.shift_report_recon(report_id, data, updated_by) values (p_id, public.app__recon_snapshot(p_id), a.id)
    on conflict (report_id) do nothing;
    update public.shift_reports set recon_status = 'hoan_thanh', recon_by = a.id, recon_at = public.vn_now_text() where id = p_id;
    insert into public.shift_recon_log(report_id, action, by_account) values (p_id, 'hoan_thanh_doi_soat', a.id);
  end if;
  perform public.app_log('doi_soat_ca', 'report=' || p_id || ' ' || p_item || '=' || p_on);
end $$;

-- Mở lại đối soát (phiếu nhân viên không đổi)
create or replace function public.app_ca_recon_reopen(p_id bigint, p_reason text) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts;
begin
  a := public.app__need('doi_soat');
  update public.shift_reports set recon_status = 'mo_lai', recon_by = null, recon_at = null where id = p_id and recon_status = 'hoan_thanh';
  if not found then raise exception 'Phiếu chưa hoàn thành đối soát.'; end if;
  insert into public.shift_recon_log(report_id, action, reason, by_account) values (p_id, 'mo_lai_doi_soat', nullif(trim(coalesce(p_reason, '')), ''), a.id);
  perform public.app_log('mo_lai_doi_soat', 'report=' || p_id);
end $$;

-- Hoàn thành đối soát (dùng khi đang đối soát lại; cần đủ hạng mục)
create or replace function public.app_ca_recon_finish(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts; r public.shift_reports; n int;
begin
  a := public.app__need('doi_soat');
  select * into r from public.shift_reports where id = p_id for update;
  if r.id is null or r.status <> 'hoan_thanh' then raise exception 'Phiếu chưa hoàn thành.'; end if;
  if r.recon_status = 'hoan_thanh' then return; end if;
  select count(*) into n from public.shift_report_checks where report_id = p_id;
  if n < array_length(public.app__ca_check_items(), 1) then
    raise exception 'Còn % hạng mục chưa đối soát.', array_length(public.app__ca_check_items(), 1) - n;
  end if;
  insert into public.shift_report_recon(report_id, data, updated_by) values (p_id, public.app__recon_snapshot(p_id), a.id)
  on conflict (report_id) do nothing;
  update public.shift_reports set recon_status = 'hoan_thanh', recon_by = a.id, recon_at = public.vn_now_text() where id = p_id;
  insert into public.shift_recon_log(report_id, action, by_account) values (p_id, 'hoan_thanh_doi_soat', a.id);
  perform public.app_log('hoan_thanh_doi_soat', 'report=' || p_id);
end $$;

-- Mở lại phiếu cho nhân viên sửa phiếu gốc: bản đối soát làm lại từ đầu (lịch sử vẫn giữ)
create or replace function public.app_ca_reopen(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts;
begin
  a := public.app__need('mo_lai_phieu_ca');
  update public.shift_reports set status = 'dang_chot', recon_status = 'chua', recon_by = null, recon_at = null,
         completed_at = null, completed_by = null, updated_by = a.id, updated_at = public.vn_now_text()
   where id = p_id and status = 'hoan_thanh';
  if not found then raise exception 'Phiếu chưa hoàn thành hoặc không tồn tại.'; end if;
  delete from public.shift_report_checks where report_id = p_id;
  delete from public.shift_report_recon where report_id = p_id;
  insert into public.shift_recon_log(report_id, action, by_account) values (p_id, 'lam_lai', a.id);
  perform public.app_log('mo_lai_phieu_ca', 'report=' || p_id);
end $$;

-- Tiền mặt cuối ngày: dùng số liệu chính thức (bản đối soát), kèm số ca chưa xong đối soát / đang đối soát lại
create or replace function public.app_ca_day(p_date text) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare out jsonb;
begin
  perform public.app__need('doi_soat');
  select coalesce(jsonb_agg(jsonb_build_object(
      'branch_id', b.id, 'branch_code', coalesce(b.display_code, b.code), 'branch_name', b.name,
      'shifts', (select count(*) from public.branch_shifts bs join public.shifts s on s.id = bs.shift_id and s.status = 'Đang sử dụng'
                  where bs.branch_id = b.id and bs.enabled = 1),
      'done', (select count(*) from public.shift_reports r where r.branch_id = b.id and r.work_date = p_date and r.status = 'hoan_thanh'),
      'recon_done', (select count(*) from public.shift_reports r where r.branch_id = b.id and r.work_date = p_date and r.recon_status = 'hoan_thanh'),
      'recon_reopen', (select count(*) from public.shift_reports r where r.branch_id = b.id and r.work_date = p_date and r.recon_status = 'mo_lai'),
      'opening', (select (public.app__ca_eff(r.id) ->> 'opening_cash')::bigint from public.shift_reports r where r.branch_id = b.id and r.work_date = p_date
                   order by array_position(public.app__shifts(), r.shift) limit 1),
      'pos_cash', (select sum((public.app__ca_eff(r.id) ->> 'pos_cash')::bigint) from public.shift_reports r
                    where r.branch_id = b.id and r.work_date = p_date and r.status = 'hoan_thanh'),
      'moves_cash', (select coalesce(sum((m ->> 'amount')::bigint), 0) from public.shift_reports r
                     cross join lateral jsonb_array_elements(public.app__ca_eff(r.id) -> 'moves') m
                     where r.branch_id = b.id and r.work_date = p_date and r.status = 'hoan_thanh' and m ->> 'kind' = 'tien_mat'),
      'last_counted', (select (public.app__ca_eff(r.id) ->> 'cash_counted')::bigint from public.shift_reports r
                        where r.branch_id = b.id and r.work_date = p_date and r.status = 'hoan_thanh'
                        order by array_position(public.app__shifts(), r.shift) desc limit 1),
      'last_shift', (select r.shift from public.shift_reports r where r.branch_id = b.id and r.work_date = p_date and r.status = 'hoan_thanh'
                      order by array_position(public.app__shifts(), r.shift) desc limit 1),
      'has_debt', exists (select 1 from public.shift_debts d join public.shift_reports r on r.id = d.report_id
                           where r.branch_id = b.id and r.work_date = p_date),
      'counted', c.counted, 'note', c.note, 'done_by', public.app__acc_name(c.done_by), 'done_at', c.done_at
    ) order by b.sort_order), '[]'::jsonb) into out
    from public.branches b
    left join public.daily_cash_closings c on c.branch_id = b.id and c.work_date = p_date
   where b.status = 'Đang hoạt động';
  return out;
end $$;

-- Tổng quan ca: tiền theo số liệu chính thức (bản đối soát nếu có)
create or replace function public.app_ca_overview(p_date text) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare out jsonb;
begin
  perform public.app__need('chot_ca');
  select coalesce(jsonb_agg(x.j order by x.ord, x.sord), '[]'::jsonb) into out from (
    select b.sort_order as ord, sh.sort_order as sord,
           jsonb_build_object('branch_id', b.id, 'branch_code', coalesce(b.display_code, b.code), 'branch_name', b.name,
             'shift', sh.name, 'start_time', bs.start_time, 'end_time', bs.end_time,
             'report_id', r.id, 'status', r.status, 'recon_status', r.recon_status,
             'created_by', public.app__acc_name(r.created_by), 'completed_by', public.app__acc_name(r.completed_by),
             'completed_at', r.completed_at,
             'cash_diff', case when r.status = 'hoan_thanh' then (e.d ->> 'cash_counted')::bigint - (e.d ->> 'opening_cash')::bigint - (e.d ->> 'pos_cash')::bigint end,
             'transfer_diff', case when r.status = 'hoan_thanh' then (e.d ->> 'reported_transfer')::bigint - (e.d ->> 'pos_transfer')::bigint end,
             'cash_left', case when r.status = 'hoan_thanh' then (e.d ->> 'cash_counted')::bigint - (e.d ->> 'opening_cash')::bigint - (e.d ->> 'pos_cash')::bigint
                - coalesce((select sum((m ->> 'amount')::bigint) from jsonb_array_elements(e.d -> 'moves') m where m ->> 'kind' = 'tien_mat'), 0) end,
             'transfer_left', case when r.status = 'hoan_thanh' then (e.d ->> 'reported_transfer')::bigint - (e.d ->> 'pos_transfer')::bigint
                - coalesce((select sum((m ->> 'amount')::bigint) from jsonb_array_elements(e.d -> 'moves') m where m ->> 'kind' = 'chuyen_khoan'), 0) end,
             'checks', (select count(*) from public.shift_report_checks c where c.report_id = r.id),
             'has_debt', exists (select 1 from public.shift_debts d where d.report_id = r.id)) as j
      from public.branches b
      join public.branch_shifts bs on bs.branch_id = b.id and bs.enabled = 1
      join public.shifts sh on sh.id = bs.shift_id and sh.status = 'Đang sử dụng'
      left join public.shift_reports r on r.branch_id = b.id and r.work_date = p_date and r.shift = sh.name
      left join lateral (select case when r.status = 'hoan_thanh' then public.app__ca_eff(r.id) end as d) e on true
     where b.status = 'Đang hoạt động'
  ) x;
  return out;
end $$;

