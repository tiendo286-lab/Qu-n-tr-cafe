-- ---------------------------------------------------------------- Quyền
create or replace function public.app__fin_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce((select a.system_role in ('chu', 'ql_tong') from public.accounts a where a.id = (public.app_account()).id), false)
$$;

create or replace function public.app__fin_can(p_branch bigint) returns boolean
language plpgsql stable security definer set search_path = public as $$
declare a public.accounts;
begin
  a := public.app_account();
  if a.id is null or coalesce(a.locked, 0) = 1 then return false; end if;
  if coalesce(a.system_role, '') in ('chu', 'ql_tong') then return true; end if;
  if coalesce(a.system_role, '') = 'ql' then
    return exists (select 1 from public.fin_branch_managers m where m.account_id = a.id and m.branch_id = p_branch);
  end if;
  return false;
end $$;

create or replace function public.app__fin_need(p_branch bigint) returns public.accounts
language plpgsql stable security definer set search_path = public as $$
begin
  if not public.app__fin_can(p_branch) then raise exception 'Bạn không được xem / sửa chốt tháng của cơ sở này.'; end if;
  return public.app_account();
end $$;

create or replace function public.app__fin_month_ok(p text) returns text
language plpgsql immutable as $$
begin
  if p is null or p !~ '^\d{4}-(0[1-9]|1[0-2])$' then raise exception 'Tháng không hợp lệ.'; end if;
  return p;
end $$;

-- ---------------------------------------------------------------- Khóa số liệu tháng đã chốt
create or replace function public.app__fin_locked(p_branch bigint, p_date text) returns boolean
language sql stable security definer set search_path = public as $$
  select p_branch is not null and p_date is not null
     and exists (select 1 from public.fin_month_closes c where c.branch_id = p_branch and c.month = left(p_date, 7))
$$;

create or replace function public.app__fin_guard() returns trigger
language plpgsql security definer set search_path = public as $$
declare b bigint; d text; b2 bigint; d2 text; rid bigint;
begin
  if TG_TABLE_NAME in ('shift_reports', 'daily_cash_closings') then
    if TG_OP <> 'INSERT' then b := OLD.branch_id; d := OLD.work_date; end if;
    if TG_OP <> 'DELETE' then b2 := NEW.branch_id; d2 := NEW.work_date; end if;
  elsif TG_TABLE_NAME = 'fin_entries' then
    if TG_OP <> 'INSERT' then b := OLD.branch_id; d := OLD.entry_date; end if;
    if TG_OP <> 'DELETE' then b2 := NEW.branch_id; d2 := NEW.entry_date; end if;
  else  -- bảng gắn với phiếu ca qua report_id
    rid := case when TG_OP = 'DELETE' then OLD.report_id else NEW.report_id end;
    select branch_id, work_date into b, d from public.shift_reports where id = rid;
  end if;
  if public.app__fin_locked(b, d) or public.app__fin_locked(b2, d2) then
    raise exception 'Tháng % của cơ sở này đã CHỐT nên không sửa được. Chủ mở lại tháng (ghi lý do) trước khi sửa.',
      to_char((left(coalesce(d2, d), 7) || '-01')::date, 'MM/YYYY');
  end if;
  return case when TG_OP = 'DELETE' then OLD else NEW end;
end $$;

do $$
declare t text;
begin
  foreach t in array array['shift_reports', 'shift_report_recon', 'shift_report_results', 'shift_report_checks', 'daily_cash_closings', 'fin_entries', 'fin_move_cats'] loop
    execute format('drop trigger if exists fin_guard on public.%I', t);
    execute format('create trigger fin_guard before insert or update or delete on public.%I for each row execute function public.app__fin_guard()', t);
  end loop;
end $$;

-- ---------------------------------------------------------------- Tính số liệu tháng của một cơ sở
create or replace function public.app__fin_calc(p_branch bigint, p_month text) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare b public.branches; d0 date; d1 date; today text := to_char(public.vn_now(), 'YYYY-MM-DD'); upto date;
        rev jsonb; days jsonb; moves jsonb; entries jsonb; bank jsonb; ka jsonb; n_chain int; expect_shifts int;
        chi_auto bigint; thu_auto bigint; chi_tay bigint; thu_tay bigint; by_cat jsonb; c public.fin_month_closes;
begin
  select * into b from public.branches where id = p_branch;
  if b.id is null then raise exception 'Không tìm thấy cơ sở.'; end if;
  d0 := (p_month || '-01')::date; d1 := (d0 + interval '1 month' - interval '1 day')::date;
  upto := least(d1, today::date);
  select count(*) into n_chain from public.branch_shifts bs join public.shifts s on s.id = bs.shift_id
   where bs.branch_id = p_branch and bs.enabled = 1 and s.status = 'Đang sử dụng' and public.app__ca_chain(s.name);
  expect_shifts := case when upto < d0 then 0 else n_chain * ((upto - d0) + 1) end;

  -- doanh thu theo phiếu ca (số chính thức)
  with r as (
    select x.*, public.app__ca_eff(x.id) as e from public.shift_reports x
     where x.branch_id = p_branch and x.work_date between d0::text and d1::text
  )
  select jsonb_build_object(
    'reports', count(*), 'done', count(*) filter (where status = 'hoan_thanh'),
    'recon', count(*) filter (where recon_status = 'hoan_thanh'), 'in_progress', count(*) filter (where status = 'dang_chot'),
    'expect', expect_shifts,
    'total_revenue', coalesce(sum((e ->> 'total_revenue')::bigint) filter (where status = 'hoan_thanh'), 0),
    'pos_cash', coalesce(sum((e ->> 'pos_cash')::bigint) filter (where status = 'hoan_thanh'), 0),
    'pos_transfer', coalesce(sum((e ->> 'pos_transfer')::bigint) filter (where status = 'hoan_thanh'), 0),
    'cups', coalesce(sum((e ->> 'cups')::int) filter (where status = 'hoan_thanh'), 0),
    'debt_new', coalesce((select sum(dd.amount) from public.shift_debts dd join r rr on rr.id = dd.report_id where rr.status = 'hoan_thanh'), 0),
    'debt_col_tm', coalesce((select sum(dd.amount) from public.shift_debts dd join r rr on rr.id = dd.closed_report_id
                              where rr.status = 'hoan_thanh' and dd.collect_kind = 'tien_mat'), 0),
    'debt_col_ck', coalesce((select sum(dd.amount) from public.shift_debts dd join r rr on rr.id = dd.closed_report_id
                              where rr.status = 'hoan_thanh' and dd.collect_kind = 'chuyen_khoan'), 0))
    into rev from r;

  -- tiền mặt theo ngày (giống Đối soát cuối ngày)
  select coalesce(jsonb_agg(z.j order by z.dd), '[]') into days from (
    select g.dd, jsonb_build_object('date', g.dd, 'done', q.done, 'opening', q.opening, 'pos_cash', q.pos_cash, 'moves_cash', q.moves_cash,
             'debt_cash', q.debt_cash, 'counted', c2.counted, 'counted_by', public.app__acc_name(c2.done_by),
             'expected', case when q.opening is not null and q.pos_cash is not null then q.opening + q.pos_cash + q.moves_cash + q.debt_cash end) as j
      from (select to_char(x, 'YYYY-MM-DD') as dd from generate_series(d0, d1, interval '1 day') x) g
      cross join lateral (
        select count(*) filter (where r.status = 'hoan_thanh') as done,
               (select (public.app__ca_eff(r2.id) ->> 'opening_cash')::bigint from public.shift_reports r2
                 where r2.branch_id = p_branch and r2.work_date = g.dd order by array_position(public.app__shifts(), r2.shift) limit 1) as opening,
               sum((public.app__ca_eff(r.id) ->> 'pos_cash')::bigint) filter (where r.status = 'hoan_thanh') as pos_cash,
               coalesce((select sum((m ->> 'amount')::bigint) from public.shift_reports r3
                          cross join lateral jsonb_array_elements(public.app__ca_eff(r3.id) -> 'moves') m
                          where r3.branch_id = p_branch and r3.work_date = g.dd and r3.status = 'hoan_thanh' and m ->> 'kind' = 'tien_mat'), 0) as moves_cash,
               coalesce((select sum(dd.amount) from public.shift_debts dd join public.shift_reports r4 on r4.id = dd.closed_report_id
                          where r4.branch_id = p_branch and r4.work_date = g.dd and r4.status = 'hoan_thanh' and dd.collect_kind = 'tien_mat'), 0) as debt_cash
          from public.shift_reports r where r.branch_id = p_branch and r.work_date = g.dd) q
      left join public.daily_cash_closings c2 on c2.branch_id = p_branch and c2.work_date = g.dd
     where q.done > 0 or c2.counted is not null
  ) z;

  -- chuyển khoản thực nhận (kế toán) — chỉ các ca đã nhập đủ tài khoản
  select jsonb_build_object('pos_transfer', coalesce(sum(pt), 0), 'received', coalesce(sum(rc) filter (where ok), 0),
           'pos_transfer_ok', coalesce(sum(pt) filter (where ok), 0), 'shifts_ok', count(*) filter (where ok), 'shifts', count(*))
    into bank from (
      select (public.app__ca_eff(x.id) ->> 'pos_transfer')::bigint as pt, (k ->> 'received')::bigint as rc,
             coalesce((k ->> 'account_count')::int, 0) > 0 and (k ->> 'entered')::int = (k ->> 'account_count')::int as ok
        from public.shift_reports x cross join lateral (select public.app__kt_bank_json(x) as k) kk
       where x.branch_id = p_branch and x.work_date between d0::text and d1::text and x.status = 'hoan_thanh') y;

  -- khoản thu chi ghi ở phiếu ca + phân nhóm
  select coalesce(jsonb_agg(jsonb_build_object('report_id', m.rid, 'date', m.work_date, 'shift', m.shift, 'kind', m.kind, 'amount', m.amount, 'note', m.note,
           'mkey', m.mkey, 'category_id', fc.category_id, 'excluded', coalesce(fc.excluded, case when m.amount > 0 then 1 else 0 end) = 1,
           'set', fc.report_id is not null) order by m.work_date, array_position(public.app__shifts(), m.shift), m.ord), '[]')
    into moves from (
      select x.id as rid, x.work_date, x.shift, t.ord, t.v ->> 'kind' as kind, (t.v ->> 'amount')::bigint as amount, coalesce(t.v ->> 'note', '') as note,
             md5((t.v ->> 'kind') || '|' || (t.v ->> 'amount') || '|' || coalesce(t.v ->> 'note', '')) || '#'
               || row_number() over (partition by x.id, md5((t.v ->> 'kind') || '|' || (t.v ->> 'amount') || '|' || coalesce(t.v ->> 'note', '')) order by t.ord) as mkey
        from public.shift_reports x
        cross join lateral jsonb_array_elements(public.app__ca_eff(x.id) -> 'moves') with ordinality t(v, ord)
       where x.branch_id = p_branch and x.work_date between d0::text and d1::text and x.status = 'hoan_thanh') m
    left join public.fin_move_cats fc on fc.report_id = m.rid and fc.mkey = m.mkey;

  select coalesce(jsonb_agg(to_jsonb(e) || jsonb_build_object('category', c3.name, 'by', public.app__acc_name(e.created_by)) order by e.entry_date, e.id), '[]')
    into entries from public.fin_entries e left join public.fin_categories c3 on c3.id = e.category_id
   where e.branch_id = p_branch and e.entry_date between d0::text and d1::text;

  -- khoản âm của tháng
  select jsonb_build_object('total', coalesce(sum(s.amount), 0),
           'chua_xu_ly', coalesce(sum(s.amount) filter (where s.status = 'chua_xu_ly'), 0),
           'da_bu', coalesce(sum(s.amount) filter (where s.status = 'da_bu'), 0),
           'tru_luong', coalesce(sum(s.amount) filter (where s.status = 'tru_luong'), 0),
           'mien', coalesce(sum(s.amount) filter (where s.status = 'mien'), 0), 'count', count(*))
    into ka from public.shift_shortfalls s join public.shift_reports x on x.id = s.report_id
   where x.branch_id = p_branch and x.work_date between d0::text and d1::text and s.status <> 'huy';

  -- tổng chi / thu: khoản ở phiếu ca (âm = chi, dương = thu; "Không tính" bỏ qua) + nhập tay
  select coalesce(sum(-(m ->> 'amount')::bigint) filter (where (m ->> 'amount')::bigint < 0 and not (m ->> 'excluded')::boolean), 0),
         coalesce(sum((m ->> 'amount')::bigint) filter (where (m ->> 'amount')::bigint > 0 and not (m ->> 'excluded')::boolean), 0)
    into chi_auto, thu_auto from jsonb_array_elements(moves) m;
  select coalesce(sum(amount) filter (where kind = 'chi'), 0), coalesce(sum(amount) filter (where kind = 'thu'), 0)
    into chi_tay, thu_tay from public.fin_entries where branch_id = p_branch and entry_date between d0::text and d1::text;
  select coalesce(jsonb_agg(jsonb_build_object('kind', y.kind, 'category_id', y.cid, 'name', coalesce(fc.name, 'Chưa phân nhóm'), 'amount', y.amt)
           order by y.kind, coalesce(fc.sort_order, 1000), fc.name), '[]')
    into by_cat from (
      select kind, cid, sum(amt) as amt from (
        select case when (m ->> 'amount')::bigint < 0 then 'chi' else 'thu' end as kind, (m ->> 'category_id')::bigint as cid, abs((m ->> 'amount')::bigint) as amt
          from jsonb_array_elements(moves) m where not (m ->> 'excluded')::boolean
        union all
        select kind, category_id, amount from public.fin_entries where branch_id = p_branch and entry_date between d0::text and d1::text) u
      group by kind, cid) y
    left join public.fin_categories fc on fc.id = y.cid;

  select * into c from public.fin_month_closes where branch_id = p_branch and month = p_month;
  return jsonb_build_object('branch_id', b.id, 'branch_code', coalesce(b.display_code, b.code), 'branch_name', b.name, 'month', p_month,
    'from', d0, 'to', d1, 'revenue', rev, 'days', days, 'bank', bank, 'moves', moves, 'entries', entries, 'shortfalls', ka, 'by_cat', by_cat,
    'cash', jsonb_build_object(
       'pos_cash', (rev ->> 'pos_cash')::bigint, 'debt_cash', (rev ->> 'debt_col_tm')::bigint,
       'moves_cash', coalesce((select sum((x ->> 'moves_cash')::bigint) from jsonb_array_elements(days) x), 0),
       'gap', coalesce((select sum((x ->> 'counted')::bigint - (x ->> 'expected')::bigint) from jsonb_array_elements(days) x
                         where x ->> 'counted' is not null and x ->> 'expected' is not null), 0),
       'days_counted', (select count(*) from jsonb_array_elements(days) x where x ->> 'counted' is not null),
       'days_open', (select count(*) from jsonb_array_elements(days) x where (x ->> 'done')::int > 0)),
    'totals', jsonb_build_object('revenue', (rev ->> 'total_revenue')::bigint, 'chi_ca', chi_auto, 'thu_ca', thu_auto, 'chi_tay', chi_tay, 'thu_tay', thu_tay,
       'chi', chi_auto + chi_tay, 'thu', thu_auto + thu_tay,
       'profit', (rev ->> 'total_revenue')::bigint + thu_auto + thu_tay - chi_auto - chi_tay,
       'uncat', (select count(*) from jsonb_array_elements(moves) m where not (m ->> 'excluded')::boolean and m ->> 'category_id' is null)),
    'closed', case when c.branch_id is null then null else jsonb_build_object('by', public.app__acc_name(c.closed_by), 'at', c.closed_at, 'note', c.note) end);
end $$;

-- ---------------------------------------------------------------- Đọc
create or replace function public.app_fin_branches() returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare a public.accounts := public.app_account();
begin
  if a.id is null then raise exception 'Chưa đăng nhập.'; end if;
  return jsonb_build_object('admin', public.app__fin_admin(), 'owner', coalesce(a.system_role, '') = 'chu',
    'branches', coalesce((select jsonb_agg(jsonb_build_object('id', b.id, 'code', coalesce(b.display_code, b.code), 'name', b.name) order by b.sort_order)
                 from public.branches b where b.status = 'Đang hoạt động' and public.app__fin_can(b.id)), '[]'));
end $$;

create or replace function public.app_fin_month(p_branch bigint, p_month text) returns jsonb
language plpgsql stable security definer set search_path = public as $$
begin
  perform public.app__fin_need(p_branch);
  perform public.app__fin_month_ok(p_month);
  return public.app__fin_calc(p_branch, p_month) || jsonb_build_object(
    'categories', coalesce((select jsonb_agg(to_jsonb(c) order by c.kind, c.sort_order, c.name) from public.fin_categories c), '[]'),
    'log', coalesce((select jsonb_agg(jsonb_build_object('action', l.action, 'reason', l.reason, 'by', public.app__acc_name(l.by_account), 'at', l.at) order by l.id desc)
                       from public.fin_close_log l where l.branch_id = p_branch and l.month = p_month), '[]'),
    'can_reopen', coalesce((public.app_account()).system_role, '') = 'chu');
end $$;

create or replace function public.app_fin_overview(p_month text) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare j jsonb;
begin
  perform public.app__fin_month_ok(p_month);
  select coalesce(jsonb_agg(jsonb_build_object('branch_id', b.id, 'code', coalesce(b.display_code, b.code), 'name', b.name,
           'revenue', c.j -> 'revenue', 'totals', c.j -> 'totals', 'cash', c.j -> 'cash', 'shortfalls', c.j -> 'shortfalls', 'closed', c.j -> 'closed')
           order by b.sort_order), '[]')
    into j from public.branches b cross join lateral (select public.app__fin_calc(b.id, p_month) as j) c
   where b.status = 'Đang hoạt động' and public.app__fin_can(b.id);
  return j;
end $$;

-- ---------------------------------------------------------------- Ghi: chi phí / thu khác nhập tay
create or replace function public.app_fin_entry_save(p_id bigint, p jsonb) returns bigint
language plpgsql security definer set search_path = public as $$
declare a public.accounts; br bigint := (p ->> 'branch_id')::bigint; d text := p ->> 'entry_date'; k text := p ->> 'kind';
        cat bigint := nullif(p ->> 'category_id', '')::bigint; amt bigint := nullif(p ->> 'amount', '')::bigint; nid bigint; old public.fin_entries;
begin
  if p_id is not null then
    select * into old from public.fin_entries where id = p_id;
    if old.id is null then raise exception 'Không tìm thấy khoản này.'; end if;
    perform public.app__fin_need(old.branch_id);
    br := old.branch_id;
  end if;
  a := public.app__fin_need(br);
  if d is null or d !~ '^\d{4}-\d{2}-\d{2}$' then raise exception 'Chọn ngày.'; end if;
  if k not in ('chi', 'thu') then raise exception 'Chọn Chi hay Thu.'; end if;
  if amt is null or amt <= 0 then raise exception 'Nhập số tiền lớn hơn 0.'; end if;
  if trim(coalesce(p ->> 'note', '')) = '' then raise exception 'Ghi nội dung khoản %.', case when k = 'chi' then 'chi' else 'thu' end; end if;
  if cat is not null and not exists (select 1 from public.fin_categories where id = cat and kind = k) then raise exception 'Nhóm không đúng loại Chi / Thu.'; end if;
  if p_id is null then
    insert into public.fin_entries(branch_id, entry_date, kind, category_id, amount, note, pay_method, created_by, updated_by)
    values (br, d, k, cat, amt, trim(p ->> 'note'), coalesce(nullif(p ->> 'pay_method', ''), 'tien_mat'), a.id, a.id) returning id into nid;
  else
    update public.fin_entries set entry_date = d, kind = k, category_id = cat, amount = amt, note = trim(p ->> 'note'),
           pay_method = coalesce(nullif(p ->> 'pay_method', ''), 'tien_mat'), updated_by = a.id, updated_at = public.vn_now_text()
     where id = p_id;
    nid := p_id;
  end if;
  perform public.app_log('chot_thang_khoan', 'entry=' || nid || ' ' || k || ' ' || amt);
  return nid;
end $$;

create or replace function public.app_fin_entry_delete(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
declare e public.fin_entries;
begin
  select * into e from public.fin_entries where id = p_id;
  if e.id is null then return; end if;
  perform public.app__fin_need(e.branch_id);
  delete from public.fin_entries where id = p_id;
  perform public.app_log('chot_thang_xoa_khoan', 'entry=' || p_id || ' ' || e.kind || ' ' || e.amount);
end $$;

-- Phân nhóm khoản ở phiếu ca: p_category = nhóm; p_excluded = true → "Không tính"
create or replace function public.app_fin_move_set(p_report bigint, p_mkey text, p_category bigint, p_excluded boolean) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts; r public.shift_reports;
begin
  select * into r from public.shift_reports where id = p_report;
  if r.id is null then raise exception 'Không tìm thấy phiếu ca.'; end if;
  a := public.app__fin_need(r.branch_id);
  if p_category is not null and not exists (select 1 from public.fin_categories where id = p_category) then raise exception 'Nhóm không hợp lệ.'; end if;
  insert into public.fin_move_cats(report_id, mkey, category_id, excluded, by_account, at)
  values (p_report, p_mkey, case when coalesce(p_excluded, false) then null else p_category end, case when coalesce(p_excluded, false) then 1 else 0 end, a.id, public.vn_now_text())
  on conflict (report_id, mkey) do update set category_id = excluded.category_id, excluded = excluded.excluded, by_account = excluded.by_account, at = excluded.at;
end $$;

-- ---------------------------------------------------------------- Chốt / mở lại tháng
create or replace function public.app_fin_close(p_branch bigint, p_month text, p_note text) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts; j jsonb;
begin
  a := public.app__fin_need(p_branch);
  perform public.app__fin_month_ok(p_month);
  if p_month >= to_char(public.vn_now(), 'YYYY-MM') then raise exception 'Chỉ chốt được tháng đã kết thúc.'; end if;
  if exists (select 1 from public.fin_month_closes where branch_id = p_branch and month = p_month) then raise exception 'Tháng này đã chốt rồi.'; end if;
  j := public.app__fin_calc(p_branch, p_month);
  if (j -> 'revenue' ->> 'in_progress')::int > 0 then
    raise exception 'Còn % phiếu chốt ca đang chốt dở trong tháng. Hoàn thành hết rồi mới chốt tháng.', j -> 'revenue' ->> 'in_progress';
  end if;
  if (j -> 'revenue' ->> 'recon')::int < (j -> 'revenue' ->> 'done')::int then
    raise exception 'Còn % ca chưa hoàn thành đối soát. Đối soát xong rồi mới chốt tháng.', (j -> 'revenue' ->> 'done')::int - (j -> 'revenue' ->> 'recon')::int;
  end if;
  if (j -> 'totals' ->> 'uncat')::int > 0 then
    raise exception 'Còn % khoản chi ở phiếu ca chưa phân nhóm. Chọn nhóm hoặc "Không tính" trước khi chốt.', j -> 'totals' ->> 'uncat';
  end if;
  insert into public.fin_month_closes(branch_id, month, note, snapshot, closed_by) values (p_branch, p_month, nullif(trim(coalesce(p_note, '')), ''), j, a.id);
  insert into public.fin_close_log(branch_id, month, action, reason, by_account) values (p_branch, p_month, 'chot', nullif(trim(coalesce(p_note, '')), ''), a.id);
  perform public.app_log('chot_thang', 'branch=' || p_branch || ' ' || p_month);
end $$;

create or replace function public.app_fin_reopen(p_branch bigint, p_month text, p_reason text) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts := public.app_account();
begin
  if coalesce(a.system_role, '') <> 'chu' then raise exception 'Chỉ Chủ được mở lại tháng đã chốt.'; end if;
  perform public.app__fin_month_ok(p_month);
  if trim(coalesce(p_reason, '')) = '' then raise exception 'Ghi lý do mở lại tháng.'; end if;
  delete from public.fin_month_closes where branch_id = p_branch and month = p_month;
  if not found then raise exception 'Tháng này chưa chốt.'; end if;
  insert into public.fin_close_log(branch_id, month, action, reason, by_account) values (p_branch, p_month, 'mo_lai', trim(p_reason), a.id);
  perform public.app_log('mo_lai_thang', 'branch=' || p_branch || ' ' || p_month);
end $$;

-- ---------------------------------------------------------------- Cài đặt: nhóm chi / thu, quản lý phụ trách cơ sở
create or replace function public.app_fin_category_save(p_id bigint, p_kind text, p_name text, p_sort integer, p_active boolean) returns bigint
language plpgsql security definer set search_path = public as $$
declare nid bigint;
begin
  if not public.app__fin_admin() then raise exception 'Chỉ Chủ và Quản lý tổng sửa được nhóm chi / thu.'; end if;
  if trim(coalesce(p_name, '')) = '' then raise exception 'Nhập tên nhóm.'; end if;
  if p_id is null then
    if p_kind not in ('chi', 'thu') then raise exception 'Chọn Chi hay Thu.'; end if;
    insert into public.fin_categories(kind, name, sort_order) values (p_kind, trim(p_name), coalesce(p_sort, 50)) returning id into nid;
  else
    update public.fin_categories set name = trim(p_name), sort_order = coalesce(p_sort, sort_order), active = case when coalesce(p_active, true) then 1 else 0 end
     where id = p_id returning id into nid;
    if nid is null then raise exception 'Không tìm thấy nhóm.'; end if;
  end if;
  return nid;
exception when unique_violation then raise exception 'Đã có nhóm tên này.';
end $$;

create or replace function public.app_fin_managers() returns jsonb
language plpgsql stable security definer set search_path = public as $$
begin
  if coalesce((public.app_account()).system_role, '') <> 'chu' then raise exception 'Chỉ Chủ giao cơ sở cho quản lý.'; end if;
  return coalesce((select jsonb_agg(jsonb_build_object('account_id', a.id, 'name', public.app__acc_name(a.id),
            'branches', coalesce((select jsonb_agg(m.branch_id) from public.fin_branch_managers m where m.account_id = a.id), '[]')) order by public.app__acc_name(a.id))
           from public.accounts a where a.system_role = 'ql' and coalesce(a.locked, 0) = 0), '[]');
end $$;

create or replace function public.app_fin_manager_set(p_account bigint, p_branches bigint[]) returns void
language plpgsql security definer set search_path = public as $$
begin
  if coalesce((public.app_account()).system_role, '') <> 'chu' then raise exception 'Chỉ Chủ giao cơ sở cho quản lý.'; end if;
  if not exists (select 1 from public.accounts where id = p_account and system_role = 'ql') then raise exception 'Chỉ giao cho tài khoản Quản lý.'; end if;
  delete from public.fin_branch_managers where account_id = p_account;
  insert into public.fin_branch_managers(account_id, branch_id) select p_account, x from unnest(coalesce(p_branches, '{}')) x
   where exists (select 1 from public.branches b where b.id = x) on conflict do nothing;
  perform public.app_log('giao_co_so_chot_thang', 'account=' || p_account || ' ' || coalesce(array_to_string(p_branches, ','), ''));
end $$;

-- ---------------------------------------------------------------- Sửa: đối soát cuối ngày chỉ đếm các ca trong chuỗi két (bỏ ca FULL TIME)
-- (trước đây LHP có 2 ca FULL TIME không có phiếu nên không bao giờ đủ ca để đối soát cuối ngày)
create or replace function public.app_ca_day_save(p_branch bigint, p_date text, p_counted bigint, p_note text) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts; total int; done int;
begin
  a := public.app__need('doi_soat');
  select count(*) into total from public.branch_shifts bs join public.shifts s on s.id = bs.shift_id and s.status = 'Đang sử dụng'
   where bs.branch_id = p_branch and bs.enabled = 1 and public.app__ca_chain(s.name);
  select count(*) into done from public.shift_reports where branch_id = p_branch and work_date = p_date and status = 'hoan_thanh' and public.app__ca_chain(shift);
  if done < total then raise exception 'Chưa đủ % phiếu ca hoàn thành trong ngày (mới có %).', total, done; end if;
  if p_counted is null or p_counted < 0 then raise exception 'Nhập số tiền mặt cuối ngày đã kiểm đếm.'; end if;
  insert into public.daily_cash_closings(branch_id, work_date, counted, note, done_by, done_at)
  values (p_branch, p_date, p_counted, nullif(trim(coalesce(p_note, '')), ''), a.id, public.vn_now_text())
  on conflict (branch_id, work_date) do update set counted = excluded.counted, note = excluded.note, done_by = excluded.done_by, done_at = excluded.done_at;
  perform public.app_log('doi_soat_cuoi_ngay', 'branch=' || p_branch || ' ' || p_date);
end $$;

create or replace function public.app_ca_day(p_date text) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare out jsonb;
begin
  perform public.app__need('doi_soat');
  select coalesce(jsonb_agg(jsonb_build_object(
      'branch_id', b.id, 'branch_code', coalesce(b.display_code, b.code), 'branch_name', b.name,
      'shifts', (select count(*) from public.branch_shifts bs join public.shifts s on s.id = bs.shift_id and s.status = 'Đang sử dụng'
                  where bs.branch_id = b.id and bs.enabled = 1 and public.app__ca_chain(s.name)),
      'done', (select count(*) from public.shift_reports r where r.branch_id = b.id and r.work_date = p_date and r.status = 'hoan_thanh' and public.app__ca_chain(r.shift)),
      'recon_done', (select count(*) from public.shift_reports r where r.branch_id = b.id and r.work_date = p_date and r.recon_status = 'hoan_thanh' and public.app__ca_chain(r.shift)),
      'recon_reopen', (select count(*) from public.shift_reports r where r.branch_id = b.id and r.work_date = p_date and r.recon_status = 'mo_lai'),
      'opening', (select (public.app__ca_eff(r.id) ->> 'opening_cash')::bigint from public.shift_reports r where r.branch_id = b.id and r.work_date = p_date
                   order by array_position(public.app__shifts(), r.shift) limit 1),
      'pos_cash', (select sum((public.app__ca_eff(r.id) ->> 'pos_cash')::bigint) from public.shift_reports r
                    where r.branch_id = b.id and r.work_date = p_date and r.status = 'hoan_thanh'),
      'moves_cash', (select coalesce(sum((m ->> 'amount')::bigint), 0) from public.shift_reports r
                     cross join lateral jsonb_array_elements(public.app__ca_eff(r.id) -> 'moves') m
                     where r.branch_id = b.id and r.work_date = p_date and r.status = 'hoan_thanh' and m ->> 'kind' = 'tien_mat'),
      'debt_cash', (select coalesce(sum(d.amount), 0) from public.shift_debts d join public.shift_reports r on r.id = d.closed_report_id
                     where r.branch_id = b.id and r.work_date = p_date and r.status = 'hoan_thanh' and d.collect_kind = 'tien_mat'),
      'last_counted', (select (public.app__ca_eff(r.id) ->> 'cash_counted')::bigint from public.shift_reports r
                        where r.branch_id = b.id and r.work_date = p_date and r.status = 'hoan_thanh' and public.app__ca_chain(r.shift)
                        order by array_position(public.app__shifts(), r.shift) desc limit 1),
      'last_shift', (select r.shift from public.shift_reports r where r.branch_id = b.id and r.work_date = p_date and r.status = 'hoan_thanh' and public.app__ca_chain(r.shift)
                      order by array_position(public.app__shifts(), r.shift) desc limit 1),
      'has_debt', exists (select 1 from public.shift_debts d join public.shift_reports r on r.id = d.report_id
                           where r.branch_id = b.id and r.work_date = p_date),
      'locked', public.app__fin_locked(b.id, p_date),
      'counted', c.counted, 'note', c.note, 'done_by', public.app__acc_name(c.done_by), 'done_at', c.done_at
    ) order by b.sort_order), '[]'::jsonb) into out
    from public.branches b
    left join public.daily_cash_closings c on c.branch_id = b.id and c.work_date = p_date
   where b.status = 'Đang hoạt động';
  return out;
end $$;
grant execute on function public.app_ca_day_save(bigint, text, bigint, text) to authenticated;
grant execute on function public.app_ca_day(text) to authenticated;

