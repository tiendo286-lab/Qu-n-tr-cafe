  'docs','doc_reads','employee_commitments',
  'training_programs','training_items','trainings','training_marks','training_days',
  'support_requests','support_messages','support_reads',
  'fin_categories','fin_branch_managers','fin_entries','fin_move_cats','fin_month_closes','fin_close_log'] $$;

do $$
declare f record;
begin
  for f in select p.oid::regprocedure as sig, p.proname from pg_proc p join pg_namespace n on n.oid = p.pronamespace
            where n.nspname = 'public' and (p.proname like 'app\_fin\_%' or p.proname like 'app\_\_fin\_%' or p.proname = 'app__backup_tables') loop
    execute format('revoke execute on function %s from public, anon', f.sig);
    if f.proname like 'app\_\_%' then execute format('revoke execute on function %s from authenticated', f.sig);
    else execute format('grant execute on function %s to authenticated', f.sig); end if;
  end loop;
end $$;
