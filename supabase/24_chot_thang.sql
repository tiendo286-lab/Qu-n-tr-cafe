create table if not exists public.fin_categories (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('chi', 'thu')),
  name text not null,
  sort_order integer not null default 0,
  active integer not null default 1,
  created_at text not null default public.vn_now_text()
);
create unique index if not exists fin_categories_name on public.fin_categories (kind, lower(name));

create table if not exists public.fin_branch_managers (
  account_id bigint not null references public.accounts(id) on delete cascade,
  branch_id bigint not null references public.branches(id) on delete cascade,
  primary key (account_id, branch_id)
);

create table if not exists public.fin_entries (
  id bigint generated by default as identity primary key,
  branch_id bigint not null references public.branches(id) on delete cascade,
  entry_date text not null,                         -- YYYY-MM-DD
  kind text not null check (kind in ('chi', 'thu')),
  category_id bigint references public.fin_categories(id),
  amount bigint not null check (amount > 0),
  note text not null default '',
  pay_method text not null default 'tien_mat' check (pay_method in ('tien_mat', 'chuyen_khoan')),
  created_by bigint, created_at text not null default public.vn_now_text(),
  updated_by bigint, updated_at text not null default public.vn_now_text()
);
create index if not exists idx_fin_entries on public.fin_entries (branch_id, entry_date);

-- Phân nhóm khoản thu chi ghi ở phiếu chốt ca (khóa theo nội dung khoản: kind|amount|note + thứ tự trùng)
create table if not exists public.fin_move_cats (
  report_id bigint not null references public.shift_reports(id) on delete cascade,
  mkey text not null,
  category_id bigint references public.fin_categories(id),
  excluded integer not null default 0,
  by_account bigint, at text not null default public.vn_now_text(),
  primary key (report_id, mkey)
);

create table if not exists public.fin_month_closes (
  branch_id bigint not null references public.branches(id) on delete cascade,
  month text not null,                              -- YYYY-MM
  note text,
  snapshot jsonb,
  closed_by bigint, closed_at text not null default public.vn_now_text(),
  primary key (branch_id, month)
);
create table if not exists public.fin_close_log (
  id bigint generated by default as identity primary key,
  branch_id bigint not null references public.branches(id) on delete cascade,
  month text not null,
  action text not null check (action in ('chot', 'mo_lai')),
  reason text,
  by_account bigint, at text not null default public.vn_now_text()
);

