create or replace function public.vn_now() returns timestamp
language sql stable set search_path = public as
$$ select (now() at time zone 'Asia/Ho_Chi_Minh') $$;

create or replace function public.vn_now_text() returns text
language sql stable set search_path = public as
$$ select to_char(now() at time zone 'Asia/Ho_Chi_Minh', 'YYYY-MM-DD HH24:MI:SS') $$;

-- ---------------------------------------------------------------- Danh mục
create table if not exists public.settings (
  key text primary key,
  value text not null
);

create table if not exists public.branches (
  id bigint generated by default as identity primary key,
  code text not null unique,
  system_code text,
  display_code text,
  name text not null,
  status text not null default 'Đang hoạt động',
  sort_order integer not null default 0
);

create table if not exists public.shifts (
  id bigint generated by default as identity primary key,
  code text not null,
  name text not null,
  color text not null default '#DBEAFE',
  status text not null default 'Đang sử dụng',
  sort_order integer not null default 0,
  created_at text not null default public.vn_now_text(),
  updated_at text not null default public.vn_now_text()
);
create unique index if not exists shifts_code_ci on public.shifts (lower(code));
create unique index if not exists shifts_name_ci on public.shifts (lower(name));

create table if not exists public.branch_shifts (
  branch_id bigint not null references public.branches(id) on delete cascade,
  shift_id bigint not null references public.shifts(id) on delete cascade,
  enabled integer not null default 0,
  start_time text,
  end_time text,
  sort_order integer not null default 0,
  updated_at text not null default public.vn_now_text(),
  primary key (branch_id, shift_id)
);

create table if not exists public.work_roles (
  id bigint generated by default as identity primary key,
  name text not null,
  sort_order integer not null default 0,
  status text not null default 'Đang sử dụng',
  created_at text not null default public.vn_now_text()
);
create unique index if not exists work_roles_name_ci on public.work_roles (lower(name));

create table if not exists public.weeks (
  id bigint generated by default as identity primary key,
  start_date text not null unique,
  end_date text not null,
  created_at text not null default public.vn_now_text()
);

