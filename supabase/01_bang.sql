-- ---------------------------------------------------------------- Tài khoản, quyền, thông báo
-- Không có khóa ngoại tới employees: khi nhập lại dữ liệu (xóa & nạp nhân viên) tài khoản vẫn còn,
-- rồi được gắn lại theo mã nhân viên.
create table if not exists public.accounts (
  id bigint generated by default as identity primary key,
  employee_id bigint unique,
  employee_code text,                -- mã NV lúc gắn, dùng để gắn lại sau khi nhập dữ liệu
  login_name text,                   -- tài khoản riêng (không phải nhân viên), vd 'admin'
  display_name text,
  system_role text not null default 'nv' check (system_role in ('chu', 'ql_tong', 'ql', 'nv')),
  auth_user_id uuid unique,
  auth_email text unique,
  has_password integer not null default 0,
  must_change integer not null default 1,
  locked integer not null default 0,
  password_set_at text,
  password_set_by bigint,
  last_login_at text,
  created_at text not null default public.vn_now_text()
);
create unique index if not exists accounts_login_ci on public.accounts (lower(login_name)) where login_name is not null;

create table if not exists public.role_permissions (
  role text not null,
  perm text not null,
  allowed integer not null default 0,
  updated_at text not null default public.vn_now_text(),
  primary key (role, perm)
);

create table if not exists public.audit_log (
  id bigint generated by default as identity primary key,
  account_id bigint,
  action text not null,
  detail text,
  created_at text not null default public.vn_now_text()
);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  account_id bigint not null references public.accounts(id) on delete cascade,
  title text not null,
  body text,
  link text,
  created_at text not null,
  read_at text
);
create index if not exists idx_notifications_account on public.notifications (account_id, created_at);

create table if not exists public.notification_events (
  event_key text primary key,
  created_at text not null
);

