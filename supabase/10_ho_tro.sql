create table if not exists public.support_requests (
  id bigint generated by default as identity primary key,
  account_id bigint not null references public.accounts(id) on delete cascade,   -- người gửi
  title text not null,
  status text not null default 'mo' check (status in ('mo', 'da_xong')),
  created_at text not null default public.vn_now_text(),
  last_message_at text not null default public.vn_now_text(),
  closed_at text, closed_by bigint
);
create index if not exists idx_support_account on public.support_requests (account_id);

create table if not exists public.support_messages (
  id bigint generated by default as identity primary key,
  request_id bigint not null references public.support_requests(id) on delete cascade,
  account_id bigint,
  body text not null,
  created_at text not null default public.vn_now_text()
);
create index if not exists idx_support_msg on public.support_messages (request_id, id);

create table if not exists public.support_reads (
  request_id bigint not null references public.support_requests(id) on delete cascade,
  account_id bigint not null,
  last_read_id bigint not null default 0,
  primary key (request_id, account_id)
);

do $$
declare t text;
begin
  foreach t in array array['support_requests', 'support_messages', 'support_reads'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon, authenticated', t);
  end loop;
end $$;

-- ---------------------------------------------------------------- Quyền
create or replace function public.app__perm_keys() returns text[]
language sql immutable as $$
  select array['order_ca','xem_lich_minh','xem_tat_ca','xep_lich','chot_tuan','sua_order_sau_han',
    'quan_ly_nhan_vien','cai_gio_order','sua_danh_muc','bao_cao','danh_gia','phan_quyen','xoa_du_lieu_tuan','du_lieu',
    'chot_ca','doi_soat','mo_lai_phieu_ca','hop_giao_viec','nhan_viec','soan_tai_lieu','dao_tao','xu_ly_ho_tro']
$$;

create or replace function public.app_can(p text) returns boolean
language plpgsql stable security definer set search_path = public as $$
declare a public.accounts;
begin
  a := public.app_account();
  if a.id is null then return false; end if;
  if a.system_role = 'chu' then return true; end if;
  if p in ('phan_quyen', 'xoa_du_lieu_tuan', 'du_lieu') then return false; end if;
  if p = 'chot_ca' then return true; end if;                                    -- ai cũng chốt ca được
  if p in ('nhan_viec', 'xu_ly_ho_tro') then return a.system_role in ('ql_tong', 'ql'); end if;   -- theo vai trò quản lý
  if a.system_role = 'nv' then
    if p in ('order_ca', 'xem_lich_minh') then return true; end if;
    if p <> 'xem_tat_ca' then return false; end if;
  end if;
  return coalesce((select r.allowed = 1 from public.role_permissions r where r.role = a.system_role and r.perm = p), false);
end $$;

create or replace function public.app_set_perm(p_role text, p_perm text, p_allowed boolean) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.app_can('phan_quyen') then raise exception 'Chỉ Chủ được sửa phân quyền.'; end if;
  if p_role not in ('ql_tong', 'ql', 'nv') then raise exception 'Vai trò không hợp lệ.'; end if;
  if not coalesce(p_perm = any(public.app__perm_keys()), false)
     or p_perm in ('phan_quyen', 'xoa_du_lieu_tuan', 'du_lieu', 'chot_ca', 'nhan_viec', 'xu_ly_ho_tro') then
    raise exception 'Quyền không hợp lệ.';
  end if;
  if p_role = 'nv' and p_perm <> 'xem_tat_ca' then raise exception 'Quyền này không cấp được cho Nhân viên.'; end if;
  insert into public.role_permissions(role, perm, allowed, updated_at)
  values (p_role, p_perm, case when p_allowed then 1 else 0 end, public.vn_now_text())
  on conflict (role, perm) do update set allowed = excluded.allowed, updated_at = excluded.updated_at;
  perform public.app_log('phan_quyen', p_role || '.' || p_perm || '=' || p_allowed);
end $$;

-- ---------------------------------------------------------------- Hàm phụ
create or replace function public.app__ht_managers() returns setof bigint
language sql stable security definer set search_path = public as $$
  select a.id from public.accounts a left join public.employees e on e.id = a.employee_id
   where a.system_role in ('chu', 'ql_tong', 'ql') and a.locked = 0 and (a.employee_id is null or e.status = 'Đang làm')
$$;

create or replace function public.app__ht_need(p_id bigint) returns public.support_requests
language plpgsql security definer set search_path = public as $$
declare a public.accounts; r public.support_requests;
begin
  a := public.app__need(null);
  select * into r from public.support_requests where id = p_id;
  if r.id is null then raise exception 'Không tìm thấy yêu cầu hỗ trợ.'; end if;
  if r.account_id <> a.id and not public.app_can('xu_ly_ho_tro') then raise exception 'Bạn chỉ xem được yêu cầu của chính mình.'; end if;
  return r;
end $$;

-- ---------------------------------------------------------------- Danh sách, tạo, xem, nhắn
create or replace function public.app_ht_list() returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare a public.accounts; mgr boolean;
begin
  a := public.app__need(null);
  mgr := public.app_can('xu_ly_ho_tro');
  return coalesce((select jsonb_agg(jsonb_build_object(
      'id', r.id, 'title', r.title, 'status', r.status, 'created_at', r.created_at, 'last_message_at', r.last_message_at,
      'mine', r.account_id = a.id, 'from', public.app__acc_name(r.account_id),
      'messages', (select count(*) from public.support_messages m where m.request_id = r.id),
      'last', (select jsonb_build_object('body', left(m.body, 120), 'by', public.app__acc_name(m.account_id), 'from_requester', m.account_id = r.account_id)
                 from public.support_messages m where m.request_id = r.id order by m.id desc limit 1),
      'unread', (select count(*) from public.support_messages m where m.request_id = r.id and m.account_id is distinct from a.id
                  and m.id > coalesce((select rd.last_read_id from public.support_reads rd where rd.request_id = r.id and rd.account_id = a.id), 0)))
    order by (r.status = 'da_xong'), r.last_message_at desc)
    from public.support_requests r where mgr or r.account_id = a.id), '[]');
end $$;

create or replace function public.app_ht_unread() returns integer
language plpgsql stable security definer set search_path = public as $$
declare a public.accounts; mgr boolean;
begin
  a := public.app_account();
  if a.id is null then return 0; end if;
  mgr := public.app_can('xu_ly_ho_tro');
  return (select count(distinct r.id) from public.support_requests r join public.support_messages m on m.request_id = r.id
           where (mgr or r.account_id = a.id) and m.account_id is distinct from a.id
             and m.id > coalesce((select rd.last_read_id from public.support_reads rd where rd.request_id = r.id and rd.account_id = a.id), 0));
end $$;

create or replace function public.app_ht_create(p_title text, p_body text) returns bigint
language plpgsql security definer set search_path = public as $$
declare a public.accounts; nid bigint; mid bigint; x bigint;
begin
  a := public.app__need(null);
  if trim(coalesce(p_title, '')) = '' then raise exception 'Nhập tiêu đề yêu cầu.'; end if;
  if trim(coalesce(p_body, '')) = '' then raise exception 'Nhập nội dung cần hỗ trợ.'; end if;
  if length(p_title) > 200 or length(p_body) > 5000 then raise exception 'Nội dung quá dài.'; end if;
  insert into public.support_requests(account_id, title) values (a.id, trim(p_title)) returning id into nid;
  insert into public.support_messages(request_id, account_id, body) values (nid, a.id, trim(p_body)) returning id into mid;
  insert into public.support_reads(request_id, account_id, last_read_id) values (nid, a.id, mid);
  for x in select * from public.app__ht_managers() loop
    if x <> a.id then perform public.app__notify(x, 'Yêu cầu hỗ trợ mới', public.app__acc_name(a.id) || ': ' || trim(p_title), '/ho-tro/chi-tiet?id=' || nid); end if;
  end loop;
  return nid;
end $$;

create or replace function public.app_ht_get(p_id bigint) returns jsonb
language plpgsql security definer set search_path = public as $$
declare a public.accounts; r public.support_requests; last_id bigint;
begin
  r := public.app__ht_need(p_id);
  a := public.app_account();
  select max(id) into last_id from public.support_messages where request_id = r.id;
  insert into public.support_reads(request_id, account_id, last_read_id) values (r.id, a.id, coalesce(last_id, 0))
  on conflict (request_id, account_id) do update set last_read_id = greatest(public.support_reads.last_read_id, excluded.last_read_id);
  -- đánh dấu đã đọc các thông báo trỏ tới yêu cầu này
  update public.notifications set read_at = public.vn_now_text() where account_id = a.id and read_at is null and link = '/ho-tro/chi-tiet?id=' || r.id;
  return to_jsonb(r) || jsonb_build_object(
    'from', public.app__acc_name(r.account_id), 'mine', r.account_id = a.id, 'closed_by_name', public.app__acc_name(r.closed_by),
    'is_manager', public.app_can('xu_ly_ho_tro'),
    'messages', coalesce((select jsonb_agg(jsonb_build_object('id', m.id, 'body', m.body, 'at', m.created_at, 'by', public.app__acc_name(m.account_id),
                    'me', m.account_id = a.id, 'from_requester', m.account_id = r.account_id) order by m.id)
                   from public.support_messages m where m.request_id = r.id), '[]'));
end $$;

create or replace function public.app_ht_send(p_id bigint, p_body text) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts; r public.support_requests; mid bigint; x bigint;
begin
  r := public.app__ht_need(p_id);
  a := public.app_account();
  if trim(coalesce(p_body, '')) = '' then raise exception 'Nhập nội dung tin nhắn.'; end if;
  if length(p_body) > 5000 then raise exception 'Tin nhắn quá dài.'; end if;
  insert into public.support_messages(request_id, account_id, body) values (r.id, a.id, trim(p_body)) returning id into mid;
  update public.support_requests set last_message_at = public.vn_now_text(),
         status = 'mo', closed_at = null, closed_by = null where id = r.id;
  insert into public.support_reads(request_id, account_id, last_read_id) values (r.id, a.id, mid)
  on conflict (request_id, account_id) do update set last_read_id = excluded.last_read_id;
  if a.id = r.account_id then
    for x in select * from public.app__ht_managers() loop
      if x <> a.id then perform public.app__notify(x, 'Tin nhắn mới trong yêu cầu hỗ trợ', public.app__acc_name(a.id) || ' – ' || r.title || ': ' || left(trim(p_body), 100), '/ho-tro/chi-tiet?id=' || r.id); end if;
    end loop;
  else
    perform public.app__notify(r.account_id, 'Trả lời yêu cầu hỗ trợ', public.app__acc_name(a.id) || ' – ' || r.title || ': ' || left(trim(p_body), 100), '/ho-tro/chi-tiet?id=' || r.id);
  end if;
end $$;

create or replace function public.app_ht_status(p_id bigint, p_done boolean) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts; r public.support_requests;
begin
  r := public.app__ht_need(p_id);
  a := public.app_account();
  update public.support_requests set status = case when p_done then 'da_xong' else 'mo' end,
         closed_at = case when p_done then public.vn_now_text() end, closed_by = case when p_done then a.id end
   where id = r.id;
end $$;

-- ---------------------------------------------------------------- Cấp quyền gọi hàm
do $$
declare f record;
begin
  for f in select p.oid::regprocedure as sig, p.proname from pg_proc p join pg_namespace n on n.oid = p.pronamespace
            where n.nspname = 'public' and (p.proname like 'app\_ht\_%' or p.proname like 'app\_\_ht\_%' or p.proname in ('app__perm_keys', 'app_can', 'app_set_perm')) loop
    execute format('revoke execute on function %s from public, anon', f.sig);
    if f.proname like 'app\_\_%' then
      execute format('revoke execute on function %s from authenticated', f.sig);
    else
      execute format('grant execute on function %s to authenticated', f.sig);
    end if;
  end loop;
end $$;
