-- GIẢ ĐỊNH tạm (đặc tả còn chờ chốt — chủ hệ thống xem lại):
--  * "Quản lý" = tài khoản Chủ / Quản lý tổng / Quản lý: xem mọi yêu cầu, trả lời được.
--  * Thông báo: trong web (chuông). Yêu cầu mới → mọi quản lý; quản lý trả lời → người gửi; người gửi nhắn thêm → mọi quản lý.
--  * Trạng thái: Đang mở / Đã xong (người gửi hoặc quản lý đóng, mở lại được). Nhắn vào yêu cầu đã xong → tự mở lại.
