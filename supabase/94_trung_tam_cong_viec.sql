create or replace function public.app_cv_restore(p_task bigint,p_reason text) returns void
language plpgsql security definer set search_path = public as $$
declare t public.tasks; who bigint;
begin
  perform public.app__need('hop_giao_viec');
  if trim(coalesce(p_reason,''))='' then raise exception 'Ghi lý do khôi phục.'; end if;
  select * into t from public.tasks where id=p_task and cancelled_at is not null for update;
  if t.id is null then raise exception 'Việc không còn ở trạng thái Đã hủy.'; end if;
  who:=case when public.app__cv_eligible(t.assignee_id,coalesce(t.source_state,jsonb_build_object('kind','manual'))) then t.assignee_id end;
  update public.tasks set cancelled_at=null,assignee_id=who,updated_at=public.vn_now_text() where id=p_task;
  perform public.app__viec_event(p_task,'khoi_phuc',p_reason);
  perform public.app__cv_sync();
end $$;

