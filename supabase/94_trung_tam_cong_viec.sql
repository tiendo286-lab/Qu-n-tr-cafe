-- Bảo vệ cả đường gọi RPC cũ: không giao sai quyền hoặc khép nguồn bằng báo cáo thủ công.
create or replace function public.app__cv_source_done(s jsonb) returns boolean
language plpgsql stable security definer set search_path = public as $$
declare k text:=s->>'kind'; cv_ref bigint:=(s->>'ref')::bigint; r public.shift_reports; i public.delivery_invoices; d public.docs; t public.trainings;
begin
  if k in ('recon','accounting') then
    select * into r from public.shift_reports where id=cv_ref;
    if r.id is null then return true; end if;
    if k='recon' then return r.recon_status='hoan_thanh'; end if;
    return r.status<>'hoan_thanh' or coalesce((public.app__ca_kt_state(cv_ref)->>'ready')::boolean,false);
  elsif k in ('goods_recon','goods_bill','goods_photo') then
    select * into i from public.delivery_invoices where id=cv_ref;
    if i.id is null then return true; end if;
    if k='goods_recon' then return i.recon_at is not null; end if;
    if k='goods_photo' then return i.state='dang_chuyen' or i.recon_at is not null or not exists(select 1 from public.delivery_lines l where l.invoice_id=cv_ref
      and coalesce(l.qty_checked,l.qty_received,0)>0 and not exists(select 1 from public.delivery_photo_lines pl where pl.line_id=l.id)); end if;
    return i.deliv_path is not null or i.bu_path is not null or i.state='dang_chuyen';
  elsif k='goods_followup' then return not exists(select 1 from public.delivery_followups where id=cv_ref and status='cho');
  elsif k in ('doc_read','doc_followup') then
    select * into d from public.docs where id=cv_ref;
    if d.id is null or d.published_version<>(s->>'version')::int then return true; end if;
    return not exists(select 1 from public.employees e where e.status='Đang làm' and (k='doc_followup' or e.id=(s->>'employee_id')::bigint)
      and not exists(select 1 from public.doc_reads rd where rd.doc_id=cv_ref and rd.employee_id=e.id and rd.version>=d.published_version));
  elsif k='commitment' then return not exists(select 1 from public.employees e left join public.employee_commitments c on c.employee_id=e.id where e.id=cv_ref and e.status='Đang làm' and coalesce(c.status,'chua_ky')<>'da_ky_nop');
  elsif k='training' then
    select * into t from public.trainings where id=cv_ref;
    return t.id is null or not exists(select 1 from public.employees where id=t.employee_id and status='Đang làm') or public.app__dt_status(t)='hoan_thanh' or coalesce(t.cont_result='dat',false);
  end if;
  return false;
end $$;

create or replace function public.app__cv_refresh(s jsonb) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare k text:=s->>'kind'; cv_ref bigint:=(s->>'ref')::bigint; blocked text; detail text:=s->>'detail'; r public.shift_reports; i public.delivery_invoices; t public.trainings; kt jsonb;
begin
  if k in ('recon','accounting') then
    select * into r from public.shift_reports where id=cv_ref; kt:=public.app__ca_kt_state(cv_ref);
    if k='recon' then
      if r.id is not null and r.status<>'hoan_thanh' then blocked:='Chờ nhân viên gửi lại phiếu ca';
      elsif r.id is not null and not coalesce((kt->>'ready')::boolean,false) then
        blocked:='Chờ kế toán: '||(select string_agg(x,', ') from jsonb_array_elements_text(kt->'missing') x);
      end if;
    else detail:=coalesce((select string_agg(x,', ') from jsonb_array_elements_text(kt->'missing') x),'Đã đủ dữ liệu'); end if;
  elsif k='goods_recon' then
    select * into i from public.delivery_invoices where id=cv_ref;
    if i.state='dang_chuyen' then blocked:='Chờ nhân viên nhận hàng';
    elsif i.id is not null and i.deliv_path is null and i.bu_path is null then blocked:='Chờ kế toán bổ sung hóa đơn giao'; end if;
  elsif k='goods_photo' then
    select * into i from public.delivery_invoices where id=cv_ref; s:=s||jsonb_build_object('received_date',i.received_date);
  elsif k='doc_followup' then
    detail:=(select count(*) from public.employees e where e.status='Đang làm' and exists(select 1 from public.doc_reads rd where rd.doc_id=cv_ref and rd.employee_id=e.id and rd.version>=(s->>'version')::int))||'/'||
      (select count(*) from public.employees where status='Đang làm')||' nhân viên đã xác nhận đúng phiên bản. Người phụ trách chỉ theo dõi tiến độ.';
  elsif k='commitment' then
    detail:=case coalesce((select status from public.employee_commitments where employee_id=cv_ref),'chua_ky') when 'da_ky_nop' then 'Đã ký và nộp đủ' when 'da_ky_chua_nop' then 'Đã ký, đang chờ nộp bản cam kết' else 'Chưa ký cam kết' end;
  elsif k='training' then
    select * into t from public.trainings where id=cv_ref;
    if t.id is not null then detail:=public.app__dt_achieved(cv_ref)||'/'||public.app__dt_total(t.program_id)||' tiêu chí đạt'; end if;
  end if;
  return s||jsonb_build_object('done',public.app__cv_source_done(s),'blocked',blocked,'detail',detail);
end $$;

create or replace function public.app__cv_task_guard() returns trigger
language plpgsql security definer set search_path = public as $$
declare s jsonb;
begin
  if tg_op='DELETE' then
    if old.cv_key is not null then raise exception 'Hãy hủy có lý do để giữ lịch sử công việc.'; end if;
    return old;
  end if;
  if tg_op='UPDATE' then new.cv_revision:=old.cv_revision+1; end if;
  if new.assignee_id is not null and (tg_op='INSERT' or new.assignee_id is distinct from old.assignee_id) then
    if not public.app__cv_eligible(new.assignee_id,coalesce(new.source_state,jsonb_build_object('kind','manual'))) then raise exception 'Người nhận thiếu quyền thực hiện hồ sơ gốc.'; end if;
  end if;
  if new.reviewer_id is not null and new.reviewer_id=new.assignee_id then raise exception 'Người làm không tự xác nhận kết quả.'; end if;
  if new.cv_kind is not null and new.cv_kind<>'recurring' then
    if tg_op='UPDATE' and new.cv_key is distinct from old.cv_key then raise exception 'Không đổi được định danh hồ sơ gốc.'; end if;
    if new.status='hoan_thanh' or (tg_op='UPDATE' and old.status='hoan_thanh' and new.status<>'hoan_thanh') then
      if new.status='hoan_thanh' and not public.app__cv_source_done(new.source_state) then raise exception 'Hồ sơ gốc chưa hoàn thành.'; end if;
      if new.status<>'hoan_thanh' and public.app__cv_source_done(new.source_state) then raise exception 'Mở lại tại hồ sơ gốc trước; công việc sẽ tự cập nhật.'; end if;
    end if;
  end if;
  return new;
end $$;
