create or replace function public.app__cv_eligible(p_account bigint, s jsonb) returns boolean
language plpgsql stable security definer set search_path = public as $$
declare k text:=s->>'kind'; a public.accounts; b bigint:=nullif(s->>'branch_id','')::bigint;
begin
  if not public.app__cv_can_as(p_account,'nhan_viec') then return false; end if;
  select * into a from public.accounts where id=p_account;
  if k in ('accounting','goods_bill','goods_followup') then return public.app__cv_can_as(a.id,'ke_toan'); end if;
  if k in ('recon','goods_recon') then return public.app__cv_can_as(a.id,'doi_soat'); end if;
  if k='goods_photo' then return public.app__cv_can_as(a.id,'chot_ca') and (s->>'received_date'=public.app__nh_today() or public.app__cv_can_as(a.id,'doi_soat')); end if;
  if k='doc_read' then return coalesce(a.id=(s->>'subject_id')::bigint,false); end if;
  if k in ('doc_followup','commitment') then return public.app__cv_can_as(a.id,'quan_ly_nhan_vien'); end if;
  if k='training' then return public.app__cv_can_as(a.id,'dao_tao') or exists(select 1 from public.trainings t where t.id=(s->>'ref')::bigint and a.employee_id=any(array[t.instructor_id,t.cont_trainer_id])); end if;
  return k in ('manual','recurring');
end $$;

create or replace function public.app__cv_pick(p jsonb, s jsonb) returns bigint
language plpgsql stable security definer set search_path = public as $$
declare chosen bigint; ids bigint[]; mode text:=coalesce(p->>'assign_mode','account');
begin
  if mode='subject' then chosen:=(s->>'subject_id')::bigint;
  elsif mode='branch_manager' then
    select array_agg(m.account_id order by m.account_id) into ids from public.fin_branch_managers m
     where m.branch_id=(s->>'branch_id')::bigint and public.app__cv_eligible(m.account_id,s);
    if coalesce(array_length(ids,1),0)=1 then chosen:=ids[1]; end if;
  else chosen:=nullif(p->>'assignee_id','')::bigint; end if;
  if public.app__cv_eligible(chosen,s) then return chosen; end if;
  chosen:=nullif(p->>'backup_id','')::bigint;
  if public.app__cv_eligible(chosen,s) then return chosen; end if;
  return null;
end $$;

-- Quy tắc lịch chạy theo ngày Việt Nam, giữ tất cả lượt chưa chạy từ ngày hiệu lực.
-- Không giới hạn lookback làm mất nghĩa vụ. Ngày 29–31 của tháng ngắn rơi vào cuối tháng.
create or replace function public.app__cv_rule_sources(p_id bigint, p jsonb) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare out jsonb; d date; start_ date:=(p->>'effective_date')::date; today date:=public.vn_now()::date; b bigint:=nullif(p->>'branch_id','')::bigint; freq text:=p->>'frequency';
begin
  if p->>'kind'<>'recurring' then
    select coalesce(jsonb_agg(s),'[]') into out from jsonb_array_elements(public.app__cv_sources()) s
     where s->>'kind'=p->>'kind' and not coalesce((s->>'done')::boolean,false)
       and (b is null or (s->>'branch_id')::bigint=b)
       and (coalesce((p->>'include_backlog')::boolean,false) or left(s->>'at',10)>=start_::text);
    return out;
  end if;
  out:='[]';
  for d in select g::date from generate_series(start_::timestamp,today::timestamp,interval '1 day') g loop
    if (d=today and coalesce(p->>'run_time','08:00')>to_char(public.vn_now(),'HH24:MI')) then continue; end if;
    if freq='weekly' and extract(isodow from d)::int<>coalesce((p->>'weekday')::int,1) then continue; end if;
    if freq='monthly' and extract(day from d)::int<>least(coalesce((p->>'monthday')::int,1),extract(day from (date_trunc('month',d)+interval '1 month -1 day'))::int) then continue; end if;
    out:=out||jsonb_build_array(jsonb_build_object('key','recurring:'||p_id||':'||d,'kind','recurring','title',p->>'title','detail',p->>'instructions',
      'branch_id',b,'link',null,'at',d||' '||coalesce(p->>'run_time','08:00'),'done',false));
  end loop;
  return out;
end $$;

create or replace function public.app__cv_validate(p jsonb) returns void
language plpgsql stable security definer set search_path = public as $$
declare k text:=p->>'kind'; mode text:=p->>'assign_mode'; b bigint:=nullif(p->>'branch_id','')::bigint; aid bigint;
begin
  if coalesce(k,'') not in ('recon','accounting','goods_recon','goods_photo','goods_bill','goods_followup','doc_read','doc_followup','commitment','training','recurring') then raise exception 'Chọn loại quy tắc hợp lệ.'; end if;
  if length(trim(coalesce(p->>'title','')))=0 or length(p->>'title')>500 then raise exception 'Nhập tên quy tắc (tối đa 500 ký tự).'; end if;
  if coalesce(mode,'') not in ('account','branch_manager','subject') then raise exception 'Chọn cách giao việc.'; end if;
  if mode='subject' and k not in ('doc_read','training','goods_photo') then raise exception 'Loại này cần chọn người cụ thể hoặc quản lý cơ sở.'; end if;
  if k='doc_read' and mode<>'subject' then raise exception 'Việc đọc tài liệu phải giao chính nhân viên. Chọn Đôn đốc đọc nếu giao người theo dõi.'; end if;
  if mode='branch_manager' and k in ('doc_read','doc_followup','commitment') then raise exception 'Nghĩa vụ nhân sự toàn công ty cần người phụ trách cụ thể.'; end if;
  if b is not null and not exists(select 1 from public.branches where id=b and status='Đang hoạt động') then raise exception 'Cơ sở không còn hoạt động.'; end if;
  if b is not null and k in ('doc_read','doc_followup','commitment') then raise exception 'Nhóm hồ sơ này áp dụng toàn công ty, không chia trùng theo cơ sở.'; end if;
  if mode='account' and nullif(p->>'assignee_id','') is null then raise exception 'Chọn người phụ trách chính.'; end if;
  foreach aid in array array[nullif(p->>'assignee_id','')::bigint,nullif(p->>'backup_id','')::bigint,nullif(p->>'watcher_id','')::bigint,nullif(p->>'reviewer_id','')::bigint] loop
    if aid is not null and not public.app__cv_can_as(aid,'nhan_viec') then raise exception 'Người được chọn đã khóa hoặc ngừng làm.'; end if;
  end loop;
  aid:=nullif(p->>'watcher_id','')::bigint;
  if aid is not null and not public.app__cv_can_as(aid,'hop_giao_viec') then raise exception 'Người theo dõi cần quyền Giao việc để xem tiến độ quản trị.'; end if;
  if nullif(p->>'reviewer_id','') is not null and k<>'recurring' then raise exception 'Việc từ hồ sơ dùng bước xác nhận của nghiệp vụ gốc.'; end if;
  if nullif(p->>'reviewer_id','') is not null and not public.app__cv_can_as((p->>'reviewer_id')::bigint,'hop_giao_viec') then raise exception 'Người xác nhận cần quyền Giao việc.'; end if;
  if nullif(p->>'reviewer_id','') is not null and p->>'reviewer_id'=p->>'assignee_id' then raise exception 'Người làm và người xác nhận phải khác nhau.'; end if;
  if nullif(p->>'reviewer_id','') is not null and p->>'reviewer_id'=p->>'backup_id' then raise exception 'Người dự phòng không đồng thời là người xác nhận.'; end if;
  if mode='branch_manager' and k='recurring' and b is null then raise exception 'Chọn cơ sở cho việc định kỳ giao quản lý cơ sở.'; end if;
  if coalesce(p->>'priority','') not in ('gap','binh_thuong','thap') then raise exception 'Mức độ không hợp lệ.'; end if;
  if coalesce(p->>'effective_date','')!~'^\d{4}-\d{2}-\d{2}$' then raise exception 'Chọn ngày hiệu lực.'; end if;
  perform (p->>'effective_date')::date;
  if coalesce((p->>'due_days')::int,0) not between 0 and 365 or coalesce((p->>'escalate_days')::int,0) not between 0 and 365 then raise exception 'Số ngày phải từ 0 đến 365.'; end if;
  if coalesce(p->>'due_time','')!~'^([01][0-9]|2[0-3]):[0-5][0-9]$' then raise exception 'Chọn giờ hết hạn.'; end if;
  if k='recurring' then
    if coalesce(p->>'frequency','') not in ('daily','weekly','monthly') or coalesce(p->>'run_time','')!~'^([01][0-9]|2[0-3]):[0-5][0-9]$' then raise exception 'Chọn lịch lặp và giờ giao.'; end if;
    if coalesce((p->>'weekday')::int,1) not between 1 and 7 or coalesce((p->>'monthday')::int,1) not between 1 and 31 then raise exception 'Ngày lặp không hợp lệ.'; end if;
  end if;
end $$;

create or replace function public.app_cv_preview(p_id bigint, p jsonb) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare rows_ jsonb;
begin
  perform public.app__need('hop_giao_viec'); perform public.app__cv_validate(p);
  select coalesce(jsonb_agg(s||jsonb_build_object('assignee_id',public.app__cv_pick(p,s),'assignee_name',public.app__acc_name(public.app__cv_pick(p,s)),
    'existing',exists(select 1 from public.tasks t where t.cv_key=s->>'key')) order by s->>'key'),'[]') into rows_
    from jsonb_array_elements(public.app__cv_rule_sources(coalesce(p_id,0),p)) s;
  return jsonb_build_object('rows',rows_,'total',jsonb_array_length(rows_),'token',md5(coalesce(p_id,0)::text||p::text||rows_::text));
end $$;

create or replace function public.app_cv_rule_save(p_id bigint, p jsonb, p_preview text) returns bigint
language plpgsql security definer set search_path = public as $$
declare a public.accounts:=public.app__need('hop_giao_viec'); nid bigint; en boolean:=coalesce((p->>'enabled')::boolean,false); v jsonb;
begin
  perform pg_advisory_xact_lock(930107);
  perform public.app__cv_validate(p);
  if en then
    v:=public.app_cv_preview(p_id,p);
    if p_preview is distinct from v->>'token' then raise exception 'Hãy xem trước lại danh sách việc/người nhận rồi mới bật.'; end if;
    if exists(select 1 from public.task_rules r where r.enabled and r.id<>coalesce(p_id,0) and r.config->>'kind'=p->>'kind' and p->>'kind'<>'recurring'
      and (nullif(r.config->>'branch_id','') is null or nullif(p->>'branch_id','') is null or r.config->>'branch_id'=p->>'branch_id')) then
      raise exception 'Đã có quy tắc đang bật cho nguồn và cơ sở này. Tắt hoặc sửa quy tắc đó trước.';
    end if;
  end if;
  if p_id is null then insert into public.task_rules(config,enabled,created_by) values(p,en,a.id) returning id into nid;
  else update public.task_rules set config=p,enabled=en,last_run=null,updated_at=public.vn_now_text() where id=p_id returning id into nid;
    if nid is null then raise exception 'Không tìm thấy quy tắc.'; end if;
  end if;
  insert into public.task_rule_events(rule_id,by_account,action,config) values(nid,a.id,case when en then 'luu_bat' else 'luu_tat' end,p);
  perform public.app_log('quy_tac_cong_viec','rule='||nid||' enabled='||en);
  return nid;
end $$;

-- Bộ chạy duy nhất, khóa giao dịch + ràng buộc UNIQUE bảo vệ khi cron và nhiều trình duyệt cùng chạy.
create or replace function public.app__cv_sync() returns void
language plpgsql security definer set search_path = public as $$
declare sources jsonb; s jsonb; t public.tasks; r public.task_rules; who bigint; nid bigint; msg text; now_ text:=public.vn_now_text(); d text;
begin
  if not pg_try_advisory_xact_lock(930107) then return; end if;
  for t in select * from public.tasks where cv_kind is not null and cv_kind<>'recurring' and cancelled_at is null order by id for update loop
    s:=public.app__cv_refresh(t.source_state);
    if coalesce((s->>'done')::boolean,false) and t.status<>'hoan_thanh' then
      update public.tasks set status='hoan_thanh',done_at=now_,source_state=s,updated_at=now_ where id=t.id;
      insert into public.task_events(task_id,action,note) values(t.id,'nguon_xong','Hồ sơ gốc đã hoàn thành hoặc nghĩa vụ đã ngừng áp dụng.');
    elsif not coalesce((s->>'done')::boolean,false) and t.status='hoan_thanh' then
      update public.tasks set status=case when assignee_id is null then 'chua_phan_cong' else 'dang_xu_ly' end,done_at=null,source_state=s,updated_at=now_ where id=t.id;
      insert into public.task_events(task_id,action,note) values(t.id,'nguon_mo_lai','Hồ sơ gốc đang cần xử lý lại.');
    elsif s is distinct from t.source_state then update public.tasks set source_state=s,updated_at=now_ where id=t.id;
    end if;
  end loop;
  for r in select * from public.task_rules where enabled and config->>'effective_date'<=left(now_,10)
    and (last_run is null or last_run::timestamp<public.vn_now()-interval '15 seconds') order by id loop
    for s in select x from jsonb_array_elements(public.app__cv_rule_sources(r.id,r.config)) x loop
      s:=s||jsonb_build_object('instructions',r.config->>'instructions');
      who:=public.app__cv_pick(r.config,s);
      d:=coalesce(s->>'due_date',to_char(greatest(left(s->>'at',10)::date,(r.config->>'effective_date')::date)+coalesce((r.config->>'due_days')::int,0),'YYYY-MM-DD'));
      insert into public.tasks(content,created_by,cv_key,cv_kind,cv_rule_id,source_state,branch_id,link,category,topic,priority,
        assignee_id,status,assigned_at,due_date,due_time,backup_id,watcher_id,reviewer_id)
      values(s->>'title',r.created_by,s->>'key',s->>'kind',r.id,s,(s->>'branch_id')::bigint,s->>'link',
        case when s->>'kind' in ('doc_read','doc_followup','commitment','training') then 'quan_ly' else 'van_hanh' end,
        case s->>'kind' when 'training' then 'dao_tao' when 'commitment' then 'cam_ket' when 'doc_read' then 'noi_quy' when 'doc_followup' then 'noi_quy'
          when 'recon' then 'doi_soat_ca' when 'accounting' then 'doi_soat_ca' when 'recurring' then 'khac_vh' else 'nhap_hang' end,
        r.config->>'priority',who,case when who is null then 'chua_phan_cong' else 'da_giao' end,case when who is not null then now_ end,
        d,r.config->>'due_time',nullif(r.config->>'backup_id','')::bigint,nullif(r.config->>'watcher_id','')::bigint,nullif(r.config->>'reviewer_id','')::bigint)
      on conflict(cv_key) where cv_key is not null do nothing returning id into nid;
      if nid is not null then
        insert into public.task_events(task_id,action,note) values(nid,'tu_giao','Quy tắc #'||r.id||case when who is null then ' · Chờ phân công: thiếu người đủ quyền hoặc nhiều quản lý cùng phụ trách' else ' · '||public.app__acc_name(who) end);
      end if;
    end loop;
    update public.task_rules set last_run=now_ where id=r.id;
  end loop;
  -- Tài khoản mất quyền/ngừng làm: giữ việc, chuyển dự phòng hợp lệ hoặc đưa về chờ phân công.
  for t in select * from public.tasks where status in ('da_giao','dang_xu_ly','cho_duyet') and cancelled_at is null order by id for update loop
    s:=coalesce(t.source_state,jsonb_build_object('kind','manual'));
    if not public.app__cv_eligible(t.assignee_id,s) then
      who:=case when public.app__cv_eligible(t.backup_id,s) and t.backup_id is distinct from t.reviewer_id then t.backup_id end;
      update public.tasks set assignee_id=who,status=case when who is null then 'chua_phan_cong' else 'da_giao' end,started_at=null,updated_at=now_ where id=t.id;
      insert into public.task_events(task_id,action,note) values(t.id,'chuyen_du_phong','Người cũ không còn đủ quyền/đang làm. '||case when who is null then 'Chờ phân công.' else 'Chuyển dự phòng: '||public.app__acc_name(who) end);
    end if;
  end loop;
end $$;

-- Nhắc gộp theo tài khoản/ngày, không đưa chi tiết tài chính/nhân sự vào thông báo.
create or replace function public.app__cv_tick() returns void
language plpgsql security definer set search_path = public as $$
declare x record; today text:=to_char(public.vn_now(),'YYYY-MM-DD');
begin
  perform public.app__cv_sync();
  for x in select assignee_id,count(*) n from public.tasks where assignee_id is not null and status in ('da_giao','dang_xu_ly') and cancelled_at is null
    and coalesce(left(last_reminded,10),'')<today and coalesce(source_state->>'blocked','')=''
    and (status='da_giao' or due_date<=today) group by assignee_id loop
    perform public.app__notify(x.assignee_id,'Công việc cần xử lý',x.n||' công việc mới hoặc đến hạn. Mở Việc của tôi để xem.','/viec');
    update public.tasks set last_reminded=public.vn_now_text() where assignee_id=x.assignee_id and status in ('da_giao','dang_xu_ly') and cancelled_at is null;
  end loop;
  for x in select coalesce(t.watcher_id,t.created_by) aid,count(*) n from public.tasks t left join public.task_rules r on r.id=t.cv_rule_id
    where t.status<>'hoan_thanh' and t.cancelled_at is null and coalesce(left(t.last_escalated,10),'')<today
      and (t.assignee_id is null or (t.due_date is not null and (t.due_date||' '||coalesce(t.due_time,'23:59'))::timestamp+make_interval(days=>coalesce((r.config->>'escalate_days')::int,1))<=public.vn_now()))
    group by coalesce(t.watcher_id,t.created_by) loop
    if public.app__cv_can_as(x.aid,'hop_giao_viec') then perform public.app__notify(x.aid,'Cần kiểm tra phân công',x.n||' việc chưa có người hoặc đã quá hạn.','/quan-ly/giao-viec'); end if;
  end loop;
  update public.tasks t set last_escalated=public.vn_now_text() where status<>'hoan_thanh' and cancelled_at is null
    and (assignee_id is null or (due_date is not null and (due_date||' '||coalesce(due_time,'23:59'))::timestamp+
      make_interval(days=>coalesce((select (r.config->>'escalate_days')::int from public.task_rules r where r.id=t.cv_rule_id),1))<=public.vn_now()));
  update public.tasks set last_reminded=public.vn_now_text() where assignee_id is null and status<>'hoan_thanh' and cancelled_at is null;
end $$;

