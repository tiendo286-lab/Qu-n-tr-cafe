-- Cùng ngữ nghĩa app_can (40), nhưng kiểm tài khoản ĐƯỢC GIAO, không dùng quyền của người giao.
create or replace function public.app__cv_can_as(p_account bigint, p_perm text) returns boolean
language plpgsql stable security definer set search_path = public as $$
declare a public.accounts;
begin
  select x.* into a from public.accounts x left join public.employees e on e.id=x.employee_id
   where x.id=p_account and x.locked=0 and (x.employee_id is null or e.status='Đang làm');
  if a.id is null then return false; end if;
  if a.system_role='chu' then return true; end if;
  if p_perm='nhan_viec' then return true; end if;
  if p_perm='ke_toan' and exists(select 1 from public.account_perms where account_id=a.id and perm='ke_toan') then return true; end if;
  if p_perm in ('phan_quyen','xoa_du_lieu_tuan','du_lieu') then return false; end if;
  if a.system_role='ke_toan' then return p_perm='ke_toan'; end if;
  if p_perm='ke_toan' then return false; end if;
  if p_perm='chot_ca' then return true; end if;
  if p_perm='xu_ly_ho_tro' then return a.system_role in ('ql_tong','ql'); end if;
  if a.system_role='nv' then
    if p_perm in ('order_ca','xem_lich_minh') then return true; end if;
    if p_perm<>'xem_tat_ca' then return false; end if;
  end if;
  return coalesce((select allowed=1 from public.role_permissions where role=a.system_role and perm=p_perm),false);
end $$;

