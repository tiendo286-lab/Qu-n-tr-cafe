-- Thêm/sửa nguyên tử; hồ sơ nguồn do máy chủ tra lại, không tin nội dung từ web.
create or replace function public.app_cv_task_save(p_id bigint, p jsonb) returns bigint
language plpgsql security definer set search_path = public as $$
declare a public.accounts:=public.app__need('hop_giao_viec'); t public.tasks; s jsonb; who bigint:=nullif(p->>'assignee_id','')::bigint;
  nid bigint; h public.handover_items; k text:=nullif(p->>'source_key',''); now_ text:=public.vn_now_text(); new_ass boolean; cat text; top text;
begin
  perform pg_advisory_xact_lock(930107);
  if p_id is not null then select * into t from public.tasks where id=p_id for update;
    if t.id is null or t.status='hoan_thanh' or t.cancelled_at is not null then raise exception 'Việc đã xong, đã hủy hoặc không còn.'; end if;
    s:=t.source_state;
  elsif k is not null then
    select x into s from jsonb_array_elements(public.app__cv_sources()) x where x->>'key'=k;
    if s is null or coalesce((s->>'done')::boolean,false) then raise exception 'Nghĩa vụ này đã xong hoặc đổi phiên bản. Tải lại danh sách.'; end if;
    if exists(select 1 from public.tasks where cv_key=k) then raise exception 'Hồ sơ này đã có công việc. Tải lại danh sách.'; end if;
  end if;
  if who is not null and not public.app__cv_eligible(who,coalesce(s,jsonb_build_object('kind','manual'))) then raise exception 'Người nhận thiếu quyền thực hiện hồ sơ này hoặc đã ngừng làm. Giao việc không tự cấp quyền.'; end if;
  if coalesce(p->>'priority','') not in ('gap','binh_thuong','thap') then raise exception 'Chọn mức độ hợp lệ.'; end if;
  if nullif(p->>'due_date','') is not null then
    if p->>'due_date'!~'^\d{4}-\d{2}-\d{2}$' then raise exception 'Ngày hết hạn không hợp lệ.'; end if;
    perform (p->>'due_date')::date;
  end if;
  if nullif(p->>'due_time','') is not null and p->>'due_time'!~'^([01][0-9]|2[0-3]):[0-5][0-9]$' then raise exception 'Giờ hết hạn không hợp lệ.'; end if;
  if (s is null or s->>'kind'='recurring') and trim(coalesce(p->>'content',''))='' then raise exception 'Nhập nội dung công việc.'; end if;
  if nullif(p->>'branch_id','') is not null and not exists(select 1 from public.branches where id=(p->>'branch_id')::bigint) then raise exception 'Cơ sở không hợp lệ.'; end if;
  if nullif(p->>'backup_id','') is not null and not public.app__cv_eligible((p->>'backup_id')::bigint,coalesce(s,jsonb_build_object('kind','manual'))) then raise exception 'Người dự phòng thiếu quyền thực hiện.'; end if;
  if nullif(p->>'watcher_id','') is not null and not public.app__cv_can_as((p->>'watcher_id')::bigint,'hop_giao_viec') then raise exception 'Người theo dõi cần quyền Giao việc.'; end if;
  if nullif(p->>'reviewer_id','') is not null and ((s is not null and s->>'kind'<>'recurring') or not public.app__cv_can_as((p->>'reviewer_id')::bigint,'hop_giao_viec')) then raise exception 'Chỉ việc thủ công mới chọn người xác nhận có quyền Giao việc.'; end if;
  if who is not null and who=nullif(p->>'reviewer_id','')::bigint then raise exception 'Người làm và người xác nhận phải khác nhau.'; end if;
  if nullif(p->>'backup_id','') is not null and p->>'backup_id'=p->>'reviewer_id' then raise exception 'Người dự phòng không đồng thời là người xác nhận.'; end if;
  cat:=case when s->>'kind' in ('doc_read','doc_followup','commitment','training') then 'quan_ly'
    when s is not null and s->>'kind'<>'recurring' then 'van_hanh' else coalesce(nullif(p->>'category',''),'van_hanh') end;
  top:=case s->>'kind' when 'training' then 'dao_tao' when 'commitment' then 'cam_ket' when 'doc_read' then 'noi_quy' when 'doc_followup' then 'noi_quy'
    when 'recon' then 'doi_soat_ca' when 'accounting' then 'doi_soat_ca' when 'goods_recon' then 'nhap_hang' when 'goods_bill' then 'nhap_hang'
    when 'goods_photo' then 'nhap_hang' when 'goods_followup' then 'nhap_hang' else coalesce(nullif(p->>'topic',''),case when cat='quan_ly' then 'khac_ql' else 'khac_vh' end) end;
  if cat not in ('van_hanh','quan_ly') or not coalesce(top=any(public.app__viec_topics(cat)),false) then raise exception 'Nhóm công việc không hợp lệ.'; end if;
  if p_id is null then
    if nullif(p->>'handover_item_id','') is not null then
      select * into h from public.handover_items where id=(p->>'handover_item_id')::bigint for update;
      if h.id is null or h.done_at is not null or h.task_id is not null then raise exception 'Nội dung bàn giao đã xong hoặc đã được giao.'; end if;
    end if;
    insert into public.tasks(content,created_by,cv_key,cv_kind,source_state,link,branch_id,handover_item_id,priority,category,topic)
      values(coalesce(s->>'title',nullif(trim(p->>'content'),''),h.content),a.id,k,s->>'kind',s,s->>'link',coalesce((s->>'branch_id')::bigint,nullif(p->>'branch_id','')::bigint),h.id,
        p->>'priority',cat,top) returning id into nid;
    if h.id is not null then update public.handover_items set task_id=nid where id=h.id; end if;
    perform public.app__viec_event(nid,'tao',case when k is not null then 'Từ hồ sơ gốc: '||k end);
  else nid:=p_id; end if;
  new_ass:=who is distinct from t.assignee_id;
  update public.tasks set content=case when s is not null and s->>'kind'<>'recurring' then s->>'title' else trim(p->>'content') end,
    assignee_id=who,status=case when who is null then 'chua_phan_cong' when new_ass or p_id is null then 'da_giao' when status='cho_duyet' and nullif(p->>'reviewer_id','') is null then 'dang_xu_ly' else status end,
    assigned_at=case when new_ass then now_ else assigned_at end,started_at=case when new_ass then null else started_at end,
    branch_id=coalesce((s->>'branch_id')::bigint,nullif(p->>'branch_id','')::bigint),due_date=nullif(p->>'due_date',''),due_time=nullif(p->>'due_time',''),priority=p->>'priority',
    backup_id=nullif(p->>'backup_id','')::bigint,watcher_id=nullif(p->>'watcher_id','')::bigint,reviewer_id=nullif(p->>'reviewer_id','')::bigint,category=cat,topic=top,updated_at=now_ where id=nid;
  perform public.app__viec_event(nid,case when new_ass then 'giao' else 'sua' end,case when who is null then 'Chờ phân công' else public.app__acc_name(who) end);
  if new_ass and who is not null then perform public.app__notify(who,'Việc mới được giao','Mở Việc của tôi để xem nội dung và hạn xử lý.','/viec'); end if;
  return nid;
end $$;

-- Không thể báo xong hồ sơ nguồn bằng nút thủ công. Nhận việc không phải hoàn thành.
create or replace function public.app_viec_submit(p_task bigint, p_report text) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts:=public.app__need('nhan_viec'); t public.tasks; now_ text:=public.vn_now_text();
begin
  perform public.app__cv_sync();
  select * into t from public.tasks where id=p_task for update;
  if t.id is null or t.assignee_id is distinct from a.id or t.cancelled_at is not null then raise exception 'Chỉ người nhận mới báo kết quả công việc đang mở.'; end if;
  if t.cv_kind is not null and t.cv_kind<>'recurring' then raise exception 'Việc này tự hoàn thành theo hồ sơ gốc. Bấm Mở hồ sơ để xử lý.'; end if;
  if t.status not in ('da_giao','dang_xu_ly') then raise exception 'Việc không còn ở trạng thái đang làm.'; end if;
  if t.reviewer_id is not null and trim(coalesce(p_report,''))='' then raise exception 'Ghi kết quả để người phụ trách xác nhận.'; end if;
  if t.reviewer_id is not null and not public.app__cv_can_as(t.reviewer_id,'hop_giao_viec') then raise exception 'Người xác nhận không còn đủ quyền. Báo người giao chọn lại.'; end if;
  update public.tasks set status=case when reviewer_id is null then 'hoan_thanh' else 'cho_duyet' end,report=nullif(trim(p_report),''),submitted_at=now_,
    done_at=case when reviewer_id is null then now_ end,started_at=coalesce(started_at,now_),review_note=null,updated_at=now_ where id=p_task;
  if t.reviewer_id is null then update public.handover_items set done_at=now_,done_by=a.id where id=t.handover_item_id; end if;
  perform public.app__viec_event(p_task,'bao_cao',p_report);
  perform public.app__notify(coalesce(t.reviewer_id,t.created_by),case when t.reviewer_id is null then 'Việc đã hoàn thành' else 'Việc chờ xác nhận' end,'Mở Công việc để xem kết quả.','/quan-ly/giao-viec');
end $$;

create or replace function public.app_cv_review(p_task bigint,p_accept boolean,p_note text) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts:=public.app__need('hop_giao_viec'); t public.tasks;
begin
  select * into t from public.tasks where id=p_task for update;
  if t.id is null or t.reviewer_id is distinct from a.id or t.status<>'cho_duyet' or t.cancelled_at is not null then raise exception 'Chỉ người xác nhận được chọn mới xử lý việc Chờ xác nhận.'; end if;
  if not coalesce(p_accept,false) and trim(coalesce(p_note,''))='' then raise exception 'Ghi rõ nội dung cần làm lại.'; end if;
  update public.tasks set status=case when p_accept then 'hoan_thanh' else 'dang_xu_ly' end,done_at=case when p_accept then public.vn_now_text() end,
    approved_by=case when p_accept then a.id end,approved_at=case when p_accept then public.vn_now_text() end,review_note=nullif(trim(p_note),''),updated_at=public.vn_now_text() where id=p_task;
  if p_accept then update public.handover_items set done_at=public.vn_now_text(),done_by=a.id where id=t.handover_item_id; end if;
  perform public.app__viec_event(p_task,case when p_accept then 'duyet' else 'lam_lai' end,p_note);
  perform public.app__notify(t.assignee_id,case when p_accept then 'Kết quả đã được xác nhận' else 'Công việc cần làm lại' end,'Mở Việc của tôi để xem.','/viec');
end $$;

