-- Chuyển hàng loạt là thao tác riêng: chỉ danh sách ID và phiên bản người nhận đã xem trước.
create or replace function public.app_cv_transfer(p_tasks jsonb,p_to bigint,p_reason text) returns integer
language plpgsql security definer set search_path = public as $$
declare t public.tasks; x jsonb; n int:=0;
begin
  perform public.app__need('hop_giao_viec'); perform pg_advisory_xact_lock(930107);
  if trim(coalesce(p_reason,''))='' then raise exception 'Ghi lý do chuyển người.'; end if;
  for x in select value from jsonb_array_elements(p_tasks) loop
    select * into t from public.tasks where id=(x->>'id')::bigint for update;
    if t.id is null or t.updated_at is distinct from x->>'updated_at' or t.cv_revision is distinct from (x->>'cv_revision')::bigint or t.status='hoan_thanh' or t.cancelled_at is not null then raise exception 'Một việc đã thay đổi. Hãy xem trước lại danh sách chuyển.'; end if;
    if not public.app__cv_eligible(p_to,coalesce(t.source_state,jsonb_build_object('kind','manual'))) or p_to=t.reviewer_id then raise exception 'Người mới thiếu quyền hoặc trùng người xác nhận.'; end if;
    update public.tasks set assignee_id=p_to,status='da_giao',started_at=null,assigned_at=public.vn_now_text(),updated_at=public.vn_now_text() where id=t.id;
    perform public.app__viec_event(t.id,'giao','Chuyển từ '||coalesce(public.app__acc_name(t.assignee_id),'chưa giao')||' sang '||public.app__acc_name(p_to)||' · '||p_reason); n:=n+1;
  end loop;
  if n>0 then perform public.app__notify(p_to,'Đã chuyển công việc cho bạn',n||' công việc được chuyển. Mở Việc của tôi để xem.','/viec'); end if;
  return n;
end $$;

