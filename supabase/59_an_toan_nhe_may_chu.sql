-- Quyền bảng: khách (anon) không cần quyền nào; người đăng nhập chỉ giữ quyền có luật cho phép đi kèm
do $g$
declare t record; p text;
begin
  for t in select c.relname from pg_class c join pg_namespace n on n.oid = c.relnamespace where n.nspname = 'public' and c.relkind = 'r' loop
    execute format('revoke all on public.%I from anon', t.relname);
    execute format('revoke truncate, references, trigger on public.%I from authenticated', t.relname);
    foreach p in array array['SELECT', 'INSERT', 'UPDATE', 'DELETE'] loop
      if not exists (select 1 from pg_policies pp where pp.schemaname = 'public' and pp.tablename = t.relname
                      and (pp.cmd = p or pp.cmd = 'ALL') and ('authenticated' = any(pp.roles) or 'public' = any(pp.roles))) then
        execute format('revoke %s on public.%I from authenticated', p, t.relname);
      end if;
    end loop;
  end loop;
end $g$;
