create or replace function public.app_migrations_list() returns jsonb
language plpgsql stable security definer set search_path = public as $$
begin
  if not public.app_can('phan_quyen') then raise exception 'Bạn không có quyền thực hiện thao tác này.'; end if;
  return coalesce((select jsonb_agg(jsonb_build_object('file', file, 'at', applied_at, 'note', note) order by file desc) from public.app_migrations), '[]');
end $$;

-- ---------------------------------------------------------------- 2. Sao lưu đủ mọi bảng
create or replace function public.app__backup_tables() returns text[]
language sql stable security definer set search_path = public as $$
  select coalesce(array_agg(c.relname::text order by c.relname), '{}')
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and c.relkind = 'r' and not (c.relname::text = any(public.app_import_tables()))
$$;

-- ---------------------------------------------------------------- 3. Sao lưu tự động hằng ngày
create schema if not exists sao_luu;
revoke all on schema sao_luu from public, anon, authenticated;
create table if not exists sao_luu.snapshots (
  id bigint generated by default as identity primary key,
  taken_at text not null default public.vn_now_text(),
  tables int not null default 0,
  rows_total bigint not null default 0,
  data jsonb not null
);
revoke all on sao_luu.snapshots from public, anon, authenticated;

create or replace function public.app__auto_backup() returns text
language plpgsql security definer set search_path = public as $$
declare t text; out jsonb := '{}'::jsonb; rws jsonb; n int := 0; tot bigint := 0;
begin
  foreach t in array (public.app_import_tables() || public.app__backup_tables()) loop
    if to_regclass('public.' || t) is null or out ? t then continue; end if;
    execute format('select coalesce(jsonb_agg(to_jsonb(x)), ''[]''::jsonb) from public.%I x', t) into rws;
    out := out || jsonb_build_object(t, rws); n := n + 1; tot := tot + jsonb_array_length(rws);
  end loop;
  insert into sao_luu.snapshots(tables, rows_total, data) values (n, tot, out);
  delete from sao_luu.snapshots where id not in (select id from sao_luu.snapshots order by id desc limit 7);
  return n || ' bảng, ' || tot || ' dòng';
end $$;

-- Chủ xem danh sách / tải 1 bản (JSON)
create or replace function public.app_auto_backups() returns jsonb
language plpgsql stable security definer set search_path = public as $$
begin
  if not public.app_can('du_lieu') then raise exception 'Chỉ Chủ được xem bản sao lưu.'; end if;
  return jsonb_build_object(
    'list', coalesce((select jsonb_agg(jsonb_build_object('id', id, 'at', taken_at, 'tables', tables, 'rows', rows_total, 'kb', round(pg_column_size(data) / 1024.0)) order by id desc) from sao_luu.snapshots), '[]'),
    'last_zip', (select max(created_at) from public.audit_log where action = 'xuat_du_lieu_zip'));
end $$;
create or replace function public.app_auto_backup_get(p_id bigint) returns jsonb
language plpgsql stable security definer set search_path = public as $$
begin
  if not public.app_can('du_lieu') then raise exception 'Chỉ Chủ được tải bản sao lưu.'; end if;
  return (select jsonb_build_object('at', taken_at, 'data', data) from sao_luu.snapshots where id = p_id);
end $$;

-- Nhắc Chủ tải gói ZIP về máy nếu 7 ngày chưa tải
create or replace function public.app__backup_remind() returns void
language plpgsql security definer set search_path = public as $$
declare x bigint; last text := (select max(created_at) from public.audit_log where action = 'xuat_du_lieu_zip');
begin
  if last is not null and last >= to_char(public.vn_now() - interval '7 days', 'YYYY-MM-DD HH24:MI:SS') then return; end if;
  for x in select id from public.accounts where system_role = 'chu' and coalesce(locked, 0) = 0 loop
    perform public.app__notify(x, 'Nhắc tải bản sao lưu về máy',
      'Đã ' || case when last is null then 'lâu' else (current_date - left(last, 10)::date) || ' ngày' end
      || ' chưa tải gói sao lưu ZIP. Máy chủ có tự lưu 7 ngày, nhưng nên giữ thêm 1 bản trên máy anh (Dữ liệu & sao lưu › Tải gói ZIP).', '/quan-ly/du-lieu');
  end loop;
end $$;

-- ---------------------------------------------------------------- 4. Thông báo đến hạn chạy trên máy chủ
create or replace function public.app__notify_tick_sys() returns jsonb
language plpgsql security definer set search_path = public as $$
declare w public.weeks; win jsonb; label text; k text; n_mo int := 0; n_sap int := 0; now_ timestamp := public.vn_now();
begin
  for w in select * from public.weeks where end_date >= (now_::date - 1)::text loop
    if public.app__week_status(w.id) is not null then continue; end if;
    win := public.app_order_window(w.id);
    if win ->> 'state' <> 'dang_mo' then continue; end if;
    label := public.app__week_label(w);
    k := 'order_mo:' || w.id || ':' || to_char((win ->> 'open')::timestamp, 'YYYYMMDDHH24MI');
    insert into public.notification_events(event_key, created_at) values (k, public.vn_now_text()) on conflict do nothing;
    if found then
      insert into public.notifications(account_id, title, body, link, created_at)
      select ac.id, 'Đã mở order tuần ' || label, 'Hạn order: ' || (win ->> 'close_text') || '. Hãy chọn đủ các ô Đi làm được / Nghỉ.',
             '/order', public.vn_now_text()
        from public.accounts ac join public.employees e on e.id = ac.employee_id where e.status = 'Đang làm';
      get diagnostics n_mo = row_count;
    end if;
    if (win ->> 'close')::timestamp - now_ <= interval '3 hours' then
      k := 'sap_het_han:' || w.id || ':' || to_char((win ->> 'close')::timestamp, 'YYYYMMDDHH24MI');
      insert into public.notification_events(event_key, created_at) values (k, public.vn_now_text()) on conflict do nothing;
      if found then
        insert into public.notifications(account_id, title, body, link, created_at)
        select ac.id, 'Sắp hết hạn order tuần ' || label, 'Bạn chưa gửi order. Hạn: ' || (win ->> 'close_text') || '.',
               '/order', public.vn_now_text()
          from public.accounts ac join public.employees e on e.id = ac.employee_id
         where e.status = 'Đang làm' and not public.app__has_submitted(w.id, e.id);
        get diagnostics n_sap = row_count;
      end if;
    end if;
  end loop;
  delete from public.notifications where created_at < to_char(now_ - interval '60 days', 'YYYY-MM-DD HH24:MI:SS');
  delete from public.notification_events where created_at < to_char(now_ - interval '60 days', 'YYYY-MM-DD HH24:MI:SS');
  return jsonb_build_object('mo', n_mo, 'sap_het_han', n_sap);
end $$;

-- Trình duyệt cũ còn gọi: không làm gì (máy chủ đã tự chạy mỗi phút)
create or replace function public.app_notify_tick() returns jsonb
language sql stable security definer set search_path = public as $$ select null::jsonb $$;

do $cron$
begin
  perform cron.unschedule(jobid) from cron.job where jobname in ('thong-bao-den-han', 'sao-luu-hang-ngay', 'nhac-tai-sao-luu');
  perform cron.schedule('thong-bao-den-han', '* * * * *', 'select public.app__notify_tick_sys()');
  perform cron.schedule('sao-luu-hang-ngay', '30 19 * * *', 'select public.app__auto_backup()');        -- 02:30 giờ VN
  perform cron.schedule('nhac-tai-sao-luu', '0 2 * * 1', 'select public.app__backup_remind()');        -- Thứ Hai 9:00 giờ VN
end $cron$;

