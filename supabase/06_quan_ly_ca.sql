-- BƯỚC 6: QUẢN LÝ CA (phiếu chốt ca + đối soát). Chạy sau 01→05. Chạy lại nhiều lần không sao.
--
-- GIẢ ĐỊNH tạm (đặc tả mục 8 còn chờ chốt — chủ hệ thống xem lại):
--  * Ai đăng nhập (đang làm) cũng mở/điền được phiếu; "người chốt ca" = người bấm Xác nhận hoàn thành.
--  * Ca Chiều: giờ bắt đầu doanh thu lấy giờ kết thúc của phiếu ca Sáng đã hoàn thành; nếu ca Sáng chưa xong
--    thì nhân viên tự nhập. Ca Tối: nhân viên tự chọn giờ bắt đầu và kết thúc.
--  * Tiền đầu ca lệch ca trước: chỉ cảnh báo đỏ, vẫn cho hoàn thành.
--  * Mở lại phiếu đã hoàn thành: người có quyền "Mở lại phiếu chốt ca" (mặc định Chủ, Quản lý tổng);
--    mở lại thì xóa các dấu đã đối soát của phiếu.
--  * Việc bàn giao chưa xong: người chốt ca sau đánh dấu Đã xong (lưu người, giờ).
--  * Công nợ: chỉ ghi sổ (bàn, số tiền, ghi chú, đánh dấu đã thu). KHÔNG đưa vào công thức tiền.
--    Phiếu có công nợ mới thì không áp công thức Mục 1 = Mục 2 + Mục 3 để chặn hoàn thành.
--  * Nhập hàng: chọn Không nhận hàng / ĐỦ / THIẾU (THIẾU phải ghi ít nhất 1 mặt hàng).
-- =====================================================================

-- ---------------------------------------------------------------- Bảng
create table if not exists public.shift_reports (
  id bigint generated by default as identity primary key,
  branch_id bigint not null references public.branches(id) on delete cascade,
  work_date text not null,                         -- YYYY-MM-DD (ngày làm việc của ca)
  shift text not null,                             -- Sáng / Chiều / Tối
  status text not null default 'dang_chot' check (status in ('dang_chot', 'hoan_thanh')),
  recon_status text not null default 'chua' check (recon_status in ('chua', 'hoan_thanh')),
  created_by bigint,
  created_at text not null default public.vn_now_text(),
  completed_by bigint,
  completed_at text,
  rev_start text,                                  -- 'YYYY-MM-DD HH:MM'
  rev_end text,
  total_revenue bigint,                            -- Mục 1
  pos_cash bigint,                                 -- Mục 2
  pos_transfer bigint,                             -- Mục 3
  reported_transfer bigint,                        -- Mục 4 (cộng hóa đơn hotline)
  cash_counted bigint,                             -- Mục 5 (két cuối ca)
  opening_cash bigint,                             -- tiền mặt đầu ca
  cups integer,
  goods_status text check (goods_status in ('khong', 'du', 'thieu')),
  goods_note text,
  recon_by bigint,
  recon_at text,
  updated_by bigint,
  updated_at text not null default public.vn_now_text(),
  unique (branch_id, work_date, shift)
);
create index if not exists idx_shift_reports_date on public.shift_reports (work_date);

-- Chi tiết thu chi (giải trình chênh lệch)
create table if not exists public.shift_report_moves (
  id bigint generated by default as identity primary key,
  report_id bigint not null references public.shift_reports(id) on delete cascade,
  kind text not null check (kind in ('tien_mat', 'chuyen_khoan')),
  amount bigint not null,                          -- có dấu: âm = chi/thiếu, dương = thu/thừa
  note text not null default '',
  sort_order integer not null default 0
);
create index if not exists idx_srm_report on public.shift_report_moves (report_id);

-- Nhân viên thực tế làm trong ca
create table if not exists public.shift_report_staff (
  id bigint generated by default as identity primary key,
  report_id bigint not null references public.shift_reports(id) on delete cascade,
  employee_id bigint not null references public.employees(id) on delete cascade,
  source text not null default 'lich' check (source in ('lich', 'ho_tro')),
  role text,
  worked integer not null default 1,               -- 1 = có làm, 0 = phát sinh nghỉ
  absent_reason text,
  time_in text,                                    -- HH:MM
  time_out text,
  note text,
  unique (report_id, employee_id)
);

-- Nội dung bàn giao ca sau (việc chưa xong hiện tiếp ở các phiếu sau cùng cơ sở, không sao chép)
create table if not exists public.handover_items (
  id bigint generated by default as identity primary key,
  branch_id bigint not null references public.branches(id) on delete cascade,
  report_id bigint not null references public.shift_reports(id) on delete cascade,
  content text not null,
  created_by bigint,
  created_at text not null default public.vn_now_text(),
  done_at text,
  done_by bigint,
  done_report_id bigint,
  task_id bigint                                   -- dùng ở phần Họp & giao việc (giao cho quản lý)
);
create index if not exists idx_handover_open on public.handover_items (branch_id) where done_at is null;

-- Nhập hàng: mặt hàng thiếu
create table if not exists public.shift_report_goods (
  id bigint generated by default as identity primary key,
  report_id bigint not null references public.shift_reports(id) on delete cascade,
  item text not null,
  qty text not null default ''
);

-- Ảnh hàng nhận và hóa đơn (file nằm trong Storage, bucket phieu-ca)
create table if not exists public.shift_report_photos (
  id bigint generated by default as identity primary key,
  report_id bigint not null references public.shift_reports(id) on delete cascade,
  path text not null,
  created_by bigint,
  created_at text not null default public.vn_now_text()
);

-- Đối soát từng hạng mục
create table if not exists public.shift_report_checks (
  report_id bigint not null references public.shift_reports(id) on delete cascade,
  item text not null,
  checked_by bigint,
  checked_at text not null,
  primary key (report_id, item)
);

-- Công nợ (chỉ ghi sổ, chờ chốt cách tính)
create table if not exists public.shift_debts (
  id bigint generated by default as identity primary key,
  branch_id bigint not null references public.branches(id) on delete cascade,
  report_id bigint not null references public.shift_reports(id) on delete cascade,
  table_name text not null,
  amount bigint not null,
  note text,
  created_by bigint,
  created_at text not null default public.vn_now_text(),
  closed_at text,
  closed_by bigint,
  closed_report_id bigint,
  close_note text
);

-- Đối soát tiền mặt cuối ngày theo cơ sở
create table if not exists public.daily_cash_closings (
  branch_id bigint not null references public.branches(id) on delete cascade,
  work_date text not null,
  counted bigint,
  note text,
  done_by bigint,
  done_at text,
  primary key (branch_id, work_date)
);

