create or replace function public.app_ka_set_status(p_id bigint, p_status text, p_note text) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts; s public.shift_shortfalls; r public.shift_reports; lbl text;
begin
  a := public.app__need('doi_soat');
  if p_status not in ('chua_xu_ly', 'da_bu', 'tru_luong', 'mien') then raise exception 'Tình trạng không hợp lệ.'; end if;
  if p_status = 'mien' and trim(coalesce(p_note, '')) = '' then raise exception 'Miễn khoản âm phải ghi lý do.'; end if;
  update public.shift_shortfalls set status = p_status, status_note = nullif(trim(coalesce(p_note, '')), ''), status_by = a.id, status_at = public.vn_now_text()
   where id = p_id and status <> 'huy' returning * into s;
  if s.id is null then raise exception 'Không tìm thấy khoản âm.'; end if;
  select * into r from public.shift_reports where id = s.report_id;
  lbl := case p_status when 'da_bu' then 'Đã bù' when 'tru_luong' then 'Trừ lương' when 'mien' then 'Miễn' else 'Chưa xử lý' end;
  perform public.app__notify_emp(s.employee_id, 'Khoản âm: ' || lbl,
    public.app__ca_title(r) || ' · ' || public.app__vnd(s.amount) || ' → ' || lbl || coalesce(E'\n' || nullif(trim(coalesce(p_note, '')), ''), ''), '/cua-toi/khoan-am');
  perform public.app_log('khoan_am_tinh_trang', 'report=' || s.report_id || ' ' || p_status);
end $$;

-- ---------------------------------------------------------------- Tổng quan ca / tiền cuối ngày theo công thức mới
create or replace function public.app_ca_overview(p_date text) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare out jsonb;
begin
  perform public.app__need('chot_ca');
  select coalesce(jsonb_agg(x.j order by x.ord, x.sord), '[]'::jsonb) into out from (
    select b.sort_order as ord, sh.sort_order as sord,
           jsonb_build_object('branch_id', b.id, 'branch_code', coalesce(b.display_code, b.code), 'branch_name', b.name,
             'shift', sh.name, 'start_time', bs.start_time, 'end_time', bs.end_time,
             'report_id', r.id, 'status', r.status, 'recon_status', r.recon_status,
             'created_by', public.app__acc_name(r.created_by), 'completed_by', public.app__acc_name(r.completed_by),
             'completed_at', r.completed_at,
             'cash_left', (m.j ->> 'tm_left')::bigint, 'transfer_left', (m.j ->> 'ck_left')::bigint, 'ck_basis', m.j ->> 'ck_basis',
             'revenue', (e.d ->> 'total_revenue')::bigint, 'cups', (e.d ->> 'cups')::int,
             'checks', (select count(*) from public.shift_report_checks c where c.report_id = r.id),
             'short_total', (select sum(x.amount) from public.shift_report_results x where x.report_id = r.id and x.result = 'thieu'),
             'over_total', (select sum(x.amount) from public.shift_report_results x where x.report_id = r.id and x.result = 'thua'),
             'has_debt', exists (select 1 from public.shift_debts d where d.report_id = r.id)) as j
      from public.branches b
      join public.branch_shifts bs on bs.branch_id = b.id and bs.enabled = 1
      join public.shifts sh on sh.id = bs.shift_id and sh.status = 'Đang sử dụng'
      left join public.shift_reports r on r.branch_id = b.id and r.work_date = p_date and r.shift = sh.name
      left join lateral (select case when r.status = 'hoan_thanh' then public.app__ca_eff(r.id) end as d) e on true
      left join lateral (select case when r.status = 'hoan_thanh' and public.app_can('doi_soat') then public.app__ca_money(r.id) end as j) m on true
     where b.status = 'Đang hoạt động'
  ) x;
  return out;
end $$;

create or replace function public.app_ca_day(p_date text) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare out jsonb;
begin
  perform public.app__need('doi_soat');
  select coalesce(jsonb_agg(jsonb_build_object(
      'branch_id', b.id, 'branch_code', coalesce(b.display_code, b.code), 'branch_name', b.name,
      'shifts', (select count(*) from public.branch_shifts bs join public.shifts s on s.id = bs.shift_id and s.status = 'Đang sử dụng'
                  where bs.branch_id = b.id and bs.enabled = 1),
      'done', (select count(*) from public.shift_reports r where r.branch_id = b.id and r.work_date = p_date and r.status = 'hoan_thanh'),
      'recon_done', (select count(*) from public.shift_reports r where r.branch_id = b.id and r.work_date = p_date and r.recon_status = 'hoan_thanh'),
      'recon_reopen', (select count(*) from public.shift_reports r where r.branch_id = b.id and r.work_date = p_date and r.recon_status = 'mo_lai'),
      'opening', (select (public.app__ca_eff(r.id) ->> 'opening_cash')::bigint from public.shift_reports r where r.branch_id = b.id and r.work_date = p_date
                   order by array_position(public.app__shifts(), r.shift) limit 1),
      'pos_cash', (select sum((public.app__ca_eff(r.id) ->> 'pos_cash')::bigint) from public.shift_reports r
                    where r.branch_id = b.id and r.work_date = p_date and r.status = 'hoan_thanh'),
      'moves_cash', (select coalesce(sum((m ->> 'amount')::bigint), 0) from public.shift_reports r
                     cross join lateral jsonb_array_elements(public.app__ca_eff(r.id) -> 'moves') m
                     where r.branch_id = b.id and r.work_date = p_date and r.status = 'hoan_thanh' and m ->> 'kind' = 'tien_mat'),
      'debt_cash', (select coalesce(sum(d.amount), 0) from public.shift_debts d join public.shift_reports r on r.id = d.closed_report_id
                     where r.branch_id = b.id and r.work_date = p_date and r.status = 'hoan_thanh' and d.collect_kind = 'tien_mat'),
      'last_counted', (select (public.app__ca_eff(r.id) ->> 'cash_counted')::bigint from public.shift_reports r
                        where r.branch_id = b.id and r.work_date = p_date and r.status = 'hoan_thanh'
                        order by array_position(public.app__shifts(), r.shift) desc limit 1),
      'last_shift', (select r.shift from public.shift_reports r where r.branch_id = b.id and r.work_date = p_date and r.status = 'hoan_thanh'
                      order by array_position(public.app__shifts(), r.shift) desc limit 1),
      'has_debt', exists (select 1 from public.shift_debts d join public.shift_reports r on r.id = d.report_id
                           where r.branch_id = b.id and r.work_date = p_date),
      'counted', c.counted, 'note', c.note, 'done_by', public.app__acc_name(c.done_by), 'done_at', c.done_at
    ) order by b.sort_order), '[]'::jsonb) into out
    from public.branches b
    left join public.daily_cash_closings c on c.branch_id = b.id and c.work_date = p_date
   where b.status = 'Đang hoạt động';
  return out;
end $$;

-- ---------------------------------------------------------------- G. Báo cáo (Chủ, Quản lý tổng)
create or replace function public.app_ca_report(p_from text, p_to text) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare a public.accounts;
begin
  a := public.app__need('doi_soat');
  if coalesce(a.system_role, '') not in ('chu', 'ql_tong') then raise exception 'Chỉ Chủ và Quản lý tổng xem được báo cáo.'; end if;
  if p_from !~ '^\d{4}-\d{2}-\d{2}$' or p_to !~ '^\d{4}-\d{2}-\d{2}$' or p_to < p_from then raise exception 'Khoảng ngày không hợp lệ.'; end if;
  if p_to::date - p_from::date > 400 then raise exception 'Khoảng ngày tối đa khoảng 1 năm.'; end if;
  return jsonb_build_object(
    'reports', coalesce((select jsonb_agg(jsonb_build_object('id', r.id, 'work_date', r.work_date, 'shift', r.shift, 'branch_id', r.branch_id,
                 'branch', coalesce(b.display_code, b.code), 'revenue', (e.d ->> 'total_revenue')::bigint, 'cups', (e.d ->> 'cups')::int,
                 'pos_cash', (e.d ->> 'pos_cash')::bigint, 'pos_transfer', (e.d ->> 'pos_transfer')::bigint,
                 'debt_new', (select coalesce(sum(x.amount), 0) from public.shift_debts x where x.report_id = r.id),
                 'recon', r.recon_status,
                 'short', (select coalesce(sum(x.amount), 0) from public.shift_report_results x where x.report_id = r.id and x.result = 'thieu'),
                 'over', (select coalesce(sum(x.amount), 0) from public.shift_report_results x where x.report_id = r.id and x.result = 'thua'))
                 order by r.work_date, b.sort_order, array_position(public.app__shifts(), r.shift))
               from public.shift_reports r join public.branches b on b.id = r.branch_id
               cross join lateral (select public.app__ca_eff(r.id) as d) e
              where r.status = 'hoan_thanh' and r.work_date between p_from and p_to), '[]'),
    'shortfalls', coalesce((select jsonb_agg(public.app__ka_json(s) order by s.employee_id, s.id)
               from public.shift_shortfalls s join public.shift_reports r on r.id = s.report_id
              where s.status <> 'huy' and r.work_date between p_from and p_to), '[]'),
    'shifts', to_jsonb(public.app__shifts()),
    'branches', coalesce((select jsonb_agg(jsonb_build_object('id', b.id, 'code', coalesce(b.display_code, b.code), 'name', b.name) order by b.sort_order)
               from public.branches b where b.status = 'Đang hoạt động'), '[]'));
end $$;

