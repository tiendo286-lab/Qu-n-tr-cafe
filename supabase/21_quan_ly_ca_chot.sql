create or replace function public.app_ka_reply(p_id bigint, p_text text) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts; s public.shift_shortfalls; r public.shift_reports;
begin
  a := public.app__need(null);
  if trim(coalesce(p_text, '')) = '' then raise exception 'Nhập nội dung giải trình.'; end if;
  update public.shift_shortfalls set reply = trim(p_text), reply_at = public.vn_now_text(), seen_at = coalesce(seen_at, public.vn_now_text())
   where id = p_id and employee_id = a.employee_id and status <> 'huy' returning * into s;
  if s.id is null then raise exception 'Không tìm thấy khoản âm của bạn.'; end if;
  select * into r from public.shift_reports where id = s.report_id;
  if s.created_by is not null then
    perform public.app__notify(s.created_by, 'Nhân viên giải trình khoản âm',
      public.app__acc_name(a.id) || ' · ' || public.app__ca_title(r) || ' · ' || public.app__vnd(s.amount) || E'\n' || trim(p_text), '/quan-ly/khoan-am');
  end if;
end $$;

