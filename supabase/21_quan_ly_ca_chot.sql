-- Hạng mục tiền chỉ đánh dấu qua kết quả KHỚP/THIẾU/THỪA
create or replace function public.app_ca_check(p_id bigint, p_item text, p_on boolean) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts; r public.shift_reports;
begin
  a := public.app__need('doi_soat');
  select * into r from public.shift_reports where id = p_id for update;
  if r.id is null then raise exception 'Không tìm thấy phiếu.'; end if;
  if r.status <> 'hoan_thanh' then raise exception 'Nhân viên chưa hoàn thành phiếu này.'; end if;
  if r.recon_status = 'hoan_thanh' then raise exception 'Phiếu đã HOÀN THÀNH ĐỐI SOÁT. Bấm "Mở lại đối soát" trước khi sửa.'; end if;
  if not (p_item = any(public.app__ca_check_items())) then raise exception 'Hạng mục không hợp lệ.'; end if;
  if p_item = any(public.app__ca_money_items()) then raise exception 'Hạng mục tiền: chọn kết quả KHỚP / THIẾU / THỪA.'; end if;
  if p_on then
    insert into public.shift_report_checks(report_id, item, checked_by, checked_at) values (p_id, p_item, a.id, public.vn_now_text())
    on conflict (report_id, item) do nothing;
  else
    delete from public.shift_report_checks where report_id = p_id and item = p_item;
  end if;
  perform public.app__ca_auto_finish(p_id, a.id);
  perform public.app_log('doi_soat_ca', 'report=' || p_id || ' ' || p_item || '=' || p_on);
end $$;

-- Hoàn thành đối soát lại: cần đủ hạng mục và đủ kết quả các hạng mục tiền
create or replace function public.app_ca_recon_finish(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts; r public.shift_reports; n int;
begin
  a := public.app__need('doi_soat');
  select * into r from public.shift_reports where id = p_id for update;
  if r.id is null or r.status <> 'hoan_thanh' then raise exception 'Phiếu chưa hoàn thành.'; end if;
  if r.recon_status = 'hoan_thanh' then return; end if;
  select count(*) into n from public.shift_report_checks where report_id = p_id;
  if n < array_length(public.app__ca_check_items(), 1) then
    raise exception 'Còn % hạng mục chưa đối soát.', array_length(public.app__ca_check_items(), 1) - n;
  end if;
  if (select count(*) from public.shift_report_results where report_id = p_id) < array_length(public.app__ca_money_items(), 1) then
    raise exception 'Các hạng mục tiền cần chọn kết quả KHỚP / THIẾU / THỪA.';
  end if;
  insert into public.shift_report_recon(report_id, data, updated_by) values (p_id, public.app__recon_snapshot(p_id), a.id)
  on conflict (report_id) do nothing;
  update public.shift_reports set recon_status = 'hoan_thanh', recon_by = a.id, recon_at = public.vn_now_text() where id = p_id;
  insert into public.shift_recon_log(report_id, action, by_account) values (p_id, 'hoan_thanh_doi_soat', a.id);
  perform public.app_log('hoan_thanh_doi_soat', 'report=' || p_id);
end $$;

