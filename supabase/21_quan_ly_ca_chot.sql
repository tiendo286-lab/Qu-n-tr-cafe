  report_id bigint not null references public.shift_reports(id) on delete cascade,
  item text not null check (item in ('tien_mat', 'chuyen_khoan', 'thu_chi', 'cong_no')),
  result text not null check (result in ('khop', 'thieu', 'thua')),
  amount bigint not null default 0 check (amount >= 0),
  computed bigint,                 -- số lệch web tính lúc xác nhận (có dấu)
  basis text,                      -- chuyển khoản: 'ke_toan' | 'nhan_vien'
  reason text,
  by_account bigint,
  at text not null default public.vn_now_text(),
  primary key (report_id, item)
);
create table if not exists public.shift_shortfalls (
  id bigint generated by default as identity primary key,
  report_id bigint not null references public.shift_reports(id) on delete cascade,
  item text not null,
  employee_id bigint not null references public.employees(id),
  amount bigint not null check (amount > 0),
  reason text,
  status text not null default 'chua_xu_ly' check (status in ('chua_xu_ly', 'da_bu', 'tru_luong', 'mien', 'huy')),
  status_note text, status_by bigint, status_at text,
  seen_at text, reply text, reply_at text,
  created_by bigint,
  created_at text not null default public.vn_now_text()
);
create index if not exists idx_shortfalls_emp on public.shift_shortfalls (employee_id, status);
create index if not exists idx_shortfalls_report on public.shift_shortfalls (report_id);
create table if not exists public.bank_late_receipts (
  id bigint generated by default as identity primary key,
  account_id bigint not null references public.bank_accounts(id),
  origin_report_id bigint not null references public.shift_reports(id) on delete cascade,   -- ca tiền thuộc về
  arrived_report_id bigint not null references public.shift_reports(id) on delete cascade,  -- ca tiền thực về tài khoản
  amount bigint not null check (amount > 0),
  note text,
  created_by bigint,
  created_at text not null default public.vn_now_text()
);
