--  * Chuyển khoản của ca lệch vì có tiền đi ra khỏi tài khoản (trả tiền hàng, chủ rút...) → tạo phiếu chi ngay trên trang Đối soát ca:
--      - "Chi phí của quán": chọn nhóm chi → ghi vào Thu chi của tháng (fin_entries, hình thức chuyển khoản);
--      - "Chủ / quản lý rút tiền": ghi vào Sổ quỹ là phiếu rút chuyển khoản (fund_withdrawals, chờ Chủ xác nhận như phiếu rút thường).
--  * Số tiền tự cộng vào "tiền chuyển ra" của tài khoản đã chọn ở ca đó (bank_account_balances.transfers_out) → web tự đối soát lại;
--    xoá phiếu thì trừ lại. Không xoá được khi mục Chuyển khoản đã khoá (web tự đối soát) — Chủ mở khoá trước.
--  * Người tạo / xoá: Chủ, Quản lý tổng, Kế toán.
-- =====================================================================

create table if not exists public.shift_bank_outs (
  id bigint generated by default as identity primary key,
  report_id bigint not null references public.shift_reports(id) on delete cascade,
  account_id bigint not null references public.bank_accounts(id),
  kind text not null check (kind in ('chi_phi', 'rut_quy')),
  amount bigint not null check (amount > 0),
  category_id bigint references public.fin_categories(id),
  note text not null default '',
  fin_entry_id bigint references public.fin_entries(id) on delete set null,
  fund_withdrawal_id bigint references public.fund_withdrawals(id) on delete set null,
  created_by bigint, created_at text not null default public.vn_now_text()
);
create index if not exists idx_shift_bank_outs on public.shift_bank_outs (report_id);
alter table public.shift_bank_outs enable row level security;
revoke all on public.shift_bank_outs from anon, authenticated;

create or replace function public.app__bank_out_can() returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce((select coalesce(a.locked, 0) = 0 and (a.system_role in ('chu', 'ql_tong') or public.app_can('ke_toan'))
                     from public.accounts a where a.id = (public.app_account()).id), false)
$$;

create or replace function public.app__bank_out_json(o public.shift_bank_outs) returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object('id', o.id, 'kind', o.kind, 'amount', o.amount, 'note', o.note, 'account_id', o.account_id,
    'account', (select k.bank || ' ' || k.account_no || coalesce(' · ' || k.holder, '') from public.bank_accounts k where k.id = o.account_id),
    'category', (select c.name from public.fin_categories c where c.id = o.category_id),
    'fund_status', (select w.status from public.fund_withdrawals w where w.id = o.fund_withdrawal_id),
    'by', public.app__acc_name(o.created_by), 'at', o.created_at)
$$;

-- Trang đối soát: phiếu chi của ca + dữ liệu để tạo phiếu
create or replace function public.app_ca_bank_outs(p_id bigint) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare r public.shift_reports; m jsonb;
begin
  perform public.app__need(null);
  if not (public.app_can('doi_soat') or public.app_can('ke_toan')) then raise exception 'Bạn không có quyền thực hiện thao tác này.'; end if;
  select * into r from public.shift_reports where id = p_id;
  if r.id is null then raise exception 'Không tìm thấy phiếu.'; end if;
  m := public.app__ca_money(p_id);
  return jsonb_build_object('can', public.app__bank_out_can() and r.status = 'hoan_thanh' and r.recon_status <> 'hoan_thanh',
    'ck_left', (m ->> 'ck_left')::bigint, 'bank_ok', (m ->> 'bank_ok')::boolean,
    'locked', exists (select 1 from public.shift_report_checks c where c.report_id = p_id and c.item = 'chuyen_khoan' and c.auto = 1),
    'rows', coalesce((select jsonb_agg(public.app__bank_out_json(o) order by o.id) from public.shift_bank_outs o where o.report_id = p_id), '[]'),
    'accounts', coalesce((select jsonb_agg(jsonb_build_object('id', k.id, 'label', k.bank || ' ' || k.account_no || coalesce(' · ' || k.holder, ''),
                   'entered', x.closing is not null and x.opening is not null) order by k.sort_order, k.id)
                 from public.bank_accounts k left join public.bank_account_balances x on x.report_id = p_id and x.account_id = k.id
                where k.branch_id = r.branch_id and (k.active = 1 or x.report_id is not null)), '[]'),
    'categories', coalesce((select jsonb_agg(jsonb_build_object('id', c.id, 'name', c.name) order by c.sort_order, c.name)
                   from public.fin_categories c where c.kind = 'chi' and c.active = 1), '[]'));
end $$;

create or replace function public.app_ca_bank_out_save(p_id bigint, p jsonb) returns bigint
language plpgsql security definer set search_path = public as $$
declare a public.accounts; r public.shift_reports; k public.bank_accounts; x public.bank_account_balances; b public.branches;
        kd text := p ->> 'kind'; amt bigint := nullif(p ->> 'amount', '')::bigint; cat bigint := nullif(p ->> 'category_id', '')::bigint;
        nt text := trim(coalesce(p ->> 'note', '')); fe bigint; fw bigint; nid bigint; ad bigint;
begin
  a := public.app__need(null);
  if not public.app__bank_out_can() then raise exception 'Chỉ Chủ, Quản lý tổng, Kế toán tạo phiếu chi ở đây.'; end if;
  select * into r from public.shift_reports where id = p_id for update;
  if r.id is null or r.status <> 'hoan_thanh' then raise exception 'Phiếu ca chưa hoàn thành.'; end if;
  if r.recon_status = 'hoan_thanh' then raise exception 'Phiếu đã HOÀN THÀNH ĐỐI SOÁT. Bấm "Mở lại đối soát" trước khi sửa.'; end if;
  if coalesce(kd, '') not in ('chi_phi', 'rut_quy') then raise exception 'Chọn "Chi phí của quán" hay "Chủ / quản lý rút tiền".'; end if;
  if amt is null or amt <= 0 then raise exception 'Nhập số tiền lớn hơn 0.'; end if;
  if nt = '' then raise exception 'Ghi nội dung phiếu chi (chi gì / ai rút).'; end if;
  select * into k from public.bank_accounts where id = nullif(p ->> 'account_id', '')::bigint;
  if k.id is null or k.branch_id <> r.branch_id then raise exception 'Chọn tài khoản ngân hàng của cơ sở.'; end if;
  select * into x from public.bank_account_balances where report_id = p_id and account_id = k.id for update;
  if x.report_id is null or x.opening is null or x.closing is null then
    raise exception 'Tài khoản % chưa có số dư đầu / cuối của ca này. Kế toán nhập số dư trước.', k.account_no;
  end if;
  ad := (select id from public.accounts where id = a.id);
  if kd = 'chi_phi' then
    if cat is null or not exists (select 1 from public.fin_categories where id = cat and kind = 'chi') then raise exception 'Chọn nhóm chi.'; end if;
    insert into public.fin_entries(branch_id, entry_date, kind, category_id, amount, note, pay_method, created_by, updated_by)
    values (r.branch_id, r.work_date, 'chi', cat, amt, nt || ' (chuyển khoản từ ' || k.bank || ' ' || k.account_no || ', ca ' || r.shift || ')', 'chuyen_khoan', ad, ad)
    returning id into fe;
  else
    if r.work_date < public.app__fund_start() then raise exception 'Sổ quỹ bắt đầu từ %.', to_char(public.app__fund_start()::date, 'DD/MM/YYYY'); end if;
    insert into public.fund_withdrawals(branch_id, method, kind, wdate, amount, note, created_by, updated_by)
    values (r.branch_id, 'chuyen_khoan', 'giua_thang', r.work_date, amt, nt || ' (từ ' || k.bank || ' ' || k.account_no || ', ca ' || r.shift || ')', ad, ad)
    returning id into fw;
    if coalesce(a.system_role, '') <> 'chu' then
      select * into b from public.branches where id = r.branch_id;
      perform public.app__notify(o.id, 'Phiếu rút ' || coalesce(b.display_code, b.code) || ' chờ anh xác nhận: ' || public.app__vnd(amt),
          public.app__acc_name(a.id) || ' ghi chuyển khoản rút ngày ' || to_char(r.work_date::date, 'DD/MM') || ' · ' || nt || '. Đúng thì bấm "Đã nhận tiền".',
          '/quan-ly/so-quy?cn=' || r.branch_id || '&thang=' || left(r.work_date, 7))
        from public.accounts o where o.system_role = 'chu' and coalesce(o.locked, 0) = 0;
    end if;
  end if;
  insert into public.shift_bank_outs(report_id, account_id, kind, amount, category_id, note, fin_entry_id, fund_withdrawal_id, created_by)
  values (p_id, k.id, kd, amt, case when kd = 'chi_phi' then cat end, nt, fe, fw, ad) returning id into nid;
  update public.bank_account_balances set transfers_out = coalesce(transfers_out, 0) + amt,
         note = concat_ws(' · ', nullif(note, ''), 'phiếu chi ' || public.app__vnd(amt) || ': ' || nt), updated_by = ad, updated_at = public.vn_now_text()
   where report_id = p_id and account_id = k.id;
  insert into public.shift_recon_log(report_id, action, field, before, after, reason, by_account)
  values (p_id, 'phieu_chi', 'bank_transfers_out', to_jsonb(coalesce(x.transfers_out, 0)), to_jsonb(coalesce(x.transfers_out, 0) + amt),
          case when kd = 'chi_phi' then 'Chi phí' else 'Rút tiền' end || ' ' || public.app__vnd(amt) || ' từ ' || k.bank || ' ' || k.account_no || ': ' || nt, ad);
  perform public.app_log('phieu_chi_ck', 'report=' || p_id || ' ' || kd || ' ' || amt);
  return nid;
end $$;

create or replace function public.app_ca_bank_out_delete(p_out bigint) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts; o public.shift_bank_outs; r public.shift_reports;
begin
  a := public.app__need(null);
  if not public.app__bank_out_can() then raise exception 'Chỉ Chủ, Quản lý tổng, Kế toán xoá phiếu chi ở đây.'; end if;
  select * into o from public.shift_bank_outs where id = p_out for update;
  if o.id is null then raise exception 'Không tìm thấy phiếu chi.'; end if;
  select * into r from public.shift_reports where id = o.report_id for update;
  if r.recon_status = 'hoan_thanh' then raise exception 'Phiếu đã HOÀN THÀNH ĐỐI SOÁT. Bấm "Mở lại đối soát" trước khi sửa.'; end if;
  if exists (select 1 from public.shift_report_checks c where c.report_id = o.report_id and c.item = 'chuyen_khoan' and c.auto = 1) then
    raise exception 'Mục Chuyển khoản web đã tự đối soát nên đã KHOÁ. Chủ mở khoá (Đèn đối soát) rồi mới xoá phiếu chi.';
  end if;
  if o.fund_withdrawal_id is not null and exists (select 1 from public.fund_withdrawals w where w.id = o.fund_withdrawal_id and w.status = 'da_nhan') then
    raise exception 'Chủ đã xác nhận phiếu rút này ở Sổ quỹ nên không xoá được.';
  end if;
  delete from public.fin_entries where id = o.fin_entry_id;
  delete from public.fund_withdrawals where id = o.fund_withdrawal_id;
  update public.bank_account_balances set transfers_out = greatest(coalesce(transfers_out, 0) - o.amount, 0), updated_by = a.id, updated_at = public.vn_now_text()
   where report_id = o.report_id and account_id = o.account_id;
  delete from public.shift_bank_outs where id = p_out;
  insert into public.shift_recon_log(report_id, action, field, reason, by_account)
  values (o.report_id, 'xoa_phieu_chi', 'bank_transfers_out', 'Xoá phiếu chi ' || public.app__vnd(o.amount) || ': ' || o.note, a.id);
  perform public.app_log('phieu_chi_ck_xoa', 'out=' || p_out);
end $$;

