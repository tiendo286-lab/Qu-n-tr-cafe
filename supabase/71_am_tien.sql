-- Bước 71 (anh Tiến chốt 13/11): tab ÂM TIỀN (Quản lý ca › Âm tiền) — mọi ca thiếu / dư tiền mặt, chuyển khoản của 1 cơ sở
--   * Lệch ≤ 5.000 coi như khớp (đối soát tự duyệt; tab bỏ qua).
--   * Đối soát: tiền mặt / chuyển khoản THIẾU được để tab xử lý (không chọn người): CK = "Chờ tiền về" (không hạn), TM = "Chờ gán". Ca vẫn hoàn thành đối soát.
--   * Ghép ca thiếu với ca dư (cùng cơ sở, cùng loại tiền, ghép từng phần, lý do bắt buộc): Chủ / QL tổng ghép có hiệu lực ngay;
--     QL cơ sở ghép thì chờ Chủ / QL tổng duyệt. Ghép chỉ là bản ghi đối chiếu — KHÔNG sửa số tiền của ca đã đối soát.
--     Ghép được sau khi đã trừ lương → tự huỷ / giảm khoản trừ lương (đã nộp bù thì huỷ = hoàn lại), báo nhân viên.
--   * Không có tiền về: Trừ lương (chia người) hoặc Quán chịu (chỉ Chủ / QL tổng; khoản chi nhóm "Âm tiền – quán chịu", không đổi quỹ).
--   * Ca dư không ghép: Thu khác (khoản thu nhóm "Thu khác", không đổi quỹ).
--   * Còn ca Chờ tiền về / Chờ gán / ghép chờ duyệt → không cho chốt tháng.
-- Người dùng: Chủ, QL tổng, QL cơ sở (kế toán không). Chạy lại nhiều lần không sao.

alter table public.fin_entries add column if not exists no_fund boolean not null default false;

create table if not exists public.gap_matches (
  id bigint generated by default as identity primary key,
  branch_id bigint not null references public.branches(id),
  item text not null check (item in ('tien_mat', 'chuyen_khoan')),
  short_report bigint not null references public.shift_reports(id) on delete cascade,   -- ca thiếu
  over_report bigint not null references public.shift_reports(id) on delete cascade,    -- ca dư
  amount bigint not null check (amount > 0),
  reason text not null,
  status text not null default 'cho_duyet' check (status in ('cho_duyet', 'da_duyet')),
  created_by bigint, created_at text not null default public.vn_now_text(),
  approved_by bigint, approved_at text
);
create index if not exists gap_matches_short on public.gap_matches(short_report);
create index if not exists gap_matches_over on public.gap_matches(over_report);

create table if not exists public.gap_decisions (
  id bigint generated by default as identity primary key,
  report_id bigint not null references public.shift_reports(id) on delete cascade,
  item text not null check (item in ('tien_mat', 'chuyen_khoan')),
  kind text not null check (kind in ('quan_chiu', 'thu_khac')),
  amount bigint not null check (amount > 0),
  reason text not null default '',
  fin_entry_id bigint references public.fin_entries(id) on delete set null,
  created_by bigint, created_at text not null default public.vn_now_text()
);
create index if not exists gap_decisions_report on public.gap_decisions(report_id);
revoke all on public.gap_matches, public.gap_decisions from anon, authenticated;

-- 'admin' (Chủ / QL tổng), 'ql' (quản lý cơ sở được xem thu chi cơ sở này), null (không được)
create or replace function public.app__gap_role(p_branch bigint) returns text
language sql stable security definer set search_path = public as $$
  select case when coalesce(public.app__fin_admin(), false) then 'admin'
              when coalesce((select a.system_role = 'ql' from public.accounts a where a.id = (public.app_account()).id), false)
                   and coalesce(public.app__tc_can(p_branch), false) then 'ql' end
$$;

-- Mỗi ca đã chốt × (tiền mặt, chuyển khoản) có lệch > 5.000: thiếu / dư, đã xử lý bao nhiêu, còn lại, trạng thái
create or replace function public.app__gap_rows(p_branch bigint, p_from text, p_to text)
returns table(report_id bigint, work_date text, shift text, item text, lech bigint, kind text, total bigint,
              tl bigint, dcs bigint, mt bigint, mp bigint, remain bigint, state text)
language sql stable security definer set search_path = public as $$
  with r as (
    select x.id, x.work_date, x.shift, public.app__ca_money(x.id) m
      from public.shift_reports x
     where x.branch_id = p_branch and x.status = 'hoan_thanh' and x.work_date between p_from and p_to),
  v as (
    select r.id, r.work_date, r.shift, it.item,
           case it.item when 'tien_mat' then coalesce((r.m ->> 'tm_left')::bigint, 0) else coalesce((r.m ->> 'ck_left')::bigint, 0) end lech
      from r cross join (values ('tien_mat'), ('chuyen_khoan')) it(item)),
  w as (
    select v.id, v.work_date, v.shift, v.item, v.lech, case when v.lech < 0 then 'thieu' else 'du' end kind, abs(v.lech) total,
           case when v.lech < 0 then coalesce((select sum(s.amount) from public.shift_shortfalls s where s.report_id = v.id and s.item = v.item and s.status <> 'huy'), 0) else 0 end tl,
           coalesce((select sum(g.amount) from public.gap_decisions g where g.report_id = v.id and g.item = v.item), 0) dcs,
           coalesce((select sum(mm.amount) from public.gap_matches mm where mm.item = v.item and mm.status = 'da_duyet'
                       and ((v.lech < 0 and mm.short_report = v.id) or (v.lech > 0 and mm.over_report = v.id))), 0) mt,
           coalesce((select sum(mm.amount) from public.gap_matches mm where mm.item = v.item and mm.status = 'cho_duyet'
                       and ((v.lech < 0 and mm.short_report = v.id) or (v.lech > 0 and mm.over_report = v.id))), 0) mp
      from v where abs(v.lech) > 5000)
  select w.id, w.work_date, w.shift, w.item, w.lech, w.kind, w.total, w.tl, w.dcs, w.mt, w.mp,
         greatest(w.total - w.tl - w.dcs - w.mt, 0),
         case when greatest(w.total - w.tl - w.dcs - w.mt, 0) <= 5000 then 'xong' when w.kind = 'du' then 'du'
              when w.item = 'chuyen_khoan' then 'cho_tien' else 'cho_gan' end
    from w
$$;

create or replace function public.app__gap_pending(p_branch bigint, p_from text, p_to text) returns int
language sql stable security definer set search_path = public as $$
  select (select count(*)::int from public.app__gap_rows(p_branch, p_from, p_to) g where g.kind = 'thieu' and g.state in ('cho_tien', 'cho_gan'))
       + (select count(*)::int from public.gap_matches mm join public.shift_reports x on x.id = mm.short_report
           where mm.branch_id = p_branch and mm.status = 'cho_duyet' and x.work_date between p_from and p_to)
$$;

-- Sau khi ghép (đã duyệt): khoản trừ lương của ca thiếu vượt phần còn phải chịu → huỷ / giảm (đã nộp bù → huỷ = hoàn lại), báo nhân viên
create or replace function public.app__gap_release(p_report bigint, p_item text, p_why text) returns bigint
language plpgsql security definer set search_path = public as $$
declare r public.shift_reports; g record; need bigint; tl bigint; excess bigint; s record; take bigint; done bigint := 0;
begin
  select * into r from public.shift_reports where id = p_report;
  select * into g from public.app__gap_rows(r.branch_id, r.work_date, r.work_date) x where x.report_id = p_report and x.item = p_item and x.kind = 'thieu';
  if g.report_id is null then   -- hết lệch (≤ 5.000): cả khoản trừ lương thừa
    need := 0;
    select coalesce(sum(amount), 0) into tl from public.shift_shortfalls where report_id = p_report and item = p_item and status in ('tru_luong', 'da_bu');
  else
    need := greatest(g.total - g.dcs - g.mt, 0);
    select coalesce(sum(amount), 0) into tl from public.shift_shortfalls where report_id = p_report and item = p_item and status in ('tru_luong', 'da_bu', 'mien');
  end if;
  excess := tl - need;
  if excess <= 0 then return 0; end if;
  for s in select * from public.shift_shortfalls where report_id = p_report and item = p_item and status in ('tru_luong', 'da_bu')
            order by (status = 'da_bu'), id desc loop
    exit when excess <= 0;
    take := least(excess, s.amount);
    if take = s.amount then
      update public.shift_shortfalls set status = 'huy', status_note = case when s.status = 'da_bu' then 'Hoàn lại: ' else 'Huỷ: ' end || p_why,
             status_by = (public.app_account()).id, status_at = public.vn_now_text() where id = s.id;
    else
      update public.shift_shortfalls set amount = amount - take, status_note = 'Giảm ' || public.app__vnd(take) || ': ' || p_why where id = s.id;
    end if;
    perform public.app__notify_emp(s.employee_id,
      case when s.status = 'da_bu' then 'Quán hoàn lại tiền bạn đã nộp bù' else 'Khoản âm của bạn được giảm / huỷ' end,
      public.app__ca_title(r) || ' · ' || public.app__ca_item_label(p_item) || ': ' || case when take = s.amount then 'huỷ cả ' else 'giảm ' end || public.app__vnd(take)
      || E'\nLý do: ' || p_why || case when s.status = 'da_bu' then E'\nQuản lý sẽ trả lại bạn số tiền này.' else '' end, '/cua-toi/khoan-am');
    excess := excess - take; done := done + take;
  end loop;
  return done;
end $$;

-- Danh sách cho tab Âm tiền (tháng ± 3 ngày để gợi ý ghép qua đầu / cuối tháng)
create or replace function public.app_gap_list(p_branch bigint, p_month text) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare role text := public.app__gap_role(p_branch); f text; t text; f3 text; t3 text;
begin
  if (public.app_account()).id is null then raise exception 'Phiên đăng nhập đã hết. Hãy đăng nhập lại.'; end if;
  if role is null then raise exception 'Chỉ Chủ, Quản lý tổng, Quản lý cơ sở dùng tab Âm tiền.'; end if;
  if p_month !~ '^\d{4}-\d{2}$' then raise exception 'Tháng không hợp lệ.'; end if;
  f := p_month || '-01'; t := to_char(f::date + interval '1 month' - interval '1 day', 'YYYY-MM-DD');
  f3 := to_char(f::date - 3, 'YYYY-MM-DD'); t3 := to_char(t::date + 3, 'YYYY-MM-DD');
  return jsonb_build_object('role', role, 'from', f, 'to', t, 'pending', public.app__gap_pending(p_branch, f, t),
    'locked', public.app__fin_locked(p_branch, f),
    'rows', coalesce((select jsonb_agg(jsonb_build_object('report_id', g.report_id, 'date', g.work_date, 'shift', g.shift, 'item', g.item, 'lech', g.lech,
               'kind', g.kind, 'total', g.total, 'tl', g.tl, 'dcs', g.dcs, 'mt', g.mt, 'mp', g.mp, 'remain', g.remain, 'state', g.state,
               'in_month', g.work_date between f and t, 'locked', public.app__fin_locked(p_branch, g.work_date),
               'result', (select jsonb_build_object('result', rr.result, 'amount', rr.amount, 'reason', rr.reason, 'by', public.app__acc_name(rr.by_account))
                            from public.shift_report_results rr where rr.report_id = g.report_id and rr.item = g.item),
               'staff', coalesce((select jsonb_agg(jsonb_build_object('employee_id', st.employee_id, 'name', coalesce(em.code || ' – ', '') || em.name) order by st.id)
                            from public.shift_report_staff st join public.employees em on em.id = st.employee_id
                           where st.report_id = g.report_id and coalesce(st.worked, 1) = 1), '[]'),
               'people', coalesce((select jsonb_agg(jsonb_build_object('id', s.id, 'name', coalesce(em.code || ' – ', '') || em.name, 'amount', s.amount, 'status', s.status, 'note', s.status_note) order by s.id)
                            from public.shift_shortfalls s join public.employees em on em.id = s.employee_id
                           where s.report_id = g.report_id and s.item = g.item and s.status <> 'huy'), '[]'),
               'decisions', coalesce((select jsonb_agg(jsonb_build_object('id', d.id, 'kind', d.kind, 'amount', d.amount, 'reason', d.reason, 'by', public.app__acc_name(d.created_by), 'at', d.created_at) order by d.id)
                            from public.gap_decisions d where d.report_id = g.report_id and d.item = g.item), '[]'),
               'matches', coalesce((select jsonb_agg(jsonb_build_object('id', mm.id, 'amount', mm.amount, 'reason', mm.reason, 'status', mm.status,
                              'other', case when mm.short_report = g.report_id then mm.over_report else mm.short_report end,
                              'other_date', o.work_date, 'other_shift', o.shift, 'by', public.app__acc_name(mm.created_by), 'mine', mm.created_by = (public.app_account()).id,
                              'approved_by', public.app__acc_name(mm.approved_by)) order by mm.id)
                            from public.gap_matches mm join public.shift_reports o on o.id = case when mm.short_report = g.report_id then mm.over_report else mm.short_report end
                           where mm.item = g.item and (mm.short_report = g.report_id or mm.over_report = g.report_id)), '[]'))
             order by g.work_date desc, array_position(public.app__shifts(), g.shift) desc, g.item)
           from public.app__gap_rows(p_branch, f3, t3) g), '[]'),
    'branches', coalesce((select jsonb_agg(jsonb_build_object('id', b.id, 'code', coalesce(b.display_code, b.code), 'name', b.name) order by b.sort_order)
               from public.branches b where b.status = 'Đang hoạt động' and public.app__gap_role(b.id) is not null), '[]'));
end $$;

create or replace function public.app_gap_match(p_short bigint, p_over bigint, p_item text, p_amount bigint, p_reason text) returns bigint
language plpgsql security definer set search_path = public as $$
declare a public.accounts := public.app_account(); rs public.shift_reports; ro public.shift_reports; role text; gs record; go record; why text := nullif(trim(coalesce(p_reason, '')), ''); nid bigint;
begin
  select * into rs from public.shift_reports where id = p_short; select * into ro from public.shift_reports where id = p_over;
  if rs.id is null or ro.id is null then raise exception 'Không tìm thấy ca.'; end if;
  if rs.branch_id <> ro.branch_id then raise exception 'Chỉ ghép ca cùng cơ sở.'; end if;
  role := public.app__gap_role(rs.branch_id);
  if role is null then raise exception 'Chỉ Chủ, Quản lý tổng, Quản lý cơ sở được ghép.'; end if;
  if p_item not in ('tien_mat', 'chuyen_khoan') then raise exception 'Loại tiền không hợp lệ.'; end if;
  if why is null then raise exception 'Ghi lý do ghép (vd: khách CK tối 13 về sáng 14).'; end if;
  if public.app__fin_locked(rs.branch_id, rs.work_date) or public.app__fin_locked(ro.branch_id, ro.work_date) then raise exception 'Tháng đã CHỐT nên không ghép được.'; end if;
  select * into gs from public.app__gap_rows(rs.branch_id, rs.work_date, rs.work_date) x where x.report_id = p_short and x.item = p_item and x.kind = 'thieu';
  select * into go from public.app__gap_rows(ro.branch_id, ro.work_date, ro.work_date) x where x.report_id = p_over and x.item = p_item and x.kind = 'du';
  if gs.report_id is null then raise exception 'Ca thiếu không còn thiếu % (lệch ≤ 5.000).', public.app__ca_item_label(p_item); end if;
  if go.report_id is null then raise exception 'Ca dư không còn dư % (lệch ≤ 5.000).', public.app__ca_item_label(p_item); end if;
  if p_amount is null or p_amount <= 0 then raise exception 'Nhập số tiền ghép lớn hơn 0.'; end if;
  -- ca thiếu: ghép được cả phần đã trừ lương (ghép xong sẽ huỷ / giảm trừ lương)
  if p_amount > greatest(gs.total - gs.dcs - gs.mt - gs.mp, 0) then raise exception 'Ca thiếu chỉ còn % để ghép.', public.app__vnd(greatest(gs.total - gs.dcs - gs.mt - gs.mp, 0)); end if;
  if p_amount > greatest(go.total - go.dcs - go.mt - go.mp, 0) then raise exception 'Ca dư chỉ còn % để ghép.', public.app__vnd(greatest(go.total - go.dcs - go.mt - go.mp, 0)); end if;
  insert into public.gap_matches(branch_id, item, short_report, over_report, amount, reason, status, created_by, approved_by, approved_at)
  values (rs.branch_id, p_item, p_short, p_over, p_amount, why, case when role = 'admin' then 'da_duyet' else 'cho_duyet' end, a.id,
          case when role = 'admin' then a.id end, case when role = 'admin' then public.vn_now_text() end) returning id into nid;
  if role = 'admin' then perform public.app__gap_after(nid); end if;
  perform public.app_log('am_tien_ghep', 'match=' || nid || ' ' || p_item || ' ' || p_amount || ' ' || p_short || '<-' || p_over);
  return nid;
end $$;

-- ghép có hiệu lực: huỷ / giảm trừ lương thừa + báo nhân viên ca thiếu
create or replace function public.app__gap_after(p_match bigint) returns void
language plpgsql security definer set search_path = public as $$
declare mm public.gap_matches; rs public.shift_reports; ro public.shift_reports; st record; rel bigint;
begin
  select * into mm from public.gap_matches where id = p_match;
  select * into rs from public.shift_reports where id = mm.short_report; select * into ro from public.shift_reports where id = mm.over_report;
  rel := public.app__gap_release(mm.short_report, mm.item, 'ghép với ' || public.app__ca_title(ro) || ' (' || mm.reason || ')');
  if rel = 0 then
    for st in select distinct s.employee_id from public.shift_report_staff s where s.report_id = mm.short_report and coalesce(s.worked, 1) = 1 loop
      perform public.app__notify_emp(st.employee_id, 'Ca thiếu tiền đã được ghép',
        public.app__ca_title(rs) || ' · ' || public.app__ca_item_label(mm.item) || ': thiếu ' || public.app__vnd(mm.amount) || ' đã được ghép với ' || public.app__ca_title(ro)
        || E'\nLý do: ' || mm.reason, '/cua-toi/khoan-am');
    end loop;
  end if;
end $$;
revoke execute on function public.app__gap_after(bigint) from public, anon, authenticated;

create or replace function public.app_gap_match_approve(p_id bigint, p_ok boolean) returns void
language plpgsql security definer set search_path = public as $$
declare mm public.gap_matches; a public.accounts := public.app_account();
begin
  select * into mm from public.gap_matches where id = p_id for update;
  if mm.id is null then raise exception 'Không tìm thấy khoản ghép.'; end if;
  if coalesce(public.app__gap_role(mm.branch_id), '') <> 'admin' then raise exception 'Chỉ Chủ / Quản lý tổng duyệt ghép.'; end if;
  if mm.status <> 'cho_duyet' then raise exception 'Khoản ghép này đã duyệt rồi.'; end if;
  if coalesce(p_ok, false) then
    update public.gap_matches set status = 'da_duyet', approved_by = a.id, approved_at = public.vn_now_text() where id = p_id;
    perform public.app__gap_after(p_id);
  else
    delete from public.gap_matches where id = p_id;
  end if;
  perform public.app_log(case when p_ok then 'am_tien_duyet_ghep' else 'am_tien_tu_choi_ghep' end, 'match=' || p_id);
end $$;

create or replace function public.app_gap_match_delete(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
declare mm public.gap_matches; role text; rs public.shift_reports;
begin
  select * into mm from public.gap_matches where id = p_id;
  if mm.id is null then return; end if;
  role := public.app__gap_role(mm.branch_id);
  if role is null or (role <> 'admin' and not (mm.status = 'cho_duyet' and mm.created_by = (public.app_account()).id)) then
    raise exception 'Chỉ Chủ / Quản lý tổng bỏ ghép đã duyệt (Quản lý cơ sở bỏ được ghép mình tạo khi chưa duyệt).';
  end if;
  select * into rs from public.shift_reports where id = mm.short_report;
  if public.app__fin_locked(rs.branch_id, rs.work_date) then raise exception 'Tháng đã CHỐT nên không bỏ ghép được.'; end if;
  delete from public.gap_matches where id = p_id;
  perform public.app_log('am_tien_bo_ghep', 'match=' || p_id || ' ' || mm.amount);
end $$;

-- Trừ lương phần còn thiếu (chia người; mặc định trừ lương, báo nhân viên)
create or replace function public.app_gap_tl(p_report bigint, p_item text, p_people jsonb, p_reason text) returns void
language plpgsql security definer set search_path = public as $$
declare a public.accounts := public.app_account(); r public.shift_reports; g record; x jsonb; tot bigint := 0; why text := nullif(trim(coalesce(p_reason, '')), ''); emps bigint[] := '{}'; e bigint; ea bigint;
begin
  select * into r from public.shift_reports where id = p_report;
  if r.id is null then raise exception 'Không tìm thấy ca.'; end if;
  if public.app__gap_role(r.branch_id) is null then raise exception 'Chỉ Chủ, Quản lý tổng, Quản lý cơ sở được gán trừ lương.'; end if;
  if public.app__fin_locked(r.branch_id, r.work_date) then raise exception 'Tháng đã CHỐT.'; end if;
  select * into g from public.app__gap_rows(r.branch_id, r.work_date, r.work_date) z where z.report_id = p_report and z.item = p_item and z.kind = 'thieu';
  if g.report_id is null then raise exception 'Ca này không còn thiếu %.', public.app__ca_item_label(p_item); end if;
  if why is null then raise exception 'Ghi lý do.'; end if;
  if jsonb_typeof(coalesce(p_people, '[]')) <> 'array' or jsonb_array_length(coalesce(p_people, '[]')) = 0 then raise exception 'Chọn nhân viên chịu.'; end if;
  for x in select * from jsonb_array_elements(p_people) loop
    e := (x ->> 'employee_id')::bigint; ea := coalesce((x ->> 'amount')::bigint, 0);
    if not exists (select 1 from public.employees where id = e) then raise exception 'Nhân viên không hợp lệ.'; end if;
    if e = any(emps) then raise exception 'Mỗi nhân viên chỉ chọn một lần.'; end if;
    if ea <= 0 then raise exception 'Số tiền của từng nhân viên phải lớn hơn 0.'; end if;
    emps := emps || e; tot := tot + ea;
  end loop;
  if tot > g.remain then raise exception 'Tổng trừ lương (%) lớn hơn số còn thiếu (%).', public.app__vnd(tot), public.app__vnd(g.remain); end if;
  for x in select * from jsonb_array_elements(p_people) loop
    insert into public.shift_shortfalls(report_id, item, employee_id, amount, reason, created_by, status, auto_tru, status_note, status_by, status_at)
    values (p_report, p_item, (x ->> 'employee_id')::bigint, (x ->> 'amount')::bigint, why, a.id, 'tru_luong', true, 'Mặc định trừ lương (tab Âm tiền)', a.id, public.vn_now_text());
    perform public.app__notify_emp((x ->> 'employee_id')::bigint, 'Bạn có khoản âm — mặc định trừ lương',
      public.app__ca_title(r) || ' · ' || public.app__ca_item_label(p_item) || ': bạn chịu ' || public.app__vnd((x ->> 'amount')::bigint)
      || E'\nLý do: ' || why || E'\nNgười gán: ' || public.app__acc_name(a.id)
      || E'\nMặc định: TRỪ LƯƠNG. Không đồng ý thì gửi giải trình ở mục Khoản âm của tôi.', '/cua-toi/khoan-am');
  end loop;
  perform public.app_log('am_tien_tru_luong', 'report=' || p_report || ' ' || p_item || ' ' || tot);
end $$;

-- Quán chịu (ca thiếu, chỉ Chủ / QL tổng) hoặc Thu khác (ca dư): khoản chi / thu ở Thu chi, KHÔNG đổi quỹ
create or replace function public.app_gap_decide(p_report bigint, p_item text, p_kind text, p_amount bigint, p_reason text) returns bigint
language plpgsql security definer set search_path = public as $$
declare a public.accounts := public.app_account(); r public.shift_reports; g record; role text; cat bigint; eid bigint; nid bigint; why text := trim(coalesce(p_reason, ''));
begin
  select * into r from public.shift_reports where id = p_report;
  if r.id is null then raise exception 'Không tìm thấy ca.'; end if;
  role := public.app__gap_role(r.branch_id);
  if role is null then raise exception 'Bạn không dùng được tab Âm tiền.'; end if;
  if p_kind not in ('quan_chiu', 'thu_khac') then raise exception 'Chọn Quán chịu hoặc Thu khác.'; end if;
  if p_kind = 'quan_chiu' and role <> 'admin' then raise exception 'Chỉ Chủ / Quản lý tổng bấm Quán chịu.'; end if;
  if public.app__fin_locked(r.branch_id, r.work_date) then raise exception 'Tháng đã CHỐT.'; end if;
  select * into g from public.app__gap_rows(r.branch_id, r.work_date, r.work_date) z
   where z.report_id = p_report and z.item = p_item and z.kind = case when p_kind = 'quan_chiu' then 'thieu' else 'du' end;
  if g.report_id is null then raise exception 'Ca này không còn % %.', case when p_kind = 'quan_chiu' then 'thiếu' else 'dư' end, public.app__ca_item_label(p_item); end if;
  if p_amount is null or p_amount <= 0 then raise exception 'Nhập số tiền lớn hơn 0.'; end if;
  if p_amount > greatest(g.remain - g.mp, 0) then raise exception 'Chỉ còn % chưa xử lý.', public.app__vnd(greatest(g.remain - g.mp, 0)); end if;
  select id into cat from public.fin_categories where kind = case when p_kind = 'quan_chiu' then 'chi' else 'thu' end
     and name = case when p_kind = 'quan_chiu' then 'Âm tiền – quán chịu' else 'Thu khác' end order by id limit 1;
  if cat is null then raise exception 'Chưa có nhóm "%". Vào Cài đặt › Loại & nhóm thu chi tạo nhóm này.', case when p_kind = 'quan_chiu' then 'Âm tiền – quán chịu' else 'Thu khác' end; end if;
  insert into public.fin_entries(branch_id, entry_date, kind, category_id, amount, note, pay_method, created_by, updated_by, no_fund)
  values (r.branch_id, r.work_date, case when p_kind = 'quan_chiu' then 'chi' else 'thu' end, cat, p_amount,
          case when p_kind = 'quan_chiu' then 'Âm tiền ' else 'Tiền dư ' end || public.app__ca_item_label(p_item) || ' – ca ' || r.shift || ' ' || to_char(r.work_date::date, 'DD/MM')
          || case when why <> '' then ' · ' || why else '' end, p_item, a.id, a.id, true) returning id into eid;
  insert into public.gap_decisions(report_id, item, kind, amount, reason, fin_entry_id, created_by)
  values (p_report, p_item, p_kind, p_amount, why, eid, a.id) returning id into nid;
  perform public.app_log('am_tien_' || p_kind, 'report=' || p_report || ' ' || p_item || ' ' || p_amount);
  return nid;
end $$;

create or replace function public.app_gap_decision_delete(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
declare d public.gap_decisions; r public.shift_reports; role text;
begin
  select * into d from public.gap_decisions where id = p_id;
  if d.id is null then return; end if;
  select * into r from public.shift_reports where id = d.report_id;
  role := public.app__gap_role(r.branch_id);
  if role is null or (d.kind = 'quan_chiu' and role <> 'admin') then raise exception 'Chỉ Chủ / Quản lý tổng bỏ Quán chịu.'; end if;
  if public.app__fin_locked(r.branch_id, r.work_date) then raise exception 'Tháng đã CHỐT.'; end if;
  delete from public.gap_decisions where id = p_id;
  if d.fin_entry_id is not null then delete from public.fin_entries where id = d.fin_entry_id; end if;
  perform public.app_log('am_tien_bo_' || d.kind, 'report=' || d.report_id || ' ' || d.amount);
end $$;

