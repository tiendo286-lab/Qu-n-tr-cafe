create table if not exists public.login_attempts (
  id bigint generated by default as identity primary key,
  ip text not null,
  login text,
  at timestamptz not null default now()
);
create index if not exists ix_login_attempts_ip_at on public.login_attempts (ip, at);
alter table public.login_attempts enable row level security;
revoke all on public.login_attempts from anon, authenticated;

create or replace function public.app_login_email(p_login text) returns jsonb
language plpgsql volatile security definer set search_path = public as $$
declare a record; v_ip text; n int; lg text := lower(trim(coalesce(p_login, '')));
begin
  begin v_ip := nullif(trim(split_part(coalesce(current_setting('request.headers', true)::json ->> 'x-forwarded-for', ''), ',', 1)), '');
  exception when others then v_ip := null; end;
  if v_ip is not null then
    select count(*) into n from public.login_attempts where login_attempts.ip = v_ip and at > now() - interval '10 minutes';
    if n >= 40 then raise exception 'Bạn đã thử đăng nhập quá nhiều lần. Đợi 10 phút rồi thử lại.'; end if;
    insert into public.login_attempts(ip, login) values (v_ip, left(lg, 40));
    delete from public.login_attempts where at < now() - interval '1 day';
  end if;
  select ac.*, e.status as emp_status into a
    from public.accounts ac left join public.employees e on e.id = ac.employee_id
   where (ac.employee_id is not null and lower(e.code) = lg)
      or (ac.employee_id is null and ac.login_name is not null and lower(ac.login_name) = lg)
   order by ac.employee_id nulls last limit 1;
  if not found or (a.employee_id is not null and a.emp_status <> 'Đang làm')
     or a.locked = 1 or a.has_password = 0 or a.auth_email is null then
    -- địa chỉ giả cố định theo mã (cùng dạng địa chỉ thật) — đăng nhập bằng địa chỉ này luôn thất bại như sai mật khẩu
    return jsonb_build_object('email', 'a' || (1000 + abs(hashtext('milano:' || lg)) % 9000) || '@milano.invalid');
  end if;
  return jsonb_build_object('email', a.auth_email);
end $$;

revoke execute on function public.app_login_email(text) from public;
grant execute on function public.app_login_email(text) to anon, authenticated;

