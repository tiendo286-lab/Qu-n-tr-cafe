--    → người lạ không phân biệt được mã nào có tài khoản; đăng nhập sau đó báo chung "sai mã hoặc mật khẩu".
--  * Giới hạn thử: quá 40 lần / 10 phút từ cùng địa chỉ mạng → đợi 10 phút (đủ rộng cho cả quán đổi ca).
--    Nhật ký thử giữ 1 ngày (login_attempts).
