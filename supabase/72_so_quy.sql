-- Bước 72 (anh Tiến chốt 13/11): SỔ QUỸ
--   * Nộp quỹ cuối ngày TỰ ĐỘNG = số đếm két của ca cuối đã chốt trong ngày − tiền gối đầu (1.000.000); quản lý đếm cuối ngày thì lấy số quản lý;
--     khác thì quản lý sửa (như cũ).
--   * Phiếu LUÂN CHUYỂN QUỸ tiền mặt ↔ tài khoản (Chủ, QL tổng, QL cơ sở; lưu là xong) — không tính thu / chi, không hiện ở Thu chi.
--   * Kiểm quỹ lệch → "Điều chỉnh": tạo khoản chi / thu ở Thu chi (nhóm bắt buộc) để sổ khớp tiền thật.
--   * Mỗi lần xem 1 cơ sở (giao diện); nhắc kiểm quỹ khi quá 7 ngày; nhắc rút khi tiền mặt quá 20.000.000 (cài đặt có sẵn).
-- Chạy lại nhiều lần không sao.

create table if not exists public.fund_transfers (
  id bigint generated by default as identity primary key,
  branch_id bigint not null references public.branches(id),
  tdate text not null,
  direction text not null check (direction in ('tm_tk', 'tk_tm')),
  amount bigint not null check (amount > 0),
  note text not null default '',
  created_by bigint, created_at text not null default public.vn_now_text()
);
revoke all on public.fund_transfers from anon, authenticated;
alter table public.fund_counts add column if not exists adj_entry_id bigint;

-- Số tiền mặt cuối ngày: quản lý đếm cuối ngày (nếu có), nếu không thì số đếm két của ca cuối đã chốt trong ngày
create or replace function public.app__fund_last_count(p_branch bigint, p_date text)
returns table(counted bigint, src text)
language sql stable security definer set search_path = public as $$
  select coalesce(c.counted, k.cc), case when c.counted is not null then 'quản lý đếm' when k.cc is not null then 'két ca ' || k.shift end
    from (select 1) one
    left join public.daily_cash_closings c on c.branch_id = p_branch and c.work_date = p_date
    left join lateral (select (public.app__ca_eff(r.id) ->> 'cash_counted')::bigint cc, r.shift
                         from public.shift_reports r where r.branch_id = p_branch and r.work_date = p_date and r.status = 'hoan_thanh'
                        order by array_position(public.app__shifts(), r.shift) desc limit 1) k on true
$$;

create or replace function public.app__fund_mover(p_branch bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce(public.app__fin_admin(), false)
      or (coalesce((select a.system_role = 'ql' from public.accounts a where a.id = (public.app_account()).id), false) and coalesce(public.app__tc_can(p_branch), false))
$$;

create or replace function public.app_fund_transfer_save(p_id bigint, p jsonb) returns bigint
language plpgsql security definer set search_path = public as $$
declare a public.accounts := public.app_account(); br bigint := nullif(p ->> 'branch_id', '')::bigint; d text := p ->> 'date'; dir text := p ->> 'direction';
        amt bigint := nullif(p ->> 'amount', '')::bigint; nt text := trim(coalesce(p ->> 'note', '')); old public.fund_transfers; nid bigint;
begin
  if p_id is not null then
    select * into old from public.fund_transfers where id = p_id;
    if old.id is null then raise exception 'Không tìm thấy phiếu luân chuyển.'; end if;
    br := old.branch_id;
    if public.app__fin_locked(old.branch_id, old.tdate) then raise exception 'Tháng đã CHỐT nên không sửa được.'; end if;
  end if;
  if br is null or not public.app__fund_mover(br) then raise exception 'Chỉ Chủ, Quản lý tổng, Quản lý cơ sở tạo phiếu luân chuyển quỹ.'; end if;
  if d is null or d !~ '^\d{4}-\d{2}-\d{2}$' then raise exception 'Chọn ngày.'; end if;
  if d < public.app__fund_start() then raise exception 'Sổ quỹ bắt đầu từ %.', public.app__fund_start(); end if;
  if dir not in ('tm_tk', 'tk_tm') then raise exception 'Chọn chiều luân chuyển.'; end if;
  if amt is null or amt <= 0 then raise exception 'Nhập số tiền lớn hơn 0.'; end if;
  if public.app__fin_locked(br, d) then raise exception 'Tháng này đã CHỐT.'; end if;
  if p_id is null then
    insert into public.fund_transfers(branch_id, tdate, direction, amount, note, created_by) values (br, d, dir, amt, nt, a.id) returning id into nid;
  else
    update public.fund_transfers set tdate = d, direction = dir, amount = amt, note = nt where id = p_id; nid := p_id;
  end if;
  perform public.app_log('luan_chuyen_quy', 'id=' || nid || ' ' || dir || ' ' || amt);
  return nid;
end $$;

create or replace function public.app_fund_transfer_delete(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
declare old public.fund_transfers;
begin
  select * into old from public.fund_transfers where id = p_id;
  if old.id is null then return; end if;
  if not public.app__fund_mover(old.branch_id) then raise exception 'Chỉ Chủ, Quản lý tổng, Quản lý cơ sở xoá phiếu luân chuyển.'; end if;
  if public.app__fin_locked(old.branch_id, old.tdate) then raise exception 'Tháng đã CHỐT nên không xoá được.'; end if;
  delete from public.fund_transfers where id = p_id;
  perform public.app_log('luan_chuyen_quy_xoa', 'id=' || p_id || ' ' || old.amount);
end $$;

-- Kiểm quỹ lệch → điều chỉnh: khoản chi (thực tế thiếu) / thu (thực tế dư) ở Thu chi, cùng ngày kiểm, hình thức theo quỹ
create or replace function public.app_fund_count_adjust(p_count bigint, p_category bigint, p_note text) returns bigint
language plpgsql security definer set search_path = public as $$
declare a public.accounts := public.app_account(); c public.fund_counts; k text; eid bigint; nt text := trim(coalesce(p_note, ''));
begin
  select * into c from public.fund_counts where id = p_count for update;
  if c.id is null then raise exception 'Không tìm thấy lần kiểm quỹ.'; end if;
  if not public.app__fund_mover(c.branch_id) then raise exception 'Chỉ Chủ, Quản lý tổng, Quản lý cơ sở điều chỉnh quỹ.'; end if;
  if c.adj_entry_id is not null and exists (select 1 from public.fin_entries where id = c.adj_entry_id) then raise exception 'Lần kiểm này đã điều chỉnh rồi.'; end if;
  if c.counted = c.book then raise exception 'Lần kiểm này khớp, không cần điều chỉnh.'; end if;
  if public.app__fin_locked(c.branch_id, c.count_date) then raise exception 'Tháng đã CHỐT.'; end if;
  k := case when c.counted < c.book then 'chi' else 'thu' end;
  if p_category is null or not exists (select 1 from public.fin_categories where id = p_category and kind = k and active = 1) then
    raise exception 'Chọn nhóm % cho khoản điều chỉnh.', k;
  end if;
  insert into public.fin_entries(branch_id, entry_date, kind, category_id, amount, note, pay_method, created_by, updated_by)
  values (c.branch_id, c.count_date, k, p_category, abs(c.book - c.counted),
          'Điều chỉnh kiểm quỹ ' || to_char(c.count_date::date, 'DD/MM') || case when nt <> '' then ' · ' || nt when coalesce(c.note, '') <> '' then ' · ' || c.note else '' end,
          c.method, a.id, a.id) returning id into eid;
  update public.fund_counts set adj_entry_id = eid where id = p_count;
  perform public.app_log('kiem_quy_dieu_chinh', 'count=' || p_count || ' ' || k || ' ' || abs(c.book - c.counted));
  return eid;
end $$;


-- Thay bản đang chạy (lấy từ máy chủ 13/11)
CREATE OR REPLACE FUNCTION public.app__fund_rows(p_branch bigint, p_from text, p_to text)
 RETURNS TABLE(d text, method text, typ text, label text, amount bigint, auto boolean, ref jsonb)
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare st text := public.app__fund_start(); fl bigint := coalesce(public.app__fund_set('fund_cash_float')::bigint, 1000000);
        f text := greatest(p_from, public.app__fund_start()); dd date;
begin
  if f > p_to then return; end if;
  for dd in select generate_series(f::date, p_to::date, interval '1 day')::date loop
    -- tiền mặt nộp quỹ cuối ngày
    return query
      select to_char(dd, 'YYYY-MM-DD'), 'tien_mat'::text, 'nop_quy'::text,
             case when v.cash_amount is not null then 'Nộp quỹ cuối ngày (quản lý sửa)'
                  else 'Nộp quỹ cuối ngày (' || coalesce(lc.src, 'đếm') || ' ' || public.app__vnd(lc.counted) || ' − để lại ' || public.app__vnd(fl) || ')' end,
             coalesce(v.cash_amount, lc.counted - fl), v.cash_amount is null,
             jsonb_build_object('counted', lc.counted, 'src', lc.src, 'note', v.cash_note)
        from (select 1) one
        left join lateral (select x.counted, x.src from public.app__fund_last_count(p_branch, to_char(dd, 'YYYY-MM-DD')) x) lc on true
        left join public.fund_day_values v on v.branch_id = p_branch and v.work_date = to_char(dd, 'YYYY-MM-DD')
       where coalesce(v.cash_amount, lc.counted - fl) is not null and coalesce(v.cash_amount, lc.counted - fl) <> 0;
    -- bước 72: luân chuyển quỹ tiền mặt ↔ tài khoản (không tính thu / chi)
    return query
      select t.tdate, m.method, 'luan_chuyen'::text,
             case when t.direction = 'tm_tk' then 'Luân chuyển: tiền mặt → tài khoản' else 'Luân chuyển: tài khoản → tiền mặt' end || case when t.note <> '' then ' · ' || t.note else '' end,
             case when (t.direction = 'tm_tk') = (m.method = 'tien_mat') then -t.amount else t.amount end, false, jsonb_build_object('transfer_id', t.id)
        from public.fund_transfers t cross join (values ('tien_mat'), ('chuyen_khoan')) m(method)
       where t.branch_id = p_branch and t.tdate = to_char(dd, 'YYYY-MM-DD');
    -- bước 45: tiền mặt nộp quỹ khi giao ca (ca sau mở với tiền gối đầu)
    return query
      select to_char(dd, 'YYYY-MM-DD'), 'tien_mat'::text, 'nop_quy'::text,
             'Nộp quỹ khi giao ca ' || (hh.h ->> 'prev_shift') || ' → ' || r.shift || ' (két để lại ' || public.app__vnd(fl) || ')',
             (hh.h ->> 'rut')::bigint, true, jsonb_build_object('report_id', r.id)
        from public.shift_reports r cross join lateral (select public.app__ca_hand(r.id) h) hh
       where r.branch_id = p_branch and r.work_date = to_char(dd, 'YYYY-MM-DD') and r.status = 'hoan_thanh'
         and public.app__ca_chain(r.shift) and hh.h ->> 'state' = 'rut_quy';
    -- chuyển khoản về
    return query
      select to_char(dd, 'YYYY-MM-DD'), 'chuyen_khoan'::text, 'ck_ve'::text,
             case when v.bank_amount is not null then 'Chuyển khoản về (quản lý nhập)' else 'Chuyển khoản thực nhận (kế toán)' end,
             coalesce(v.bank_amount, a.s), v.bank_amount is null, jsonb_build_object('note', v.bank_note)
        from (select public.app__fund_bank_auto(p_branch, to_char(dd, 'YYYY-MM-DD')) s) a
        left join public.fund_day_values v on v.branch_id = p_branch and v.work_date = to_char(dd, 'YYYY-MM-DD')
       where coalesce(v.bank_amount, a.s) is not null and coalesce(v.bank_amount, a.s) <> 0;
  end loop;
  -- khoản thu chi quản lý tạo
  return query
    select e.entry_date, e.pay_method, 'thu_chi'::text, (case when e.kind = 'chi' then 'Chi: ' else 'Thu: ' end) || e.note || coalesce(' · ' || c.name, ''),
           case when e.kind = 'chi' then -e.amount else e.amount end, false, jsonb_build_object('entry_id', e.id)
      from public.fin_entries e left join public.fin_categories c on c.id = e.category_id
     where e.branch_id = p_branch and e.entry_date between f and p_to and not coalesce(e.no_fund, false);   -- bước 71: quán chịu / thu khác (âm tiền) không đổi quỹ
  -- nhân viên bù khoản âm (tiền mặt)
  return query
    select left(s.status_at, 10), 'tien_mat'::text, 'bu_khoan_am'::text, 'NV bù khoản âm: ' || coalesce(em.code || ' – ' || em.name, '?'),
           s.amount, false, jsonb_build_object('shortfall_id', s.id, 'report_id', s.report_id)
      from public.shift_shortfalls s join public.shift_reports r on r.id = s.report_id left join public.employees em on em.id = s.employee_id
     where r.branch_id = p_branch and s.status = 'da_bu' and left(s.status_at, 10) between f and p_to;
  -- phiếu rút
  return query
    select w.wdate, w.method, 'rut'::text,
           (case when w.kind = 'cuoi_thang' then 'Rút cuối tháng' else 'Rút giữ hộ' end) || case when w.status = 'da_nhan' then ' · Chủ đã nhận' else ' · chờ Chủ xác nhận' end
             || case when w.note <> '' then ' · ' || w.note else '' end,
           -w.amount, false, jsonb_build_object('withdrawal_id', w.id, 'status', w.status)
      from public.fund_withdrawals w where w.branch_id = p_branch and w.wdate between f and p_to;
  -- bước 64: cho vay (tiền ra khỏi quỹ) và người vay trả nợ (tiền về quỹ) — không tính chi phí / doanh thu
  return query
    select l.loan_date, l.method, 'cho_vay'::text, case when l.kind = 'tra_ho' then 'Trả hộ Kho tổng' else 'Cho vay: ' || p.name end || case when l.note <> '' then ' · ' || l.note else '' end,
           -l.amount, false, jsonb_build_object('loan_id', l.id)
      from public.branch_loans l join public.loan_people p on p.id = l.person_id
     where l.branch_id = p_branch and l.loan_date between f and p_to and l.report_id is null;   -- bước 65: khoản vay từ phiếu ca đã ra khỏi két trong ca
  return query
    select y.pay_date, y.method, 'tra_vay'::text, 'Trả nợ vay: ' || p.name || case when y.note <> '' then ' · ' || y.note else '' end,
           y.amount, false, jsonb_build_object('loan_id', l.id, 'payment_id', y.id)
      from public.branch_loan_payments y join public.branch_loans l on l.id = y.loan_id join public.loan_people p on p.id = l.person_id
     where l.branch_id = p_branch and y.pay_date between f and p_to;
end $function$;

-- Thay bản đang chạy (lấy từ máy chủ 13/11)
CREATE OR REPLACE FUNCTION public.app_fund_branch(p_branch bigint, p_month text)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare d0 text; d1 text; upto text; st text := public.app__fund_start(); b public.branches; fl bigint := coalesce(public.app__fund_set('fund_cash_float')::bigint, 1000000);
        open_tm bigint; open_ck bigint; rows jsonb; days jsonb;
begin
  perform public.app__tc_need(p_branch);
  perform public.app__fin_month_ok(p_month);
  select * into b from public.branches where id = p_branch;
  d0 := p_month || '-01'; d1 := to_char((d0::date + interval '1 month' - interval '1 day'), 'YYYY-MM-DD');
  upto := least(d1, to_char(public.vn_now(), 'YYYY-MM-DD'));
  open_tm := public.app__fund_balance(p_branch, 'tien_mat', to_char(d0::date - 1, 'YYYY-MM-DD'));
  open_ck := public.app__fund_balance(p_branch, 'chuyen_khoan', to_char(d0::date - 1, 'YYYY-MM-DD'));
  if d0 <= st then   -- tháng bắt đầu sổ: số dư đầu là số quản lý nhập
    open_tm := coalesce((select amount from public.fund_openings where branch_id = p_branch and method = 'tien_mat'), 0);
    open_ck := coalesce((select amount from public.fund_openings where branch_id = p_branch and method = 'chuyen_khoan'), 0);
  end if;
  select coalesce(jsonb_agg(jsonb_build_object('date', r.d, 'method', r.method, 'type', r.typ, 'label', r.label, 'amount', r.amount, 'auto', r.auto, 'ref', r.ref)
           order by r.d, case r.typ when 'nop_quy' then 1 when 'ck_ve' then 1 when 'bu_khoan_am' then 2 when 'thu_chi' then 3 else 4 end), '[]')
    into rows from public.app__fund_rows(p_branch, d0, d1) r;
  -- bảng theo ngày (để quản lý nhập bổ sung)
  select coalesce(jsonb_agg(jsonb_build_object('date', g.dd, 'counted', lc.counted, 'counted_src', lc.src,
           'cash_auto', case when lc.counted is not null then lc.counted - fl end, 'cash_set', v.cash_amount, 'cash_note', v.cash_note,
           'bank_auto', public.app__fund_bank_auto(p_branch, g.dd), 'bank_set', v.bank_amount, 'bank_note', v.bank_note,
           'reports', (select count(*) from public.shift_reports x where x.branch_id = p_branch and x.work_date = g.dd and x.status = 'hoan_thanh'))
           order by g.dd), '[]')
    into days
    from (select to_char(x, 'YYYY-MM-DD') dd from generate_series(greatest(d0, st)::date, upto::date, interval '1 day') x) g
    left join lateral (select x.counted, x.src from public.app__fund_last_count(p_branch, g.dd) x) lc on true
    left join public.fund_day_values v on v.branch_id = p_branch and v.work_date = g.dd;
  return jsonb_build_object('branch_id', b.id, 'code', coalesce(b.display_code, b.code), 'name', b.name, 'month', p_month,
    'from', d0, 'to', d1, 'upto', upto, 'start', st, 'float', fl, 'alert', coalesce(public.app__fund_set('fund_cash_alert')::bigint, 20000000),
    'is_start_month', left(st, 7) = p_month,
    'openings', jsonb_build_object('tien_mat', (select to_jsonb(o) from public.fund_openings o where o.branch_id = p_branch and o.method = 'tien_mat'),
                                   'chuyen_khoan', (select to_jsonb(o) from public.fund_openings o where o.branch_id = p_branch and o.method = 'chuyen_khoan')),
    'open', jsonb_build_object('tien_mat', open_tm, 'chuyen_khoan', open_ck),
    'balance', jsonb_build_object('tien_mat', public.app__fund_balance(p_branch, 'tien_mat', upto), 'chuyen_khoan', public.app__fund_balance(p_branch, 'chuyen_khoan', upto)),
    'bank_actual', public.app__fund_bank_actual(p_branch, upto),
    'rows', rows, 'days', days,
    'withdrawals', coalesce((select jsonb_agg(to_jsonb(w) || jsonb_build_object('by', public.app__acc_name(w.created_by), 'received_name', public.app__acc_name(w.received_by),
                       'locked', w.status = 'da_nhan' or public.app__fin_locked(w.branch_id, w.wdate)) order by w.wdate desc, w.id desc)
                     from public.fund_withdrawals w where w.branch_id = p_branch and (w.wdate between d0 and d1 or w.status = 'cho_nhan')), '[]'),
    'counts', coalesce((select jsonb_agg(to_jsonb(c) || jsonb_build_object('by', public.app__acc_name(c.created_by), 'adj', (select jsonb_build_object('id', e.id, 'kind', e.kind, 'amount', e.amount, 'category', fc.name)
                                  from public.fin_entries e left join public.fin_categories fc on fc.id = e.category_id where e.id = c.adj_entry_id)) order by c.count_date desc, c.id desc)
                 from public.fund_counts c where c.branch_id = p_branch and c.count_date between d0 and d1), '[]'),
    'locked', public.app__fin_locked(p_branch, d0),
    'transfers', coalesce((select jsonb_agg(to_jsonb(t) || jsonb_build_object('by', public.app__acc_name(t.created_by), 'locked', public.app__fin_locked(t.branch_id, t.tdate)) order by t.tdate desc, t.id desc)
                 from public.fund_transfers t where t.branch_id = p_branch and t.tdate between d0 and d1), '[]'),
    'last_count', jsonb_build_object('tien_mat', (select max(count_date) from public.fund_counts where branch_id = p_branch and method = 'tien_mat'),
                                     'chuyen_khoan', (select max(count_date) from public.fund_counts where branch_id = p_branch and method = 'chuyen_khoan')),
    'can_move', public.app__fund_mover(p_branch),
    'owner', coalesce((public.app_account()).system_role, '') = 'chu');
end $function$;

